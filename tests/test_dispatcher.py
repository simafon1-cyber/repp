def test_главный_цикл_проводит_минуты_и_сделки():
    """Иначе диспетчер считал бы пустоту, а окно не закрывалось никогда."""
    print("\n[Торговый цикл действительно проводит учёт]")
    исходник = (APP / "main.py").read_text(encoding="utf-8")
    дерево = ast.parse(исходник)
    зовут = set()
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.Call):
            имя = getattr(узел.func, "id", getattr(узел.func, "attr", ""))
            if имя in ("учесть_круг_в_диспетчере", "учесть_закрытие_в_диспетчере",
                       "учесть_работу", "учесть_закрытую_сделку"):
                зовут.add(имя)
    check("учесть_круг_в_диспетчере" in зовут,
          "Минуты проводятся из главного цикла", str(sorted(зовут)))
    check("учесть_закрытие_в_диспетчере" in зовут,
          "А сделки — из обработки закрытий брокера", str(sorted(зовут)))

    # И именно там, где закрытие подтверждено и не посчитано дважды.
    внутри = исходник.split("def process_closed_deals", 1)[1].split("\ndef ", 1)[0]
    check("учесть_закрытие_в_диспетчере()" in внутри,
          "Счёт сделок стоит внутри process_closed_deals")
    check(внутри.index("_processed_deal_tickets.add")
          < внутри.index("учесть_закрытие_в_диспетчере()"),
          "И ПОСЛЕ отсева уже посчитанных тикетов — иначе двойной счёт")


