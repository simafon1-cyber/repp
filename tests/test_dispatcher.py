def test_окно_не_закрывается_раньше_недели():
    """Поведение, а не запись в файле: четырёх дней теперь мало.

    Раньше трёх полных дней и двадцати сделок хватало, чтобы шаг С-001
    считался завершённым. Теперь — нет."""
    print("\n[Четырёх дней больше не хватает]")
    к = json.loads(
        (ROOT / "preregistration" / "strategy_catalog.json").read_text(
            encoding="utf-8"))
    шаг = к["очередь"][0]

    минут = int(к.get("минут_для_полного_дня") or 360)

    def завершено(дней, сделок):
        готово, почему = dp.окно_завершено(
            шаг, состояние_с(дней_полных=дней, сделок=сделок), минут)
        return готово, почему

    готово, почему = завершено(3, 25)
    check(not готово, "Три дня и 25 сделок — окно НЕ завершено", почему)
    check("дней 3 из 5" in почему, "И сказано, чего не хватает", почему)

    готово, почему = завершено(4, 25)
    check(not готово, "Четыре дня и 25 сделок — окно НЕ завершено", почему)

    готово, почему = завершено(5, 19)
    check(not готово, "Пять дней, но 19 сделок — окно НЕ завершено", почему)

    готово, почему = завершено(5, 20)
    check(готово, "Пять дней И двадцать сделок — окно завершено", почему)


