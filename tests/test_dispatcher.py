def test_окно_только_по_обоим_условиям():
    """Главная проверка. «Или» закрыло бы окно на пяти сделках."""
    print("\n[Окно завершается по ОБОИМ условиям]")
    к = каталог()
    шаг = к["очередь"][0]

    с = состояние_с(дней_полных=3, сделок=5)
    готово, почему = dp.окно_завершено(шаг, с, 360)
    check(not готово, "Три дня, но пять сделок — окно НЕ завершено", почему)
    check("сделок 5 из 20" in почему, "И сказано, чего не хватает", почему)

    с = состояние_с(дней_полных=1, сделок=50)
