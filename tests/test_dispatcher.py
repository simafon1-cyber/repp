def test_прибыль_не_может_попасть_в_решение():
    """Структурно: у решения нет входа для денег, и оно их не читает."""
    print("\n[Прибыль в решение не входит]")
    дерево = ast.parse((APP / "strategy_dispatcher.py").read_text(encoding="utf-8"))
    решающие = ("решение", "окно_завершено", "текущий_шаг", "полных_дней",
                "закрытых_сделок", "шаг_готов")
    денежные = ("pnl", "profit", "прибыл", "убыт", "баланс", "эквит",
                "equity", "balance")
    беды = []
    for узел in ast.walk(дерево):
        if not isinstance(узел, ast.FunctionDef) or узел.name not in решающие:
            continue
        имена = узел.args.args
        for а in имена:
            if any(d in а.arg.lower() for d in денежные):
                беды.append(f"{узел.name}: аргумент {а.arg}")
        # Строки-комментарии не в счёт: смотрим обращения к полям и именам.
        for под in ast.walk(узел):
            if isinstance(под, ast.Attribute) and any(
                    d in под.attr.lower() for d in денежные):
                беды.append(f"{узел.name}: поле {под.attr}")
            if isinstance(под, ast.Name) and any(
                    d in под.id.lower() for d in денежные):
                беды.append(f"{узел.name}: имя {под.id}")
    check(not беды, "Ни одна решающая функция не берёт и не читает деньги",
          str(беды[:3]))

    # И поведенчески: состояние вообще не хранит денег.
    с = состояние_с(дней_полных=3, сделок=20)
    текст = json.dumps(с, ensure_ascii=False).lower()
    check(not any(d in текст for d in денежные),
          "В состоянии на диске денег нет", текст[:120])


