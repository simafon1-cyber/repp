def test_hour_candle_is_built_correctly() -> None:
    """Открытие первой, максимум и минимум по всем, закрытие последней."""
    print("\n[Часовая свеча собрана верно]")
    m5 = пятиминутки(часов=1)
    r = build_h1.собрать(m5)
    check(r["часов_получено"] == 1, "Получен один час")
    b = r["bars"][0]
    check(b["open"] == m5[0]["open"], "Открытие — от первой пятиминутки")
    check(b["close"] == m5[-1]["close"], "Закрытие — от последней")
    check(b["high"] == max(x["high"] for x in m5), "Максимум — по всем")
    check(b["low"] == min(x["low"] for x in m5), "Минимум — по всем")
    check(b["time"] % 3600 == 0, "Время — ровно начало часа", str(b["time"]))
    check(b["tick_volume"] == sum(x["tick_volume"] for x in m5),
          "Объём — сумма")


def test_spread_is_the_worst_of_the_twelve() -> None:
    """Спред берётся МАКСИМАЛЬНЫЙ, а не средний.

    Вход в часовую свечу происходит в какой-то момент внутри неё, и какой
    спред был в ту секунду, мы не знаем. Средний означал бы предположение
    об удаче."""
    print("\n[Спред часа — максимальный из двенадцати]")
    m5 = пятиминутки(часов=1)
    b = build_h1.собрать(m5)["bars"][0]
    максимум = max(x["spread"] for x in m5)
    средний = sum(x["spread"] for x in m5) / 12
    check(b["spread"] == максимум, "Взят максимум", str(b["spread"]))
    check(b["spread"] > средний, "И он больше среднего — это осторожнее",
          f"{b['spread']} против {средний:.1f}")


def test_incomplete_hours_are_dropped() -> None:
    """Неполный час выбрасывается целиком.

    Соблазн «взять что есть» опасен: неполный час это час с другим
    диапазоном, а на диапазоне стоит весь расчёт риска."""
    print("\n[Неполный час выбрасывается]")
    m5 = пятиминутки(часов=3, пропустить=(14,))   # второй час неполон
    r = build_h1.собрать(m5)
    check(r["часов_получено"] == 2, "Осталось два полных часа",
          str(r["часов_получено"]))
    check(r["часов_отброшено_неполных"] == 1, "Один отброшен")

    only_one = build_h1.собрать(пятиминутки(часов=1)[:11])
    check(only_one["часов_получено"] == 0, "Один неполный — ничего не вышло")


def test_a_gap_does_not_glue_different_hours() -> None:
    """Дыра в данных не склеивает куски разных часов.

    Если группировать «по двенадцать штук подряд», после дыры в ряд
    попали бы пятиминутки из двух разных часов, и получилась бы свеча,
    которой не было."""
    print("\n[Дыра не склеивает разные часы]")
    m5 = пятиминутки(часов=2)
    # Выбрасываем середину ПЕРВОГО часа: подряд идущих двенадцати больше
    # нет, и «счёт по двенадцать штук» слепил бы конец первого часа с
    # началом второго. Группировка по номеру часа не путается.
    первый_час = 100 * 3600
    испорченные = [b for b in m5
                   if not (первый_час + 1500 <= b["time"] <= первый_час + 1800)]
    r = build_h1.собрать(испорченные)
    check(r["часов_получено"] == 1, "Уцелел ровно один час",
          str(r["часов_получено"]))
    check(r["bars"][0]["time"] == 101 * 3600,
          "И это ВТОРОЙ час, а не склейка", str(r["bars"][0]["time"]))


def test_the_hash_is_deterministic_and_sensitive() -> None:
    """Одни и те же данные — один хеш; любая правка его меняет."""
    print("\n[Хеш сборки повторяем и чувствителен]")
    m5 = пятиминутки(часов=4)
    первый = build_h1.собрать(m5)["хеш"]
    второй = build_h1.собрать(list(m5))["хеш"]
    check(первый == второй, "Повторная сборка даёт тот же хеш")

    # Правим тот элемент, который И ЕСТЬ максимум часа: правка любого
    # другого на максимум не влияет, и хеш законно не изменится.
    изменённые = [dict(b) for b in m5]
    самый_высокий = max(range(12), key=lambda i: изменённые[i]["high"])
    изменённые[самый_высокий]["high"] += 0.0010
    check(build_h1.собрать(изменённые)["хеш"] != первый,
          "Правка максимума меняет хеш")

    изменённые = [dict(b) for b in m5]
    самый_широкий = max(range(12), key=lambda i: изменённые[i]["spread"])
    изменённые[самый_широкий]["spread"] += 5
    check(build_h1.собрать(изменённые)["хеш"] != первый,
          "И правка спреда тоже")

    # А правка НЕмаксимального элемента хеш менять не должна — иначе
    # проверка ловила бы что попало.
    изменённые = [dict(b) for b in m5]
    самый_низкий = min(range(12), key=lambda i: изменённые[i]["high"])
    изменённые[самый_низкий]["high"] += 0.00001
    check(build_h1.собрать(изменённые)["хеш"] == первый,
          "А правка НЕмаксимального значения хеш не меняет")


def test_order_of_input_does_not_matter() -> None:
    """Пятиминутки внутри часа сортируются — порядок в файле не влияет."""
    print("\n[Порядок пятиминуток в файле не влияет]")
    m5 = пятиминутки(часов=2)
    прямо = build_h1.собрать(m5)["хеш"]
    вперемешку = build_h1.собрать(list(reversed(m5)))["хеш"]
    check(прямо == вперемешку, "Хеш тот же")


