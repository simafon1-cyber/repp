def пятиминутки(часов=3, начало_часа=100, спред=2, пропустить=()):
    """Ровные пятиминутки. пропустить — какие по счёту выбросить."""
    bars = []
    n = 0
    for ч in range(часов):
        for k in range(12):
            n += 1
            if n in пропустить:
                continue
            цена = 1.1000 + ч * 0.0100 + k * 0.0001
            bars.append({
                "time": (начало_часа + ч) * 3600 + k * 300,
                "open": цена, "high": цена + 0.0005,
                "low": цена - 0.0005, "close": цена + 0.0002,
                "tick_volume": 10, "spread": спред + k, "real_volume": 0,
            })
    return bars


