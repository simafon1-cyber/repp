def test_actual_scenario_is_refused_without_broker_terms() -> None:
    """ГЛАВНАЯ ПРОВЕРКА ВТОРОЙ ЧАСТИ.

    Раньше имя «фактический» принималось, а под ним стояли типовые числа.
    Ярлык «фактический» на предположениях — это ровно та подмена, против
    которой делался И7."""
    print("\n[«Фактический» сценарий без выгрузки недоступен]")
    было = costs.текущий_сценарий()
    try:
        costs.выбрать_сценарий(costs.ФАКТИЧЕСКИЙ)
        check(False, "Сценарий обязан быть отвергнут")
    except ValueError as e:
        check(True, "Отвергнут")
        check("не выгружены" in str(e), "И сказано, почему", str(e)[:70])
        check("capture_broker_terms" in str(e),
              "И что делать, чтобы выгрузить")
    finally:
        costs.выбрать_сценарий(было)
    check(costs.текущий_сценарий() == было, "Текущий сценарий не сбился")


def test_incomplete_broker_terms_are_refused() -> None:
    """Неполная выгрузка хуже, чем никакой.

    Под ярлыком «фактический» оказалась бы смесь настоящих чисел и
    типовых заглушек — а различить их потом было бы нечем."""
    print("\n[Неполная выгрузка отвергается]")
    папка = tempfile.mkdtemp(prefix="broker_")
    try:
        полная = {
            "выгружено": "2026-08-20 10:00:00 UTC",
            "счёт": {"номер": 5054028014},
            "комиссия_за_круг_на_лот": 6.5,
            "инструменты": [{"инструмент": "EURUSD"}],
        }
        for пропущено in ("комиссия_за_круг_на_лот", "выгружено",
                          "инструменты", "счёт"):
            неполная = dict(полная)
            неполная[пропущено] = None
            путь = os.path.join(папка, "b.json")
            json.dump(неполная, open(путь, "w", encoding="utf-8"),
                      ensure_ascii=False)
            try:
                costs.загрузить_условия_счёта(путь)
                check(False, f"Без «{пропущено}» должно быть отвергнуто")
            except ValueError as e:
                check(пропущено in str(e),
                      f"Без «{пропущено}» отвергнуто и названо", str(e)[:70])
    finally:
        shutil.rmtree(папка, ignore_errors=True)


def test_complete_broker_terms_unlock_the_scenario() -> None:
    """КОНТРОЛЬ. С полной выгрузкой сценарий включается и берёт ЕЁ числа.

    Без этой проверки предыдущие были бы зелёными и у кода, который
    «фактический» не включает никогда."""
    print("\n[С полной выгрузкой сценарий работает и берёт её числа]")
    папка = tempfile.mkdtemp(prefix="broker_")
    было = costs.текущий_сценарий()
    try:
        путь = os.path.join(папка, "b.json")
        json.dump({
            "выгружено": "2026-08-20 10:00:00 UTC",
            "счёт": {"номер": 5054028014, "сервер": "MetaQuotes-Demo"},
            "комиссия_за_круг_на_лот": 6.5,
            "инструменты": [{"инструмент": "EURUSD"}],
        }, open(путь, "w", encoding="utf-8"), ensure_ascii=False)

        costs.загрузить_условия_счёта(путь)
        check(costs.условия_счёта().get("комиссия_за_круг_на_лот") == 6.5,
              "Выгрузка загрузилась")

        costs.выбрать_сценарий(costs.ФАКТИЧЕСКИЙ)
        check(costs.текущий_сценарий() == costs.ФАКТИЧЕСКИЙ,
              "Сценарий включился")
        check(abs(costs.комиссия(1.0) - 6.5) < 1e-9,
              "И комиссия взята ИЗ ВЫГРУЗКИ, а не типовая",
              str(costs.комиссия(1.0)))
        check(abs(costs.комиссия(2.0) - 13.0) < 1e-9,
              "И масштабируется по лоту")
    finally:
        costs.выбрать_сценарий(было)
        costs._условия_счёта = None
        shutil.rmtree(папка, ignore_errors=True)
    check(costs.условия_счёта() == {}, "Выгрузка сброшена после проверки")


