        check(завёрнутый["защита"] == da.ПОДПИСЬ, "Файл записан подписанным",
              str(завёрнутый.get("защита")))

        # Ровно то, что сделал бы подделыватель без ключа.
        завёрнутый["снимок"]["позиции_все"][0]["volume"] = 9.99
