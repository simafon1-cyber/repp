def test_молчание_терминала_не_становится_пустотой():
    """Терминал промолчал про позиции — в снимке НЕ должно быть «нет».

    Наоборот: замените в _спросить() возврат НЕИЗВЕСТНО на пустой список
    — эта проверка падает, и вместе с ней исчезает единственная защита от
    вывода «сделки не было»."""
    _поставить_настройки()
    брокер = ПоддельныйБрокер(молчит=("позиции",),
                              счёт={"login": 1, "balance": 1.0})
    _поставить_брокера(брокер)
    import demo_acceptance as da
    данные = da.снимок()

    check("позиции" in данные["не_спросилось"],
          "Молчание про позиции записано как «не спросилось»",
          str(данные["не_спросилось"]))
    check(данные["позиции"] != [],
          "И это НЕ пустой список — иначе читалось бы как «позиций нет»",
          repr(данные["позиции"]))
    check(isinstance(данные["позиции"], str)
          and "НЕИЗВЕСТНО" in данные["позиции"],
          "А прямо сказано словом НЕИЗВЕСТНО", repr(данные["позиции"])[:80])
    check(данные["всё_ли_спросилось"] is False,
          "Снимок помечен как неполный")


def test_пустой_ответ_и_молчание_выглядят_по_разному():
    """Позиций нет — это ответ. Терминал молчит — это не ответ.

    Если бы они выглядели одинаково, весь смысл снимка пропал бы."""
    _поставить_настройки()

    брокер1 = ПоддельныйБрокер(позиции=[], счёт={"login": 1})
    _поставить_брокера(брокер1)
    import demo_acceptance as da
    ответ = da.снимок()

    брокер2 = ПоддельныйБрокер(молчит=("позиции",), счёт={"login": 1})
    _поставить_брокера(брокер2)
    молчание = da.снимок()

    check(ответ["позиции"] == [], "«Позиций нет» — это пустой список")
    check(молчание["позиции"] != ответ["позиции"],
          "А молчание выглядит ИНАЧЕ, чем «позиций нет»")
    check(ответ["всё_ли_спросилось"] is True,
          "Полный снимок помечен полным")


