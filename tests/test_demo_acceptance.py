def test_молчание_терминала_не_становится_пустотой():
    """Терминал промолчал про позиции — в снимке НЕ должно быть «нет».

    Наоборот: замените в _спросить() возврат НЕИЗВЕСТНО на пустой список
    — эта проверка падает, и вместе с ней исчезает единственная защита от
    вывода «сделки не было»."""
    _поставить_настройки()
    брокер = ПоддельныйБрокер(молчит=("позиции",),
                              счёт={"login": 1, "balance": 1.0})
    _поставить_брокера(брокер)
    import demo_acceptance as da
    данные = da.снимок()

    check("позиции_все" in данные["не_спросилось"],
          "Молчание про позиции записано как «не спросилось»",
          str(данные["не_спросилось"]))
    check(данные["позиции_все"] != [],
          "И это НЕ пустой список — иначе читалось бы как «позиций нет»",
          repr(данные["позиции_все"]))
    check(isinstance(данные["позиции_все"], str)
          and "НЕИЗВЕСТНО" in данные["позиции_все"],
          "А прямо сказано словом НЕИЗВЕСТНО", repr(данные["позиции_все"])[:80])
    check(данные["позиции_свои"] == da.НЕИЗВЕСТНО,
          "Разделение на своих и чужих тоже НЕИЗВЕСТНО, а не пустой список",
          repr(данные["позиции_свои"])[:60])
    check(данные["условия"]["О2"]["состояние"] == da.НЕ_ДОКАЗАНО,
          "И условие О2 не считается выполненным: о чужих ничего не известно",
          str(данные["условия"]["О2"]))
    check(данные["всё_ли_спросилось"] is False,
          "Снимок помечен как неполный")


