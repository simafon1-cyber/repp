#!/usr/bin/env python3
"""ДП: СНИМКИ СОСТОЯНИЯ СЧЁТА ДЛЯ ПРОГОНА НА ДЕМО.

ПОЧЕМУ ЭТИ ТЕСТЫ ПОЯВИЛИСЬ

Прогон на демо — первое настоящее свидетельство того, как программа
исполняет заявки. Всё до него проверено на подделке. Но свидетельство
годится, только если его нельзя незаметно испортить: снимок должен быть
полным, честным про «не спросилось» и защищённым от правки задним числом.

ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ, И ПОЧЕМУ ИМЕННО ЭТО

1. Сборщик НЕ ТОРГУЕТ. Проверяется разбором дерева кода, а не обещанием
   в комментарии.

2. «Не спросилось» никогда не превращается в «нет». Это раздел 5 правил
   проекта, перенесённый на снимки: если записать пустоту там, где
   терминал промолчал, потом по такому снимку решат, что сделки не было.
   Ошибка тихая и необратимая.

3. Снимок нельзя поправить задним числом незаметно — отпечаток разойдётся.

4. Сверка двух снимков не вычитает из неизвестного. Ноль, полученный из
   «неизвестно минус неизвестно», выглядит как «ничего не произошло» —
   самый опасный вид вранья в этом файле.

ЧЕГО ЭТИ ТЕСТЫ НЕ ПРОВЕРЯЮТ

Поведение у настоящего брокера. Здесь подделка, и она отвечает так, как
я её научил. Зелёный результат тут не является доказательством того, что
демо-счёт ответит так же.

Запуск:  python3 tests/test_demo_acceptance.py
"""

