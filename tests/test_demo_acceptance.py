def test_правка_снимка_после_записи_видна():
    """Наоборот: уберите сверку отпечатка в прочитать_снимок() — правка
    пройдёт незамеченной, и проверка падает."""
    _поставить_настройки()
    брокер = ПоддельныйБрокер(
        позиции=[{"ticket": 111, "symbol": "EURUSD", "volume": 0.01}],
        счёт={"login": 1, "balance": 100.0})
    _поставить_брокера(брокер)
    import demo_acceptance as da

    папка = tempfile.mkdtemp(prefix="демо_снимки_")
    try:
        путь = da.записать_снимок(папка, "до", da.снимок())
        прочитан = da.прочитать_снимок(путь)
        check(прочитан["метка"] == "до", "Неправленый снимок читается")

        # Правим ОДНО число — объём позиции. Именно так и выглядела бы
        # подтасовка: не «всё переписал», а «чуть-чуть подправил».
        завёрнутый = json.loads(Path(путь).read_text(encoding="utf-8"))
        завёрнутый["снимок"]["позиции"][0]["volume"] = 0.10
        Path(путь).write_text(json.dumps(завёрнутый, ensure_ascii=False),
                              encoding="utf-8")
        try:
            da.прочитать_снимок(путь)
            check(False, "Правка снимка замечена", "прочитался как ни в чём не бывало")
        except ValueError as e:
            check(True, "Правка снимка замечена")
            check("доказательством быть не может" in str(e),
                  "И сказано, что таким снимком доказывать нельзя")
    finally:
        shutil.rmtree(папка, ignore_errors=True)


def test_снимки_не_затирают_друг_друга():
    """Две метки «до» подряд — два файла, а не один.

    Потерять снимок «до» из-за повторённой метки нельзя: он невосстановим,
    время уже ушло."""
    _поставить_настройки()
    брокер = ПоддельныйБрокер(счёт={"login": 1})
    _поставить_брокера(брокер)
    import demo_acceptance as da

    папка = tempfile.mkdtemp(prefix="демо_снимки_")
    try:
        первый = da.записать_снимок(папка, "до", da.снимок())
        снимок2 = da.снимок()
        снимок2["время_utc"] = "2026-01-01T00:00:00+00:00"
        второй = da.записать_снимок(папка, "до", снимок2)
        check(первый != второй, "Два снимка с одной меткой — два файла")
        check(len(list(Path(папка).glob("*.json"))) == 2,
              "Оба лежат на месте")
    finally:
        shutil.rmtree(папка, ignore_errors=True)


