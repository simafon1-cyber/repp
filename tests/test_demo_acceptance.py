class ПоддельныйБрокер:
    """Ведёт счёт и СЧИТАЕТ, сколько раз его просили торговать.

    Счётчик — суть проверки: доказательством служит не возвращённое
    значение, а факт, что торговых обращений не было ни одного."""

    def __init__(self, позиции=None, заявки=None, сделки=None,
                 счёт=None, молчит=(), история_позиций=None):
        self.позиции = позиции if позиции is not None else []
        self.заявки = заявки if заявки is not None else []
        self.сделки = сделки if сделки is not None else []
        self.счёт = счёт
        self.молчит = set(молчит)
        self.торговых_обращений = 0
        # История ПО НОМЕРУ ПОЗИЦИИ: {номер: [сделки]}. Отсутствие номера
        # в словаре означает «терминал ответил пустотой», а строка
        # "молчит" — «спросить не удалось». Это разные вещи.
        self.история_позиций = история_позиций or {}

    # --- то, что спрашивают ---
    def get_account_info(self):
        if "счёт" in self.молчит:
            return None
        return self.счёт

    def positions_or_none(self, symbol=None, magic=None):
        """ФИЛЬТР ЗДЕСЬ НАСТОЯЩИЙ, и это принципиально.

        Раньше подделка возвращала весь список, что бы у неё ни спросили.
        Из-за этого проверка «чужая позиция попала в снимок» проходила
        даже с восстановленным фильтром magic — то есть не ловила тот
        самый дефект, ради которого написана.

        Настоящий mt5_connector.positions_or_none() фильтрует. Подделка
        обязана вести себя так же, иначе она проверяет не то."""
        if "позиции" in self.молчит:
            return None
        записи = list(self.позиции)
        if magic is not None:
            записи = [з for з in записи if з.get("magic") == magic]
        return записи

    def orders_or_none(self, symbol=None, magic=None):
        if "заявки" in self.молчит:
            return None
        записи = list(self.заявки)
        if magic is not None:
            записи = [з for з in записи if з.get("magic") == magic]
        return записи

    def deals_or_none(self, date_from, date_to, symbol=None):
        return None if "сделки" in self.молчит else list(self.сделки)

    def deals_by_position(self, номер):
        ответ = self.история_позиций.get(номер, [])
        if ответ == "молчит":
            return None
        return list(ответ)

    def trading_permission_status(self):
        return {"trade_allowed": True}

    def get_tick(self, символ):
        return {"bid": 1.1, "ask": 1.1001}

    def get_spread_points(self, символ):
        return 10

    def get_symbol_point(self, символ):
        return 0.00001

    # --- то, чего быть не должно ---
    def send_market_order(self, *a, **k):
        self.торговых_обращений += 1
        raise AssertionError("Сборщик снимков попытался торговать")


def _поставить_брокера(брокер):
    м = types.ModuleType("mt5_connector")
    for имя in ("get_account_info", "positions_or_none", "orders_or_none",
                "deals_or_none", "trading_permission_status", "get_tick",
                "get_spread_points", "get_symbol_point", "send_market_order",
                "deals_by_position"):
        setattr(м, имя, getattr(брокер, имя))
    м.connect = lambda: брокер.счёт
    м.disconnect = lambda: None
    sys.modules["mt5_connector"] = м
    return м


class ПоддельныйТерминал(types.ModuleType):
    """Модуль MetaTrader5 для СТРОГИХ вопросов сборщика.

    Сборщик спрашивает сведения об инструменте и разрешения напрямую у
    терминала, а не через торговые обёртки: обёртки при молчании
    подставляют защитные значения (999999 пунктов спреда, 0.0001 пункт), и
    в снимке они выглядели бы как настоящие числа. Аудит назвал это P1-1.

    Здесь «молчит» означает ровно молчание: None."""

    def __init__(self, молчит=()):
        super().__init__("MetaTrader5")
        self.молчит = set(молчит)

    def symbol_info(self, символ):
        if "symbol_info" in self.молчит:
            return None
        return types.SimpleNamespace(spread=10, point=0.00001, digits=5,
                                     volume_step=0.01, trade_mode=4)

    def symbol_info_tick(self, символ):
        if "tick" in self.молчит:
            return None
        return types.SimpleNamespace(bid=1.1, ask=1.1001)

    def terminal_info(self):
        if "terminal_info" in self.молчит:
            return None
        return types.SimpleNamespace(trade_allowed=True, trade_expert=True)

    def account_info(self):
        if "account_info" in self.молчит:
            return None
        return types.SimpleNamespace(trade_allowed=True)


def _поставить_терминал(молчит=()):
    т = ПоддельныйТерминал(молчит=молчит)
    sys.modules["MetaTrader5"] = т
    return т


