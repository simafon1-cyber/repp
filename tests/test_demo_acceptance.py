def test_сверка_видит_что_появилось():
    """Обычный случай: открылась позиция, в истории появилась сделка."""
    import demo_acceptance as da
    до = {"позиции": [], "активные_заявки": [], "сделки_за_окно": [],
          "счёт": {"balance": 10000.0, "equity": 10000.0}}
    после = {"позиции": [{"ticket": 777}],
             "активные_заявки": [],
             "сделки_за_окно": [{"ticket": 555}],
             "счёт": {"balance": 10000.0, "equity": 9994.5}}
    итог = da.сверить(до, после)
    check(итог["позиции_появились"] == [777], "Новая позиция найдена по номеру",
          str(итог["позиции_появились"]))
    check(итог["сделки_появились"] == [555], "И новая сделка тоже")
    check(итог["средства_разница"] == -5.5,
          "Изменение средств посчитано", str(итог["средства_разница"]))
    check(итог["всё_ли_известно"] is True, "Сверка полная")
    check(итог["предупреждения"] == [],
          "Позиция со сделкой — предупреждать не о чем")


def test_сверка_не_выдаёт_ноль_за_неизвестное():
    """ГЛАВНАЯ проверка этого раздела.

    Если в снимке «до» позиции не спросились, разницу вычислять НЕЛЬЗЯ.
    Ноль здесь читался бы как «ничего не произошло» — и это самый опасный
    вид вранья в этом файле: по нему решат, что входов не было.

    Наоборот: пусть сверить() считает разницу как обычно, подставляя
    пустой список вместо неизвестного — проверка падает."""
    import demo_acceptance as da
    до = {"позиции": da.НЕИЗВЕСТНО + " (терминал молчал)",
          "активные_заявки": [], "сделки_за_окно": [],
          "счёт": {"balance": 10000.0, "equity": 10000.0}}
    после = {"позиции": [{"ticket": 777}], "активные_заявки": [],
             "сделки_за_окно": [{"ticket": 555}],
             "счёт": {"balance": 10000.0, "equity": 9994.5}}
    итог = da.сверить(до, после)

    check(итог["позиции_появились"] != [],
          "Разница по позициям НЕ выдана пустым списком",
          repr(итог["позиции_появились"]))
    check(итог["позиции_появились"] != [777],
          "И не выдана так, будто «до» был пустым")
    check("НЕИЗВЕСТНО" in str(итог["позиции_появились"]),
          "А прямо сказано НЕИЗВЕСТНО", str(итог["позиции_появились"])[:60])
    check("позиции" in итог["неизвестно"], "Раздел помечен неизвестным")
    check(итог["всё_ли_известно"] is False, "Сверка помечена неполной")
    check(итог["сделки_появились"] == [555],
          "При этом раздел, который спросился, посчитан как обычно")


def test_позиция_без_сделки_вызывает_вопрос():
    """Позиция появилась, а сделки в истории нет — повод разбираться.

    И формулировка важна: «это НЕ доказывает, что сделок не было».
    История у брокера может отставать, а окно запроса — быть узким."""
    import demo_acceptance as da
    до = {"позиции": [], "активные_заявки": [], "сделки_за_окно": [],
          "счёт": {"balance": 100.0, "equity": 100.0}}
    после = {"позиции": [{"ticket": 777}], "активные_заявки": [],
             "сделки_за_окно": [],
             "счёт": {"balance": 100.0, "equity": 99.0}}
    итог = da.сверить(до, после)
    check(len(итог["предупреждения"]) == 1, "Выдано предупреждение",
          str(итог["предупреждения"]))
    check("НЕ доказывает" in итог["предупреждения"][0],
          "И оно НЕ утверждает, что сделок не было",
          итог["предупреждения"][0][:80])


def main() -> int:
    print("=" * 70)
    print("ДП: СНИМКИ СОСТОЯНИЯ СЧЁТА ДЛЯ ПРОГОНА НА ДЕМО")
    print("=" * 70)
    for имя, ф in sorted(globals().items()):
        if имя.startswith("test_") and callable(ф):
            print(f"\n--- {имя}")
            try:
                ф()
            except Exception as e:  # noqa: BLE001
                check(False, f"{имя} доработала до конца",
                      f"{type(e).__name__}: {str(e).splitlines()[0]}")
    print("\n" + "=" * 70)
    print(f"Пройдено: {passed}   Сбоев: {failed}")
    print("=" * 70)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
