def test_в_сборщике_нет_ни_одного_торгового_вызова():
    """Разбор дерева кода, а не поиск по тексту.

    Поиск по тексту нашёл бы слова «order_send» в этой самой шапке файла и
    в комментариях — то есть ловил бы собственные пояснения.

    Наоборот: допишите в demo_acceptance.py вызов mt5.order_send(...) —
    эта проверка падает."""
    дерево = ast.parse((APP / "demo_acceptance.py").read_text(encoding="utf-8"))
    запрещённые = {"order_send", "order_check", "send_market_order",
                   "modify_position", "close_position_partial"}
    найдено = []
    for узел in ast.walk(дерево):
        if not isinstance(узел, ast.Call):
            continue
        имя = None
        if isinstance(узел.func, ast.Attribute):
            имя = узел.func.attr
        elif isinstance(узел.func, ast.Name):
            имя = узел.func.id
        if имя in запрещённые:
            найдено.append(f"{имя} в строке {узел.lineno}")
    check(not найдено, "В сборщике нет ни одного торгового вызова",
          "; ".join(найдено))


