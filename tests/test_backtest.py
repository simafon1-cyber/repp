#!/usr/bin/env python3
"""Тесты проверки настроек на истории.

ЗАЧЕМ ЭТО ВООБЩЕ. Десятки настроек за эти дни менялись по РАССУЖДЕНИЮ, а не по
измерению. Теперь их можно прогнать по истории и получить числа.

ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ, ПО ВАЖНОСТИ:
  1. Проверка не врёт В СВОЮ ПОЛЬЗУ. Если внутри одного бара задет и стоп, и
     цель — засчитывается СТОП. Обманывать себя на своих же деньгах нельзя, и
     это правило надо закрепить тестом, а не надеждой.
  2. Спред действительно вычитается, а не забывается.
  3. Профит-фактор ниже единицы честно называется убытком.
  4. На малой выборке результат сопровождается предупреждением: на двадцати
     сделках «улучшение» чаще везение, чем работа настройки.

Запуск:  python3 tests/test_backtest.py
"""

from __future__ import annotations

import sys
import types
from pathlib import Path

BASE = Path(__file__).resolve().parent
ROOT = BASE.parent
APP = ROOT / "ai_scalper_standalone"
sys.path.insert(0, str(APP))

passed = 0
failed = 0


def check(ok: bool, name: str, detail: str = "") -> None:
    global passed, failed
    if ok:
        passed += 1
        print(f"  OK   {name}")
    else:
        failed += 1
        print(f"  СБОЙ {name}" + (f" -> {detail}" if detail else ""))


cfg = types.ModuleType("config")
cfg.__file__ = str(APP / "config.py.example")
exec((APP / "config.py.example").read_text(encoding="utf-8"), cfg.__dict__)
sys.modules["config"] = cfg
sys.modules["MetaTrader5"] = types.ModuleType("MetaTrader5")

import backtest as bt      # noqa: E402

ТОЧКА = 0.0001


def бары(*строки):
    """(максимум, минимум, закрытие) — как отдаёт терминал."""
    return list(строки)


def test_stop_wins_ties_against_us() -> None:
    """САМОЕ ВАЖНОЕ ПРАВИЛО ЧЕСТНОСТИ. Внутри одного бара известны только
    четыре цены, и что случилось раньше — стоп или цель — узнать нельзя.

    Если засчитывать цель, проверка на истории будет рисовать прибыль там,
    где в жизни был убыток. Это самый простой способ обмануть себя на
    собственных деньгах, поэтому в спорном баре засчитывается СТОП."""
    print("\n[В спорном баре засчитывается стоп, а не цель]")
    вход = 1.1000
    # Бар, который задел И цель (+50), И стоп (-20)
    спорный = бары((вход, вход, вход),                       # бар входа
                   (вход + 50 * ТОЧКА, вход - 20 * ТОЧКА, вход))
    сделки = bt.simulate(спорный, {0: 1}, stop_points=20, target_points=50,
                         point=ТОЧКА)
    check(len(сделки) == 1 and abs(сделки[0] + 20.0) < 0.01,
          "Задеты обе цены — засчитан УБЫТОК, а не прибыль", str(сделки))

    # Дробные цены не сравниваем на точное равенство: 50.0 и
    # 50.000000000000426 — одно и то же число, разошедшееся на пыли
    # двоичной арифметики. Точное сравнение здесь ловило бы не ошибку, а пыль.
    def равно(получено, ожидалось):
        return (len(получено) == 1
                and abs(получено[0] - ожидалось) < 0.01)

    # А если стоп не задет — цель засчитывается честно
    чистый = бары((вход, вход, вход),
                  (вход + 50 * ТОЧКА, вход - 5 * ТОЧКА, вход))
    получено = bt.simulate(чистый, {0: 1}, 20, 50, ТОЧКА)
    check(равно(получено, 50.0), "Стоп не задет — цель засчитана", str(получено))

    # ЭТОТ СЛУЧАЙ НАШЁЛСЯ ПЕРВЫМ ЖЕ ПРОГОНОМ. Расстояние в пунктах считается
    # делением дробных цен, и ровно 50 пунктов превратилось в
    # 49.999999999998934 — цель «не достигнута», выигрышная сделка потерялась.
    # Проверка на истории, которая теряет выигрыши, занижает результат и
    # заставляет чинить то, что не сломано.
    ровно_на_границе = бары((вход, вход, вход),
                            (вход + 50 * ТОЧКА, вход, вход))
    получено = bt.simulate(ровно_на_границе, {0: 1}, 20, 50, ТОЧКА)
    check(равно(получено, 50.0),
          "Цель ровно на границе засчитывается, а не теряется в дробной пыли",
          str(получено))

    # То же для продажи: направление не должно менять правило
    спорный_вниз = бары((вход, вход, вход),
                        (вход + 20 * ТОЧКА, вход - 50 * ТОЧКА, вход))
    получено = bt.simulate(спорный_вниз, {0: -1}, 20, 50, ТОЧКА)
    check(равно(получено, -20.0), "В продаже правило то же самое", str(получено))


def test_spread_is_actually_paid() -> None:
    """Спред — это плата за вход, и она берётся сразу. Забыть её значит
    систематически завышать результат на каждой сделке."""
    print("\n[Спред вычитается, а не забывается]")
    вход = 1.1000
    ряд = бары((вход, вход, вход),
               (вход + 30 * ТОЧКА, вход - 100 * ТОЧКА, вход + 30 * ТОЧКА))

    без = bt.simulate(ряд, {0: 1}, 200, 30, ТОЧКА, spread_points=0)
    со = bt.simulate(ряд, {0: 1}, 200, 30, ТОЧКА, spread_points=10)
    check(без and со, "Обе сделки состоялись", f"{без} / {со}")
    check(со[0] < без[0],
          "Со спредом результат ХУЖЕ — иначе спред нигде не учтён",
          f"без спреда {без[0]}, со спредом {со[0]}")


def test_losing_system_is_called_losing() -> None:
    """Профит-фактор ниже единицы означает убыток. Смягчать эту формулировку
    нельзя: у владельца по реальному отчёту он был 0.42, и именно это, а не
    настройки, решало судьбу счёта."""
    print("\n[Убыточная система названа убыточной]")
    итог = bt.summarize([10, -30, 15, -40, 5, -20])
    check(итог["профит_фактор"] < 1.0,
          "Профит-фактор ниже единицы", str(итог["профит_фактор"]))
    check(итог["ожидание"] < 0,
          "И ожидание на сделку отрицательное", str(итог["ожидание"]))
    check(итог["сделок"] == 6 and итог["выигрышных"] == 3, "Счёт сделок верный")
    check(итог["винрейт"] == 50.0,
          "Винрейт 50% — и он НЕ означает прибыль: средний минус больше "
          "среднего плюса", str(итог["винрейт"]))
    check(итог["средний_минус"] > итог["средний_плюс"],
          "Что и видно по средним", f"{итог['средний_плюс']} / {итог['средний_минус']}")

    хорошая = bt.summarize([30, 30, -10, 30, -10])
    check(хорошая["профит_фактор"] > 1.0, "Прибыльная — выше единицы",
          str(хорошая["профит_фактор"]))

    # Без убытков профит-фактор не «бесконечность»: это мало данных, а не
    # безубыточная система
    check(bt.summarize([10, 20])["профит_фактор"] == 0.0,
          "Убытков не было — не выдаём бесконечность")
    check(bt.summarize([])["сделок"] == 0, "Пустой список не роняет")
    check(bt.summarize(None)["ожидание"] == 0.0, "None тоже")


def test_small_sample_is_flagged() -> None:
    """Главная ловушка любой проверки на истории — маленькая выборка. На двух
    десятках сделок «улучшение» чаще означает везение."""
    print("\n[Малая выборка сопровождается предупреждением]")
    было = bt.summarize([-5] * 10 + [10] * 5)
    стало = bt.summarize([-5] * 8 + [12] * 7)
    текст = bt.compare(было, стало)
    check("ВНИМАНИЕ" in текст, "Про малую выборку сказано", текст[-80:])
    check("везени" in текст, "И названо своим словом", текст[-90:])

    много_до = bt.summarize(([-5] * 70 + [10] * 40))
    много_после = bt.summarize(([-5] * 60 + [10] * 60))
    текст = bt.compare(много_до, много_после)
    check("ВНИМАНИЕ" not in текст, "На большой выборке лишнего шума нет", текст[-60:])
    check("Лучше на" in текст, "И сказано, что стало лучше", текст[-60:])

    хуже = bt.compare(много_после, много_до)
    check("ХУЖЕ" in хуже, "А ухудшение названо ухудшением", хуже[-60:])
    check(bt.compare({}, {}) != "", "Пустые данные не роняют")


def test_trailing_stop_can_only_tighten() -> None:
    """Трейлинг-стоп, который умеет РАСШИРЯТЬСЯ, — это не защита, а способ
    досидеть до большего убытка. Правило одностороннее, и проверка на истории
    обязана вести себя так же, как торговля."""
    print("\n[Стоп в проверке только ужимается]")
    вход = 1.1000
    # Цена сходила на +40, потом развернулась и упала на -100 от входа
    ряд = бары((вход, вход, вход),
               (вход + 40 * ТОЧКА, вход, вход + 40 * ТОЧКА),
               (вход + 5 * ТОЧКА, вход - 100 * ТОЧКА, вход - 100 * ТОЧКА))

    # Без трейлинга — полный стоп в 60 пунктов
    без = bt.simulate(ряд, {0: 1}, 60, 500, ТОЧКА)
    check(len(без) == 1 and abs(без[0] + 60.0) < 0.01,
          "Без трейлинга — полный убыток", str(без))

    # С трейлингом: при пике 40 фиксируем +20
    def лесенка(пик):
        return 20.0 if пик >= 40 else None

    с_трейлингом = bt.simulate(ряд, {0: 1}, 60, 500, ТОЧКА, trail=лесенка)
    check(с_трейлингом and с_трейлингом[0] > без[0],
          "С трейлингом убыток МЕНЬШЕ — ради этого он и нужен",
          str(с_трейлингом))
    check(len(с_трейлингом) == 1 and abs(с_трейлингом[0] - 20.0) < 0.01,
          "И закрылись ровно там, куда подтянули стоп", str(с_трейлингом))

    # А ТЕПЕРЬ ГЛАВНОЕ: стоп НЕ РАСШИРЯЕТСЯ ОБРАТНО. Лесенку можно задать
    # криво — так, что на большем пике она просит меньшую защиту. Программа
    # обязана оставить прежнюю, более тесную: стоп, умеющий отъезжать назад,
    # это не защита, а способ досидеть до большего убытка.
    вниз_по_лесенке = бары(
        (вход, вход, вход),
        (вход + 40 * ТОЧКА, вход, вход + 40 * ТОЧКА),
        (вход + 60 * ТОЧКА, вход + 35 * ТОЧКА, вход + 35 * ТОЧКА),
        (вход + 20 * ТОЧКА, вход + 10 * ТОЧКА, вход + 10 * ТОЧКА))

    def кривая_лесенка(пик):
        if пик >= 60:
            return 5.0        # просит МЕНЬШЕ защиты, чем на прошлой ступени
        if пик >= 40:
            return 30.0
        return None

    итог = bt.simulate(вниз_по_лесенке, {0: 1}, 60, 500, ТОЧКА,
                       trail=кривая_лесенка)
    check(len(итог) == 1 and abs(итог[0] - 30.0) < 0.01,
          "Кривая лесенка не отодвигает стоп назад: осталась защита +30, "
          "а не ослабленная +5", str(итог))


def test_garbage_input_does_not_lie() -> None:
    print("\n[Мусор на входе не превращается в красивые числа]")
    check(bt.simulate([], {0: 1}, 20, 50, ТОЧКА) == [], "Нет баров — нет сделок")
    check(bt.simulate([(1, 1, 1)], {}, 20, 50, ТОЧКА) == [], "Нет входов — нет сделок")
    check(bt.simulate([(1, 1, 1)], {0: 1}, 20, 50, 0) == [],
          "Размер пункта неизвестен — считать нельзя, а не выдумывать")
    check(bt.simulate([(1, 1, 1)], {0: 1}, 0, 50, ТОЧКА) == [],
          "Стопа нет — сделки без стопа не считаем вовсе")
    check(bt.simulate([(1, 1, 1)], {99: 1}, 20, 50, ТОЧКА) == [],
          "Вход за пределами истории пропускается")
    check(bt.simulate([(1, 1, 1)], {0: 0}, 20, 50, ТОЧКА) == [],
          "Направление «никуда» пропускается")


def test_limits_are_written_down() -> None:
    """Проверка на истории опасна ровно тем, что её числа выглядят
    убедительно. Ограничения должны лежать рядом с кодом, а не в памяти."""
    print("\n[Ограничения проверки записаны прямо в коде]")
    doc = (APP / "backtest.py").read_text(encoding="utf-8")
    for что, где in (("фитил", "про неизвестный порядок внутри бара"),
                     ("ХУДШИЙ", "что берётся худший вариант"),
                     ("спред", "что спред взят постоянным"),
                     ("роскальзыван", "что проскальзывания нет"),
                     ("одгонка", "про подгонку под историю")):
        check(что.lower() in doc.lower(), f"Сказано {где}")
    check("НЕ равны будущей прибыли" in doc,
          "И прямо сказано, что это не обещание прибыли")


