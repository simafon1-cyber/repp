#!/usr/bin/env python3
"""ПОЧЕМУ НЕТ СДЕЛОК — ПРОГРАММА ОБЯЗАНА СКАЗАТЬ САМА.

ПОЧЕМУ ЭТОТ НАБОР ПОЯВИЛСЯ

Владелец, дословно: «все сделал как надо выше, сделки не вижу! проверяй
и исправляй». Программа в этот момент знала ответ, но держала его в трёх
разных местах: состояние торгового цикла — на «Обзоре», предторговый
барьер — строкой в логе при запуске, список пар — на «Символах». А
выключенная «Реальная торговля» не показывалась НИГДЕ. Человеку
оставалось обходить вкладки и догадываться.

ЧТО ПРОВЕРЯЕТСЯ ПО ФАКТУ

Вызывается настоящий метод настоящего окна (App._почему_нет_сделок) при
разных состояниях программы, и проверяется ТЕКСТ, который увидит
человек: названа ли причина и сказано ли, что нажать. Не «функция
существует», а «в таком-то состоянии сказано то-то».

ЧЕГО ЭТОТ НАБОР НЕ ПРОВЕРЯЕТ

Что строка видна на экране глазами: подделка tkinter не рисует.
Что причина ВЕРНА у настоящего брокера: MetaTrader здесь заглушка.

Запуск:  python3 tests/test_silence_diagnosis.py
"""

from __future__ import annotations

import sys
from pathlib import Path

BASE = Path(__file__).resolve().parent
ROOT = BASE.parent
APP = ROOT / "ai_scalper_standalone"
sys.path.insert(0, str(BASE))
sys.path.insert(0, str(APP))

passed = 0
failed = 0


def check(ok: bool, name: str, detail: str = "") -> None:
    global passed, failed
    if ok:
        passed += 1
        print(f"  OK   {name}")
    else:
        failed += 1
        print(f"  СБОЙ {name}" + (f"  -> {detail}" if detail else ""))


import run_baseline  # noqa: E402  (заглушка MetaTrader5)
import поддельный_tk as пт  # noqa: E402

for _имя, _модуль in пт.собрать_модули().items():
    sys.modules[_имя] = _модуль

import desktop_app as da  # noqa: E402
import pretrade_gate  # noqa: E402
import config as cfg  # noqa: E402


class ЖивойПоток:
    """Поток, который «жив». Настоящий здесь не нужен и только мешает."""

    def is_alive(self):
        return True


class Счёт:
    def __init__(self, login, server, trade_mode):
        self.login = login
        self.server = server
        self.trade_mode = trade_mode


def окно():
    """Только то, что нужно методу. Целое окно здесь не собирается:
    метод читает ровно одно своё поле, и подмена остального дала бы
    проверку подделке, а не программе."""
    об = object.__new__(da.App)
    об.bot_thread = None
    return об


def состояние(live, барьер_включён, логин, сервер, барьер_открыт=False):
    cfg.LIVE_TRADING = live
    cfg.DEMO_ACCEPTANCE_MODE = барьер_включён
    cfg.DEMO_ACCEPTANCE_LOGIN = логин
    cfg.DEMO_ACCEPTANCE_SERVER = сервер
    cfg.DEMO_ACCEPTANCE_REQUIRE_DEMO = True
    pretrade_gate.закрыть()
    if барьер_открыт:
        pretrade_gate.открыть(
            cfg, lambda: Счёт(логин, сервер, pretrade_gate.СЧЁТ_ДЕМО))


def одна_про(строки, кусок):
    return [с for с in строки if кусок.lower() in с.lower()]


def test_цикл_не_запущен():
    print("\n[Торговый цикл не запущен]")
    состояние(True, False, 0, "")
    об = окно()
    об.bot_thread = None
    строки = об._почему_нет_сделок({})
    найдено = одна_про(строки, "цикл не запущен")
    check(найдено, "Сказано, что цикл не запущен", str(строки))
    check(найдено and "Старт" in найдено[0],
          "И сказано, что нажать — «Старт»", str(найдено))


def test_сухой_прогон():
    print("\n[Реальная торговля выключена]")
    состояние(False, False, 0, "")
    об = окно()
    об.bot_thread = ЖивойПоток()
    строки = об._почему_нет_сделок({})
    найдено = одна_про(строки, "Реальная торговля» выключена")
    check(найдено, "Сказано, что заявки не уходят", str(строки))
    check(найдено and "Настройка" in найдено[0],
          "И сказано, где включить", str(найдено))


def test_барьер_закрыт_без_счёта():
    print("\n[Барьер включён, но счёт не задан]")
    состояние(True, True, 0, "")
    об = окно()
    об.bot_thread = ЖивойПоток()
    строки = об._почему_нет_сделок({})
    найдено = одна_про(строки, "барьер закрыт")
    check(найдено, "Сказано, что барьер закрыт", str(строки))
    check(найдено and "DEMO_ACCEPTANCE_LOGIN" in найдено[0],
          "Названо, ЧЕГО не хватает — номера счёта", str(найдено))
    check(найдено and "DEMO_ACCEPTANCE_SERVER" in найдено[0],
          "И имени сервера", str(найдено))


def test_барьер_называет_точную_причину():
    """Раньше здесь стояла отсылка «причина в логе при запуске». Владелец
    один раз её и искал — этого достаточно, чтобы так больше не делать."""
    print("\n[Барьер закрыт: счёт не тот]")
    состояние(True, True, 5054028014, "MetaQuotes-Demo")
    # Барьер спрашивают с ЧУЖИМ счётом — он закрывается и запоминает причину.
    pretrade_gate.открыть(
        cfg, lambda: Счёт(9999999, "MetaQuotes-Demo", pretrade_gate.СЧЁТ_ДЕМО))
    об = окно()
    об.bot_thread = ЖивойПоток()
    строки = об._почему_нет_сделок({})
    найдено = одна_про(строки, "барьер закрыт")
    check(найдено, "Сказано, что барьер закрыт", str(строки))
    текст = найдено[0] if найдено else ""
    check("9999999" in текст and "5054028014" in текст,
          "Названы ОБА номера: к какому подключены и какой разрешён", текст)
    check("в логе при запуске" not in текст,
          "И человека больше не отправляют искать причину в журнале", текст)


def test_нет_пар():
    print("\n[Не отобрано ни одной пары]")
    состояние(True, False, 0, "")
    об = окно()
    об.bot_thread = ЖивойПоток()
    строки = об._почему_нет_сделок({"symbols": []})
    check(одна_про(строки, "ни одной пары"),
          "Сказано, что пар нет", str(строки))


def test_всё_в_порядке_молчит():
    """Главная проверка. Предупреждение, которое горит всегда, —
    не предупреждение: его перестают читать."""
    print("\n[Всё настроено — лишнего не говорим]")
    состояние(True, True, 5054028014, "MetaQuotes-Demo", барьер_открыт=True)
    об = окно()
    об.bot_thread = ЖивойПоток()
    строки = об._почему_нет_сделок({"symbols": [{"symbol": "EURUSD"}]})
    check(not строки, "Ни одной строки «СДЕЛОК НЕ БУДЕТ»", str(строки))
    check(pretrade_gate.открыт(), "Барьер при этом действительно открыт")


def main() -> int:
    print("=" * 62)
    print("ТЕСТЫ: ПОЧЕМУ НЕТ СДЕЛОК — ПРОГРАММА ГОВОРИТ САМА")
    print("=" * 62)
    test_цикл_не_запущен()
    test_сухой_прогон()
    test_барьер_закрыт_без_счёта()
    test_барьер_называет_точную_причину()
    test_нет_пар()
    test_всё_в_порядке_молчит()
    print("\n" + "=" * 70)
    print(f"Пройдено: {passed}   Сбоев: {failed}")
    print("=" * 70)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
