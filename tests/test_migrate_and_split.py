def _прежние(папка, границы):
    """Каталог «уже сохранённых» M5 с заданным началом у каждого."""
    папка.mkdir(parents=True, exist_ok=True)
    for инструмент, начало in границы.items():
        ряд = [начало + i * 300 for i in range(50)]
        (папка / f"{инструмент}_M5.csv").write_text(
            "\n".join([ШАПКА] + [_строка(t) for t in ряд]) + "\n",
            encoding="utf-8")
    return папка


def test_граница_берётся_из_точной_отметки_а_не_из_даты():
    """ГЛАВНАЯ проверка P1-H5.

    Граница — точная отметка времени в секундах. Округление до даты и было
    моей ошибкой: числа переставали воспроизводиться."""
    корень = Path(tempfile.mkdtemp(prefix="границы_"))
    try:
        h1 = _снимок(корень / "h1")
        времена = us._времена(str(h1 / "EURUSD_H1.csv"))
        середина = времена[len(времена) // 2] + 1800
        _прежние(корень / "прежние", {"EURUSD": середина, "XAUUSD": середина})

        итог = us.посчитать(str(h1), str(корень / "прежние"))
        з = итог["инструменты"]["EURUSD"]
        check(з["граница_секунды"] == середина,
              "Граница записана В СЕКУНДАХ, а не датой",
              str(з.get("граница_секунды")))
        ожидалось = sum(1 for t in времена if t < середина)
        check(з["невидено"] == ожидалось,
              "Невиданные посчитаны по точной отметке",
              f"{з['невидено']} вместо {ожидалось}")
    finally:
        shutil.rmtree(корень, ignore_errors=True)


def test_обе_договорённости_печатаются_рядом():
    """Выбор договорённости должен быть виден, а не подразумеваться."""
    корень = Path(tempfile.mkdtemp(prefix="границы_"))
    try:
        # ТРИ инструмента, а не два: при двух «общая граница валютных пар»
        # совпадает с границей единственной валютной пары, и различать
        # нечего. Первая версия этого теста именно так себя и обманула.
        h1 = _снимок(корень / "h1",
                     инструменты=("EURUSD", "GBPUSD", "XAUUSD"))
        времена = us._времена(str(h1 / "EURUSD_H1.csv"))
        _прежние(корень / "прежние",
                 {"EURUSD": времена[100], "GBPUSD": времена[500],
                  "XAUUSD": времена[300]})
        итог = us.посчитать(str(h1), str(корень / "прежние"))

        check("покомпонентная строгая" in итог["договорённость"],
              "Названа выбранная договорённость")
        с = итог["для_сравнения_общая_граница"]
        check(bool(с) and "невидено" in с,
              "И рядом посчитана вторая — для сравнения")
        check(итог["итого"]["невидено"] != с["невидено"],
              "Числа договорённостей различаются — потому и печатаются обе",
              f"{итог['итого']['невидено']} и {с['невидено']}")
    finally:
        shutil.rmtree(корень, ignore_errors=True)


def test_разрезание_идёт_по_времени_без_перемешивания():
    """train — самое раннее, oos — самое позднее.

    Резать вперемешку нельзя: тогда «будущее» попадёт в обучение, и вся
    проверка превратится в пересказ."""
    пары = [(i, f"строка{i}") for i in range(100)]
    куски = us.разрезать(пары, (0.5, 0.25, 0.25))
    check(len(куски["train"]) == 50, "train — половина", str(len(куски["train"])))
    check(len(куски["validation"]) == 25, "validation — четверть")
    check(len(куски["oos"]) == 25, "oos — четверть")
    check(куски["train"][-1][0] < куски["validation"][0][0],
          "train целиком РАНЬШЕ validation")
    check(куски["validation"][-1][0] < куски["oos"][0][0],
          "validation целиком РАНЬШЕ oos")
    собрано = куски["train"] + куски["validation"] + куски["oos"]
    check(собрано == пары, "И вместе они дают исходный ряд без потерь")


def test_у_каждого_среза_свой_отпечаток():
    """Отпечаток среза — чтобы кусок нельзя было подменить незаметно."""
    корень = Path(tempfile.mkdtemp(prefix="границы_"))
    try:
        h1 = _снимок(корень / "h1")
        времена = us._времена(str(h1 / "EURUSD_H1.csv"))
        _прежние(корень / "прежние",
                 {"EURUSD": времена[-1], "XAUUSD": времена[-1]})
        итог = us.посчитать(str(h1), str(корень / "прежние"))
        части = итог["инструменты"]["EURUSD"]["части"]
        отпечатки = {ч: части[ч]["sha256"] for ч in us.ЧАСТИ}
        check(len(set(отпечатки.values())) == 3,
              "У трёх срезов три РАЗНЫХ отпечатка", str(отпечатки))
        for ч in us.ЧАСТИ:
            check(len(отпечатки[ч]) == 64, f"У {ч} полноценный отпечаток")

        a = us.отпечаток_среза(["1;2", "3;4"])
        b = us.отпечаток_среза(["1;2", "3;5"])
        check(a != b, "Правка одной строки меняет отпечаток среза")
    finally:
        shutil.rmtree(корень, ignore_errors=True)


