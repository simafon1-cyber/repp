def test_перенос_чинит_смещение_и_не_трогает_свечи():
    """ГЛАВНАЯ проверка P1-H4.

    Доказательство — отпечатки CSV до и после: обязаны совпасть побайтно.
    Заново выгружать нельзя, окно терминала уехало бы вперёд.

    Наоборот: пусть перенос запишет что-нибудь в CSV — проверка падает,
    и перенос отменяется целиком."""
    корень = Path(tempfile.mkdtemp(prefix="перенос_"))
    try:
        папка = _снимок(корень / "снимок")
        до = _отпечатки(папка)

        журнал = mm.перенести(str(папка))

        check(журнал["csv_не_менялись"] is True,
              "Журнал утверждает, что свечи не менялись")
        после = _отпечатки(папка)
        разошлись = [и for и in до if до[и] != после.get(и)]
        check(not разошлись,
              "И ПО ФАКТУ отпечатки всех CSV совпали", str(разошлись))

        меты = {з["файл"]: з for з in журнал["паспорта"]}
        check(меты["EURUSD_H1.csv"]["было"] == -1.0, "Было неверное −1")
        check(меты["EURUSD_H1.csv"]["стало"] == 3.0,
              "Стало верное +3", str(меты["EURUSD_H1.csv"]["стало"]))
        check(журнал["изменено_паспортов"] == 4,
              "Изменены все четыре паспорта снимка",
              str(журнал["изменено_паспортов"]))

        мета = json.loads((папка / "EURUSD_H1.meta.json").read_text(encoding="utf-8"))
        check(мета["server_utc_offset_hours"] == 3.0,
              "В паспорте на диске записано +3",
              str(мета.get("server_utc_offset_hours")))
        check("server_utc_offset_note" in мета,
              "И пояснение рядом с числом")
    finally:
        shutil.rmtree(корень, ignore_errors=True)


