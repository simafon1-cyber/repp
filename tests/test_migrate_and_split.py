ШАПКА = "time;open;high;low;close;tick_volume;spread;real_volume"


def _строка(t):
    return f"{t};1.1;1.2;1.0;1.15;10;8;0"


def _часы_недель(начало, недель=60):
    """Часовые бары: пн 00:00 .. пт 23:00, выходные пусты."""
    времена, t = [], начало
    for _ in range(недель):
        времена += [t + ч * 3600 for ч in range(5 * 24)]
        t += 7 * 24 * 3600
    return времена


def _снимок(папка, смещение_в_паспорте=-1.0, недель=60,
            инструменты=("EURUSD", "XAUUSD")):
    """Каталог со свечами и паспортами, как после выгрузки."""
    папка.mkdir(parents=True, exist_ok=True)
    # Понедельник мая 2026 — летнее время, значит верный ответ +3.
    пн = int(datetime(2026, 5, 4, 0, 0, tzinfo=timezone.utc).timestamp())
    времена = _часы_недель(пн, недель)
    for инструмент in инструменты:
        for тф, шаг in (("H1", 3600), ("M5", 300)):
            ряд = времена if тф == "H1" else [времена[0] + i * шаг
                                              for i in range(200)]
            (папка / f"{инструмент}_{тф}.csv").write_text(
                "\n".join([ШАПКА] + [_строка(t) for t in ряд]) + "\n",
                encoding="utf-8")
            (папка / f"{инструмент}_{тф}.meta.json").write_text(json.dumps({
                "version": 1, "symbol": инструмент, "timeframe": тф,
                "server_utc_offset_hours": смещение_в_паспорте,
                "exported_utc": "2026-08-22 01:01:00",
                "bars": len(ряд), "last_bar_closed": True,
            }, ensure_ascii=False), encoding="utf-8")
    he.записать_манифест(str(папка))
    return папка


def _отпечатки(папка):
    return {f.name: hashlib.sha256(f.read_bytes()).hexdigest()
            for f in sorted(папка.glob("*.csv"))}


