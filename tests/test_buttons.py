passed = 0
failed = 0


def check(ok: bool, name: str, detail: str = "") -> None:
    global passed, failed
    if ok:
        passed += 1
        print(f"  OK   {name}")
    else:
        failed += 1
        print(f"  СБОЙ {name}" + (f" -> {detail}" if detail else ""))


import run_baseline            # noqa: E402  (заглушка MetaTrader5)
import поддельный_tk as пт     # noqa: E402

for _имя, _модуль in пт.собрать_модули().items():
    sys.modules[_имя] = _модуль

import desktop_app as da       # noqa: E402
import ui_indicator as ind     # noqa: E402


# Сколько секунд ждать один обработчик, прежде чем считать его зависшим.
ТЕРПЕНИЕ_СЕКУНД = 5

# Сколько раз обходить список. Нажатие открывает окошки, в них появляются
# новые кнопки, те открывают следующие. Три захода покрывают всё, что
# программа успевает породить; больше — только время.
ЗАХОДОВ = 3


def собрать_окно():
    """Собрать ИНТЕРФЕЙС, но не запускать программу.

    App.__init__ поднимает потоки, веб-дашборд, значок в трее и лезет в
    сеть — на этом сборка зависала намертво. Нам нужно окно, а не
    работающая программа, поэтому повторяем ровно те шаги, что идут в
    __init__ до _build_ui, и ничего сверх."""
    пт.сброс()
    окно = object.__new__(da.App)
    окно.root = sys.modules["tkinter"].Tk()
    окно._apply_theme()
    окно.stop_event = None
    окно.bot_thread = None
    окно._bot_should_run = False
    окно.tray_icon = None
    окно._dashboard_started = False
    окно.chat_history = []
    окно._auto_update_busy = False
    окно._start_bot_waits = 0
    окно._build_ui()
    return окно


def test_окно_собирается_целиком():
    """Если окно не собралось, дальше проверять нечего."""
    print("\n[Окно собирается]")
    try:
        окно = собрать_окно()
    except Exception as e:  # noqa: BLE001
        check(False, "Интерфейс собрался",
              f"{type(e).__name__}: {str(e).splitlines()[0]}")
        return None
    check(True, "Интерфейс собрался")
    check(len(пт.КНОПКИ) > 100,
          f"Кнопок создано: {len(пт.КНОПКИ)}", str(len(пт.КНОПКИ)))
    без_обработчика = [к for к in пт.КНОПКИ
                       if к["вид"] == "Button" and not к["обработчик"]]
    check(not без_обработчика,
          "У каждой кнопки есть обработчик",
          str([к["подпись"] for к in без_обработчика[:5]]))
    return окно


def test_каждая_кнопка_нажимается():
    """ГЛАВНАЯ проверка.

    Наоборот: вернуть в _show_param_help обращение item["warn"] вместо
    item.get("warn") — тест падает, называя кнопку «?»."""
    print("\n[Каждая кнопка нажимается без ошибки]")
    окно = собрать_окно()
    if окно is None:
        return
    кнопки = [к for к in пт.КНОПКИ if к["обработчик"]]
    check(len(кнопки) > 100, f"Кнопок с обработчиком: {len(кнопки)}",
          str(len(кнопки)))

    def терпение(*a):
        raise TimeoutError("обработчик завис")

    было = signal.signal(signal.SIGALRM, терпение)
    упало = []
    нажато = 0
    # НЕСКОЛЬКО ЗАХОДОВ, А НЕ ОДИН.
    #
    # Часть кнопок открывает окошки — «Настроить», «?», «Добавить счёт», —
    # и кнопки ВНУТРИ них создаются только в момент открытия. Первый
    # вариант этого теста брал список один раз, до нажатий, и такие
    # кнопки не нажимал никогда. Их оказалось 146 из 412: больше
    # трети. То есть «все кнопки проверены» было сказано слишком
    # уверенно, и поймал это не тест, а прямой вопрос владельца
    # «ты всё пофиксил?».
    #
    # Заходы повторяются, пока появляются новые кнопки.
    уже = set()
    try:
        for заход in range(ЗАХОДОВ):
            новые = [к for к in list(пт.КНОПКИ)
                     if к["обработчик"] and id(к) not in уже]
            if not новые:
                break
            for к in новые:
                уже.add(id(к))
                нажато += 1
                signal.alarm(ТЕРПЕНИЕ_СЕКУНД)
                try:
                    к["обработчик"]()
                except TimeoutError:
                    упало.append((к["подпись"], "ЗАВИС"))
                except Exception as e:  # noqa: BLE001
                    след = traceback.format_exc().splitlines()
                    место = [с for с in след if "ai_scalper_standalone" in с]
                    упало.append((к["подпись"],
                                  f"{type(e).__name__}: {e} | "
                                  f"{место[-1].strip() if место else ''}"))
                finally:
                    signal.alarm(0)
    finally:
        signal.signal(signal.SIGALRM, было)

    check(нажато > len(кнопки),
          f"Нажаты и кнопки открывшихся окошек: всего {нажато}",
          f"{нажато} против {len(кнопки)} при сборке")
    check(not упало, "Ни одна кнопка не падает при нажатии",
          "; ".join(f"«{п}»: {ч}" for п, ч in упало[:4]))


def test_справка_есть_у_каждого_параметра_целиком():
    """Кнопка «?» падала из-за неполной записи в справке.

    Проверяется не только то, что окно теперь не падает, но и то, что
    записи полные: иначе человек молча недополучит раздел."""
    print("\n[Справка по параметрам заполнена целиком]")
    import param_help as ph
    неполные = [имя for имя, з in ph.HELP.items()
                if not {"what", "more", "less", "warn"} <= set(з)]
    check(not неполные, "У каждой записи справки все четыре раздела",
          str(неполные[:6]))
    мёртвые = [имя for имя, з in ph.HELP.items() if "default" in з]
    check(not мёртвые,
          "Нет ключа default: значение по умолчанию берётся из образца настроек",
          str(мёртвые[:6]))
    check(len(ph.HELP) > 100, f"Записей в справке: {len(ph.HELP)}")


