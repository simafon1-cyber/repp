def test_огонёк_горит_когда_действие_в_силе():
    """Огонёк показывает не «щёлкали мышью», а действует ли сейчас то,
    что кнопка делает. Иначе после перезапуска программы он врал бы:
    нажатия не было, а бот работает.

    Наоборот: поменять порядок проверок в ui_indicator.состояние так,
    чтобы недоступность перебивала включённость, — тест падает."""
    print("\n[Огонёк показывает положение дел, а не щелчок]")
    стоит = ind.состояния_кнопок(бот_запущен=False, на_паузе=False)
    работает = ind.состояния_кнопок(бот_запущен=True, на_паузе=False)
    пауза = ind.состояния_кнопок(бот_запущен=True, на_паузе=True)

    check(работает["старт"] == ind.НАЖАТА,
          "Бот работает — «Старт» зелёный", работает["старт"])
    check(стоит["старт"] != ind.НАЖАТА,
          "Бот стоит — «Старт» не зелёный", стоит["старт"])
    check(стоит["стоп"] == ind.НАЖАТА,
          "Бот стоит — «Стоп» зелёный: остановка в силе", стоит["стоп"])
    check(пауза["пауза"] == ind.НАЖАТА,
          "Пауза включена — «Пауза» зелёная", пауза["пауза"])
    check(работает["пауза"] != ind.НАЖАТА,
          "Паузы нет — «Пауза» не зелёная", работает["пауза"])
    check(стоит["пауза"] == ind.НЕДОСТУПНА,
          "У остановленного бота пауза недоступна — и это отдельное слово",
          стоит["пауза"])


def test_одноразовая_кнопка_показывает_сам_факт_нажатия():
    """У «Перезапуска», «Сохранить» и «Выхода» длящегося состояния нет.

    Им огонёк нужен ровно затем, за чем просил владелец: чтобы было
    видно нажатие."""
    print("\n[Одноразовые кнопки показывают нажатие]")
    обычно = ind.состояния_кнопок(True, False)
    for имя in ("перезапуск", "сохранить", "выход"):
        check(обычно[имя] == ind.ОТЖАТА, f"«{имя}» по умолчанию не горит")
        нажали = ind.состояния_кнопок(True, False, недавно_нажато=[имя])
        check(нажали[имя] == ind.НАЖАТА, f"«{имя}» после нажатия загорается")
        check(нажали["старт"] == обычно["старт"],
              f"И «{имя}» не влияет на соседние огоньки")


def test_цвет_берётся_из_темы_а_не_вбит():
    """Иначе огонёк выпадет из оформления и может стать нечитаемым.

    Проверяется на ВСЕХ трёх темах: зелёный и красный обязаны
    различаться в каждой."""
    print("\n[Цвет огонька берётся из темы]")
    import ui_theme
    for имя, палитра in ui_theme.THEMES.items():
        зел = ind.цвет(ind.НАЖАТА, палитра)
        кр = ind.цвет(ind.ОТЖАТА, палитра)
        check(зел == палитра["profit"], f"{имя}: зелёный — из палитры", зел)
        check(кр == палитра["loss"], f"{имя}: красный — из палитры", кр)
        check(зел != кр, f"{имя}: цвета различаются")
    # И на пустой палитре не падает, а даёт хоть какой-то цвет.
    check(ind.цвет(ind.НАЖАТА, {}).startswith("#"),
          "Без палитры огонёк всё равно получает цвет")
    check(ind.цвет("чепуха", {}).startswith("#"),
          "И на незнакомом состоянии тоже не падает")


def test_огоньки_созданы_рядом_с_кнопками():
    """Проверяется ФАКТ: окно завело огоньки под нужными именами."""
    print("\n[Огоньки на месте]")
    окно = собрать_окно()
    if окно is None:
        return
    for имя in ("старт", "стоп", "пауза", "перезапуск", "сохранить", "выход"):
        check(имя in окно._огоньки, f"Огонёк «{имя}» создан",
              str(sorted(окно._огоньки)))
    # И перекраска не падает на собранном окне.
    try:
        окно._обновить_огоньки()
        check(True, "Перекраска огоньков отрабатывает")
    except Exception as e:  # noqa: BLE001
        check(False, "Перекраска огоньков отрабатывает",
              f"{type(e).__name__}: {e}")


def test_ошибка_огонька_не_роняет_окно():
    """Огонёк — украшение поверх правды, а не сама правда."""
    print("\n[Сломанный огонёк не роняет обновление окна]")
    окно = собрать_окно()
    if окно is None:
        return

    class Битый:
        def configure(self, **k):
            raise RuntimeError("виджет уничтожен")

    окно._огоньки["старт"] = Битый()
    try:
        окно._обновить_огоньки()
        check(True, "Ошибка внутри огонька погашена")
    except Exception as e:  # noqa: BLE001
        check(False, "Ошибка внутри огонька погашена",
              f"{type(e).__name__}: {e}")


def main() -> int:
    print("=" * 70)
    print("ВСЕ КНОПКИ ОКНА: СОБИРАЮТСЯ И НАЖИМАЮТСЯ")
    print("=" * 70)
    for имя, ф in sorted(globals().items()):
        if имя.startswith("test_") and callable(ф):
            try:
                ф()
            except Exception as e:  # noqa: BLE001
                check(False, f"{имя} доработала до конца",
                      f"{type(e).__name__}: {str(e).splitlines()[0]}")
    print("\n" + "=" * 70)
    print(f"Пройдено: {passed}   Сбоев: {failed}")
    print("=" * 70)
    return 1 if failed else 0


