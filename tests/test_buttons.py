#!/usr/bin/env python3
"""ВСЕ КНОПКИ ОКНА: СОБИРАЮТСЯ И НАЖИМАЮТСЯ.

ПОЧЕМУ ЭТОТ ТЕСТ ПОЯВИЛСЯ

Владелец: «исправь всё, что не работает, все кнопки протестируй».

Проверить кнопку по-настоящему — значит НАЖАТЬ её. Разбор исходника
этого не даёт: он видит, что обработчик существует, но не видит, что
внутри тот обращается к полю, которого нет. Ровно так и было: кнопка «?»
рядом с четырьмя параметрами падала с KeyError, окошко справки не
открывалось, и человек видел, что нажатие ничего не даёт. Ни один из
тридцати восьми наборов проверок этого не ловил.

ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ ПО ФАКТУ

Окно собирается целиком на поддельном tkinter, после чего вызывается
обработчик КАЖДОЙ кнопки. Считается число упавших. Не «функция
существует», а «нажатие не приводит к ошибке».

ЧЕГО ЭТОТ ТЕСТ НЕ ПРОВЕРЯЕТ

Что окно выглядит правильно: подделка не рисует и не считает пиксели.
Что кнопка делает ПОЛЕЗНОЕ: проверяется лишь отсутствие поломки.
Поведение с настоящим терминалом: MetaTrader5 здесь заглушка.

И отдельно, потому что это видно в выводе. Часть кнопок («Старт»,
«Диагностика» и подобные) запускает работу в ОТДЕЛЬНОМ ПОТОКЕ. Здесь
проверяется, что нажатие прошло и поток запустился, — а сам поток
дальше падает, потому что терминала нет. Его трассировка попадает в
вывод и выглядит пугающе, но проверку не валит и валить не должна: это
не поломка кнопки, а отсутствие MetaTrader в среде проверки.

Что происходит внутри таких потоков — забота других наборов
(test_bot_alive, test_partial_fill и остальные), у которых есть
поддельный брокер.

Запуск:  python3 tests/test_buttons.py
"""

from __future__ import annotations

