def test_старый_прогон_привязан_к_другому_паспорту():
    """run_h1_study.py проверяет ДРУГУЮ гипотезу по ДРУГОМУ паспорту.

    Запуск его под видом проверки H1-edge был бы недействителен: другой
    архив, другой паспорт, другой OOS. Проверяется по дереву кода, а не
    по тексту."""
    import ast
    старый = ast.parse((APP / "run_h1_study.py").read_text(encoding="utf-8"))
    строки = []
    for узел in ast.walk(старый):
        if isinstance(узел, ast.Constant) and isinstance(узел.value, str):
            строки.append(узел.value)
    check(any("manifest_h1.json" in с for с in строки),
          "Старый прогон привязан к manifest_h1.json")
    check(not any("manifest_h1_edge" in с for с in строки),
          "И НЕ знает про новый паспорт")

    новый = ast.parse((APP / "run_h1_edge_study.py").read_text(encoding="utf-8"))
    строки_н = [у.value for у in ast.walk(новый)
                if isinstance(у, ast.Constant) and isinstance(у.value, str)]
    check(any("manifest_h1_edge.json" in с for с in строки_н),
          "Новый прогон привязан к manifest_h1_edge.json")
    check(any("history_h1_snapshots.tar.gz" in с for с in строки_н),
          "И к выгруженному часовому архиву")


