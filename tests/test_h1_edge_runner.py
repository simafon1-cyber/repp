def test_oos_не_читается_раньше_train_и_validation():
    """ГЛАВНАЯ проверка порядка.

    Открыть OOS первым и потом сказать «а теперь посмотрим train»
    технически возможно, а честно — нет. Проверяется ФАКТ: в каком
    порядке прогон запрашивал срезы.

    Наоборот: переставьте в main() чтение OOS выше train — проверка
    падает."""
    корень, снимок, прежние, архив, границы, паспорт = _окружение(баров=300)
    было = _подставить(архив, границы, паспорт, прежние, корень)
    порядок = []
    настоящая = прогон.сделки_среза

    def следящая(папка, инструмент, часть):
        # Запоминаем ИНСТРУМЕНТ тоже. Первая версия следила только за
        # временем начала среза — а инструменты в тесте одинаковые, и
        # два разных чтения выглядели как одно и то же.
        порядок.append((инструмент, часть.get("начало_utc")))
        return настоящая(папка, инструмент, часть)

    прогон.сделки_среза = следящая
    try:
        прогон.main([])
        д = json.loads(Path(границы).read_text(encoding="utf-8"))
        первый = next(iter(д["инструменты"]))
        oos_начало = д["инструменты"][первый]["части"]["oos"]["начало_utc"]
        тр_начало = д["инструменты"][первый]["части"]["train"]["начало_utc"]

        места_oos = [i for i, (и, н) in enumerate(порядок)
                     if и == первый and н == oos_начало]
        места_train = [i for i, (и, н) in enumerate(порядок)
                       if и == первый and н == тр_начало]
        check(места_oos and места_train, "Читались и train, и OOS",
              f"train {места_train}, oos {места_oos}")
        if места_oos and места_train:
            check(max(места_train) < min(места_oos),
                  "ВСЕ чтения train идут РАНЬШЕ первого чтения OOS",
                  f"train до {max(места_train)}, oos с {min(места_oos)}")
            check(len(места_oos) == 1,
                  "И OOS этого инструмента прочитан РОВНО ОДИН раз",
                  str(len(места_oos)))
    finally:
        прогон.сделки_среза = настоящая
        _вернуть(было)
        shutil.rmtree(корень, ignore_errors=True)


def test_при_train_и_validation_ни_одна_строка_oos_не_прочитана():
    """P1-E3. ФИЗИЧЕСКАЯ проверка, а не проверка порядка вызовов.

    Соседний тест следит за тем, КОГО позвали. Этого мало: прежний код
    звал train, а внутри читал файл целиком — строки OOS оказывались в
    памяти сразу. Порядок вызовов был правильный, поведение — нет.

    Здесь подменяется построчный источник и записывается КАЖДАЯ выданная
    строка. Момент открытия OOS отмечается отдельно. Всё, что прочитано
    до этого момента, обязано лежать левее начала OOS.

    Наоборот: вернуть в _ряд_среза чтение всего файла перед фильтром —
    тест падает."""
    корень, снимок, прежние, архив, границы, паспорт = _окружение(баров=300)
    было = _подставить(архив, границы, паспорт, прежние, корень)
    прочитано = []          # отметки времени всех выданных строк
    отсечка = []            # сколько было прочитано к моменту открытия OOS
    настоящий_поток = прогон._построчно
    настоящее_занятие = прогон._занять_oos

    def следящий(путь):
        for строка in настоящий_поток(путь):
            ч = строка.strip().split(";")
            if ч and ч[0].isdigit():
                прочитано.append(int(ч[0]))
            yield строка

    def следящее_занятие(паспорт_):
        отсечка.append(len(прочитано))
        return настоящее_занятие(паспорт_)

    прогон._построчно = следящий
    прогон._занять_oos = следящее_занятие
    try:
        прогон.main([])
        начало_oos = _границы_oos(границы)
        check(bool(отсечка), "OOS вообще открывался — есть что проверять",
              str(отсечка))
        if отсечка:
            до = прочитано[:отсечка[0]]
            после = прочитано[отсечка[0]:]
            лишние = [t for t in до if t >= начало_oos]
            check(not лишние,
                  "До открытия OOS не прочитано НИ ОДНОЙ строки из OOS",
                  f"прочитано лишних {len(лишние)}, первая "
                  f"{лишние[0] if лишние else '-'} при границе "
                  f"{int(начало_oos)}")
            check(bool(до), "При этом train и validation читались",
                  f"строк до отсечки {len(до)}")
            # Без этого тест прошёл бы и на прогоне, который OOS не читает
            # вовсе: «ничего не прочитано» тоже даёт пустой список лишних.
            check(any(t >= начало_oos for t in после),
                  "А после открытия OOS его строки действительно читаются",
                  f"строк после отсечки {len(после)}")
    finally:
        прогон._построчно = настоящий_поток
        прогон._занять_oos = настоящее_занятие
        _вернуть(было)
        shutil.rmtree(корень, ignore_errors=True)


def test_чтение_среза_обрывается_на_первой_свече_за_границей():
    """Файл не дочитывается до конца — он закрывается на границе.

    Проверяется не «сколько вернули», а сколько строк источник успел
    ВЫДАТЬ. Это разные числа: фильтр отбрасывает лишнее уже после
    чтения, обрыв — до."""
    корень = Path(tempfile.mkdtemp(prefix="обрыв_"))
    try:
        начало = int(datetime(2024, 1, 1, tzinfo=timezone.utc).timestamp())
        путь = корень / "X_H1.csv"
        путь.write_text("\n".join([ШАПКА] + _свечи(начало, 1000)) + "\n",
                        encoding="utf-8")
        выдано = []
        настоящий = прогон._построчно

        def следящий(п):
            for строка in настоящий(п):
                выдано.append(строка)
                yield строка

        прогон._построчно = следящий
        try:
            бары = прогон._ряд_среза(str(путь), начало,
                                     начало + 49 * 3600, 50)
        finally:
            прогон._построчно = настоящий
        check(len(бары) == 50, "Вернулись ровно 50 свечей среза", str(len(бары)))
        check(len(выдано) == 50,
              "И источник выдал РОВНО 50 строк из 1000 — ни одной лишней",
              str(len(выдано)))
    finally:
        shutil.rmtree(корень, ignore_errors=True)


