def test_первый_прогон_создаёт_отметку_и_она_описывает_входы():
    """Отметка — не пустой флаг: по ней видно, ЧТО именно открывали."""
    корень, снимок, прежние, архив, границы, паспорт = _окружение(баров=300)
    было = _подставить(архив, границы, паспорт, прежние, корень)
    try:
        код = прогон.main([])
        check(код == 4, "Первый прогон дошёл до OOS (мало сделок, код 4)",
              str(код))
        check(Path(прогон.МАРКЕР).exists(), "Отметка об открытии OOS создана")
        if Path(прогон.МАРКЕР).exists():
            м = json.loads(Path(прогон.МАРКЕР).read_text(encoding="utf-8"))
            п = json.loads(Path(паспорт).read_text(encoding="utf-8"))
            check(м.get("хеш_паспорта") == п["хеш_паспорта"],
                  "В отметке записан хеш паспорта")
            check(м.get("архив_h1") == hashlib.sha256(
                      Path(архив).read_bytes()).hexdigest(),
                  "И отпечаток архива данных")
            check(bool(м.get("когда_utc")) and bool(м.get("ревизия")),
                  "И время с ревизией")
        check(Path(прогон.РЕЗУЛЬТАТ).exists(), "Результат записан")
    finally:
        _вернуть(было)
        shutil.rmtree(корень, ignore_errors=True)


def test_второй_прогон_блокируется_ДО_чтения_oos():
    """ГЛАВНАЯ проверка одноразовости.

    Проверяется не «вернул ненулевой код», а что OOS во второй раз
    вообще НЕ читался и прошлый результат не тронут. Иначе повтор после
    неудобного числа стоил бы одну команду.

    Наоборот: убрать проверку_6_одноразовость — тест падает."""
    корень, снимок, прежние, архив, границы, паспорт = _окружение(баров=300)
    было = _подставить(архив, границы, паспорт, прежние, корень)
    try:
        прогон.main([])
        первый = Path(прогон.РЕЗУЛЬТАТ).read_bytes()

        читали = []
        настоящая = прогон.сделки_среза

        def следящая(папка, инструмент, часть):
            читали.append(часть.get("начало_utc"))
            return настоящая(папка, инструмент, часть)

        прогон.сделки_среза = следящая
        try:
            код = прогон.main([])
        finally:
            прогон.сделки_среза = настоящая

        check(код == 5, "Второй прогон остановлен кодом 5", str(код))
        check(not читали,
              "И ни один срез не читался — остановка ДО расчёта",
              f"прочитано срезов {len(читали)}")
        check(Path(прогон.РЕЗУЛЬТАТ).read_bytes() == первый,
              "Прошлый результат не изменён")
    finally:
        _вернуть(было)
        shutil.rmtree(корень, ignore_errors=True)


def test_удалённая_отметка_это_инцидент_а_не_разрешение_повторить():
    """Стереть файл не должно означать «можно заново».

    Иначе защита стоит одну команду удаления. Отсутствие отметки при
    существующем результате — отдельное состояние, и оно тоже отказ.

    Первая версия этого теста проверяла код возврата и целость файла — и
    ПРОХОДИЛА при выключенной защите. Без неё прогон доходил до конца,
    ЧИТАЛ OOS второй раз и спотыкался лишь на запись результата: код всё
    равно 5, файл всё равно цел. А невиданные данные уже посмотрели
    дважды. Поэтому проверяется факт чтения, а не код."""
    корень, снимок, прежние, архив, границы, паспорт = _окружение(баров=300)
    было = _подставить(архив, границы, паспорт, прежние, корень)
    try:
        прогон.main([])
        первый = Path(прогон.РЕЗУЛЬТАТ).read_bytes()
        Path(прогон.МАРКЕР).unlink()

        читали = []
        настоящая = прогон.сделки_среза

        def следящая(папка, инструмент, часть):
            читали.append(часть.get("начало_utc"))
            return настоящая(папка, инструмент, часть)

        прогон.сделки_среза = следящая
        try:
            код = прогон.main([])
        finally:
            прогон.сделки_среза = настоящая

        check(код == 5, "Прогон без отметки, но с результатом — код 5", str(код))
        check(not читали,
              "И НИ ОДИН срез не читался — OOS второй раз не открывали",
              f"прочитано срезов {len(читали)}")
        check(Path(прогон.РЕЗУЛЬТАТ).read_bytes() == первый,
              "И результат по-прежнему не тронут")
    finally:
        _вернуть(было)
        shutil.rmtree(корень, ignore_errors=True)


