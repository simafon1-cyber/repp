def _свечи(начало, сколько, шаг=3600):
    """Часовые бары с лёгким ходом цены — чтобы сделки вообще случались."""
    строки = []
    цена = 1.1000
    for i in range(сколько):
        цена += (0.0007 if (i // 7) % 2 == 0 else -0.0006)
        h = цена + 0.0009
        l = цена - 0.0009
        строки.append(f"{начало + i * шаг};{цена:.5f};{h:.5f};{l:.5f};"
                      f"{цена:.5f};50;8;0")
    return строки


