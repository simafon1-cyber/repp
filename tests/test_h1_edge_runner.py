def test_oos_не_читается_раньше_train_и_validation():
    """ГЛАВНАЯ проверка порядка.

    Открыть OOS первым и потом сказать «а теперь посмотрим train»
    технически возможно, а честно — нет. Проверяется ФАКТ: в каком
    порядке прогон запрашивал срезы.

    Наоборот: переставьте в main() чтение OOS выше train — проверка
    падает."""
    корень, снимок, прежние, архив, границы, паспорт = _окружение(баров=300)
    было = _подставить(архив, границы, паспорт, прежние)
    порядок = []
    настоящая = прогон.сделки_среза

    def следящая(папка, инструмент, часть):
        # Запоминаем ИНСТРУМЕНТ тоже. Первая версия следила только за
        # временем начала среза — а инструменты в тесте одинаковые, и
        # два разных чтения выглядели как одно и то же.
        порядок.append((инструмент, часть.get("начало_utc")))
        return настоящая(папка, инструмент, часть)

    прогон.сделки_среза = следящая
    try:
        прогон.main(["--вывод", str(корень / "итог.json")])
        д = json.loads(Path(границы).read_text(encoding="utf-8"))
        первый = next(iter(д["инструменты"]))
        oos_начало = д["инструменты"][первый]["части"]["oos"]["начало_utc"]
        тр_начало = д["инструменты"][первый]["части"]["train"]["начало_utc"]

        места_oos = [i for i, (и, н) in enumerate(порядок)
                     if и == первый and н == oos_начало]
        места_train = [i for i, (и, н) in enumerate(порядок)
                       if и == первый and н == тр_начало]
        check(места_oos and места_train, "Читались и train, и OOS",
              f"train {места_train}, oos {места_oos}")
        if места_oos and места_train:
            check(max(места_train) < min(места_oos),
                  "ВСЕ чтения train идут РАНЬШЕ первого чтения OOS",
                  f"train до {max(места_train)}, oos с {min(места_oos)}")
            check(len(места_oos) == 1,
                  "И OOS этого инструмента прочитан РОВНО ОДИН раз",
                  str(len(места_oos)))
    finally:
        прогон.сделки_среза = настоящая
        _вернуть(было)
        shutil.rmtree(корень, ignore_errors=True)


