def _сделки(дней=40, в_дне=5, разброс=True):
    """Сделки с РАЗНЫМИ значениями R и разным средним по дням.

    Первая версия давала всем сделкам одно и то же число. Тогда любое
    бутстрэп-среднее равнялось этому числу, интервал был нулевой ширины,
    и проверки про зерно и про блочность ничего не проверяли. Тест,
    который не может различить правильное и неправильное, — не тест."""
    ген = random.Random(12345)
    ряд = []
    for д in range(дней):
        день = (datetime(2024, 3, 1, tzinfo=timezone.utc)
                + timedelta(days=д)).strftime("%Y-%m-%d")
        # У каждого дня своё среднее: иначе выбор дня ничего не менял бы.
        среднее_дня = ген.uniform(-0.5, 0.5) if разброс else 0.0
        for _ in range(в_дне):
            ряд.append({"день": день,
                        "r_чистый": среднее_дня + ген.uniform(-0.2, 0.2)})
    return ряд


def test_бутстрэп_воспроизводится_по_зерну():
    """Два запуска с одним зерном обязаны дать одинаковые числа.

    Иначе результат зависит от случая, и повторить его нельзя — а значит
    нельзя и проверить."""
    сделки = _сделки()
    a = прогон.бутстрэп(сделки, повторов=500, зерно=прогон.ЗЕРНО)
    b = прогон.бутстрэп(сделки, повторов=500, зерно=прогон.ЗЕРНО)
    check(a == b, "Одно зерно — одинаковые числа до последнего знака")
    c = прогон.бутстрэп(сделки, повторов=500, зерно=прогон.ЗЕРНО + 1)
    check(a["нижняя_граница"] != c["нижняя_граница"],
          "Другое зерно — другой результат (значит зерно вообще работает)")


def test_бутстрэп_считает_по_дням_а_не_по_сделкам():
    """Единица ресемплинга — день, а не сделка.

    Если бы ресемплинг шёл по отдельным сделкам, зависимость между ними
    считалась бы нулевой, неопределённость оказалась бы ЗАНИЖЕНА — то
    есть гипотезу было бы легче подтвердить. Это недопустимо.

    Проверка: при одинаковом числе сделок, но разном числе ДНЕЙ интервал
    обязан различаться."""
    много_дней = _сделки(дней=40, в_дне=5)
    мало_дней = _сделки(дней=4, в_дне=50)
    check(len(много_дней) == len(мало_дней) == 200,
          "Сделок поровну", f"{len(много_дней)} и {len(мало_дней)}")

    a = прогон.бутстрэп(много_дней, повторов=400)
    b = прогон.бутстрэп(мало_дней, повторов=400)
    check(a["дней"] == 40 and b["дней"] == 4,
          "Дней разное число", f"{a['дней']} и {b['дней']}")

    # РЕШАЮЩАЯ ПРОВЕРКА: ширина интервала должна отвечать числу ДНЕЙ,
    # а не числу сделок.
    #
    # Строим случай, где внутри дня все сделки ОДИНАКОВЫ, а дни разные.
    # Тогда:
    #   ресемплинг по дням    даёт разброс среднего ~ σ(дней) / √K
    #   ресемплинг по сделкам даёт разброс среднего ~ σ(сделок) / √N
    # Здесь σ(дней) = σ(сделок), K = 4, N = 200 — то есть блочный интервал
    # обязан быть примерно в √(200/4) ≈ 7 раз шире.
    #
    # Первая версия сравнивала два РАЗНЫХ набора данных и ничего не
    # доказывала: убрав блочность, я не получил ни одного сбоя.
    ровные = []
    значения_дней = [-0.6, -0.2, 0.2, 0.6]
    for н, з in enumerate(значения_дней):
        день = (datetime(2024, 3, 1, tzinfo=timezone.utc)
                + timedelta(days=н)).strftime("%Y-%m-%d")
        ровные += [{"день": день, "r_чистый": з} for _ in range(50)]

    и = прогон.бутстрэп(ровные, повторов=4000)
    ширина_факт = и["верхняя_граница"] - и["нижняя_граница"]

    сигма = statistics.pstdev(значения_дней)
    ожидание_по_дням = 2 * 1.96 * сигма / (len(значения_дней) ** 0.5)
    ожидание_по_сделкам = 2 * 1.96 * сигма / (len(ровные) ** 0.5)

    check(ширина_факт > 3 * ожидание_по_сделкам,
          "Интервал заметно ШИРЕ, чем дал бы ресемплинг отдельных сделок",
          f"факт {ширина_факт:.4f}, по сделкам было бы "
          f"{ожидание_по_сделкам:.4f}")
    check(abs(ширина_факт - ожидание_по_дням) < 0.5 * ожидание_по_дням,
          "И близок к тому, что даёт ресемплинг ДНЕЙ",
          f"факт {ширина_факт:.4f}, по дням ожидалось "
          f"{ожидание_по_дням:.4f}")


