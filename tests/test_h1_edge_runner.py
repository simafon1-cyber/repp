def _подставить(архив, границы, паспорт, прежние, корень):
    """Подменить пути в модуле прогона на тестовые.

    Результат и отметку об открытии OOS тоже уводим в тестовый каталог.
    Иначе тесты писали бы в настоящий research/ и либо портили бы
    будущий единственный прогон, либо блокировали его отметкой."""
    было = (прогон.АРХИВ, прогон.ГРАНИЦЫ, прогон.ПАСПОРТ,
            прогон.РЕЗУЛЬТАТ, прогон.МАРКЕР,
            прогон._распаковать_прежние)
    прогон.АРХИВ = str(архив)
    прогон.ГРАНИЦЫ = str(границы)
    прогон.ПАСПОРТ = str(паспорт)
    прогон.РЕЗУЛЬТАТ = str(Path(корень) / "итог" / "h1_edge_results.json")
    прогон.МАРКЕР = str(Path(корень) / "итог" / "oos_открыт.json")
    прогон._распаковать_прежние = lambda: str(прежние)
    return было


def _вернуть(было):
    (прогон.АРХИВ, прогон.ГРАНИЦЫ, прогон.ПАСПОРТ,
     прогон.РЕЗУЛЬТАТ, прогон.МАРКЕР,
     прогон._распаковать_прежние) = было


def _границы_oos(границы) -> float:
    """Самое раннее начало OOS среди инструментов, секундами."""
    д = json.loads(Path(границы).read_text(encoding="utf-8"))
    return min(datetime.fromisoformat(з["части"]["oos"]["начало_utc"]).timestamp()
               for з in д["инструменты"].values())


