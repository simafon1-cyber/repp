def test_отметка_ставится_атомарно_а_не_поверх_старой():
    """Последний рубеж одноразовости, отдельно от проверки 6.

    Проверка 6 смотрит «файл есть?» и только потом создаёт — это два
    разных действия, и между ними файл может появиться. Здесь
    проверяется САМО создание: второй вызов обязан упасть, а не
    переписать чужую отметку.

    Тест понадобился потому, что поломка «создавать режимом w» не
    роняла ни одного теста: до неё срабатывала проверка 6, и защита
    выглядела рабочей, хотя её последний рубеж был снят."""
    корень = Path(tempfile.mkdtemp(prefix="отметка_"))
    было_м, было_р = прогон.МАРКЕР, прогон.РЕЗУЛЬТАТ
    прогон.МАРКЕР = str(корень / "вложено" / "oos.json")
    прогон.РЕЗУЛЬТАТ = str(корень / "вложено" / "итог.json")
    try:
        первая = прогон._занять_oos({"хеш_паспорта": "a" * 64})
        check(Path(прогон.МАРКЕР).exists(), "Первая отметка поставлена")
        упало = False
        try:
            прогон._занять_oos({"хеш_паспорта": "b" * 64})
        except FileExistsError:
            упало = True
        check(упало, "Вторая попытка отвергнута ошибкой, а не выполнена")
        сейчас = json.loads(Path(прогон.МАРКЕР).read_text(encoding="utf-8"))
        check(сейчас["хеш_паспорта"] == первая["хеш_паспорта"] == "a" * 64,
              "И на диске осталась ПЕРВАЯ отметка",
              сейчас.get("хеш_паспорта", "")[:8])
    finally:
        прогон.МАРКЕР, прогон.РЕЗУЛЬТАТ = было_м, было_р
        shutil.rmtree(корень, ignore_errors=True)


