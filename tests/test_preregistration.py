def test_scenarios_are_ordered_from_cheap_to_expensive() -> None:
    """Высокий сценарий обязан быть ХУЖЕ базового по всем статьям.

    Иначе «неблагоприятный» местами оказался бы выгоднее, и проверка
    чувствительности ничего бы не проверяла."""
    print("\n[Высокий сценарий хуже базового по всем статьям]")
    было = costs.текущий_сценарий()
    try:
        значения = {}
        for имя in (costs.НИЗКИЙ, costs.БАЗОВЫЙ, costs.ВЫСОКИЙ):
            costs.выбрать_сценарий(имя)
            значения[имя] = {
                "комиссия": costs.комиссия(1.0),
                "спред": costs.спред_пунктов("EURUSD", 0),
                "своп_минус": costs.своп("EURUSD", 1, 1),    # отрицательный
                "своп_плюс": costs.своп("EURUSD", -1, 1),    # положительный
            }
        н, б, в = (значения[costs.НИЗКИЙ], значения[costs.БАЗОВЫЙ],
                   значения[costs.ВЫСОКИЙ])
        check(н["комиссия"] < б["комиссия"] < в["комиссия"],
              "Комиссия растёт от низкого к высокому",
              f"{н['комиссия']} / {б['комиссия']} / {в['комиссия']}")
        check(б["спред"] <= в["спред"], "Спред не уменьшается")
        check(в["своп_минус"] < б["своп_минус"] < н["своп_минус"],
              "Отрицательный своп становится ХУЖЕ",
              f"{н['своп_минус']} / {б['своп_минус']} / {в['своп_минус']}")
        check(в["своп_плюс"] < б["своп_плюс"] < н["своп_плюс"],
              "А положительный — МЕНЬШЕ, а не больше",
              f"{н['своп_плюс']} / {б['своп_плюс']} / {в['своп_плюс']}")
    finally:
        costs.выбрать_сценарий(было)


def test_an_unknown_scenario_is_refused() -> None:
    print("\n[Незнакомый сценарий отвергается]")
    было = costs.текущий_сценарий()
    try:
        costs.выбрать_сценарий("подешевле")
        check(False, "Незнакомый сценарий должен быть отвергнут")
    except ValueError as e:
        check(True, "Отвергнут")
        check("Есть:" in str(e), "И перечислены настоящие", str(e))
    finally:
        costs.выбрать_сценарий(было)
    check(costs.текущий_сценарий() == было,
          "И текущий сценарий не сбился")


