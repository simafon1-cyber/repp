def test_capture_script_refuses_without_a_terminal() -> None:
    """Скрипт выгрузки честно отказывается работать без терминала.

    Он не должен выдумывать числа или молча записывать пустой файл."""
    print("\n[Выгрузка условий отказывается работать без терминала]")
    исходник = (APP / "capture_broker_terms.py").read_text(encoding="utf-8")
    без_комментариев = "\n".join(
        с.split("#", 1)[0] for с in исходник.splitlines())
    check("ImportError" in без_комментариев,
          "Отсутствие модуля терминала обрабатывается")
    check("return 2" in без_комментариев,
          "И скрипт выходит с ошибкой, а не с успехом")
    check("КОМИССИЯ" in исходник,
          "Отдельно сказано, что комиссию терминал не отдаёт")
    check("НА МОМЕНТ ВЫГРУЗКИ" in исходник,
          "И что это условия на сегодня, а не за прошлый период")


