def test_a_changed_manifest_is_refused() -> None:
    """ГЛАВНАЯ ПРОВЕРКА. Правка после заверения ломает хеш.

    Это и есть вся защита от подгонки: подкрутить условия под увиденный
    результат нельзя, не сломав заверение."""
    print("\n[Изменённый паспорт отвергается]")
    with Папка() as f:
        путь = os.path.join(f, "m.json")
        with open(путь, "w", encoding="utf-8") as ф:
            json.dump(паспорта.заверить(полный_паспорт()), ф,
                      ensure_ascii=False)

        прочитан = паспорта.прочитать(путь)
        check(прочитан["таймфрейм"] == "H1", "Целый паспорт читается")

        # Кто-то подкрутил критерий успеха, увидев результат.
        данные = json.load(open(путь, encoding="utf-8"))
        данные["критерий_успеха"] = "ожидание > 0 хотя бы на одном отрезке"
        json.dump(данные, open(путь, "w", encoding="utf-8"),
                  ensure_ascii=False)

        try:
            паспорта.прочитать(путь)
            check(False, "Подкрученный паспорт обязан быть отвергнут")
        except SystemExit as e:
            check(True, "Подкрученный паспорт отвергнут")
            check("ИЗМЕНЁН ПОСЛЕ ЗАВЕРЕНИЯ" in str(e),
                  "И сказано, что именно случилось", str(e)[:80])


def test_hash_does_not_depend_on_key_order() -> None:
    """Один и тот же паспорт даёт один и тот же хеш.

    Иначе перезапись файла другим порядком ключей ломала бы заверение на
    ровном месте, и проверка быстро стала бы поводом её отключить."""
    print("\n[Хеш не зависит от порядка полей]")
    а = полный_паспорт()
    б = dict(reversed(list(а.items())))
    check(паспорта.хеш(а) == паспорта.хеш(б), "Хеши совпали")


def test_hash_changes_when_anything_changes() -> None:
    print("\n[Любая правка меняет хеш]")
    основа = паспорта.хеш(полный_паспорт())
    for поле, новое in (("таймфрейм", "M5"),
                        ("минимум_сделок", 50),
                        ("oos", "первые 25 %"),
                        ("сценарий_издержек", "низкий")):
        check(паспорта.хеш(полный_паспорт(**{поле: новое})) != основа,
              f"Правка «{поле}» меняет хеш")


def test_an_incomplete_manifest_is_refused() -> None:
    """Незаполненное поле — это не «пока не решили».

    Недостающее условие всегда можно дописать после того, как результат
    увиден. Прогон по неполному паспорту ничего не доказывает."""
    print("\n[Неполный паспорт отвергается]")
    for поле in ("критерий_успеха", "oos", "выход", "почему"):
        try:
            паспорта.заверить(полный_паспорт(**{поле: ""}))
            check(False, f"Пустое «{поле}» должно быть отвергнуто")
        except ValueError as e:
            check(поле in str(e), f"Пустое «{поле}» названо в ошибке", str(e))


def test_a_missing_manifest_stops_the_run() -> None:
    """Нет паспорта — прогон не начинается."""
    print("\n[Без паспорта прогон не начинается]")
