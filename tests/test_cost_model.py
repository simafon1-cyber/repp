    check(len(сделки) > 30, "Сделок достаточно", str(len(сделки)))

    обычный = entry_lab.метрики(сделки)
    н = ledger.Накопитель()
    for с in сделки:
        н.добавить(с)
    потоковый = н.итог()
    беды = ledger.сходится(обычный, потоковый, допуск=0.0)
    check(not беды, "Совпали все метрики до копейки", "; ".join(беды))


