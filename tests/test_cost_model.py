def test_swap_counts_midnights_not_hours() -> None:
    """Своп берётся за переход через полночь, а не за каждые сутки.

    Сделка может прожить два часа и всё равно заплатить своп, если эти
    два часа пришлись на полночь."""
    print("\n[Своп считается по переходам через полночь]")
    полночь = 1_700_000_000 // 86_400 * 86_400
    check(costs.ночей(полночь + 3600, полночь + 7200) == 0,
          "Час внутри суток — ноль ночей")
    check(costs.ночей(полночь + 86_000, полночь + 87_000) == 1,
          "Два часа ЧЕРЕЗ полночь — одна ночь")
    check(costs.ночей(полночь, полночь + 3 * 86_400) == 3, "Трое суток — три")
    check(costs.ночей(полночь + 100, полночь) == 0,
          "Выход раньше входа — ноль, а не отрицательное число")


