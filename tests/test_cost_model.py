def test_a_tampered_ledger_fails_the_run() -> None:
    """Подменили значение в журнале — прогон обязан упасть, а не отчитаться.

    Раньше здесь печаталась строка «ПРОГОН НЕДЕЙСТВИТЕЛЕН», и на этом
    всё: процесс завершался успешно, и расходящийся результат можно было
    принять за годный."""
    print("\n[Подменённый журнал валит прогон]")
    import run_entry_search as поиск
    ряд = ряд_из([1.1000 + (i % 17) * 0.0002 for i in range(600)])
    сделки = entry_lab.прогнать(
        ряд, entry_lab.ПРИЗНАКИ["возврат к средней 2σ"],
        seed=3, symbol="EURUSD")["признак"]
    check(len(сделки) > 10, "Сделок достаточно", str(len(сделки)))

    папка = tempfile.mkdtemp(prefix="tamper_")
    было = поиск.ФАЙЛ_ЖУРНАЛА
    было_рез = поиск.ФАЙЛ_РЕЗУЛЬТАТОВ
    try:
        путь = os.path.join(папка, "l.csv")
        поиск.ФАЙЛ_ЖУРНАЛА = путь
        поиск.ФАЙЛ_РЕЗУЛЬТАТОВ = os.path.join(папка, "r.json")
        with ledger.Журнал(путь) as ж:
            ж.записать(сделки, "TRAIN", "проверка", "признак")

        честные = entry_lab.метрики(сделки)
        в_памяти = [("TRAIN", "проверка", "EURUSD", честные)]

        # КОНТРОЛЬ: с нетронутым журналом сверка проходит.
        упало = False
        try:
            поиск.сверить_с_журналом(в_памяти)
        except RuntimeError:
            упало = True
        check(not упало, "С нетронутым журналом прогон проходит")

        # А теперь портим ОДНО значение.
        строки = open(путь, encoding="utf-8").read().splitlines()
        поля = строки[1].split(",")
        поля[22] = str(float(поля[22]) + 1.0)      # чистая_прибыль
        строки[1] = ",".join(поля)
        open(путь, "w", encoding="utf-8").write("\n".join(строки) + "\n")

        упало = False
        причина = ""
        try:
            поиск.сверить_с_журналом(в_памяти)
        except RuntimeError as e:
            упало = True
            причина = str(e)
        check(упало, "ПРОГОН УПАЛ на подменённом значении")
        check("НЕДЕЙСТВИТЕЛЕН" in причина, "И сказал почему", причина[:120])
    finally:
        поиск.ФАЙЛ_ЖУРНАЛА = было
        поиск.ФАЙЛ_РЕЗУЛЬТАТОВ = было_рез
        shutil.rmtree(папка, ignore_errors=True)


def test_missing_data_is_a_failure_not_a_quiet_exit() -> None:
    """Нет данных — прогон обязан завершиться неуспешно."""
    print("\n[Отсутствие данных — провал, а не тихий выход]")
    import ast
    исходник = (APP / "run_entry_search.py").read_text(encoding="utf-8")
    дерево = ast.parse(исходник)
    тело = next(у for у in дерево.body
                if isinstance(у, ast.FunctionDef) and у.name == "main")
    выходы = [у for у in ast.walk(тело) if isinstance(у, ast.Raise)]
    check(выходы, "В main есть аварийные завершения", str(len(выходы)))

    без_комментариев = "\n".join(
        с.split("#", 1)[0] for с in исходник.splitlines())
    check("SystemExit" in без_комментариев,
          "Отсутствие данных завершает прогон неуспешно")
    check("НЕ ХВАТАЕТ ДАННЫХ" in без_комментариев,
          "И неполный набор инструментов — тоже")


