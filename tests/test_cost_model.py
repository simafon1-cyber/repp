def test_the_run_prints_the_preregistration() -> None:
    """Условия печатаются ДО результатов, а не после.

    Условия, названные после того, как результат увиден, ничего не стоят:
    всегда найдётся период, на котором вышло красиво."""
    print("\n[Условия печатаются до результатов]")
    import ast
    исходник = (APP / "run_entry_search.py").read_text(encoding="utf-8")
    дерево = ast.parse(исходник)
    тело = next(у for у in дерево.body
                if isinstance(у, ast.FunctionDef) and у.name == "main")
    строка_условий = строка_результатов = None
    for узел in ast.walk(тело):
        if isinstance(узел, ast.Call):
            имя = getattr(узел.func, "attr", "") or getattr(узел.func, "id", "")
            if имя == "предрегистрация" and строка_условий is None:
                строка_условий = узел.lineno
            if имя == "печать_признака" and строка_результатов is None:
                строка_результатов = узел.lineno
    check(строка_условий is not None, "Предрегистрация вызывается")
    check(строка_результатов is not None, "Результаты печатаются")
    check(строка_условий < строка_результатов,
          "И условия идут РАНЬШЕ результатов",
          f"{строка_условий} против {строка_результатов}")


