def test_every_trade_carries_its_own_costs() -> None:
    """Каждая сделка несёт свои издержки, а не общую поправку."""
    print("\n[Каждая сделка несёт свои издержки]")
    ряд = ряд_из([1.1000 + i * 0.0001 for i in range(80)])
    с = entry_lab.сделка(ряд, 50, 1, "EURUSD")
    check(с is not None, "Сделка посчиталась")
    for ключ in ("грязная_прибыль", "спред", "комиссия", "своп",
                 "издержки_всего", "чистая_прибыль", "r_грязный",
                 "r_чистый", "риск_денег", "причина_выхода"):
        check(ключ in с, f"В записи есть «{ключ}»")

    check(abs(с["издержки_всего"] - (с["спред"] + с["комиссия"] - с["своп"]))
          < 1e-9, "Издержки = спред + комиссия − своп")
    check(abs(с["чистая_прибыль"] - (с["грязная_прибыль"] - с["издержки_всего"]))
          < 1e-9, "Чистая прибыль = грязная − издержки")
    check(с["r_чистый"] < с["r_грязный"],
          "И чистый результат ХУЖЕ грязного — издержки не бывают в плюс",
          f"{с['r_чистый']} против {с['r_грязный']}")


def test_costs_in_r_do_not_depend_on_the_lot() -> None:
    """Издержки в R не зависят от размера лота.

    Это важно: иначе вывод «преимущество меньше издержек» зависел бы от
    выбранного в исследовании лота, то есть от произвольного числа.
    И комиссия, и спред, и риск растут вместе с лотом одинаково."""
    print("\n[Издержки в R не зависят от лота]")
    ряд = ряд_из([1.1000 + i * 0.0001 for i in range(80)])
    один = entry_lab.сделка(ряд, 50, 1, "EURUSD", лот=1.0)
    десять = entry_lab.сделка(ряд, 50, 1, "EURUSD", лот=10.0)
    доля_1 = один["издержки_всего"] / один["риск_денег"]
    доля_10 = десять["издержки_всего"] / десять["риск_денег"]
    check(abs(доля_1 - доля_10) < 1e-9,
          "Доля издержек от риска одна и та же",
          f"{доля_1:.6f} против {доля_10:.6f}")
    check(abs(один["r_чистый"] - десять["r_чистый"]) < 1e-9,
          "И чистый результат в R тоже")


