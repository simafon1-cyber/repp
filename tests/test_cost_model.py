def test_manifest_hashes_the_data() -> None:
    """У каждого файла данных записан отпечаток.

    Без него «те самые данные» — это слова: подменили бы одну свечу, и
    совпадение чисел объяснить было бы нечем."""
    print("\n[Паспорт записывает отпечатки данных]")
    import manifest
    папка = tempfile.mkdtemp(prefix="manifest_")
    try:
        os.makedirs(os.path.join(папка, "raw"))
        os.makedirs(os.path.join(папка, "clean"))
        путь = os.path.join(папка, "clean", "EURUSD_M5.csv")
        open(путь, "w", encoding="utf-8").write("time,open\n1,1.1\n")

        записи = manifest.файлы_данных(папка, ["EURUSD"], "M5")
        очищенные = [з for з in записи if з["вид"] == "очищенные"][0]
        check(очищенные["есть"], "Существующий файл помечен как есть")
        check(len(очищенные["sha256"]) == 64, "И у него записан SHA-256")

        сырые = [з for з in записи if з["вид"] == "сырые"][0]
        check(not сырые["есть"], "Отсутствующий помечен как отсутствующий")
        check(сырые["sha256"] == "", "И отпечатка у него нет")

        # Меняем файл на один символ — отпечаток обязан измениться.
        было = очищенные["sha256"]
        open(путь, "w", encoding="utf-8").write("time,open\n1,1.2\n")
        стало = manifest.хэш(путь)
        check(было != стало, "Правка одного символа меняет отпечаток")
    finally:
        shutil.rmtree(папка, ignore_errors=True)


def test_the_run_writes_a_manifest_before_results() -> None:
    """Паспорт пишется ДО того, как посчитаны результаты."""
    print("\n[Паспорт пишется до результатов]")
    import ast
    дерево = ast.parse((APP / "run_entry_search.py").read_text(encoding="utf-8"))
    тело = next(у for у in дерево.body
                if isinstance(у, ast.FunctionDef) and у.name == "main")
    строка_паспорта = строка_результатов = None
    for узел in ast.walk(тело):
        if isinstance(узел, ast.Call):
            имя = getattr(узел.func, "attr", "") or getattr(узел.func, "id", "")
            if имя == "предрегистрация" and строка_паспорта is None:
                строка_паспорта = узел.lineno
            if имя == "печать_признака" and строка_результатов is None:
                строка_результатов = узел.lineno
    check(строка_паспорта and строка_результатов, "Оба вызова найдены")
    check(строка_паспорта < строка_результатов,
          "Паспорт раньше результатов",
          f"{строка_паспорта} против {строка_результатов}")


def test_the_data_archive_is_in_the_repository() -> None:
    """Архив истории лежит в репозитории вместе с контрольной суммой.

    Без него опубликованный прогон нельзя повторить, а значит и
    проверить. Слова «получено прогоном» без возможности этот прогон
    повторить стоят ровно столько же, сколько посчитанная вручную
    таблица, которую И6 и исправлял."""
    print("\n[Архив данных лежит в репозитории]")
    архив = ROOT / "data" / "history_M5.tar.gz"
    сумма = ROOT / "data" / "history_M5.tar.gz.sha256"
    check(архив.exists(), "Архив на месте", str(архив))
    check(сумма.exists(), "И файл с контрольной суммой")
    if архив.exists() and сумма.exists():
        import manifest
        записано = сумма.read_text(encoding="utf-8").strip()
        check(manifest.хэш(str(архив)) == записано,
              "Контрольная сумма совпадает с архивом",
              f"{manifest.хэш(str(архив))[:16]}… против {записано[:16]}…")


