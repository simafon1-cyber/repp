def test_metrics_come_from_the_ledger_not_from_a_side_note() -> None:
    """ГЛАВНАЯ ПРОВЕРКА ЧЕСТНОСТИ.

    Метрики, посчитанные в памяти, обязаны совпасть с посчитанными из
    записанного файла. Если не совпали — значит, какое-то число взялось
    не из сделок."""
    print("\n[Метрики из журнала совпадают с метриками таблицы]")
    ряд = ряд_из([1.1000 + (i % 17) * 0.0002 for i in range(600)])
    итог = entry_lab.прогнать(ряд, entry_lab.ПРИЗНАКИ["возврат к средней 2σ"],
                              seed=3, symbol="EURUSD")
    сделки = итог["признак"]
    check(len(сделки) > 20, "Сделок достаточно для проверки", str(len(сделки)))

    в_памяти = entry_lab.метрики(сделки)
    папка = tempfile.mkdtemp(prefix="ledger_")
    try:
        путь = os.path.join(папка, "l.csv")
        with ledger.Журнал(путь) as ж:
            ж.записать(сделки, "TRAIN", "проверка", "признак")
        из_файла = entry_lab.метрики(ledger.прочитать(путь))
        беды = ledger.сходится(в_памяти, из_файла)
        check(not беды, "Все метрики сошлись", "; ".join(беды))
        check(из_файла["сделок"] == len(сделки), "И число сделок то же")
    finally:
        shutil.rmtree(папка, ignore_errors=True)


def test_streaming_count_matches_the_in_memory_one() -> None:
    """Потоковый счёт обязан совпадать с обычным ДО КОПЕЙКИ.

    Иначе сверка сравнивала бы два разных расчёта и находила расхождение
    там, где его нет, — или, хуже, не находила бы настоящего."""
    print("\n[Потоковый счёт совпадает с обычным]")
