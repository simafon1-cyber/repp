def test_point_value_differs_for_usd_on_the_left() -> None:
    """У пар с долларом слева пункт стоит иначе.

    Считать их одинаково значило бы ошибиться в разы: на USDJPY при курсе
    150 пункт стоит в 150 раз меньше, чем кажется."""
    print("\n[Стоимость пункта зависит от того, где доллар]")
    check(abs(costs.стоимость_пункта("EURUSD", 1.1000, 1.0) - 1.0) < 1e-9,
          "EURUSD: 1.00 за пункт на лот",
          str(costs.стоимость_пункта("EURUSD", 1.1000, 1.0)))
    jpy = costs.стоимость_пункта("USDJPY", 150.0, 1.0)
    check(abs(jpy - 100_000 * 0.001 / 150.0) < 1e-9,
          "USDJPY: цена пункта делится на курс", str(jpy))
    check(jpy < 1.0, "И она заметно меньше единицы", str(jpy))
    check(abs(costs.стоимость_пункта("XAUUSD", 2000.0, 1.0) - 1.0) < 1e-9,
          "XAUUSD: 1.00 за пункт на лот")


