def test_trade_never_looks_past_the_end_of_its_segment() -> None:
    """ГЛАВНОЕ ПРО РАЗДЕЛЕНИЕ ВЫБОРОК.

    Сигнал брался до конца отрезка, а исход разворачивался ещё на 100
    баров дальше. Значит, последние сто входов TRAIN смотрели в бары
    VALIDATION, последние сто входов VALIDATION — в OOS. Разбиение по
    времени переставало быть независимым.

    Проверяем прямо: ни одна сделка не выходит за конец своего отрезка."""
    print("\n[Сделка не заглядывает за конец своего отрезка]")
    ряд = ряд_из([1.1000 + (i % 19) * 0.0003 for i in range(900)])
    признак = entry_lab.ПРИЗНАКИ["возврат к средней 2σ"]
    гор = entry_lab.ГОРИЗОНТ

    for начало, конец, имя in ((0, 400, "TRAIN"), (400, 650, "VALIDATION"),
                               (650, 900, "OOS")):
        итог = entry_lab.прогнать(ряд, признак, начало, конец, seed=1,
                                  symbol="EURUSD")
        сделки = итог["признак"] + итог["зеркало"] + итог["случай"]
        check(len(сделки) > 0, f"{имя}: сделки есть", str(len(сделки)))
        поздние = [с for с in сделки
                   if с["время_выхода"] > ряд["time"][конец - 1]]
        check(not поздние,
              f"{имя}: ни одна сделка не закрывается за границей отрезка",
              f"нарушителей {len(поздние)}")


def test_holding_length_is_the_same_everywhere() -> None:
    """У всех учтённых сделок одинаковый максимально возможный горизонт.

    Раньше последние входы OOS упирались в конец файла и получали
    УКОРОЧЕННЫЙ горизонт — то есть измерялись по другим правилам, чем
    остальные."""
    print("\n[Горизонт одинаков у всех учтённых сделок]")
    ряд = ряд_из([1.1000 + (i % 19) * 0.0003 for i in range(900)])
    признак = entry_lab.ПРИЗНАКИ["возврат к средней 2σ"]
    итог = entry_lab.прогнать(ряд, признак, 650, 900, seed=1, symbol="EURUSD")
    сделки = итог["признак"]
    check(сделки, "Сделки есть", str(len(сделки)))

    # У сделки, дожившей до конца горизонта, длина ровно ГОРИЗОНТ баров.
    по_горизонту = [с for с in сделки if с["причина_выхода"] == "горизонт"]
    длины = {с["баров_в_сделке"] for с in по_горизонту}
    check(len(длины) <= 1,
          "Все досидевшие до конца сделки одной длины", str(sorted(длины)))
    if длины:
        check(длины.pop() == entry_lab.ГОРИЗОНТ,
              f"И эта длина — полный горизонт ({entry_lab.ГОРИЗОНТ})")


def test_segments_do_not_share_a_single_bar() -> None:
    """Соседние отрезки не пересекаются вообще ни одним баром."""
    print("\n[Соседние отрезки не пересекаются]")
    ряд = ряд_из([1.1000 + (i % 19) * 0.0003 for i in range(900)])
    признак = entry_lab.ПРИЗНАКИ["возврат к средней 2σ"]
    первый = entry_lab.прогнать(ряд, признак, 0, 400, seed=1, symbol="EURUSD")["признак"]
    второй = entry_lab.прогнать(ряд, признак, 400, 650, seed=1, symbol="EURUSD")["признак"]
    check(первый and второй, "Сделки есть в обоих отрезках")
    граница = ряд["time"][399]
    check(max(с["время_выхода"] for с in первый) <= граница,
          "Первый отрезок кончается не позже границы")
    check(min(с["время_входа"] for с in второй) > граница,
          "А второй начинается строго после неё")


