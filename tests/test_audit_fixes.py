def test_запись_инцидента_повторяется_три_раза():
    """B6. Одна неудачная запись — обычно мелочь: антивирус, диск, облако.

    Одна попытка превращала мелочь в потерю остановки после
    перезапуска."""
    import incident
    import safe_files
    d = tempfile.mkdtemp(prefix="инц_")
    попытки = []
    было = safe_files.atomic_write_text

    def падает(*a, **k):
        попытки.append(1)
        raise OSError("диск занят")

    try:
        safe_files.atomic_write_text = падает
        записано = incident.открыть({"причина": "проверка"}, d)
        check(записано is False, "Запись не удалась — честный False",
              str(записано))
        # Число сверяется с ТРОЙКОЙ, а не с самой константой. Первая
        # версия писала `len(попытки) == incident.ПОПЫТОК_ЗАПИСИ` — и
        # проходила, даже когда константу меняли на единицу: обе стороны
        # равенства ломались вместе. Проверка, которая ломается вместе с
        # кодом, ничего не проверяет.
        check(incident.ПОПЫТОК_ЗАПИСИ == 3, "Попыток задано три",
              str(incident.ПОПЫТОК_ЗАПИСИ))
        check(len(попытки) == 3, "И их действительно было три",
              str(len(попытки)))
    finally:
        safe_files.atomic_write_text = было
    check(incident.запись_терялась(d),
          "И оставлена метка о потере доказательства")
    метка = Path(incident.путь_потери(d)).read_text(encoding="utf-8")
    check("проверка" in метка, "В метке записана причина", метка[:60])
    shutil.rmtree(d, ignore_errors=True)


