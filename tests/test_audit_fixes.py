def test_пауза_после_серии_убытков_переживает_перезапуск():
    """C1. Раньше пауза жила в памяти.

    Перезапуск снимал наказание, и программа шла торговать тем же
    инструментом. Перезапуск в такой момент как раз и вероятен.

    Наоборот: убрать паузы из snapshot — тест падает."""
    import risk_state
    from datetime import datetime, timedelta
    from state import AccountState

    class Состояние:
        pause_until = None

    d = os.path.join(tempfile.mkdtemp(prefix="риск_"), "risk.json")
    acc = AccountState()
    acc.peak_equity = 1000.0
    живая = Состояние(); живая.pause_until = datetime.now() + timedelta(hours=2)
    истекшая = Состояние(); истекшая.pause_until = datetime.now() - timedelta(hours=2)
    risk_state.save(acc, 5054028014, d,
                    sym_states={"EURUSD": живая, "GBPUSD": истекшая})

    новая1, новая2 = Состояние(), Состояние()
    вернулись = risk_state.восстановить_паузы(
        {"EURUSD": новая1, "GBPUSD": новая2}, 5054028014, d)
    check(новая1.pause_until is not None,
          "Действующая пауза вернулась после перезапуска", str(вернулись))
    check(новая2.pause_until is None,
          "А истёкшая — нет: вчерашнее наказание сегодня не значит ничего")

    # Запись без сведений о паузах не должна их стирать.
    risk_state.save(acc, 5054028014, d)
    новая3 = Состояние()
    risk_state.восстановить_паузы({"EURUSD": новая3}, 5054028014, d)
    check(новая3.pause_until is not None,
          "Сохранение без сведений о паузах их НЕ стирает")


