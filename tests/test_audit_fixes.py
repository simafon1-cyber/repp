class Позиция:
    def __init__(self, ticket=1, symbol="EURUSD", тип=0, volume=0.10,
                 price_open=1.10000, sl=1.09800, tp=0.0, magic=None):
        self.ticket = ticket
        self.symbol = symbol
        self.type = тип                  # 0 = BUY
        self.volume = volume
        self.price_open = price_open
        self.sl = sl
        self.tp = tp
        self.magic = cfg.MAGIC_NUMBER if magic is None else magic
        self.profit = 0.0


class Тик:
    def __init__(self, bid=1.10200, ask=1.10202):
        self.bid, self.ask, self.time = bid, ask, 1


class Брокер:
    """Подделка, которая ВЕДЁТ СЧЁТ: помнит позиции и изменения стопов."""

    def __init__(self, позиции=None):
        self.позиции = list(позиции or [])
        self.изменения_стопа = []        # (ticket, sl, tp)
        self.закрытия = []               # (ticket, объём)

    def modify_position(self, ticket, sl, tp):
        self.изменения_стопа.append((ticket, sl, tp))
        for п in self.позиции:
            if п.ticket == ticket:
                п.sl, п.tp = sl, tp
        return type("R", (), {"retcode": mt5c.RETCODE_DONE, "volume": 0.0})()

    def close_position_partial(self, поз, объём):
        self.закрытия.append((поз.ticket, объём))
        осталось = round(поз.volume - объём, 8)
        if осталось <= 0:
            self.позиции = [п for п in self.позиции if п.ticket != поз.ticket]
        else:
            поз.volume = осталось
        return type("R", (), {"retcode": mt5c.RETCODE_DONE,
                              "volume": объём, "deal": 555, "order": 556})()


