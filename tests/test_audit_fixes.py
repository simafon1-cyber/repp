def test_неясный_исход_НЕ_снимает_запись_о_заявке():
    """B1. ГЛАВНАЯ проверка журнала.

    «Не вижу позиции» — не доказательство отказа. Заявка могла
    исполниться, а потеряться мог только ответ. Пока исход не доказан,
    запись остаётся, и риск считается так, будто позиция есть.

    Наоборот: снимать запись при любом исходе — тест падает."""
    d = tempfile.mkdtemp(prefix="ожид_")
    try:
        ид = po.записать("EURUSD", 1, 0.10, 25.0, d)
        check(len(po.открытые(d)) == 1, "Запись сделана ДО отправки",
              str(len(po.открытые(d))))
        check(po.риск_неподтверждённых(d) == 25.0,
              "И её риск виден", str(po.риск_неподтверждённых(d)))
        # Позиции на счету нет — это НЕ повод снять запись.
        сверка = po.сверить([], d)
        check(len(сверка["пропали"]) == 1,
              "Позиции нет — запись объявлена пропавшей", str(сверка))
        check(len(po.открытые(d)) == 1,
              "И запись НЕ снята: сверка ничего не меняет",
              str(len(po.открытые(d))))
        # Только доказанный исход снимает.
        po.подтвердить(ид, 777, 0.10, d)
        check(len(po.открытые(d)) == 0, "Подтверждение сняло запись",
              str(len(po.открытые(d))))
    finally:
        shutil.rmtree(d, ignore_errors=True)


