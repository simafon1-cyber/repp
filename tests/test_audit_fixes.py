def test_хедж_требует_обе_стороны():
    """A3. Было `buy_ok or sell_ok`.

    Хватало ОДНОЙ сильной стороны — и вторая нога открывалась вопреки
    своему счёту сигнала, «за компанию». Программа открывала позицию,
    которую её же фильтр только что отверг, и платила за неё спред,
    комиссию и своп.

    Проверяется по дереву кода: логическая операция именно `and`."""
    import ast
    текст = (APP / "main.py").read_text(encoding="utf-8")
    дерево = ast.parse(текст)
    нашли = []
    for узел in ast.walk(дерево):
        if not isinstance(узел, ast.BoolOp):
            continue
        имена = {у.id for у in ast.walk(узел) if isinstance(у, ast.Name)}
        if {"buy_ok", "sell_ok"} <= имена:
            нашли.append(узел)
    check(нашли, "Условие с buy_ok и sell_ok найдено", str(len(нашли)))
    # Ищем именно ТУ операцию, которая соединяет две стороны напрямую.
    # Первая версия проверки принимала «где-то рядом есть И» — и
    # проходила даже со сломанным кодом: внешнее условие
    # `profile.get(...) and (...)` содержит И всегда, каким бы ни было
    # внутреннее. Проверка, которая не различает исправное и сломанное,
    # проверкой не является.
    прямые = [у for у in нашли
              if {getattr(з, "id", None) for з in у.values} == {"buy_ok", "sell_ok"}]
    check(len(прямые) == 1, "Стороны соединены ровно одной операцией",
          str(len(прямые)))
    check(прямые and isinstance(прямые[0].op, ast.And),
          "И это И, а не ИЛИ",
          type(прямые[0].op).__name__ if прямые else "не найдено")
    # Проверка по тексту здесь была бы слепой ошибкой: пояснение рядом с
    # правкой цитирует прежнее условие `buy_ok or sell_ok`, и текстовый
    # поиск ловил бы собственный комментарий. Первая версия теста именно
    # так и падала. Смотрим только дерево кода.
    через_или = []
    for узел in нашли:
        for в in ast.walk(узел):
            if isinstance(в, ast.BoolOp) and isinstance(в.op, ast.Or):
                имена = {у.id for у in ast.walk(в) if isinstance(у, ast.Name)}
                if {"buy_ok", "sell_ok"} <= имена:
                    через_или.append(в)
    check(not через_или,
          "И условия «любая из сторон» в дереве кода не осталось",
          str(len(через_или)))


