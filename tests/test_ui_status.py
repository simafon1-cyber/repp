# 1. МОЛЧАНИЯ НЕ БЫВАЕТ
# =====================================================================
def test_когда_всё_хорошо_программа_всё_равно_говорит():
    """Пустое место человек читает как «программа молчит».

    Молчание он уже однажды принял за зависание — поэтому «помех нет»
    надо СКАЗАТЬ, а не показать пустоту.

    Наоборот: убрать ветку «если сказать нечего» — тест падает."""
    строки = st.собрать({"live_trading": True})
    check(len(строки) >= 1, "Список не пустой", str(строки))
    check(строки[0]["важность"] == st.СПОКОЙНО,
          "И это спокойное сообщение", строки[0]["важность"])
    check("разрешена" in строки[0]["заголовок"].lower(),
          "Сказано, что торговля разрешена", строки[0]["заголовок"])
    check("не поломку" in весь_текст(строки),
          "И объяснено, что отсутствие сделок — не поломка")
    check(st.торговля_остановлена(строки) is False,
          "Торговля не считается остановленной")


