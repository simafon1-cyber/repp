def test_самое_важное_идёт_первым():
    """Если бед несколько, человек должен прочитать главную сразу.

    Наоборот: убрать сортировку по важности — тест падает."""
    снимок = {"live_trading": False,
              "positions": [{"ticket": 5, "sl": 0.0, "is_bot": True}]}
    строки = st.собрать(снимок, на_паузе=True, инцидент_открыт=True,
                        инцидент_причина="проверка")
    важности = [с["важность"] for с in строки]
    check(важности == sorted(важности, key=lambda в: st.ПОРЯДОК[в]),
          "Строки отсортированы по важности", str(важности))

    # И отдельно — на ЗАВЕДОМО перемешанном списке.
    #
    # Без этого проверка проходила по совпадению: внутри собрать() строки
    # и так добавляются по убыванию важности, поэтому убери сортировку —
    # список выглядит точно так же. Поймано собственной проверкой
    # «наоборот»: поломка не уронила ни одного теста.
    перемешано = [
        {"важность": st.СПОКОЙНО, "заголовок": "в"},
        {"важность": st.СТОП, "заголовок": "а"},
        {"важность": st.ВНИМАНИЕ, "заголовок": "б"},
    ]
    стало = [с["заголовок"] for с in st.упорядочить(перемешано)]
    check(стало == ["а", "б", "в"],
          "Перемешанный список упорядочивается по важности", str(стало))
    check(важности[0] == st.СТОП, "Первой идёт причина «сделок не будет»",
          важности[0])
    check(st.одной_строкой(строки) == строки[0]["заголовок"],
          "Одной строкой берётся именно первая")


