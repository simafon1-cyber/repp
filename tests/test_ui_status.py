"""ЧТО СЕЙЧАС С ТОРГОВЛЕЙ — ПОНЯТНО ЛИ ЭТО ЧЕЛОВЕКУ.

ПОЧЕМУ ЭТИ ТЕСТЫ ПОЯВИЛИСЬ

У программы несколько защит, из-за которых сделок не будет: незакрытое
происшествие, потерянная отметка о нём, позиция без стоп-лосса,
неподтверждённые заявки, пауза, выключенный LIVE_TRADING. Каждая защита
правильная.

Но узнать о них было неоткуда. В окне писалось «Работает», а причина
лежала в журнале или в ленте последних ТРЁХ событий, откуда её вытесняло
следующее сообщение. Владелец видел работающую программу без сделок и
решал, что она зависла — так и написал: «нет отклика, виснет».

ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ ПО ФАКТУ

Не «функция что-то вернула», а что именно человек прочитает: названа ли
причина, стоит ли она первой, и не молчит ли программа, когда сказать
нечего.

ЧЕГО ЭТИ ТЕСТЫ НЕ ПРОВЕРЯЮТ

Как это выглядит на экране: цвет, шрифт, перенос строк. Проверяется
СОДЕРЖАНИЕ и ПОРЯДОК. Вид проверяется отдельно — контрастом в
test_ui_theme.py.

Запуск:  python3 tests/test_ui_status.py
"""

from __future__ import annotations

import sys
from pathlib import Path

BASE = Path(__file__).resolve().parent
ROOT = BASE.parent
APP = ROOT / "ai_scalper_standalone"
sys.path.insert(0, str(APP))

passed = 0
failed = 0


def check(ok: bool, name: str, detail: str = "") -> None:
    global passed, failed
    if ok:
        passed += 1
        print(f"  OK   {name}")
    else:
        failed += 1
        print(f"  СБОЙ {name}" + (f" -> {detail}" if detail else ""))


import ui_status as st            # noqa: E402


def заголовки(строки):
    return [с["заголовок"] for с in строки]


def весь_текст(строки):
    return " ".join(с["заголовок"] + " " + с.get("пояснение", "")
                    for с in строки)


