def test_модуль_ничего_не_меняет():
    """Наблюдатель не имеет права трогать наблюдаемое."""
    import ast
    дерево = ast.parse((APP / "ui_status.py").read_text(encoding="utf-8"))
    имена = set()
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.Attribute):
            имена.add(узел.attr)
        elif isinstance(узел, ast.Name):
            имена.add(узел.id)
    for опасное in ("order_send", "close_position_partial", "снять_инцидент",
                    "set_paused", "LIVE_TRADING", "открыть_инцидент"):
        check(опасное not in имена, f"Не трогает {опасное}")
    # Единственный разрешённый ввоз — __future__: он ничего не делает,
    # а лишь включает современную запись подсказок типов. Всё остальное
    # означало бы, что модуль куда-то ходит за данными; ему незачем.
    ввозы = []
    for у in ast.walk(дерево):
        if isinstance(у, ast.ImportFrom) and у.module == "__future__":
            continue
        if isinstance(у, (ast.Import, ast.ImportFrom)):
            ввозы.append(ast.unparse(у))
    check(not ввозы, "Ничего лишнего не импортирует — данные приходят снаружи",
          str(ввозы))

    # Снимок не должен меняться от того, что мы его прочитали.
    снимок = {"live_trading": True, "positions": [
        {"ticket": 1, "sl": 0.0, "is_bot": True}]}
    копия = {"live_trading": True, "positions": [
        {"ticket": 1, "sl": 0.0, "is_bot": True}]}
    st.собрать(снимок)
    check(снимок == копия, "Снимок после чтения не изменился", str(снимок))


def test_битый_снимок_не_роняет_разбор():
    """Окно не должно падать из-за странных данных."""
    for плохой in ({}, {"positions": None}, {"positions": [{}]},
                   {"positions": [{"sl": "нет", "is_bot": True}]}, None):
        try:
            строки = st.собрать(плохой)
            check(bool(строки), f"Разобрано без падения: {плохой}")
        except Exception as e:  # noqa: BLE001
            check(False, f"Разобрано без падения: {плохой}",
                  f"{type(e).__name__}: {e}")


def main() -> int:
    print("=" * 70)
    print("ЧТО СЕЙЧАС С ТОРГОВЛЕЙ: ПОНЯТНОСТЬ ДЛЯ ЧЕЛОВЕКА")
    print("=" * 70)
    for имя, ф in sorted(globals().items()):
        if имя.startswith("test_") and callable(ф):
            print(f"\n--- {имя}")
            try:
                ф()
            except Exception as e:  # noqa: BLE001
                check(False, f"{имя} доработала до конца",
                      f"{type(e).__name__}: {str(e).splitlines()[0]}")
    print("\n" + "=" * 70)
    print(f"Пройдено: {passed}   Сбоев: {failed}")
    print("=" * 70)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
