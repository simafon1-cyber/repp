def test_незакрытое_происшествие_названо_первым():
    """Это главная причина: сделок не будет вообще."""
    строки = st.собрать({"live_trading": True},
                        инцидент_открыт=True,
                        инцидент_причина="ответ брокера неясен")
    check(строки[0]["важность"] == st.СТОП, "Первая строка — стоп",
          строки[0]["важность"])
    check("происшествие" in строки[0]["заголовок"].lower(),
          "Названо происшествие", строки[0]["заголовок"])
    check("ответ брокера неясен" in весь_текст(строки),
          "И приведена причина, а не общие слова")
    check(st.торговля_остановлена(строки), "Торговля считается остановленной")


def test_потерянная_отметка_названа_отдельно():
    """Отдельный случай: файла инцидента нет, а происшествие было."""
    строки = st.собрать({"live_trading": True}, запись_терялась=True)
    текст = весь_текст(строки)
    check(any(с["важность"] == st.СТОП for с in строки), "Это стоп")
    check("потерян" in текст.lower(), "Сказано, что отметка потеряна", текст[:80])
    check("инцидент_не_записан" in текст,
          "И названо имя файла, который надо удалить после разбора")


def test_позиция_без_стопа_названа_с_номером():
    """Человеку нужен номер позиции, а не «риск превышен».

    Иначе непонятно, что чинить в терминале."""
    снимок = {"live_trading": True, "positions": [
        {"ticket": 12345, "sl": 0.0, "is_bot": True},
        {"ticket": 999, "sl": 1.09, "is_bot": True},
    ]}
    строки = st.собрать(снимок)
    текст = весь_текст(строки)
    check(any(с["важность"] == st.СТОП for с in строки), "Это стоп")
    check("12345" in текст, "Номер позиции без стопа назван", текст[:90])
    check("999" not in текст, "А позиция со стопом не упомянута")
    check("поставьте стоп" in текст.lower(),
          "И сказано, что делать")


def test_чужая_позиция_без_стопа_не_считается_нашей_бедой():
    """Сделка владельца без стопа — его решение.

    Новые входы бота она не блокирует, и пугать ею нельзя: так же
    считает и торговый цикл (rm.позиции_без_стопа фильтрует по magic)."""
    снимок = {"live_trading": True,
              "positions": [{"ticket": 777, "sl": 0.0, "is_bot": False}]}
    строки = st.собрать(снимок)
