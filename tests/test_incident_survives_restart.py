class Папка:
    """Отдельная папка на каждую проверку — чтобы они не мешали друг другу."""

    def __enter__(self):
        self.path = tempfile.mkdtemp(prefix="incident_")
        return self.path

    def __exit__(self, *a):
        shutil.rmtree(self.path, ignore_errors=True)


def перезапуск(folder: str) -> Control:
    """ЧЕСТНЫЙ перезапуск: память выбрасывается целиком.

    Новый объект Control ничего не знает о прошлой жизни. Всё, что он
    может узнать, — то, что лежит на диске."""
    новый = Control()
    новый.перечитать_инцидент(folder)
    return новый


СВЕДЕНИЯ = {"символ": "EURUSD", "вид": "исполнение",
            "причина": "не выяснено, открылась сделка или нет"}


