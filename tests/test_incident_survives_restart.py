"""И2: ОСТАНОВКА, ПЕРЕЖИВАЮЩАЯ ПЕРЕЗАПУСК.

ПОЧЕМУ ЭТИ ТЕСТЫ ПОЯВИЛИСЬ

Работа И1 научила программу останавливаться, когда положение заявки не
выяснено. Остановка делалась так:

    control.set_paused(True)

Это переменная в памяти. Программа перезапустилась — переменная исчезла, и
торговля пошла дальше как ни в чём не бывало.

То есть защита работала ровно до первого перезапуска. А перезапуск в такой
момент как раз и вероятен: программу перезапускают именно тогда, когда с
ней что-то не так.

ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ

Перезапуск изображается честно: состояние в памяти выбрасывается целиком
(создаётся НОВЫЙ объект Control), остаётся только то, что успело лечь на
диск. Если бы отметка жила в памяти, ни один тест ниже не прошёл бы.

Запуск:  python3 tests/test_incident_survives_restart.py
"""

