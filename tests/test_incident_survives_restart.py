def test_program_never_clears_the_incident_by_itself() -> None:
    """Программа не снимает инцидент нигде.

    Проверка структурная: она ловит вызов, который допишут завтра, даже
    если поведенческого случая для него не будет."""
    print("\n[В программе нет ни одного самостоятельного снятия]")
    вызовы = []
    for файл in sorted(APP.glob("*.py")):
        if файл.name in ("incident.py", "control.py"):
            continue
        текст = файл.read_text(encoding="utf-8")
        без_комментариев = "\n".join(
            с.split("#", 1)[0] for с in текст.splitlines())
        if "снять_инцидент" in без_комментариев or "incident.снять" in без_комментариев:
            вызовы.append(файл.name)
    check(not вызовы,
          "Снятие инцидента не вызывается из торгового кода", str(вызовы))

    # А в control.py — только внутри именованного метода, и нигде больше.
    текст = (APP / "control.py").read_text(encoding="utf-8")
    без_комментариев = "\n".join(
        с.split("#", 1)[0] for с in текст.splitlines())
    check(без_комментариев.count("incident.снять") == 1,
          "И в пульте вызов ровно один — в методе снятия",
          str(без_комментариев.count("incident.снять")))


