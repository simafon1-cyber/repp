def test_incident_survives_a_restart() -> None:
    """ГЛАВНАЯ ПРОВЕРКА ВСЕГО И2."""
    print("\n[Инцидент переживает перезапуск]")
    with Папка() as f:
        было = Control()
        check(not было.is_paused(), "До инцидента торговля разрешена")

        записано = было.открыть_инцидент(СВЕДЕНИЯ, f)
        check(записано, "Отметка записана на диск")
        check(было.is_paused(), "И торговля сразу остановлена")

        # Программу выключили и включили.
        стало = перезапуск(f)
        check(стало.is_paused(),
              "ПОСЛЕ ПЕРЕЗАПУСКА ТОРГОВЛЯ ПО-ПРЕЖНЕМУ ОСТАНОВЛЕНА")
        check(стало.инцидент_открыт(), "И инцидент виден как незакрытый")
        check("не выяснено" in стало.инцидент().get("причина", ""),
              "Причина сохранилась дословно", str(стало.инцидент()))


