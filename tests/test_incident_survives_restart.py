def test_trading_loop_opens_an_incident_not_a_memory_pause() -> None:
    """В торговом коде остановка делается инцидентом, а не переменной."""
    print("\n[Торговый цикл открывает инцидент, а не паузу в памяти]")
    import ast
    исходник = (APP / "main.py").read_text(encoding="utf-8")
    дерево = ast.parse(исходник)

    # Разбор ПО ДЕРЕВУ, а не по тексту: в пояснениях старый вызов
    # упоминается нарочно, и текстовая проверка ловила бы сама себя.
    # На комментариях это уже попадалось, а здесь то же самое случилось
    # со строкой документации, которую «слепота к #» не убирает.
    паузы, инциденты, перечитывания = [], [], []
    for узел in ast.walk(дерево):
        if not isinstance(узел, ast.Call):
            continue
        имя = ""
        if isinstance(узел.func, ast.Attribute):
            имя = узел.func.attr
        elif isinstance(узел.func, ast.Name):
            имя = узел.func.id
        if имя == "set_paused":
            значение = узел.args[0] if узел.args else None
            if isinstance(значение, ast.Constant) and значение.value is True:
                паузы.append(узел.lineno)
        elif имя == "_открыть_инцидент":
            инциденты.append(узел.lineno)
        elif имя == "перечитать_инцидент":
            перечитывания.append(узел.lineno)

    check(not паузы,
          "Остановки в памяти в торговом коде не осталось", str(паузы))
    check(len(инциденты) >= 2,
          "Вместо неё открывается инцидент — во всех местах остановки",
          str(инциденты))
    check(len(перечитывания) == 1,
          "А при запуске отметка читается с диска, ровно один раз",
          str(перечитывания))

    # И проверка при старте идёт ДО подготовки к торговле: иначе первый
    # обход успел бы открыть позицию прежде, чем программа узнает об
    # инциденте. Ищем внутри тела main(), а не по всему файлу — те же
    # имена встречаются и в других функциях.
    тело_main = next(у for у in дерево.body
                     if isinstance(у, ast.FunctionDef) and у.name == "main")
    строки = {"перечитать": None, "символы": None}
    for узел in ast.walk(тело_main):
        if isinstance(узел, ast.Call):
            имя = getattr(узел.func, "attr", "") or getattr(узел.func, "id", "")
            if имя == "перечитать_инцидент" and строки["перечитать"] is None:
                строки["перечитать"] = узел.lineno
            if имя == "init_states" and строки["символы"] is None:
                строки["символы"] = узел.lineno
    check(строки["перечитать"] is not None,
          "Проверка при старте вызывается внутри main()")
    check(строки["символы"] is not None, "Подготовка символов найдена")
    check(строки["перечитать"] < строки["символы"],
          "И она идёт РАНЬШЕ подготовки к торговле",
          f"инцидент на строке {строки['перечитать']}, "
          f"символы на {строки['символы']}")


