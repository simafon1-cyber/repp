ВРЕМЯ_СЕРВЕРА = 1_700_000_000       # то же, что отдаёт _Тик


def _вход_в_историю(order=5001, position_id=5001, volume=0.01,
                    тип=0, сдвиг=1.0, symbol="EURUSD"):
    """Сделка ВХОДА, случившаяся через сдвиг секунд после отправки."""
    return _Сделка(order, position_id, symbol, тип, volume,
                   cfg.MAGIC_NUMBER, ВРЕМЯ_СЕРВЕРА + сдвиг, entry=0)


def _в_поясе(смещение: str, что_делать):
    """Выполнить проверку в заданном часовом поясе.

    Ошибка часового пояса не видна, пока часы машины стоят на UTC: там
    местное время и UTC совпадают, и неверный код выглядит верным."""
    import os
    import time as _time
    было = os.environ.get("TZ")
    os.environ["TZ"] = смещение
    try:
        _time.tzset()
        return что_делать()
    finally:
        if было is None:
            os.environ.pop("TZ", None)
        else:
            os.environ["TZ"] = было
        _time.tzset()


def test_history_window_is_built_in_utc() -> None:
    """Т14. Часы машины НЕ на UTC — окно истории обязано остаться верным.

    Терминал отдаёт время в UTC и запросы понимает как UTC. Наивное
    местное время уехало бы на разницу поясов: у пользователя в UTC−6
    окно ушло бы на шесть часов назад, история вернулась бы пустой, и
    программа решила бы «сделки не было». А сделка была."""
    print("\n[Т14. Окно истории строится в UTC, а не по местным часам]")

    def проверка():
        сброс()
        брокер.шаг(TIMEOUT, доля=1.0, применить=False)
        # Позиция открылась и тут же закрылась: среди открытых её нет,
        # в истории — есть, ровно в правильной UTC-точке.
        брокер.история.append(_вход_в_историю())
        причина = прогнать()
        return причина, list(брокер.окна)

    причина, окна = _в_поясе("Etc/GMT+6", проверка)   # UTC−6

    check(bool(окна), "Историю действительно спрашивали", str(окна))
    if окна:
        начало, конец = окна[-1]
        check(начало <= ВРЕМЯ_СЕРВЕРА + 1.0 <= конец,
              "И окно накрывает момент сделки по времени СЕРВЕРА",
              f"окно {начало}..{конец}, сделка {ВРЕМЯ_СЕРВЕРА + 1.0}")
        check(abs(начало - (ВРЕМЯ_СЕРВЕРА - 5.0)) < 1.0,
              "Окно не уехало на разницу часовых поясов",
              f"начало {начало}, ожидалось {ВРЕМЯ_СЕРВЕРА - 5.0}")
    check(control.is_paused(),
          "Сделка найдена в истории — торговля ОСТАНОВЛЕНА, а не «отказ»")
    check("не выяснен" in причина.lower(), "И причина названа", repr(причина))
    control.set_paused(False)


