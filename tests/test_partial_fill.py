class Брокер:
    """Счёт, который меняется от заявок. Ответы задаются сценарием.

    Каждый шаг сценария — это (код ответа, доля исполнения, применять ли
    изменение к счёту). Третье поле нужно для TIMEOUT: там ответ не
    приходит, а на счету изменение может и произойти, и не произойти —
    именно эту развилку тесты и проверяют."""

    def __init__(self):
        self.позиции = {}
        self.история = []
        self.следующий = 1000
        self.сценарий = []
        self.заявки = []
        self.позиции_ломаются = False
        self.история_ломается = False
        self.окна = []              # какие границы времени у нас спрашивали

    def шаг(self, код=DONE, доля=1.0, применить=True):
        self.сценарий.append((код, доля, применить))
        return self

    # --- то, что вызывает программа ---------------------------------
    def order_send(self, req):
        self.заявки.append(dict(req))
        код, доля, применить = (self.сценарий.pop(0) if self.сценарий
                                else (DONE, 1.0, True))
        объём = round(req["volume"] * доля, 2)
        тикет = 0

        if применить and объём > 0:
            if req.get("position"):
                # Закрытие: уменьшаем существующую позицию.
                p = self.позиции.get(int(req["position"]))
                if p is not None:
                    p.volume = round(p.volume - объём, 2)
                    if p.volume <= 1e-9:
                        del self.позиции[p.ticket]
                тикет = int(req["position"])
            else:
                self.следующий += 1
                тикет = self.следующий
                тип = 0 if req["type"] == 0 else 1
                self.позиции[тикет] = _Позиция(
                    тикет, req["symbol"], тип, объём,
                    req.get("magic", 0), 1_700_000_100 + len(self.заявки))

        if код is None:
            return None
        return _Ответ(код, объём if применить else 0.0, тикет)

    def history_deals_get(self, *a, **k):
        """Модель history_deals_get из MetaTrader5.

        ГЛАВНОЕ В ЭТОЙ ПОДДЕЛКЕ — КАК ОНА ПОНИМАЕТ ВРЕМЯ. Терминал считает
        метки времени UTC и наивный datetime трактует как UTC, а НЕ как
        местное время. Именно поэтому наивное местное время уезжает на
        разницу часовых поясов, и именно это здесь воспроизводится: без
        такой модели ошибка часового пояса не проявилась бы вовсе —
        fromtimestamp() и .timestamp() свернулись бы обратно.
        """
        if self.история_ломается:
            return None
        if k.get("ticket"):
            return [d for d in self.история if d.order == int(k["ticket"])]
        if k.get("position"):
            return [d for d in self.история
                    if d.position_id == int(k["position"])]
        границы = list(a)[:2]
        if len(границы) < 2:
            return list(self.история)
        начало, конец = (_в_epoch(границы[0]), _в_epoch(границы[1]))
        self.окна.append((начало, конец))
        return [d for d in self.история if начало <= d.time <= конец]

    def positions_get(self, **k):
        if self.позиции_ломаются:
            return None
        symbol = k.get("symbol")
        return [p for p in self.позиции.values()
                if symbol is None or p.symbol == symbol]

    def объёмы(self, symbol=None):
        return sorted(round(p.volume, 2) for p in self.позиции.values()
                      if symbol is None or p.symbol == symbol)


def _в_epoch(момент):
    """Как это делает терминал: наивное время — UTC, а не местное."""
    from datetime import datetime as _dt, timezone as _tz
    if isinstance(момент, _dt):
        if момент.tzinfo is None:
            момент = момент.replace(tzinfo=_tz.utc)
        return момент.timestamp()
    return float(момент)


