#!/usr/bin/env python3
"""ЧЕРНОВИК С-001 ОТКРЫВАЕТСЯ ТОЛЬКО ЗАВЕРЕННЫМ ПАСПОРТОМ.

ПОЧЕМУ ЭТОТ НАБОР ПОЯВИЛСЯ

Раньше черновик был закрыт наглухо: список его не показывал, кнопка
отказывала. Владелец принял паспорт, и запрет надо было снять. Снять
запрет «просто так» — значит убрать регламент вместе с ним: дальше
кто угодно и когда угодно включает непроверенную версию.

Поэтому запрет не снят, а ПРИВЯЗАН к паспорту. И привязка должна
держать не только случай «паспорта нет», но и случай «паспорт есть, но
его подправили в блокноте» — иначе разрешение себе можно выписать
самому.

ЧТО ПРОВЕРЯЕТСЯ ПО ФАКТУ

Паспорт на диске портится по-настоящему (файл переписывается), после
чего спрашивается настоящая функция программы. Проверяется решение —
пускать или нет, — а не наличие кода.

ЧЕГО ЭТОТ НАБОР НЕ ПРОВЕРЯЕТ

Что стратегия прибыльна: паспорт этого не утверждает и утверждать не
может.
Что она правильно отработает у настоящего брокера: терминала здесь нет.

Запуск:  python3 tests/test_c001_passport.py
"""

from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

BASE = Path(__file__).resolve().parent
ROOT = BASE.parent
APP = ROOT / "ai_scalper_standalone"
sys.path.insert(0, str(BASE))
sys.path.insert(0, str(APP))

passed = 0
failed = 0


def check(ok: bool, name: str, detail: str = "") -> None:
    global passed, failed
    if ok:
        passed += 1
        print(f"  OK   {name}")
    else:
        failed += 1
        print(f"  СБОЙ {name}" + (f"  -> {detail}" if detail else ""))


import strategies as st  # noqa: E402

ПАСПОРТ = Path(st.путь_паспорта("c001_simple"))
КОПИЯ = ПАСПОРТ.with_suffix(".json.проверка")


def вернуть_как_было():
    if КОПИЯ.exists():
        shutil.move(str(КОПИЯ), str(ПАСПОРТ))


def test_целый_паспорт_пускает():
    print("\n[Паспорт на месте и печать сходится]")
    можно, почему = st.паспорт_заверен("c001_simple")
    check(можно, "С-001 разрешена к применению", почему)
    check(any("С-001" in t for t in st.titles()),
          "И показана в списке выбора")


def test_паспорта_нет():
    print("\n[Паспорта нет]")
    shutil.move(str(ПАСПОРТ), str(КОПИЯ))
    try:
        можно, почему = st.паспорт_заверен("c001_simple")
        check(not можно, "Без паспорта не пускает")
        check("не найден" in почему, "И сказано, что именно не так", почему)
        check(not any("С-001" in t for t in st.titles()),
              "И из списка выбора она пропала")
    finally:
        вернуть_как_было()


def test_печать_убрали():
    print("\n[Паспорт есть, но печати нет]")
    shutil.copy(str(ПАСПОРТ), str(КОПИЯ))
    try:
        d = json.loads(ПАСПОРТ.read_text(encoding="utf-8"))
        d.pop("хеш_паспорта", None)
        ПАСПОРТ.write_text(json.dumps(d, ensure_ascii=False, indent=2),
                           encoding="utf-8")
        можно, почему = st.паспорт_заверен("c001_simple")
        check(not можно, "Без печати не пускает")
        check("печати нет" in почему, "И сказано, что печати нет", почему)
    finally:
        вернуть_как_было()


def test_паспорт_подправили():
    """Главная проверка. Печать существует, но содержимое другое."""
    print("\n[Паспорт подправили после заверения]")
    shutil.copy(str(ПАСПОРТ), str(КОПИЯ))
    try:
        d = json.loads(ПАСПОРТ.read_text(encoding="utf-8"))
        было = d["демо_приёмка"]["минимум_закрытых_сделок"]
        d["демо_приёмка"]["минимум_закрытых_сделок"] = "1"
        ПАСПОРТ.write_text(json.dumps(d, ensure_ascii=False, indent=2),
                           encoding="utf-8")
        можно, почему = st.паспорт_заверен("c001_simple")
        check(not можно,
              "Подправленный паспорт НЕ пускает "
              f"(минимум сделок подменён с «{str(было)[:12]}...» на «1»)")
        check("НЕ СХОДИТСЯ" in почему,
              "И названа причина — печать не сходится", почему)
        check(not any("С-001" in t for t in st.titles()),
              "И из списка выбора она пропала")
    finally:
        вернуть_как_было()


def test_паспорт_испорчен():
    print("\n[Файл паспорта нечитаем]")
    shutil.copy(str(ПАСПОРТ), str(КОПИЯ))
    try:
        ПАСПОРТ.write_text("{это не json", encoding="utf-8")
        можно, почему = st.паспорт_заверен("c001_simple")
        check(not можно, "Нечитаемый паспорт не пускает")
        check("не читается" in почему, "И сказано, что не читается", почему)
    finally:
        вернуть_как_было()


def test_черновик_остался_черновиком():
    """Разрешение применить — не то же самое, что «стратегия готова»."""
    print("\n[С-001 по-прежнему помечена как черновик]")
    check(st.черновик("c001_simple"),
          "В коде она остаётся черновиком, а не рабочей стратегией")
    check("c001_simple" in st.ЧЕРНОВИКИ, "И числится в списке черновиков")


def main() -> int:
    print("=" * 62)
    print("ТЕСТЫ: С-001 ОТКРЫВАЕТСЯ ТОЛЬКО ЗАВЕРЕННЫМ ПАСПОРТОМ")
    print("=" * 62)
    try:
        test_целый_паспорт_пускает()
        test_паспорта_нет()
        test_печать_убрали()
        test_паспорт_подправили()
        test_паспорт_испорчен()
        test_черновик_остался_черновиком()
    finally:
        вернуть_как_было()
    print("\n" + "=" * 70)
    print(f"Пройдено: {passed}   Сбоев: {failed}")
    print("=" * 70)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
