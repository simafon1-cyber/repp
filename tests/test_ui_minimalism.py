#!/usr/bin/env python3
"""ОКНО: МИНИМАЛИЗМ. Чего владелец в окне видеть не должен.

ОТКУДА ЭТО ВЗЯЛОСЬ

Владелец, дословно: «Делаем максимально минимализм в управлении
программы, убрать вкладку торговля быстрые настройки… Оставить только
выбор стратегии… вкладки риски защита тоже можно убрать сигналы,
обучение убрать».

ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ ПО ФАКТУ

Окно собирается по-настоящему (подделка tkinter), и у блокнота
спрашивается, какие страницы В НЁМ ОТКРЫТЫ. Проверяется не «есть ли в
исходнике нужная строчка», а что страницы действительно нет на виду.

ПОЧЕМУ СПРЯТАНО, А НЕ УДАЛЕНО

В разделе «Риск» лежат стопы и тейк-профиты, в «Защите» — демо-приёмка.
Правило проекта: «все правки торговой логики должны быть обратимыми».
Стереть единственную дорогу к этим значениям — правка, которую нельзя
откатить. Поэтому в простом режиме их не видно совсем, а переключатель
«Продвинутый» возвращает их на место. Ниже это проверяется в обе
стороны.

ЧЕГО ЭТИ ТЕСТЫ НЕ ПРОВЕРЯЮТ

Как окно ВЫГЛЯДИТ. Подделка не рисует и не считает пиксели. И не
проверяют поведение у настоящего брокера — здесь брокера нет вовсе.

Запуск:  python3 tests/test_ui_minimalism.py
"""

from __future__ import annotations

import ast
import sys
from pathlib import Path

BASE = Path(__file__).resolve().parent
ROOT = BASE.parent
APP = ROOT / "ai_scalper_standalone"
sys.path.insert(0, str(APP))
sys.path.insert(0, str(BASE))

passed = 0
failed = 0


def check(ok: bool, name: str, detail: str = "") -> None:
    global passed, failed
    if ok:
        passed += 1
        print(f"  OK   {name}")
    else:
        failed += 1
        print(f"  СБОЙ {name}" + (f" -> {detail}" if detail else ""))


import run_baseline            # noqa: E402  (заглушка MetaTrader5)
import поддельный_tk as пт     # noqa: E402

for _имя, _модуль in пт.собрать_модули().items():
    sys.modules[_имя] = _модуль

import desktop_app as da       # noqa: E402


СПРЯТАННЫЕ = ("Риск", "Защита", "Обучение", "Профили")


def собрать_окно():
    """Собрать интерфейс, не запуская программу."""
    пт.сброс()
    окно = object.__new__(da.App)
    окно.root = sys.modules["tkinter"].Tk()
    окно._apply_theme()
    окно.stop_event = None
    окно.bot_thread = None
    окно._bot_should_run = False
    окно.tray_icon = None
    окно._dashboard_started = False
    окно.chat_history = []
    окно._auto_update_busy = False
    окно._start_bot_waits = 0
    окно._build_ui()
    return окно


# =====================================================================
def test_в_простом_режиме_разделов_риска_и_защиты_не_видно():
    print("\n[Простой режим: лишних разделов нет]")
    окно = собрать_окно()
    книга = getattr(окно, "config_sub", None)
    check(книга is not None, "Блокнот вкладки «Настройка» найден")
    if книга is None:
        return
    открытые = книга.открытые_вкладки()
    check(bool(открытые), "У блокнота вообще есть открытые страницы",
          str(открытые))
    for имя in СПРЯТАННЫЕ:
        check(имя not in открытые, f"Раздела «{имя}» в простом режиме нет",
              str(открытые))
    check("Стратегия" in открытые,
          "Выбор стратегии остался — владелец просил его оставить",
          str(открытые))
    check("Быстрый старт" not in открытые,
          "Страницы «Быстрый старт» больше нет", str(открытые))


def test_продвинутый_режим_возвращает_разделы():
    """Обратимость. Спрятать без возможности вернуть — так нельзя."""
    print("\n[Продвинутый режим возвращает всё на место]")
    окно = собрать_окно()
    книга = getattr(окно, "config_sub", None)
    if книга is None:
        check(False, "Блокнот вкладки «Настройка» найден")
        return
    окно.ui_mode_var.set("Продвинутый")
    окно._apply_ui_mode()
    открытые = книга.открытые_вкладки()
    for имя in СПРЯТАННЫЕ:
        check(имя in открытые, f"Раздел «{имя}» вернулся", str(открытые))

    # И снова убирается.
    окно.ui_mode_var.set("Простой")
    окно._apply_ui_mode()
    открытые = книга.открытые_вкладки()
    for имя in СПРЯТАННЫЕ:
        check(имя not in открытые, f"Раздел «{имя}» снова спрятан",
              str(открытые))


def test_выбора_риска_в_окне_больше_нет():
    """Владелец: «убрать выбор совсем». Значит и кода, который его
    применял, быть не должно — иначе он однажды вернётся на экран."""
    print("\n[Выбор риска убран вместе с кодом]")
    check(not hasattr(da.App, "QUICK_PRESETS"),
          "Список карточек-режимов удалён")
    check(not hasattr(da.App, "_apply_quick_preset"),
          "Код «применить режим» удалён")
    check(not hasattr(da.App, "_quick_preset_by_value"),
          "Поиск карточки по значению удалён")

    окно = собрать_окно()
    подписи = [к["подпись"] for к in пт.КНОПКИ]
    плохие = [п for п in подписи
              if "Применить режим" in п or "Применить профиль" in п]
    check(not плохие, "Кнопок «Применить режим/профиль» в окне нет",
          str(плохие))


def test_окно_не_отправляет_в_несуществующий_раздел():
    """Надпись «меняется в Настройка → Риск» после того, как раздел
    спрятан, — это указание дороги, которой нет.

    Проверка слепа к комментариям: разбирается дерево кода, а строки
    берутся только те, что реально показываются человеку."""
    print("\n[Не посылаем туда, куда в простом режиме не попасть]")
    текст = (APP / "desktop_app.py").read_text(encoding="utf-8")
    дерево = ast.parse(текст)
    строки = [у.value for у in ast.walk(дерево)
              if isinstance(у, ast.Constant) and isinstance(у.value, str)]
    беда = []
    for с in строки:
        for имя in ("«Риск»", "«Защита»", "«Обучение»", "«Профили»"):
            if f"«Настройка» → {имя}" in с and "Продвинут" not in с:
                беда.append(с[:70])
    check(not беда,
          "Ни одна надпись не отправляет в спрятанный раздел молча",
          str(беда[:2]))


def main() -> int:
    print("=" * 70)
    print("ОКНО: МИНИМАЛИЗМ — ЧЕГО ВЛАДЕЛЕЦ ВИДЕТЬ НЕ ДОЛЖЕН")
    print("=" * 70)
    for имя, ф in sorted(globals().items()):
        if имя.startswith("test_") and callable(ф):
            print(f"\n--- {имя}")
            try:
                ф()
            except Exception as e:  # noqa: BLE001
                check(False, f"{имя} доработала до конца",
                      f"{type(e).__name__}: {str(e).splitlines()[0]}")
    print("\n" + "=" * 70)
    print(f"Пройдено: {passed}   Сбоев: {failed}")
    print("=" * 70)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
