def test_нормальная_стратегия_принимается():
    """Если бы не принималась ни одна, все запреты ниже ничего не значили."""
    print("\n[Нормальная запись проходит]")
    готовые, замечания = sf.разобрать(файл(ХОРОШАЯ))
    check(len(готовые) == 1, "Одна стратегия принята", str(замечания))
    if not готовые:
        return
    s = готовые[0]
    check(s.key == "test_online", "Ключ сохранён", s.key)
    check(s.params == {"USE_SCORE_FILTER": True, "RISK_REWARD_RATIO": 2.0},
          "Настройки сохранены", str(s.params))
    check("Загружена из репозитории" in s.caution
          or "Загружена из репозитория" in s.caution,
          "К предупреждению приписано происхождение", s.caution[-60:])
    check("НЕ проверялась" in s.caution,
          "И сказано, что вместе с программой она не проверялась")


