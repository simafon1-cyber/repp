"""СТРАТЕГИИ ИЗ РЕПОЗИТОРИЯ: ЧТО ФАЙЛУ ИЗ СЕТИ ПОЗВОЛЕНО, А ЧТО НЕТ.

ОТКУДА ЭТО

Владелец, дословно: «сделай, чтобы стратегии они хранились на гитхабе и
чтобы программа просто делала запрос… чтобы не приходилось каждый раз
обновление делать самой программы сборки, пускай она просто подтягивает…
раз в пять часов».

ГЛАВНОЕ, ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ

Не «скачалось ли», а ЧТО ФАЙЛУ ИЗ СЕТИ ПОЗВОЛЕНО. Кто управляет файлом —
управляет настройками торговли. Поэтому проверяется по факту, что
отбрасывается запись, которая пытается:

  * менять размер сделки и лимиты убытка;
  * включать реальную торговлю или зеркало;
  * подменять репозиторий обновлений, токен, пароль, путь;
  * трогать предторговый барьер и номер счёта;
  * задавать настройку, которой у программы нет;
  * переопределить встроенную стратегию своим ключом;
  * подсунуть значением список или словарь вместо числа.

И отдельно — что ни одна скачанная стратегия не включается сама.

ЧЕГО ЭТИ ТЕСТЫ НЕ ПРОВЕРЯЮТ

Сеть. Здесь её нет: файл подставляется текстом. Проверяется разбор и
защита, а не то, что GitHub ответит.

Запуск:  python3 tests/test_strategies_feed.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

BASE = Path(__file__).resolve().parent
ROOT = BASE.parent
APP = ROOT / "ai_scalper_standalone"
sys.path.insert(0, str(APP))

passed = 0
failed = 0


def check(ok: bool, name: str, detail: str = "") -> None:
    global passed, failed
    if ok:
        passed += 1
        print(f"  OK   {name}")
    else:
        failed += 1
        print(f"  СБОЙ {name}" + (f" -> {detail}" if detail else ""))


import run_baseline              # noqa: E402
import strategies as st          # noqa: E402
import strategies_feed as sf     # noqa: E402


ХОРОШАЯ = {
    "key": "test_online",
    "title": "Проверочная из сети",
    "idea": "берётся из файла в репозитории",
    "when": "только для проверки",
    "caution": "прибыльность не проверена",
    "params": {"USE_SCORE_FILTER": True, "RISK_REWARD_RATIO": 2.0},
}


def файл(*стратегии) -> str:
    return json.dumps({"версия": 1, "стратегии": list(стратегии)},
                      ensure_ascii=False)


def _с(**правки) -> dict:
    з = json.loads(json.dumps(ХОРОШАЯ))
    for имя, значение in правки.items():
        if имя == "params":
            з["params"] = значение
        else:
            з[имя] = значение
    return з


