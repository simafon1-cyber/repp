def test_подтягивание_ничего_не_применяет():
    """ГЛАВНАЯ проверка замысла: список пополняется, выбор — за человеком.

    Проверяется по дереву кода: в модуле подтягивания не должно быть ни
    записи в настройки, ни переключения активной стратегии."""
    print("\n[Скачанное ничего не включает само]")
    import ast
    текст = (APP / "strategies_feed.py").read_text(encoding="utf-8")
    дерево = ast.parse(текст)
    запретные = ("_write_config_value", "set_risk_profile", "start_bot",
                 "выбрать_стратегию", "применить")
    найдено = []
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.Call):
            имя = getattr(узел.func, "attr", None) or getattr(узел.func, "id", "")
            if имя in запретные:
                найдено.append(имя)
    check(not найдено, "Модуль ничего не применяет и не запускает",
          str(найдено))

    # ACTIVE_STRATEGY в модуле упоминается — и это ПРАВИЛЬНО: имя стоит
    # в списке запретов. Проверка должна отличать «стоит в запрете» от
    # «модуль его меняет», иначе она ловит собственную защиту.
    внутри_запрета = set()
    for узел in дерево.body:
        if isinstance(узел, ast.FunctionDef) and узел.name == "запрещённые_имена":
            внутри_запрета = {getattr(у, "lineno", 0) for у in ast.walk(узел)}
    снаружи = [getattr(у, "lineno", 0) for у in ast.walk(дерево)
               if isinstance(у, ast.Constant) and у.value == "ACTIVE_STRATEGY"
               and getattr(у, "lineno", 0) not in внутри_запрета]
    check(not снаружи,
          "ACTIVE_STRATEGY упоминается только в списке запретов",
          f"строки {снаружи}")
    check(bool(внутри_запрета),
          "И список запретов в модуле действительно есть")


def test_частота_не_меньше_часа():
    """Ноль или отрицательное значение означали бы «дёргать без передышки»."""
    print("\n[Частота опроса разумна]")
    import types
    for значение, ждём in ((5, 5.0), (0, 1.0), (-3, 1.0), ("мусор", 5.0),
                           (None, 5.0)):
        cfg = types.SimpleNamespace(STRATEGY_FEED_HOURS=значение)
        check(sf.часов_между_проверками(cfg) == ждём,
              f"{значение!r} -> {ждём} ч",
              str(sf.часов_между_проверками(cfg)))


def test_файл_в_репозитории_на_месте_и_читается():
    print("\n[Файл стратегий в репозитории читается программой]")
    путь = ROOT / sf.ФАЙЛ_В_РЕПОЗИТОРИИ
    check(путь.exists(), "Файл на месте", str(путь))
    if not путь.exists():
        return
    готовые, замечания = sf.разобрать(путь.read_text(encoding="utf-8"))
    check(not замечания, "Разбирается без замечаний", str(замечания))
    check(isinstance(готовые, list), "И даёт список стратегий")


def main() -> int:
    print("=" * 70)
    print("СТРАТЕГИИ ИЗ РЕПОЗИТОРИЯ: ЧТО ФАЙЛУ ИЗ СЕТИ ПОЗВОЛЕНО")
    print("=" * 70)
    for имя, ф in sorted(globals().items()):
        if имя.startswith("test_") and callable(ф):
            print(f"\n--- {имя}")
            try:
                ф()
            except Exception as e:  # noqa: BLE001
                check(False, f"{имя} доработала до конца",
                      f"{type(e).__name__}: {str(e).splitlines()[0]}")
    print("\n" + "=" * 70)
    print(f"Пройдено: {passed}   Сбоев: {failed}")
    print("=" * 70)
    return 1 if failed else 0


