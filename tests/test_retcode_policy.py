def test_every_code_has_a_human_explanation() -> None:
    """У каждого кода в таблице есть объяснение по-русски."""
    print("\n[У каждого кода есть человеческое объяснение]")
    пустые = [к for к, (_, текст) in retcodes.ТАБЛИЦА.items()
              if not текст.strip()]
    check(not пустые, "Пустых объяснений нет", str(пустые))

    латиница = [к for к, (_, текст) in retcodes.ТАБЛИЦА.items()
                if not any("а" <= с.lower() <= "я" for с in текст)]
    check(not латиница, "Все объяснения по-русски", str(латиница))

    check("не хватает" in retcodes.объяснение(10019),
          "10019 объяснён понятно", retcodes.объяснение(10019))
    check("рынок закрыт" in retcodes.объяснение(10018),
          "10018 объяснён понятно", retcodes.объяснение(10018))
    check("10019" in retcodes.объяснение(10019),
          "И сам код тоже показан — чтобы искать в документации брокера")


def test_the_explanation_reaches_the_result() -> None:
    """Объяснение попадает в итог заявки, а не теряется."""
    print("\n[Объяснение доходит до итога заявки]")
    итог = ex.разобрать(_Ответ(10019), 0.10)
    check(итог.статус == ex.ОТКАЗ, "Отказ", итог.статус)
    check("не хватает" in итог.пояснение,
          "И в пояснении сказано, чего именно", итог.пояснение)

    итог = ex.разобрать(_Ответ(10019, comment="Not enough money"), 0.10)
    check("Not enough money" in итог.пояснение,
          "Комментарий брокера тоже сохраняется", итог.пояснение)


