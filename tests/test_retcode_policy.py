"""И4–И5: ПОЛИТИКА ОТВЕТОВ ТОРГОВОГО СЕРВЕРА.

ПОЧЕМУ ЭТИ ТЕСТЫ ПОЯВИЛИСЬ

Программа знала четыре кода из сорока с лишним. Всё остальное сваливалось
в один мешок «отказ». Это плохо двумя разными способами.

ПЕРВЫЙ, ЧЕЛОВЕЧЕСКИЙ. В журнале писалось «ошибка 10019», и владельцу
приходилось искать, что это значит. А это «на счёте не хватает денег».

ВТОРОЙ, ОПАСНЫЙ. Незнакомый код считался отказом, а отказ разрешает идти
дальше и открывать следующую сделку. Но незнакомый код на то и
незнакомый, что неизвестно, исполнилась заявка или нет. Считать его
отказом — то же самое, что считать отказом молчание брокера: порок,
разобранный в И1-C.

ГЛАВНОЕ, ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ

Что незнакомый ответ попадает в «неопределённость», а не в «отказ», и что
повторяются только временные отказы.

Запуск:  python3 tests/test_retcode_policy.py
"""

