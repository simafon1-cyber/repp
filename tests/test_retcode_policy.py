def test_unknown_code_is_uncertainty_not_a_rejection() -> None:
    """ГЛАВНАЯ ПРОВЕРКА.

    Осторожность несимметрична намеренно: лишняя сверка стоит одного
    запроса к терминалу, а неверный вывод «отказ» — неучтённой позиции."""
    print("\n[Незнакомый ответ — неопределённость, а не отказ]")
    for код in (12345, 19999, 0, -7):
        check(retcodes.класс(код) == retcodes.НЕОПРЕДЕЛЁННО,
              f"Код {код}: неопределённость", retcodes.класс(код))
        check(not retcodes.окончательный(код),
              f"Код {код}: НЕ окончательный отказ")
        check(not retcodes.повторять(код),
              f"Код {код}: и повторять его нельзя")

    итог = ex.разобрать(_Ответ(12345), 0.10)
    check(итог.статус == ex.НЕИЗВЕСТНО,
          "И разбор ответа отвечает «неизвестно»", итог.статус)
    check(not итог.решено, "Положение дел считается невыясненным")


def test_unreadable_code_is_uncertainty_too() -> None:
    print("\n[Нечитаемый код — тоже неопределённость]")
