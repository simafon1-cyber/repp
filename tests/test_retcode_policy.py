def test_the_four_classes_are_separated() -> None:
    """Окончательный отказ, повтор, частичное и неопределённость."""
    print("\n[Четыре класса ответа разделены]")
    ожидание = {
        10009: retcodes.ИСПОЛНЕНО,
        10010: retcodes.ЧАСТИЧНО,
        10004: retcodes.ПОВТОРИТЬ,        # реквот
        10020: retcodes.ПОВТОРИТЬ,        # цена изменилась
        10021: retcodes.ПОВТОРИТЬ,        # нет котировок
        10024: retcodes.ПОВТОРИТЬ,        # слишком много запросов
        10019: retcodes.ОКОНЧАТЕЛЬНО,     # нет денег
        10018: retcodes.ОКОНЧАТЕЛЬНО,     # рынок закрыт
        10016: retcodes.ОКОНЧАТЕЛЬНО,     # стопы близко
        10046: retcodes.ОКОНЧАТЕЛЬНО,     # хедж запрещён
        10008: retcodes.НЕОПРЕДЕЛЁННО,    # заявка размещена
        10012: retcodes.НЕОПРЕДЕЛЁННО,    # ответа нет
        10031: retcodes.НЕОПРЕДЕЛЁННО,    # нет связи
        10023: retcodes.НЕОПРЕДЕЛЁННО,    # состояние заявки изменилось
        10028: retcodes.НЕОПРЕДЕЛЁННО,    # заявка занята обработкой
    }
    for код, класс in ожидание.items():
        check(retcodes.класс(код) == класс,
              f"{код} → {класс}", retcodes.класс(код))


def test_placed_is_never_a_rejection() -> None:
    """PLACED переводится «заявка размещена», а не «отклонена».

    Это тот самый код, с которого начался блокер И1-C."""
    print("\n[«Заявка размещена» не считается отказом]")
    check(retcodes.класс(10008) == retcodes.НЕОПРЕДЕЛЁННО, "Неопределённость")
    check("НЕ отказ" in retcodes.объяснение(10008),
          "И объяснение говорит об этом прямо", retcodes.объяснение(10008))


def test_retry_covers_only_temporary_refusals() -> None:
    """Повторяются только временные отказы.

    Неопределённость сюда не входит: там повтор опаснее всего — первая
    заявка могла исполниться, и вторая удвоила бы позицию."""
    print("\n[Повторяются только временные отказы]")
    check(retcodes.повторять(10004), "Реквот повторяется")
    check(not retcodes.повторять(10019), "«Нет денег» — нет")
    check(not retcodes.повторять(10012), "Молчание сервера — НЕТ")
    check(not retcodes.повторять(10008), "«Заявка размещена» — НЕТ")
    check(not retcodes.повторять(12345), "Незнакомый код — НЕТ")


