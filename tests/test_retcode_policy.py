def test_order_changed_and_locked_are_uncertainty() -> None:
    """10023 и 10028 — не отказ и не повод для повтора.

    В документации MetaTrader 5 они описаны как «Order state changed» и
    «Request locked for processing». Ни то, ни другое не утверждает, что
    заявка НЕ исполнена — в отличие от «отклонена», «отменена» или
    «неверная заявка».

    Считать их окончательным отказом — разрешить открыть следующую сделку
    поверх, возможно, уже исполненной заявки. Считать поводом для повтора
    — отправить вторую заявку поверх первой. Оба варианта дают ровно тот
    вред, который закрывался в И1-C для незнакомых кодов."""
    print("\n[10023 и 10028 — неопределённость]")
    for код, имя in ((10023, "состояние заявки изменилось"),
                     (10028, "заявка занята обработкой")):
        check(retcodes.класс(код) == retcodes.НЕОПРЕДЕЛЁННО,
              f"{код} ({имя}): неопределённость", retcodes.класс(код))
        check(not retcodes.окончательный(код),
              f"{код}: НЕ окончательный отказ")
        check(not retcodes.повторять(код),
              f"{код}: и повторять его НЕЛЬЗЯ")
        check("сверить" in retcodes.объяснение(код),
              f"{код}: объяснение зовёт сверяться",
              retcodes.объяснение(код))

        итог = ex.разобрать(_Ответ(код, order=555), 0.10)
        check(итог.статус == ex.НЕИЗВЕСТНО,
              f"{код}: разбор ответа даёт «неизвестно»", итог.статус)
        check(итог.тикет == 555,
              f"{код}: номер заявки сохранён — по нему и будут сверять",
              str(итог.тикет))


