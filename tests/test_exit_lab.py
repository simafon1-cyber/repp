def test_exit_is_decided_by_order_not_by_maximum() -> None:
    """ПОЧЕМУ ЭТО ПЕРВОЕ. Сравнивать «максимум в плюс» с «максимумом в минус»
    нельзя: за восемь часов цена успевает сходить и туда, и сюда, и оба
    максимума окажутся большими. Значение имеет ТОЛЬКО порядок: что случилось
    раньше. Ошибка здесь превратила бы убыточную систему в прибыльную на
    бумаге."""
    print("\n[Выход решается порядком движения, а не максимумами]")

    # Стоп 2 ATR, цель 1R = 2 ATR. Сначала идёт вниз до стопа, потом вверх.
    вниз_сначала = путь([(0.5, 2.5, -2.5), (5.0, 0.0, 5.0)])
    и = exit_lab.simulate_one(вниз_сначала, 2.0, 1.0)
    check(и["exit"] == "стоп" and и["r"] == -1.0,
          "Сначала стоп — значит стоп, сколько бы цена ни выросла потом",
          f"{и['exit']} {и['r']}")
    check(и["bars"] == 1, "И закрылась она на первом же баре", str(и["bars"]))

    # Тот же путь, но наоборот.
    вверх_сначала = путь([(2.5, 0.5, 2.5), (0.0, 5.0, -5.0)])
    и = exit_lab.simulate_one(вверх_сначала, 2.0, 1.0)
    check(и["exit"] == "цель" and и["r"] == 1.0,
          "Сначала цель — значит цель", f"{и['exit']} {и['r']}")

    # Ни то, ни другое: закрытие по времени, по последней цене.
    ничего = путь([(0.5, 0.5, 0.3), (0.8, 0.4, 0.6)])
    и = exit_lab.simulate_one(ничего, 2.0, 1.0)
    check(и["exit"] == "по времени", "Ничего не задето — выход по времени")
    check(abs(и["r"] - 0.6 / 2.0) < 1e-9,
          "И результат считается по последней цене закрытия", str(и["r"]))


def test_intrabar_ambiguity_is_handled_three_ways() -> None:
    """Если в ОДНОМ баре задет и стоп, и цель — по четырём ценам бара
    невозможно узнать, что было раньше. Это не мелочь: именно на таких барах
    и держится разница между «система убыточна» и «система прибыльна»."""
    print("\n[Спорный бар считается тремя способами]")
    спорный = путь([(3.0, 3.0, 0.0)])

    худший = exit_lab.simulate_one(спорный, 2.0, 1.0, "worst")
    лучший = exit_lab.simulate_one(спорный, 2.0, 1.0, "best")
    check(худший["r"] == -1.0, "Худший сценарий берёт стоп", str(худший["r"]))
    check(лучший["r"] == 1.0, "Лучший берёт цель", str(лучший["r"]))
    check(худший.get("спорный") and лучший.get("спорный"),
          "И оба помечают бар как спорный")

    # Нейтральный — случайный, но воспроизводимый.
    import random
    оба = set()
    for зерно in range(20):
        и = exit_lab.simulate_one(спорный, 2.0, 1.0, "neutral",
                                  random.Random(зерно))
        оба.add(и["r"])
    check(оба == {-1.0, 1.0},
          "Нейтральный сценарий даёт оба исхода", str(sorted(оба)))
    повтор = [exit_lab.simulate_one(спорный, 2.0, 1.0, "neutral",
                                    random.Random(7))["r"] for _ in range(5)]
    check(len(set(повтор)) == 1,
          "Но при одном зерне ответ всегда один — иначе замер невоспроизводим")

    # Спорных баров не должно быть там, где их быть не может.
    просторный = путь([(0.1, 3.0, -3.0)])
    check(not exit_lab.simulate_one(просторный, 2.0, 1.0, "worst").get("спорный"),
          "Обычный стоп спорным не считается")


def test_spread_is_charged_once_and_only_once() -> None:
    """ПОЧЕМУ ЭТОТ ТЕСТ ПОЯВИЛСЯ. Спред вычитался ДВАЖДЫ.

    Цена входа в записанном пути уже сдвинута на спред — вход по худшей
    стороне, ровно как в живой программе. Значит ход цены отсчитывается от
    уже невыгодной точки. Отдельный вычет спреда сверх этого был двойной
    платой: при стопе в 1 ATR она доходила до 0.08R на сделку и превращала
    честный ноль в заметный минус. Случайные входы из-за неё «теряли» 0.1R
    там, где терять было нечего, — и сравнение с ними было бы нечестным."""
    print("\n[Спред вычитается ровно один раз]")
    со_спредом = путь([(3.0, 0.0, 3.0)], spread_atr=0.2)
    и = exit_lab.simulate_one(со_спредом, 2.0, 1.0)
    check(и["r"] == 1.0,
          "Второй раз спред не вычитается — он уже в цене входа", str(и["r"]))

    # А добавочные издержки (комиссия, своп) — вычитаются, их в данных нет.
    и = exit_lab.simulate_one(со_спредом, 2.0, 1.0, extra_cost_r=0.05)
    check(abs(и["r"] - 0.95) < 1e-9,
          "Добавочные издержки вычитаются", str(и["r"]))

    убыток = путь([(0.0, 3.0, -3.0)], spread_atr=0.2)
    и = exit_lab.simulate_one(убыток, 2.0, 1.0, extra_cost_r=0.05)
    check(abs(и["r"] - (-1.05)) < 1e-9,
          "И при убытке тоже — иначе убыток занижен", str(и["r"]))

    # ГЛАВНОЕ: у честной монеты при симметричных стопе и цели ожидание ноль.
    # Если бы спред вычитался дважды, ноль превратился бы в минус.
    вверх = путь([(1.5, 0.2, 1.5)], spread_atr=0.2)
    вниз = путь([(0.2, 1.5, -1.5)], spread_atr=0.2)
    r = [exit_lab.simulate_one(п, 1.0, 1.0)["r"] for п in (вверх, вниз)]
    check(abs(sum(r)) < 1e-9,
          "Симметричная пара даёт ровно ноль, а не минус", str(r))


