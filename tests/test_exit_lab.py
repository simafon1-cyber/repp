def test_best_cell_needs_enough_trades() -> None:
    """Без ограничения по числу сделок «лучшей» окажется клетка с десятком
    сделок и случайно красивым числом. Это самый простой способ обмануть
    себя при переборе."""
    print("\n[Лучшая клетка не выбирается из десятка сделок]")
    поверхность = {
        (1.0, 0.5): exit_lab.stats_r([5.0] * 8),          # блеск, но 8 сделок
        (2.0, 1.0): exit_lab.stats_r([0.1] * 150),        # скромно, но 150
    }
    ключ, св, хватило = exit_lab.best_cell(поверхность, минимум_сделок=100)
    check(ключ == (2.0, 1.0), "Выбрана клетка с достаточной выборкой", str(ключ))
    check(хватило, "И это отмечено")

    только_мелкие = {(1.0, 0.5): exit_lab.stats_r([5.0] * 8)}
    _, _, хватило = exit_lab.best_cell(только_мелкие, минимум_сделок=100)
    check(not хватило,
          "Если больших выборок нет вовсе — об этом сказано, а не умолчано")


def test_recorded_path_never_touches_decisions() -> None:
    """Запись пути — это взгляд в будущее относительно бара входа. Она
    допустима РОВНО потому, что не участвует ни в одном решении. Если бы
    участвовала, весь расчёт был бы подделкой."""
    print("\n[Запись будущего не участвует ни в одном решении]")
    src = (APP / "baseline_engine.py").read_text(encoding="utf-8")

    # Запись идёт ПОСЛЕ того, как позиция уже создана.
    место_входа = src.index('открытая = {')
    место_записи = src.index('пути.append(_записать_путь(')
    check(место_записи > место_входа,
          "Путь сделки пишется после решения о входе, а не до него")

    # А контрольная группа пишется ДО всех фильтров — на то она и случайная.
    место_случайных = src.index('случайные.append(_записать_путь(')
    check(место_случайных < место_входа,
          "Случайный вход берётся до фильтров — иначе он не случайный")
    тело_run = src[src.index("def run("):src.index("def _записать_путь(")]
    check("случайные[" not in тело_run and "in случайные" not in тело_run,
          "И контрольная группа внутри прогона тоже только пополняется")

    # И нигде не читается внутри прогона.
    тело = src[src.index("def run("):src.index("def _записать_путь(")]
    check(тело.count("пути.append(") == 1,
          "Список путей только пополняется — ровно в одном месте",
          str(тело.count("пути.append(")))
    check("пути[" not in тело, "Из него не читают по индексу")
    check("in пути" not in тело, "И не перебирают внутри прогона")
    check("len(пути)" not in тело, "И даже длину его не спрашивают")

    # Прогон без записи и с записью даёт ОДИНАКОВЫЕ сделки.
    ряд = []
    цена = 1.1
    for i in range(700):
        цена += 0.0001 if i % 3 else -0.0001
        ряд.append({"time": 1_700_000_000 + i * 300, "open": цена,
                    "high": цена + 0.0002, "low": цена - 0.0002,
                    "close": цена, "tick_volume": 100, "spread": 2,
                    "real_volume": 0})
    мета = {"point": 0.00001, "digits": 5, "volume_min": 0.01,
            "volume_max": 100.0, "volume_step": 0.01, "trade_tick_value": 1.0,
            "trade_tick_size": 0.00001, "trade_contract_size": 100000.0,
            "stops_level": 0, "money_per_point_per_lot": 1.0,
            "server_utc_offset_hours": 0.0}
    без = baseline_engine.run("EURUSD", ряд, мета)
    с = baseline_engine.run("EURUSD", ряд, мета, record_horizon=50)
    check([t["money"] for t in без["trades"]] == [t["money"] for t in с["trades"]],
          "Сделки с записью и без записи совпадают копейка в копейку")
    check(len(с["paths"]) >= len(с["trades"]),
          "Путей записано не меньше, чем сделок",
          f"{len(с['paths'])} и {len(с['trades'])}")
    check(без["paths"] == [], "Без просьбы пути не пишутся вовсе")

    # КОНТРОЛЬНАЯ ГРУППА ТОЖЕ НИ НА ЧТО НЕ ВЛИЯЕТ. Случайные входы не
    # торгуются: они не занимают позицию, не пополняют окно автообучения и не
    # двигают счёт. Если бы влияли — сравнение «наши против случайных»
    # сравнивало бы систему саму с собой.
    сл = baseline_engine.run("EURUSD", ряд, мета, record_horizon=50,
                             record_random=0.3, random_seed=1)
    check([t["money"] for t in без["trades"]] == [t["money"] for t in сл["trades"]],
          "Со случайными входами сделки те же самые")
    check(len(сл["random_paths"]) > 0, "Но контрольная группа записана",
          str(len(сл["random_paths"])))
    check(без["random_paths"] == [], "А без просьбы её нет")

    # Стороны у случайных входов обе — иначе это не случайность.
    стороны = {п["direction"] for п in сл["random_paths"]}
    check(стороны == {1, -1}, "И берутся обе стороны", str(стороны))

    # Одно зерно — один и тот же набор. Иначе замер невоспроизводим.
    сл2 = baseline_engine.run("EURUSD", ряд, мета, record_horizon=50,
                              record_random=0.3, random_seed=1)
    check([п["entry_time"] for п in сл["random_paths"]]
          == [п["entry_time"] for п in сл2["random_paths"]],
          "При одном зерне контрольная группа повторяется в точности")


