sys.path.insert(0, str(APP))

passed = 0
failed = 0


def check(ok: bool, name: str, detail: str = "") -> None:
    global passed, failed
    if ok:
        passed += 1
        print(f"  OK   {name}")
    else:
        failed += 1
        print(f"  СБОЙ {name}" + (f"  -> {detail}" if detail else ""))


import run_baseline  # noqa: E402  (заглушка MetaTrader5)
import поддельный_tk as пт  # noqa: E402

for _имя, _модуль in пт.собрать_модули().items():
    sys.modules[_имя] = _модуль

import desktop_app as da  # noqa: E402
import reconcile  # noqa: E402


class Пульт:
    """Пульт с известным вердиктом. Настоящий пошёл бы в терминал."""

    def __init__(self, есть_инцидент, вердикт):
        self._есть = есть_инцидент
        self._вердикт = вердикт
        self.снимали = False
        self.снимали_принудительно = False
        self.кто = ""

    def инцидент(self):
        return {"причина": "4 заявки без позиции"} if self._есть else {}

    def сверить_инцидент(self):
        return self._вердикт

    def разрешить_инцидент(self, кто="", комментарий="", folder=""):
        self.снимали = True
        return True, self._вердикт

    def снять_инцидент(self, кто="", комментарий="", folder="",
                       по_доказательству=False):
        self.снимали_принудительно = True
        self.кто = кто
        return True


def нажать(есть_инцидент, вердикт, ответ_человека=True):
    """Нажать кнопку и вернуть (пульт, что показали)."""
    пт.сброс()
    пт.ОТВЕТ_ЧЕЛОВЕКА["да"] = ответ_человека
    пульт = Пульт(есть_инцидент, вердикт)
    было = da.control
    da.control = пульт
    окно = object.__new__(da.App)
    окно._огоньки = {}
    окно._недавно_нажато = {}
    try:
        окно.разобрать_происшествие()
    finally:
        da.control = было
    return пульт, list(пт.СООБЩЕНИЯ)


def test_нет_происшествия():
    print("\n[Происшествия нет]")
    пульт, показали = нажать(False, None)
    check(not пульт.снимали, "Снимать нечего — и не снимали")
    check(показали, "Человеку что-то сказали", str(показали))


def test_исход_не_доказан_запрет_остаётся():
    """Главная проверка."""
    print("\n[Исход НЕ доказан]")
    вердикт = reconcile.Вердикт(
        reconcile.НЕ_ВЫЯСНЕНО,
        ["позиции по заявке 12345 не видно",
         "в истории сделок заявки 12345 нет"],
        "проверьте счёт в терминале")
    пульт, показали = нажать(True, вердикт, ответ_человека=False)
    check(not пульт.снимали,
          "ЗАПРЕТ НЕ СНЯТ САМА ПРОГРАММА — «позиции не вижу» ей не довод")
    check(not пульт.снимали_принудительно,
          "И принудительно тоже не снят: человека спросили, он отказался")
    текст = " ".join(str(с) for с in показали)
    check("12345" in текст, "Человеку показаны факты с номером заявки")
    check("НЕ ДОКАЗАН" in текст, "И сказано прямо, что исход не доказан")


def test_не_доказан_человек_отказался_снимать():
    """Отказался брать ответственность — запрет остаётся."""
    print("\n[Исход НЕ доказан, человек отказался снимать]")
    вердикт = reconcile.Вердикт(reconcile.НЕ_ВЫЯСНЕНО,
                                ["номер заявки в инциденте не записан"])
    пульт, показали = нажать(True, вердикт, ответ_человека=False)
    check(not пульт.снимали_принудительно, "Запрет НЕ снят")
    текст = " ".join(str(с) for с in показали)
    check("оставлен" in текст.lower(), "И сказано, что ничего не изменено")


def test_не_доказан_человек_взял_ответственность():
    """Выход из запрета должен существовать: запрет, который нельзя снять,
    это не предохранитель, а поломка."""
    print("\n[Исход НЕ доказан, человек берёт ответственность]")
    вердикт = reconcile.Вердикт(reconcile.НЕ_ВЫЯСНЕНО,
                                ["номер заявки в инциденте не записан"])
    сняли = {"сколько": 0}
    import pending_orders
    было = pending_orders.снять_человеком

    def подделка(кто, комментарий="", folder=""):
        сняли["сколько"] = 4
        сняли["кто"] = кто
        return 4

    pending_orders.снять_человеком = подделка
    try:
        пульт, показали = нажать(True, вердикт, ответ_человека=True)
    finally:
        pending_orders.снять_человеком = было
    check(пульт.снимали_принудительно, "Запрет снят принудительно")
    check(not пульт.снимали, "И именно принудительно, а не «по доказательству»")
    check(сняли["сколько"] == 4,
          "Вместе с запретом списаны и сами неподтверждённые заявки",
          str(сняли))
    текст = " ".join(str(с) for с in показали)
    check("присматривайте" in текст.lower(),
          "И человека предупредили, чем это может обернуться", текст[:80])


def test_человек_отказался():
    print("\n[Исход доказан, но человек нажал «нет»]")
