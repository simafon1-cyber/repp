#!/usr/bin/env python3
"""КНОПКА «РАЗОБРАТЬ ПРОИСШЕСТВИЕ» НЕ СНИМАЕТ ЗАПРЕТ БЕЗ ДОКАЗАТЕЛЬСТВА.

ПОЧЕМУ ЭТОТ НАБОР ПОЯВИЛСЯ

Механизм разбора был написан целиком: программа умеет сходить на счёт,
посмотреть позиции, активные заявки, историю заявок и историю сделок и
снять запрет, только если исход ДОКАЗАН. Вызвать его было нечем — ни
кнопки в окне, ни на дашборде. У владельца торговля встала на «в журнале
осталось 4 отправленных заявок, которым НЕ нашлось позиции на счету», и
снять это он не мог никак.

Кнопка появилась. Вместе с ней появился и риск: кнопка, которая снимает
запрет «чтобы не мешал», хуже, чем отсутствие кнопки.

ЧТО ПРОВЕРЯЕТСЯ ПО ФАКТУ

Вызывается настоящий обработчик кнопки при разных вердиктах, и
проверяется, ЧТО ОН СДЕЛАЛ: снял запрет или нет. Не текст, а действие.

ЧЕГО ЭТОТ НАБОР НЕ ПРОВЕРЯЕТ

Верность самого разбора: его выносит reconcile по данным терминала, а
терминала здесь нет. Проверяется решение кнопки по готовому вердикту.

Запуск:  python3 tests/test_incident_button.py
"""

from __future__ import annotations

import sys
from pathlib import Path

BASE = Path(__file__).resolve().parent
ROOT = BASE.parent
APP = ROOT / "ai_scalper_standalone"
sys.path.insert(0, str(BASE))
sys.path.insert(0, str(APP))

passed = 0
failed = 0


def check(ok: bool, name: str, detail: str = "") -> None:
    global passed, failed
    if ok:
        passed += 1
        print(f"  OK   {name}")
    else:
        failed += 1
        print(f"  СБОЙ {name}" + (f"  -> {detail}" if detail else ""))


import run_baseline  # noqa: E402  (заглушка MetaTrader5)
import поддельный_tk as пт  # noqa: E402

for _имя, _модуль in пт.собрать_модули().items():
    sys.modules[_имя] = _модуль

import desktop_app as da  # noqa: E402
import reconcile  # noqa: E402


class Пульт:
    """Пульт с известным вердиктом. Настоящий пошёл бы в терминал."""

    def __init__(self, есть_инцидент, вердикт):
        self._есть = есть_инцидент
        self._вердикт = вердикт
        self.снимали = False

    def инцидент(self):
        return {"причина": "4 заявки без позиции"} if self._есть else {}

    def сверить_инцидент(self):
        return self._вердикт

    def разрешить_инцидент(self, кто="", комментарий="", folder=""):
        self.снимали = True
        return True, self._вердикт


def нажать(есть_инцидент, вердикт, ответ_человека=True):
    """Нажать кнопку и вернуть (пульт, что показали)."""
    пт.сброс()
    пт.ОТВЕТ_ЧЕЛОВЕКА["да"] = ответ_человека
    пульт = Пульт(есть_инцидент, вердикт)
    было = da.control
    da.control = пульт
    окно = object.__new__(da.App)
    окно._огоньки = {}
    окно._недавно_нажато = {}
    try:
        окно.разобрать_происшествие()
    finally:
        da.control = было
    return пульт, list(пт.СООБЩЕНИЯ)


def test_нет_происшествия():
    print("\n[Происшествия нет]")
    пульт, показали = нажать(False, None)
    check(not пульт.снимали, "Снимать нечего — и не снимали")
    check(показали, "Человеку что-то сказали", str(показали))


def test_исход_не_доказан_запрет_остаётся():
    """Главная проверка."""
    print("\n[Исход НЕ доказан]")
    вердикт = reconcile.Вердикт(
        reconcile.НЕ_ВЫЯСНЕНО,
        ["позиции по заявке 12345 не видно",
         "в истории сделок заявки 12345 нет"],
        "проверьте счёт в терминале")
    пульт, показали = нажать(True, вердикт)
    check(not пульт.снимали,
          "ЗАПРЕТ НЕ СНЯТ — программа не поверила «позиции не вижу»")
    текст = " ".join(str(с) for с in показали)
    check("12345" in текст, "Человеку показаны факты с номером заявки")
    check("НЕ ДОКАЗАН" in текст, "И сказано прямо, что исход не доказан")


def test_человек_отказался():
    print("\n[Исход доказан, но человек нажал «нет»]")
    вердикт = reconcile.Вердикт(sorted(reconcile.ДОКАЗАННЫЕ)[0],
                                ["позиция найдена, сделка в истории есть"])
    пульт, _ = нажать(True, вердикт, ответ_человека=False)
    check(not пульт.снимали, "Отказался — не сняли")


def test_исход_доказан_и_человек_согласился():
    print("\n[Исход доказан, человек согласился]")
    вердикт = reconcile.Вердикт(sorted(reconcile.ДОКАЗАННЫЕ)[0],
                                ["позиция найдена, сделка в истории есть"])
    пульт, показали = нажать(True, вердикт, ответ_человека=True)
    check(пульт.снимали, "Запрет снят")
    текст = " ".join(str(с) for с in показали)
    check("журнал" in текст.lower(),
          "И сказано, что снятие записано в журнал", текст[:80])


def test_программа_сама_не_снимает():
    """Отдельно и намеренно: снятие только по действию человека."""
    print("\n[Сама программа инцидент не снимает]")
    import ast
    исходник = (APP / "incident.py").read_text(encoding="utf-8")
    дерево = ast.parse(исходник)
    вызовы = [у for у in ast.walk(дерево)
              if isinstance(у, ast.Call)
              and isinstance(у.func, ast.Name) and у.func.id == "снять"]
    check(not вызовы, "incident.py нигде не зовёт снять() сам", str(len(вызовы)))


def main() -> int:
    print("=" * 62)
    print("ТЕСТЫ: КНОПКА РАЗБОРА ПРОИСШЕСТВИЯ")
    print("=" * 62)
    test_нет_происшествия()
    test_исход_не_доказан_запрет_остаётся()
    test_человек_отказался()
    test_исход_доказан_и_человек_согласился()
    test_программа_сама_не_снимает()
    print("\n" + "=" * 70)
    print(f"Пройдено: {passed}   Сбоев: {failed}")
    print("=" * 70)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
