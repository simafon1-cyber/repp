def test_записи_действительно_убираются_с_диска():
    """Настоящий файл, настоящая запись. Без этого снятие запрета
    бесполезно: при следующем запуске сверка снова не найдёт заявку,
    снова откроет инцидент и снова остановит торговлю."""
    print("\n[Списанные заявки исчезают с диска]")
    import tempfile
    import pending_orders as po
    with tempfile.TemporaryDirectory() as папка:
        for i in range(4):
            po.записать("CADMXN", 1, 0.01, 1.0, folder=папка)
        было = po.открытые(папка)
        check(len(было) == 4, "Четыре заявки записаны", str(len(было)))

        убрано = po.снять_человеком("владелец", "проверил в терминале",
                                    folder=папка)
        check(убрано == 4, "Убрано ровно четыре", str(убрано))
        стало = po.открытые(папка)
        check(стало == [], "На диске не осталось ни одной", str(стало))

        # Повторное снятие ничего не ломает и не врёт про количество.
        check(po.снять_человеком("владелец", folder=папка) == 0,
              "Повторное снятие убирает ноль, а не падает")


def test_инцидент_запоминает_что_именно_не_подтвердилось():
    """Раньше в отметку клалось одно число «сколько» — и разбор потом
    честно отвечал «номер заявки не записан», то есть снять запрет по
    доказательству было невозможно В ПРИНЦИПЕ."""
    print("\n[Инцидент запоминает подробности заявок]")
    import ast
    исходник = (APP / "main.py").read_text(encoding="utf-8")
    дерево = ast.parse(исходник)
    ключи = set()
    for узел in ast.walk(дерево):
        if not isinstance(узел, ast.Call):
            continue
        if getattr(узел.func, "id", "") != "_открыть_инцидент":
            continue
        for арг in узел.args:
            if isinstance(арг, ast.Dict):
                ключи.update(k.value for k in арг.keys
                             if isinstance(k, ast.Constant))
    check("неподтверждённые" in ключи,
          "В отметку кладутся сами записи заявок", str(sorted(ключи)))
    check("тикеты_неподтверждённых" in ключи,
          "И номера заявок, когда они известны", str(sorted(ключи)))

    import reconcile as rc
    check("тикеты_неподтверждённых" in rc.ПОЛЯ_СПИСКОМ,
          "А разбор это поле читает", str(rc.ПОЛЯ_СПИСКОМ))
    номера, надёжны = rc.номера_заявок({"тикеты_неподтверждённых": [777, 888]})
    check(номера == [777, 888] and надёжны,
          "И достаёт из него номера надёжно", str((номера, надёжны)))


def test_программа_сама_не_снимает():
    """Отдельно и намеренно: снятие только по действию человека."""
    print("\n[Сама программа инцидент не снимает]")
    import ast
    исходник = (APP / "incident.py").read_text(encoding="utf-8")
    дерево = ast.parse(исходник)
    вызовы = [у for у in ast.walk(дерево)
              if isinstance(у, ast.Call)
              and isinstance(у.func, ast.Name) and у.func.id == "снять"]
    check(not вызовы, "incident.py нигде не зовёт снять() сам", str(len(вызовы)))


