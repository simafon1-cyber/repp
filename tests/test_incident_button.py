#!/usr/bin/env python3
"""КНОПКА «РАЗОБРАТЬ ПРОИСШЕСТВИЕ» НЕ СНИМАЕТ ЗАПРЕТ БЕЗ ДОКАЗАТЕЛЬСТВА.

ПОЧЕМУ ЭТОТ НАБОР ПОЯВИЛСЯ

Механизм разбора был написан целиком: программа умеет сходить на счёт,
посмотреть позиции, активные заявки, историю заявок и историю сделок и
снять запрет, только если исход ДОКАЗАН. Вызвать его было нечем — ни
кнопки в окне, ни на дашборде. У владельца торговля встала на «в журнале
осталось 4 отправленных заявок, которым НЕ нашлось позиции на счету», и
снять это он не мог никак.

Кнопка появилась. Вместе с ней появился и риск: кнопка, которая снимает
запрет «чтобы не мешал», хуже, чем отсутствие кнопки.

ЧТО ПРОВЕРЯЕТСЯ ПО ФАКТУ

Вызывается настоящий обработчик кнопки при разных вердиктах, и
проверяется, ЧТО ОН СДЕЛАЛ: снял запрет или нет. Не текст, а действие.

ЧЕГО ЭТОТ НАБОР НЕ ПРОВЕРЯЕТ

Верность самого разбора: его выносит reconcile по данным терминала, а
терминала здесь нет. Проверяется решение кнопки по готовому вердикту.

Запуск:  python3 tests/test_incident_button.py
"""

from __future__ import annotations

import sys
from pathlib import Path

BASE = Path(__file__).resolve().parent
ROOT = BASE.parent
APP = ROOT / "ai_scalper_standalone"
