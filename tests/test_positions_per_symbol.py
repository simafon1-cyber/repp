#!/usr/bin/env python3
"""СКОЛЬКО СДЕЛОК РАЗРЕШЕНО НА ОДНОЙ ПАРЕ.

ОТКУДА ЭТО

Владелец 03.09.2026, дословно: «Давай разрешим открытые на одной паре до
10 сделок. Пометь это, если что просто дальше уберем».

Решение принято им после того, как я назвал числа: ожидание входа
измерено и ОТРИЦАТЕЛЬНО (−0,0244 R на сделку до издержек), а десять
сделок на одной паре умножают не прибыль, а то, что есть.

ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ ПО ФАКТУ

1. Послабление действует и берётся из ОТДЕЛЬНОЙ помеченной настройки.
2. Оно СНИМАЕТСЯ одной строкой — возвратом нуля, и тогда действует
   лимит профиля, как было всегда.
3. Многострочный блок профилей риска НЕ ТРОНУТ — иначе «просто дальше
   уберём» превратилось бы в правку вслепую.
4. Мусор в настройке не расширяет предел: непонятное значение толкуется
   в сторону прежнего лимита, а не большего риска.
5. Программа честно говорит, ЧТО именно ограничивает число сделок —
   потому что останавливает их не этот лимит, а потолок совокупного
   риска.

ЧЕГО ЭТИ ТЕСТЫ НЕ ГОВОРЯТ

Что десять сделок выгоднее пяти. Измерения говорят обратное.

Запуск:  python3 tests/test_positions_per_symbol.py
"""

from __future__ import annotations

import ast
import sys
import types
from pathlib import Path

BASE = Path(__file__).resolve().parent
ROOT = BASE.parent
APP = ROOT / "ai_scalper_standalone"
sys.path.insert(0, str(APP))
sys.path.insert(0, str(BASE))

passed = 0
failed = 0


def check(ok: bool, name: str, detail: str = "") -> None:
    global passed, failed
    if ok:
        passed += 1
        print(f"  OK   {name}")
    else:
        failed += 1
        print(f"  СБОЙ {name}" + (f" -> {detail}" if detail else ""))


import run_baseline            # noqa: E402
import main                    # noqa: E402
import config as cfg           # noqa: E402


ПРОФИЛЬ = {"max_open_positions": 5, "max_total_risk_pct": 6.5,
           "risk_percent": 1.2}


def _с_настройкой(значение):
    """Подставить значение послабления и спросить предел."""
    было = getattr(cfg, "MAX_POSITIONS_PER_SYMBOL_OVERRIDE", 0)
    cfg.MAX_POSITIONS_PER_SYMBOL_OVERRIDE = значение
    try:
        return main._лимит_на_пару(ПРОФИЛЬ)
    finally:
        cfg.MAX_POSITIONS_PER_SYMBOL_OVERRIDE = было


# =====================================================================
def test_послабление_действует():
    print("\n[Десять сделок на пару разрешены]")
    check(_с_настройкой(10) == 10,
          "С настройкой 10 предел равен десяти", str(_с_настройкой(10)))
    check(_с_настройкой(3) == 3,
          "И любому другому заданному числу", str(_с_настройкой(3)))


def test_послабление_снимается_одной_строкой():
    """Владелец: «если что просто дальше уберем»."""
    print("\n[Снимается возвратом нуля]")
    check(_с_настройкой(0) == ПРОФИЛЬ["max_open_positions"],
          "Ноль возвращает лимит профиля", str(_с_настройкой(0)))
    check(_с_настройкой(0) == 5,
          "То есть прежние пять", str(_с_настройкой(0)))


def test_мусор_не_расширяет_предел():
    """Непонятное значение толкуется в сторону МЕНЬШЕГО риска."""
    print("\n[Мусор не даёт лишних сделок]")
    for значение in ("десять", None, -3, 0, "", 3.7):
        предел = _с_настройкой(значение)
        check(предел <= 10,
              f"{значение!r} не даёт больше десяти", str(предел))
        if not isinstance(значение, int) or значение <= 0:
            check(предел == 5 or значение == 3.7,
                  f"{значение!r} оставляет лимит профиля", str(предел))


def test_профили_риска_не_тронуты():
    """Иначе «просто дальше уберём» стало бы правкой вслепую."""
    print("\n[Блок профилей риска не тронут]")
    эталон = (APP / "config.py.example").read_text(encoding="utf-8")
    check("max_open_positions=5" in эталон.replace(" ", ""),
          "У «Агрессивного» по-прежнему пять в профиле")
    check("max_open_positions=1" in эталон.replace(" ", ""),
          "И у «Консервативного» по-прежнему одна")
    # Настройка послабления — отдельная строка верхнего уровня.
    имена = []
    for узел in ast.parse(эталон).body:
        if isinstance(узел, ast.Assign) and узел.targets:
            имена.append(getattr(узел.targets[0], "id", ""))
    check("MAX_POSITIONS_PER_SYMBOL_OVERRIDE" in имена,
          "Послабление задано отдельной строкой верхнего уровня")


def test_послабление_помечено_словами_владельца():
    """Пометка — это и есть просьба «пометь это»."""
    print("\n[Послабление помечено]")
