    check(итог["решение"] == "отклонить", "Пусто — отклонить")
    check(v.metrics(None)["сделок"] == 0, "Метрики от None не падают")
    check(v.monte_carlo_check([], [])["улучшение"] is False,
          "Monte Carlo без данных не говорит «лучше»")
    check(v.ab_check([], [1.0])["улучшение"] is False,
          "A/B без данных не говорит «лучше»")
    check(v.walk_forward_check([], [])["улучшение"] is False,
          "Walk forward без данных не говорит «лучше»")
    check("ОТКЛОНИТЬ" in v.describe(итог), "Решение читается словами",
          v.describe(итог))


