#!/usr/bin/env python3
"""Тесты ВОРОТ: изменение не входит в программу без доказательства.

ПРАВИЛО ВЛАДЕЛЬЦА, КОТОРОЕ ЗДЕСЬ ЗАКРЕПЛЯЕТСЯ:

    «НИКОГДА не считать, что новая функция улучшает систему. Любая новая
    функция считается бесполезной, пока не доказано обратное.»

Само по себе такое правило — обещание, а обещания забываются. Здесь оно
превращается в проверяемое поведение кода.

ЧТО ПРОВЕРЯЕТСЯ, ПО ВАЖНОСТИ:
  1. ПО УМОЛЧАНИЮ — ОТКЛОНИТЬ. Нет разницы — нет улучшения. Ничья
     засчитывается против изменения.
  2. МАЛО СДЕЛОК — ОТКЛОНИТЬ, какими бы красивыми ни были проценты.
  3. Улучшение, которое держится на двух везучих сделках, НЕ проходит.
     Это главная ловушка торговых систем, и её надо ловить машиной.
  4. Улучшение только на том куске истории, где настройку подбирали, НЕ
     проходит (out of sample).
  5. Улучшение в одном окне из четырёх НЕ проходит (walk forward).
  6. Настоящее, устойчивое улучшение — проходит. Ворота, которые не
     пропускают ничего, бесполезны так же, как ворота, пропускающие всё.
  7. Ответ воспроизводим: одинаковые данные дают одинаковое решение.

Запуск:  python3 tests/test_validation.py
"""

from __future__ import annotations

import sys
import types
from pathlib import Path

BASE = Path(__file__).resolve().parent
ROOT = BASE.parent
APP = ROOT / "ai_scalper_standalone"
sys.path.insert(0, str(APP))

passed = 0
failed = 0


def check(ok: bool, name: str, detail: str = "") -> None:
    global passed, failed
    if ok:
        passed += 1
        print(f"  OK   {name}")
    else:
        failed += 1
        print(f"  СБОЙ {name}" + (f" -> {detail}" if detail else ""))


cfg = types.ModuleType("config")
cfg.__file__ = str(APP / "config.py.example")
exec((APP / "config.py.example").read_text(encoding="utf-8"), cfg.__dict__)
sys.modules["config"] = cfg
sys.modules["MetaTrader5"] = types.ModuleType("MetaTrader5")

import backtest as bt        # noqa: E402
import validation as v       # noqa: E402


def повтор(шаблон, раз):
    """Ровная череда сделок — чтобы результат зависел от логики, а не от шума."""
    ряд = []
    for _ in range(раз):
        ряд.extend(шаблон)
    return ряд


# Убыточный набор: выигрыш 10, проигрыш 12 — в среднем минус пункт на сделку.
БЫЛО = повтор([10.0, -12.0], 100)
# Прибыльный набор: выигрыш 14, проигрыш 10 — в среднем плюс два пункта.
СТАЛО = повтор([14.0, -10.0], 100)


def test_no_difference_is_rejected() -> None:
    """Нет разницы — нет улучшения. Это и есть «по умолчанию отклонить»."""
    print("\n[Одинаковые результаты не считаются улучшением]")
    итог = v.gate(БЫЛО, list(БЫЛО))
    check(итог["решение"] == "отклонить", "Одинаковые наборы отклонены",
          str(итог["способов_за"]))
    check(итог["способов_за"] == 0, "Ни один способ не сказал «лучше»",
          str(итог["способов_за"]))

    # Ничья по каждой отдельной метрике тоже не улучшение.
    м = v.metrics(БЫЛО)
    лучше = v.improved(м, dict(м))
    check(not any(лучше.values()), "Ничья по метрикам не засчитана", str(лучше))


def test_small_sample_is_rejected() -> None:
    """Двадцать сделок — это не доказательство, даже если они прекрасны."""
    print("\n[Мало сделок — отклонить независимо от чисел]")
    мало_было = повтор([10.0, -12.0], 10)     # 20 сделок
    мало_стало = повтор([30.0, -2.0], 10)     # 20 сделок, явно лучше
    итог = v.gate(мало_было, мало_стало)
    check(итог["решение"] == "отклонить", "Отклонено при 20 сделках")
    check("20" in итог["причина"], "В причине названо число сделок",
          итог["причина"])
    check(итог["способы"] == [], "Способы даже не запускались")

    # Порог один на весь проект, а не свой в каждом файле.
    check(v.МАЛО_СДЕЛОК == bt.МАЛО_СДЕЛОК,
          "Порог выборки взят из backtest, не продублирован")

    # Ровно на пороге — уже считается.
    на_пороге = v.gate(повтор([10.0, -12.0], bt.МАЛО_СДЕЛОК // 2),
                       повтор([14.0, -10.0], bt.МАЛО_СДЕЛОК // 2))
    check(на_пороге["способы"] != [], "На пороге способы запускаются")


def test_real_improvement_passes() -> None:
    """Ворота обязаны пропускать настоящее улучшение, иначе они бесполезны."""
    print("\n[Устойчивое улучшение проходит]")
    итог = v.gate(БЫЛО, СТАЛО)
    check(итог["решение"] == "принять", "Ровное улучшение принято",
          v.describe(итог))
    check(итог["способов_за"] >= v.МИНИМУМ_СПОСОБОВ,
          f"За изменение минимум {v.МИНИМУМ_СПОСОБОВ} способа",
          str(итог["способов_за"]))
    имена = {с["способ"] for с in итог["способы"]}
    check(имена == {"backtest", "out of sample", "walk forward",
                    "monte carlo", "A/B"},
          "Отработали все пять способов", str(имена))


def test_worse_change_is_rejected() -> None:
    """Ухудшение обязано отклоняться — это самая дешёвая проверка ворот."""
    print("\n[Ухудшение отклоняется]")
    итог = v.gate(СТАЛО, БЫЛО)
    check(итог["решение"] == "отклонить", "Ухудшение не прошло",
          v.describe(итог))
    check(итог["способов_за"] == 0, "И ни один способ его не поддержал",
          str(итог["способов_за"]))


def test_one_good_metric_is_not_enough() -> None:
    """Улучшить одно число легко: достаточно рисковать больше. Здесь средняя
    сделка выросла в десять раз — и при этом профит-фактор упал, просадка
    углубилась в сорок раз, восстановление ухудшилось. Это не улучшение
    системы, это увеличение риска, и ворота обязаны это различать."""
    print("\n[Одной улучшенной метрики мало]")
    было = повтор([2.0, -1.0], 100)      # ровный рост, просадка 1 пункт
    стало = повтор([50.0, -40.0], 100)   # больше прибыль, но и качели больше

    м_было = v.metrics(было)
    м_стало = v.metrics(стало)
    check(м_стало["ожидание"] > м_было["ожидание"],
          "Средняя сделка и правда выросла",
          f"{м_было['ожидание']} -> {м_стало['ожидание']}")

    итог = v.backtest_check(было, стало)
    лучше = итог["по_метрикам"]
    check(лучше["ожидание"], "Ожидание засчитано как улучшение")
    check(not лучше["профит_фактор"], "Падение профит-фактора не засчитано",
          f"{м_было['профит_фактор']} -> {м_стало['профит_фактор']}")
    check(not лучше["восстановление"], "Падение восстановления не засчитано",
          f"{м_было['восстановление']} -> {м_стало['восстановление']}")
    # Просадка — единственная метрика, где МЕНЬШЕ значит ЛУЧШЕ. Если
    # перепутать направление, углубление просадки сойдёт за успех.
    check(м_стало["просадка"] > м_было["просадка"],
          "Просадка действительно углубилась",
          f"{м_было['просадка']} -> {м_стало['просадка']}")
    check(not лучше["просадка"], "И углубление просадки НЕ засчитано за успех")

    check(итог["метрик_лучше"] == 1, "Улучшена ровно одна метрика из четырёх",
          str(итог["метрик_лучше"]))
    check(not итог["улучшение"],
          f"Одной метрики мало, нужно {v.МИНИМУМ_МЕТРИК}")

    # Обратная сторона: уменьшение просадки при прочих равных — улучшение.
    мельче = v.improved({"просадка": 40.0}, {"просадка": 10.0})
    check(мельче["просадка"], "Уменьшение просадки засчитано как улучшение")


def test_ab_counts_chance_in_both_directions() -> None:
    """Случайность одинаково легко даёт разницу в любую сторону. Считать
    только удобную нам сторону — значит вдвое занизить вероятность случайности
    и объявить значимым то, что значимым не является."""
    print("\n[A/B считает случайность в обе стороны]")
    основа = повтор([10.0, -12.0], 100)
    # Разница ровно на грани: односторонний счёт назвал бы её значимой,
    # честный двусторонний — нет.
    лучше_на_2 = [x + 2.0 for x in основа]
    хуже_на_2 = [x - 2.0 for x in основа]

    вперёд = v.ab_check(основа, лучше_на_2, seed=0)
    назад = v.ab_check(основа, хуже_на_2, seed=0)

    check(вперёд["разница"] > 0, "Средняя сделка выросла на 2 пункта",
          str(вперёд["разница"]))
    check(вперёд["случайность"] > v.ПОРОГ_СЛУЧАЙНОСТИ,
          "Но такая разница слишком часто получается случайно",
          str(вперёд["случайность"]))
    check(not вперёд["улучшение"], "Поэтому улучшением она не признана")
    # Симметрия и есть признак честного счёта: одинаковая по величине разница
    # даёт одинаковую вероятность случайности, в какую бы сторону ни смотрела.
    check(abs(вперёд["случайность"] - назад["случайность"]) < 0.03,
          "Разница «в плюс» и «в минус» одинаково вероятна случайно",
          f"{вперёд['случайность']} и {назад['случайность']}")

    # А заметная разница проходит — иначе способ бесполезен.
    заметная = v.ab_check(основа, [x + 5.0 for x in основа], seed=0)
    check(заметная["улучшение"], "Крупная разница признана неслучайной",
          str(заметная["случайность"]))


def test_luck_of_two_trades_does_not_pass() -> None:
    """ГЛАВНАЯ ЛОВУШКА. Средняя сделка стала прибыльной из-за двух огромных
    выигрышей, а не из-за работы изменения. Человек на такое ведётся, ворота
    вестись не должны."""
    print("\n[Две везучие сделки не считаются улучшением]")
    было = [-1.0] * 200
    стало = [-1.0] * 200
    стало[20] = 300.0          # везение лежит в начале истории,
    стало[21] = 300.0          # то есть на «обучающем» куске

    среднее_было = sum(было) / len(было)
    среднее_стало = sum(стало) / len(стало)
    check(среднее_стало > среднее_было,
          "Средняя сделка и правда выглядит лучше",
          f"{среднее_было} -> {среднее_стало}")

    итог = v.gate(было, стало)
    check(итог["решение"] == "отклонить", "Но ворота это отклонили",
          v.describe(итог))
    check(итог["способов_за"] < v.МИНИМУМ_СПОСОБОВ,
          "Способов «за» меньше требуемого", str(итог["способов_за"]))

    mc = v.monte_carlo_check(было, стало, seed=1)
    check(not mc["улучшение"], "Monte Carlo не поверил везению",
          str(mc["худший_случай"]))
    ab = v.ab_check(было, стало, seed=1)
    check(not ab["улучшение"], "A/B назвал разницу случайной",
          str(ab["случайность"]))


def test_improvement_only_where_it_was_fitted_fails() -> None:
    """Подгонка: изменение помогает ровно там, где его подбирали."""
    print("\n[Улучшение только на «обучающем» куске не проходит]")
    было = list(БЫЛО)
    стало = list(БЫЛО)
    граница = int(len(стало) * v.ДОЛЯ_ОБУЧЕНИЯ)
    for i in range(граница):
        стало[i] = 14.0 if стало[i] > 0 else -10.0

    oos = v.out_of_sample_check(было, стало)
    check(not oos["улучшение"], "Чистая проверка улучшения не увидела",
          str(oos["стало"]))
    check(oos["сделок_в_проверке"] == len(было) - граница,
          "В чистой проверке остался нетронутый кусок",
          str(oos["сделок_в_проверке"]))

    # А целиком по истории — увидела бы. Именно поэтому одного backtest мало.
    целиком = v.backtest_check(было, стало)
    check(целиком["улучшение"], "А по всей истории «улучшение» видно",
          str(целиком["метрик_лучше"]))


def test_one_lucky_window_is_not_improvement() -> None:
    """Выиграть один месяц из четырёх — не улучшение."""
    print("\n[Улучшение в одном окне из четырёх не проходит]")
    было = list(БЫЛО)
    стало = list(БЫЛО)
    четверть = len(стало) // v.ОКОН_WALK_FORWARD
    for i in range(четверть):
        стало[i] = 40.0 if стало[i] > 0 else -2.0

    wf = v.walk_forward_check(было, стало)
    check(wf["окон"] == v.ОКОН_WALK_FORWARD, "История порезана на 4 окна",
          str(wf["окон"]))
    check(wf["окон_лучше"] == 1, "Лучше стало ровно в одном окне",
          str(wf["окон_лучше"]))
    check(not wf["улучшение"], "И это не засчитано как улучшение")

    # А если лучше в трёх окнах из четырёх — засчитано.
    хорошо = list(БЫЛО)
    for i in range(четверть * 3):
        хорошо[i] = 14.0 if хорошо[i] > 0 else -10.0
    wf2 = v.walk_forward_check(было, хорошо)
    check(wf2["улучшение"], "Три окна из четырёх — улучшение",
          str(wf2["окон_лучше"]))


def test_windows_do_not_lose_or_reorder_trades() -> None:
    """Резать историю на окна надо ПО ПОРЯДКУ и ничего не теряя."""
    print("\n[Окна не теряют и не перемешивают сделки]")
    ряд = [float(i) for i in range(97)]
    куски = v.windows(ряд, 4)
    собрано = [t for кусок in куски for t in кусок]
    check(собрано == ряд, "Собранное обратно совпадает с исходным")
    check(len(куски) == 4, "Окон ровно столько, сколько просили",
          str(len(куски)))
    check(all(куски), "Пустых окон нет")
    check(v.windows([1.0, 2.0], 4) == [[1.0, 2.0]],
          "Сделок меньше, чем окон — одно окно, а не пустота")
    check(v.windows([], 4) == [], "Пустая история — пустой список окон")


def test_drawdown_and_recovery_are_honest() -> None:
    """Просадка и фактор восстановления считаются, а не выдумываются."""
    print("\n[Просадка и восстановление]")
    # Итог по сделкам: 10, 6, 3, 8. Пик 10, дно после него 3 -> просадка 7.
    check(v.max_drawdown([10.0, -4.0, -3.0, 5.0]) == 7.0,
          "Просадка меряется от пика, а не от нуля",
          str(v.max_drawdown([10.0, -4.0, -3.0, 5.0])))
    check(v.max_drawdown([]) == 0.0, "Пустая история — просадка ноль")
    check(v.max_drawdown([-5.0, -5.0]) == 10.0,
          "Падение с самого начала тоже просадка",
          str(v.max_drawdown([-5.0, -5.0])))

    # Без просадки честнее сказать «ноль», чем «бесконечность».
    check(v.recovery_factor([10.0, 20.0]) == 0.0,
          "Бесконечного восстановления не бывает",
          str(v.recovery_factor([10.0, 20.0])))
    check(v.recovery_factor([10.0, -4.0, -3.0, 5.0]) == round(8 / 7, 2),
          "Восстановление = итог / просадка",
          str(v.recovery_factor([10.0, -4.0, -3.0, 5.0])))
    # Убыточная система не может иметь положительное восстановление.
    check(v.recovery_factor([-1.0] * 10) < 0, "Убыток даёт отрицательный ответ",
          str(v.recovery_factor([-1.0] * 10)))


def test_answer_is_repeatable() -> None:
    """Один и тот же вопрос обязан давать один и тот же ответ."""
    print("\n[Ответ воспроизводим]")
    a = v.gate(БЫЛО, СТАЛО, seed=7)
    b = v.gate(БЫЛО, СТАЛО, seed=7)
    check(a["решение"] == b["решение"], "Решение то же")
    check(a["способов_за"] == b["способов_за"], "И счёт способов тот же")
    mc1 = v.monte_carlo_check(БЫЛО, СТАЛО, seed=7)
    mc2 = v.monte_carlo_check(БЫЛО, СТАЛО, seed=7)
    check(mc1 == mc2, "Monte Carlo с тем же зерном даёт то же самое")


def test_garbage_input_does_not_crash() -> None:
    """Мусор на входе не должен ни падать, ни притворяться доказательством."""
    print("\n[Пустые и битые данные]")
