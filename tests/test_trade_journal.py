def test_каталог_выгрузки_не_переписывается():
    """Выгрузка — доказательство, а не черновик.

    Первая версия этого теста бросала FileExistsError САМА и радовалась,
    что поймала. Она прошла бы и на коде, который молча переиспользует
    каталог. Здесь вызывается настоящая функция — дважды.

    Метка времени закреплена: у неё разрешение в секунду, и два вызова
    могли бы разойтись на границе секунды. Тогда тест иногда проходил бы
    по случайности, а не по устройству кода.

    Наоборот: заменить проверку на os.makedirs(путь, exist_ok=True) —
    тест падает."""
    корень = Path(tempfile.mkdtemp(prefix="корень_"))
    настоящая = tj.метка_времени
    tj.метка_времени = lambda: "2026-08-22T10-00-00Z"
    try:
        путь = tj.новая_выгрузка(str(корень))
        check(os.path.isdir(путь), "Каталог создан")
        (Path(путь) / "доказательство.txt").write_text("важное",
                                                       encoding="utf-8")
        отказала = False
        try:
            tj.новая_выгрузка(str(корень))
        except FileExistsError as e:
            отказала = True
            check("не переписывается" in str(e),
                  "И объяснено, почему отказ", str(e)[:60])
        check(отказала, "Повторная выгрузка в тот же каталог ОТКАЗАНА")
        check((Path(путь) / "доказательство.txt").read_text(encoding="utf-8")
              == "важное", "Лежавшее там доказательство цело")
    finally:
        tj.метка_времени = настоящая
        shutil.rmtree(корень, ignore_errors=True)


