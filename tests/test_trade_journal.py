class Сделка:
    """Одна сделка так, как её отдаёт терминал."""

    def __init__(self, ticket, order, position_id, symbol, тип, entry,
                 volume, price, magic, commission=-0.7, swap=0.0,
                 profit=0.0, comment="AI_Scalper_Standalone", когда=None):
        self.ticket = ticket
        self.order = order
        self.position_id = position_id
        self.symbol = symbol
        self.type = тип
        self.entry = entry
        self.volume = volume
        self.price = price
        self.sl = price - 0.0020 if тип == 0 else price + 0.0020
        self.tp = 0.0
        self.commission = commission
        self.swap = swap
        self.profit = profit
        self.magic = magic
        self.reason = 3
        self.comment = comment
        self.time = когда or int(
            datetime(2026, 8, 22, 10, 0, tzinfo=timezone.utc).timestamp())


class Брокер:
    """Подделка, которая ВЕДЁТ СЧЁТ, а не возвращает заготовленный ответ."""

    def __init__(self, сделки=None, молчит=False):
        self.сделки = list(сделки or [])
        self.молчит = молчит
        self.спрашивали = 0

    def deals_or_none(self, начало, конец, symbol=None):
        self.спрашивали += 1
        if self.молчит:
            return None               # «спросить не удалось»
        return list(self.сделки)


МАГИЯ = 20260822


def _вход(pid, symbol="EURUSD", volume=0.10, price=1.10000, тип=0):
    return Сделка(pid * 10 + 1, pid * 10 + 2, pid, symbol, тип, 0, volume,
                  price, МАГИЯ)


def _выход(pid, symbol="EURUSD", volume=0.10, price=1.10150, тип=1,
           profit=15.0):
    return Сделка(pid * 10 + 3, pid * 10 + 4, pid, symbol, тип, 1, volume,
                  price, МАГИЯ, profit=profit)


def _решение(pid, symbol="EURUSD", лот=0.10, статус="ПОЛНОЕ"):
    return {"событие": "ВХОД", "символ": symbol, "тикет": pid,
            "лот_исполнен": лот, "статус_заявки": статус}


