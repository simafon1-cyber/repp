def _подделать_вход(лот_исполнен=0.10, статус=None):
    """Подставить брокера так, чтобы execute_market_order дошёл до конца."""
    import trade_manager as tm
    import execution as ex
    import config as cfg
    import mt5_connector as mt5c

    class Тик:
        bid, ask, time = 1.09998, 1.10002, 1

    было = (cfg.LIVE_TRADING, mt5c.get_tick, mt5c.send_market_order,
            tm.наши_тикеты, tm.rm.check_stops_distance, tm.log_trade_csv)
    cfg.LIVE_TRADING = True
