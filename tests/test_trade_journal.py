def test_проскальзывание_считается_со_знаком_по_направлению():
    """Без знака число бесполезно: «два пункта» — и подарок, и потеря."""
    # Покупка: исполнили ДОРОЖЕ ожидаемого — хуже, знак минус.
    check(tj.проскальзывание(1.10000, 1.10002, 0.00001, 1) == -2.0,
          "Покупка дороже ожидаемого — минус два пункта",
          str(tj.проскальзывание(1.10000, 1.10002, 0.00001, 1)))
    # Продажа: исполнили дороже — лучше, знак плюс.
    check(tj.проскальзывание(1.10000, 1.10002, 0.00001, -1) == 2.0,
          "Продажа дороже ожидаемого — плюс два пункта",
          str(tj.проскальзывание(1.10000, 1.10002, 0.00001, -1)))
    check(tj.проскальзывание("", 1.1, 0.00001, 1) == "",
          "Нет данных — пустое поле, а не ноль")
    check(tj.проскальзывание(1.1, 1.1, 0, 1) == "",
          "Нулевой пункт — пустое поле, а не деление на ноль")


