def test_молчание_брокера_не_превращается_в_пустую_выгрузку():
    """ГЛАВНАЯ проверка.

    Терминал недоступен — значит, доказательства нет. Записать пустой
    файл и назвать его выгрузкой значит соврать: пустая таблица
    выглядит как установленный факт «сделок не было».

    Наоборот: заменить проверку на `сделки = сделки or []` — тест
    падает."""
    куда = Path(tempfile.mkdtemp(prefix="выгр_"))
    try:
        брокер = Брокер(молчит=True)
        поймано = False
        try:
            tj.выгрузить_сделки(брокер, 0, 1, str(куда), magic=МАГИЯ)
        except tj.Неизвестно as e:
            поймано = True
            check("НЕ значит" in str(e),
                  "И сказано словами, что это не «сделок нет»", str(e)[:60])
        check(поймано, "Молчание брокера остановило выгрузку")
        check(not (куда / tj.ФАЙЛ_СДЕЛОК).exists(),
              "И файл выгрузки НЕ создан — пустой таблицы не появилось")
        check(брокер.спрашивали == 1, "Брокера спросили ровно один раз",
              str(брокер.спрашивали))
    finally:
        shutil.rmtree(куда, ignore_errors=True)


