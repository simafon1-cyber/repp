#!/usr/bin/env python3
"""ЗАПРЕТ ПОСЛЕ ПРОИСШЕСТВИЯ — ПО ИНСТРУМЕНТУ, А НЕ ПО ВСЕМУ СЧЁТУ.

ПОЧЕМУ ЭТОТ НАБОР ПОЯВИЛСЯ

Незакрытая заявка по одной паре (CADMXN) останавливала торговлю по ВСЕМ
инструментам сразу. Владелец: «он сам себя задушил бот, ни одной сделки
за три дня».

Опасность, ради которой запрет и написан, ровно одна: открыть вторую
позицию поверх возможной неучтённой. Она касается ТОЙ ЖЕ пары. Остановка
всего счёта от этого не защищала ни на грамм, зато обесценивала
программу.

ЧТО ПРОВЕРЯЕТСЯ ПО ФАКТУ

Ответ настоящего пульта на вопрос «можно ли входить по этой паре» при
разных состояниях. Не текст, а решение.

ЧЕГО ЭТОТ НАБОР НЕ ПРОВЕРЯЕТ

Что главный цикл спрашивает именно так — для этого есть отдельная
проверка ниже, структурная.
Поведение у настоящего брокера: терминала здесь нет.

Запуск:  python3 tests/test_incident_scope.py
"""

from __future__ import annotations

import sys
import tempfile
from pathlib import Path

BASE = Path(__file__).resolve().parent
ROOT = BASE.parent
APP = ROOT / "ai_scalper_standalone"
sys.path.insert(0, str(BASE))
sys.path.insert(0, str(APP))

passed = 0
failed = 0


def check(ok: bool, name: str, detail: str = "") -> None:
    global passed, failed
    if ok:
        passed += 1
        print(f"  OK   {name}")
    else:
        failed += 1
        print(f"  СБОЙ {name}" + (f"  -> {detail}" if detail else ""))


import run_baseline  # noqa: E402  (заглушка MetaTrader5)
from control import Control  # noqa: E402


def пульт_с_инцидентом(сведения, папка):
    c = Control()
    c.открыть_инцидент(сведения, папка)
    return c


def test_запрет_только_по_своей_паре():
    print("\n[Инцидент по CADMXN не трогает EURUSD]")
    with tempfile.TemporaryDirectory() as п:
        c = пульт_с_инцидентом(
            {"символ": "CADMXN", "вид": "неподтверждённая заявка",
             "причина": "4 заявки без позиции",
             "неподтверждённые": [{"символ": "CADMXN"}]}, п)
        запрещён, почему = c.вход_запрещён("CADMXN")
        check(запрещён, "По CADMXN вход запрещён", почему)
        check("CADMXN" in почему, "И названа пара", почему)
        запрещён2, почему2 = c.вход_запрещён("EURUSD")
        check(not запрещён2, "А по EURUSD — разрешён", почему2)


def test_несколько_пар_в_инциденте():
    print("\n[В инциденте две пары — обе закрыты]")
    with tempfile.TemporaryDirectory() as п:
        c = пульт_с_инцидентом(
            {"символ": "CADMXN", "вид": "неподтверждённая заявка",
             "причина": "заявки без позиции",
             "неподтверждённые": [{"символ": "CADMXN"}, {"символ": "USDJPY"}]}, п)
        check(c.вход_запрещён("CADMXN")[0], "CADMXN закрыт")
        check(c.вход_запрещён("USDJPY")[0], "USDJPY тоже закрыт")
        check(not c.вход_запрещён("GBPUSD")[0], "GBPUSD открыт")


def test_инструмент_неизвестен_закрыто_всё():
    """Отказобезопасность. Не знаем, где беда — значит везде."""
    print("\n[Инструмент в инциденте не назван]")
    with tempfile.TemporaryDirectory() as п:
        c = пульт_с_инцидентом(
            {"вид": "потеряна запись", "причина": "запись потеряна"}, п)
        запрещён, почему = c.вход_запрещён("EURUSD")
        check(запрещён, "Закрыто ВЕЗДЕ", почему)
        check("не назван" in почему, "И сказано почему", почему)


def test_обычная_пауза_останавливает_всё():
    """Её ставит человек, и он имеет в виду именно всё."""
    print("\n[Пауза с пульта — на всё]")
    c = Control()
    c.set_paused(True)
    check(c.вход_запрещён("EURUSD")[0], "EURUSD закрыт")
    check(c.вход_запрещён("CADMXN")[0], "CADMXN закрыт")
    c.set_paused(False)
    check(not c.вход_запрещён("EURUSD")[0], "Пауза снята — открыто")


def test_без_инцидента_ничего_не_закрыто():
    print("\n[Ни паузы, ни инцидента]")
    c = Control()
    запрещён, почему = c.вход_запрещён("EURUSD")
    check(not запрещён, "Вход разрешён", почему)
    check(почему == "", "И причины нет", repr(почему))


def test_главный_цикл_спрашивает_по_паре():
    """Иначе весь набор проверял бы функцию, которой никто не пользуется."""
    print("\n[Главный цикл спрашивает запрет по паре]")
    import ast
    дерево = ast.parse((APP / "main.py").read_text(encoding="utf-8"))
    зовут_по_паре = False
    зовут_общий = []
    for узел in ast.walk(дерево):
        if not isinstance(узел, ast.Call):
            continue
        имя = getattr(узел.func, "attr", "")
        if имя == "вход_запрещён" and узел.args:
            зовут_по_паре = True
        if имя == "is_paused":
            зовут_общий.append(ast.dump(узел)[:40])
    check(зовут_по_паре, "control.вход_запрещён(symbol) вызывается в main.py")
    check(not зовут_общий,
          "А общий is_paused() из главного цикла убран", str(зовут_общий))


def main() -> int:
    print("=" * 62)
    print("ТЕСТЫ: ЗАПРЕТ ПО ИНСТРУМЕНТУ, А НЕ ПО ВСЕМУ СЧЁТУ")
    print("=" * 62)
    test_запрет_только_по_своей_паре()
    test_несколько_пар_в_инциденте()
    test_инструмент_неизвестен_закрыто_всё()
    test_обычная_пауза_останавливает_всё()
    test_без_инцидента_ничего_не_закрыто()
    test_главный_цикл_спрашивает_по_паре()
    print("\n" + "=" * 70)
    print(f"Пройдено: {passed}   Сбоев: {failed}")
    print("=" * 70)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
