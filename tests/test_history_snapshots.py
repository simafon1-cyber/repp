def _неделя(начало, недель=60):
    """Часовые бары: пн 00:00 .. пт 23:00 по времени сервера, выходные пусты.

    Начало задаётся временем сервера, поэтому «смещение» задаётся тем,
    какое закрытие рынка по UTC приходится на пятницу 23:00."""
    бары, t = [], начало
    for _ in range(недель):
        for час in range(5 * 24):           # пн 00:00 .. пт 23:00
            бары.append({"time": t + час * 3600})
        t += 7 * 24 * 3600
    return бары


def test_смещение_считается_по_свечам_а_не_по_тику():
    """ГЛАВНАЯ проверка этой правки. Дефект пойман на живых данных.

    Смещение считалось как разница между временем ПОСЛЕДНЕГО ТИКА и
    текущим временем UTC. На живом рынке верно. Но если рынок ЗАКРЫТ, тик
    протух, и разница равна «истинное смещение минус возраст тика».

    Выгрузка 22 августа 2026 шла в субботу: в паспорта записалось −1 у
    валютных пар и −2 у золота вместо +3.

    И отличить одно от другого ПО ТИКУ НЕЛЬЗЯ: если тик отстал ровно на
    целое число часов — а на закрытом рынке так и бывает, — разница
    выглядит как законный часовой пояс. Поэтому считаем по свечам.

    Наоборот: верните расчёт по тику в паспорт — проверка падает."""
    ps = he
    # Понедельник 00:00 по времени сервера. Летом 2026, значит закрытие
    # рынка 21:00 UTC, и пятница 23:00 сервера даёт смещение +3.
    пн = int(dt_datetime(2026, 5, 4, 0, 0, tzinfo=dt_timezone.utc).timestamp())
    см, почему = ps.смещение_по_свечам(_неделя(пн), "H1")
    check(см == 3.0, "Летом смещение +3", f"{см} ({почему})")

    # Зимой закрытие 22:00 UTC — та же пятница 23:00 даёт +2.
    пн_зима = int(dt_datetime(2026, 1, 5, 0, 0, tzinfo=dt_timezone.utc).timestamp())
    см, почему = ps.смещение_по_свечам(_неделя(пн_зима), "H1")
    check(см == 2.0, "Зимой смещение +2", f"{см} ({почему})")

    check("МЕНЯЕТСЯ" in почему,
          "И сказано, что смещение не постоянно", почему[:80])


