"""run_optimize.py — ОДНА КОМАНДА: PHASE 3, подбор параметров под присмотром.

Запуск:

    python run_optimize.py                  — XAUUSD, затем EURUSD
    python run_optimize.py XAUUSD           — только золото
    python run_optimize.py --bars 40000     — быстрее, по последним свечам
    python run_optimize.py --workers 1      — в один поток (для отладки)

Порядок работы жёсткий и нарушить его нельзя:

    TRAIN       все варианты соревнуются между собой
    VALIDATION  выжившие проверяются на данных, которых не видели
    OOS         финалист проверяется ОДИН РАЗ, и требуется прибыль

Ничего не записывает в настройки программы. Итог — таблица и вывод.
"""

