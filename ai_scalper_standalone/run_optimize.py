import os
import sys

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, ЗДЕСЬ)

import run_baseline  # noqa: E402  (ставит config и заглушку MetaTrader5)

import baseline_engine  # noqa: E402
import history_data     # noqa: E402
import optimize         # noqa: E402
import trade_stats      # noqa: E402
import validation       # noqa: E402

logging.basicConfig(level=logging.ERROR,
                    format="%(levelname)s %(name)s: %(message)s")

СИМВОЛЫ_ПО_УМОЛЧАНИЮ = ["XAUUSD", "EURUSD"]


# Свечи лежат в глобальной переменной, а не передаются в каждую задачу.
# Причина не в красоте: свечей десятки тысяч, и упаковка их для каждого из
# восьми вариантов — это сотни мегабайт пересылки на ровном месте. При fork
# дочерний процесс видит эту память как есть, бесплатно.
_ДАННЫЕ = {"symbol": "", "bars": [], "meta": {}}


def _прогон(задача):
    """Один вариант на одном отрезке. Вынесено наружу ради нескольких ядер."""
    вариант, отрезок = задача
    try:
        return optimize.run_variant(_ДАННЫЕ["symbol"], _ДАННЫЕ["bars"],
                                    _ДАННЫЕ["meta"], вариант, отрезок)
    except Exception as e:  # noqa: BLE001
        return {"вариант": вариант.get("код", "?"), "имя": вариант.get("имя", ""),
                "trades": [], "money": [],
                "сводка": trade_stats.summarize([], вариант.get("код", "?")),
                "rejects": {}, "error": f"{type(e).__name__}: {e}"}


def прогнать_все(варианты, отрезок, workers: int):
    """Прогнать список вариантов, по возможности на нескольких ядрах."""
    задачи = [(в, отрезок) for в in варианты]
    if workers <= 1 or len(задачи) <= 1:
        return [_прогон(з) for з in задачи]
    import multiprocessing as mp
    # fork: дочерний процесс наследует уже настроенный config, заглушку
    # терминала и свечи. Пересобирать их в каждом работнике значило бы
    # рисковать тем, что варианты посчитаются по разным настройкам.
    ctx = mp.get_context("fork")
    with ctx.Pool(processes=workers) as pool:
        return pool.map(_прогон, задачи)


def строка(код, имя, св, пометка=""):
    мало = "" if св["достаточно_данных"] else "  [UNKNOWN: мало сделок]"
    return (f"  {код:<14} сделок {св['сделок']:>5}  PF {св['профит_фактор']:>6}  "
            f"ожидание {св['ожидание']:>9}  просадка {св['макс_просадка']:>8}"
            f"  {пометка}{мало}   {имя}")


def вердикт(с) -> str:
    """Короткий приговор для таблицы.

    Разделять «мало сделок» и «числа хуже» обязательно: это разные вещи.
    Первое означает «нечем судить», второе — «судили и не вышло». Написать
    в обоих случаях «отклонён (0/5)» значило бы соврать в половине строк."""
    if not с["достаточно_сделок"]:
        return f"нечем судить (сделок {с['сводка']['сделок']}, нужно {optimize.МИНИМУМ_СДЕЛОК})"
    return (f"{'ПРОШЁЛ' if с['решение'] == 'принять' else 'отклонён'} "
            f"({с['способов_за']}/5)")


def отрезок_словами(имя, границы, всего):
    начало, конец = границы
    доля = (конец - начало) / всего * 100 if всего else 0
    return f"{имя}: свечи {начало}-{конец} ({доля:.0f}% истории)"


def по_инструменту(symbol: str, max_bars: int, workers: int) -> dict:
    print()
    print("=" * 70)
    print(f"ПОДБОР ПАРАМЕТРОВ: {symbol}")
    print("=" * 70)

    данные = history_data.load(symbol)
    if not данные["clean"] or not данные["quality"]["usable"]:
        print("СТАТУС: INSUFFICIENT DATA — данных нет или они негодны. "
              "Ничего не подбирается, результат не выдумывается.")
        return {"symbol": symbol, "статус": "INSUFFICIENT DATA"}

    bars = данные["clean"]
    if max_bars and len(bars) > max_bars:
        bars = bars[-int(max_bars):]
    _ДАННЫЕ["symbol"] = symbol
    _ДАННЫЕ["bars"] = bars
    _ДАННЫЕ["meta"] = данные["meta"]
    границы = optimize.segments(bars)
    print(f"Свечей: {len(bars)}. История разрезана ПО ВРЕМЕНИ:")
    for имя in ("TRAIN", "VALIDATION", "OOS"):
        print("  " + отрезок_словами(имя, границы[имя], len(bars)))
    print("Разгон индикаторов для каждого куска берётся из свечей ПЕРЕД ним — "
          "они в прошлом, заглядыванием вперёд не являются.")

    варианты = optimize.variants(symbol)
    print(f"\nЧто проверяется ({len(варианты)} вариантов):")
    for в in варианты:
        print(f"  {в['код']}. {в['имя']}")
        print(f"     почему: {в['почему']}")

    # ---------------------------------------------------------------- TRAIN
    print()
    print("-" * 70)
    print(f"TRAIN — здесь варианты соревнуются. {symbol}")
    print("-" * 70)
    все = [optimize.БАЗА] + варианты
    прогоны = прогнать_все(все, границы["TRAIN"], workers)
    база = прогоны[0]
    if база.get("error"):
        print(f"СТАТУС: INSUFFICIENT DATA — {база['error']}")
        return {"symbol": symbol, "статус": "INSUFFICIENT DATA"}

    print(строка("БАЗА", "как сейчас", база["сводка"]))
    сравнения = []
    for п in прогоны[1:]:
        if п.get("error"):
            print(f"  {п['вариант']:<14} ОШИБКА: {п['error']}")
            continue
        с = optimize.compare(база, п)
        сравнения.append(с)
        print(строка(п["вариант"], п["имя"], п["сводка"], вердикт(с)))

    # ДИАГНОСТИКА ПЕЧАТАЕТСЯ ВСЕГДА, а не только при провале. Таблица вариантов
    # отвечает на вопрос «какая настройка лучше». Она не отвечает на вопрос
    # «а не бессмысленна ли сама конструкция» — а он важнее.
    print()
    print("ДОСТИЖИМА ЛИ ЦЕЛЬ ВООБЩЕ (замер по базовому прогону):")
    print(optimize.describe_reach(optimize.reach_report(база["trades"])))

    прошедшие = optimize.survivors(сравнения)
    if not прошедшие:
        print("\nНи один вариант не прошёл ворота на TRAIN.")
        return {"symbol": symbol, "статус": "НЕТ УЛУЧШЕНИЯ",
                "база": база["сводка"], "прошли_train": []}

    print(f"\nПрошли TRAIN: {', '.join(с['вариант'] for с in прошедшие)}")

    # ----------------------------------------------------------- VALIDATION
    print()
    print("-" * 70)
    print(f"VALIDATION — те же варианты на данных, которых они не видели. {symbol}")
    print("-" * 70)
    коды = {в["код"]: в for в in варианты}
    к_проверке = [optimize.БАЗА] + [коды[с["вариант"]] for с in прошедшие]
    прогоны_v = прогнать_все(к_проверке, границы["VALIDATION"], workers)
    база_v = прогоны_v[0]
    print(строка("БАЗА", "как сейчас", база_v["сводка"]))

    выжившие = []
    for п in прогоны_v[1:]:
        if п.get("error"):
            print(f"  {п['вариант']:<14} ОШИБКА: {п['error']}")
            continue
        с = optimize.compare(база_v, п)
        print(строка(п["вариант"], п["имя"], п["сводка"], вердикт(с)))
        if с["решение"] == "принять" and с["достаточно_сделок"]:
            выжившие.append((с, п))

    if not выжившие:
        print("\nНи один вариант не подтвердился на VALIDATION. "
              "На TRAIN они выигрывали, на новых данных — нет. Так выглядит "
              "подгонка, и именно ради этого кусок истории и держат отдельно.")
        return {"symbol": symbol, "статус": "НЕ ПОДТВЕРДИЛОСЬ НА VALIDATION",
                "база": база["сводка"],
                "прошли_train": [с["вариант"] for с in прошедшие]}

    # Финалист один: чем больше кандидатов пускают на OOS, тем выше шанс, что
    # кто-то пройдёт его случайно. Берём лучшего по ожиданию на сделку.
    выжившие.sort(key=lambda пара: float(пара[1]["сводка"]["ожидание"] or 0),
                  reverse=True)
    финалист_с, финалист_п = выжившие[0]
    финалист = коды[финалист_с["вариант"]]
    print(f"\nНа OOS допускается ОДИН вариант: {финалист['код']} — {финалист['имя']}.")
    print("Больше нельзя: чем больше кандидатов пробуют последний кусок, тем "
          "выше шанс, что кто-то пройдёт его по чистой случайности.")

    # ------------------------------------------------- УСТОЙЧИВОСТЬ (на VALIDATION)
    print()
    print("-" * 70)
    print(f"УСТОЙЧИВОСТЬ — а держится ли результат при сдвиге числа? {symbol}")
    print("-" * 70)
    соседи = optimize.sensitivity(symbol, bars, данные["meta"], финалист,
                                  границы["VALIDATION"])
    if not соседи:
        print("У этого варианта нет числа, которое можно сдвинуть "
              "(это переключатель да/нет или сторона сделки). Проверка "
              "устойчивости к нему неприменима.")
        устойчивость = {"устойчив": True, "соседей": 0, "подробно": [],
                        "неприменимо": True}
    else:
        устойчивость = optimize.robust(база_v, соседи)
        for п in устойчивость["подробно"]:
            знак = "держится" if п["держится"] else "РАССЫПАЛСЯ"
            print(строка("сосед", п["имя"], п["сводка"],
                         f"{знак} ({п['метрик_лучше']}/4)"))
        if not устойчивость["устойчив"]:
            print("\nРезультат держится только при одном значении и рассыпается "
                  "при сдвиге на 20%. Это не найденная закономерность, а точка "
                  "на графике шума. ОТКЛОНЕНО, до OOS не допускается.")
            return {"symbol": symbol, "статус": "НЕУСТОЙЧИВ",
                    "база": база["сводка"], "финалист": финалист["код"]}
        print("\nРезультат держится у всех соседей.")

    # ------------------------------------------------------------------ OOS
    print()
    print("-" * 70)
    print(f"OUT OF SAMPLE — последнее слово. Один вариант, один раз. {symbol}")
    print("-" * 70)
    прогоны_o = прогнать_все([optimize.БАЗА, финалист], границы["OOS"], workers)
    база_o, финал_o = прогоны_o
    print(строка("БАЗА", "как сейчас", база_o["сводка"]))
    с_oos = optimize.compare(база_o, финал_o)
    print(строка(финал_o["вариант"], финал_o["имя"], финал_o["сводка"],
                 f"{'лучше базы' if с_oos['решение'] == 'принять' else 'не лучше базы'} "
                 f"({с_oos['способов_за']}/5)"))
    print()
    print(validation.describe({"решение": с_oos["решение"],
                               "причина": с_oos["причина"],
                               "способы": с_oos["способы"]}))

    # ДВА ПОРОГА, А НЕ ОДИН.
    лучше_базы = с_oos["решение"] == "принять"
    прибылен = с_oos["прибылен"]
    хватает = с_oos["достаточно_сделок"]
    print()
    print(f"  Лучше базы на OOS:      {'да' if лучше_базы else 'НЕТ'}")
    print(f"  Прибылен сам по себе:   {'да' if прибылен else 'НЕТ'} "
          f"(нужно PF > {optimize.ГОДЕН_ПФ} и ожидание > {optimize.ГОДЕН_ОЖИДАНИЕ})")
    print(f"  Сделок хватает:         {'да' if хватает else 'НЕТ'} "
          f"({с_oos['сводка']['сделок']}, нужно {optimize.МИНИМУМ_СДЕЛОК})")

    принят = лучше_базы and прибылен and хватает
    if не_принят_почему(лучше_базы, прибылен, хватает):
        print("\n" + не_принят_почему(лучше_базы, прибылен, хватает))

    return {"symbol": symbol,
            "статус": "КАНДИДАТ" if принят else "ОТКЛОНЁН НА OOS",
            "база": база["сводка"], "финалист": финалист["код"],
            "финалист_имя": финалист["имя"],
            "oos": финал_o["сводка"], "oos_база": база_o["сводка"],
            "лучше_базы": лучше_базы, "прибылен": прибылен}


def не_принят_почему(лучше, прибылен, хватает) -> str:
    if лучше and прибылен and хватает:
        return ""
    if not хватает:
        return ("ОТКЛОНЁН: на чистой проверке слишком мало сделок. Это не "
                "слабое доказательство, а его отсутствие.")
    if лучше and not прибылен:
        return ("ОТКЛОНЁН. Вариант ЛУЧШЕ базы, но САМ ПО СЕБЕ убыточен. "
                "Принять такое значило бы поменять быстрый убыток на "
                "медленный и назвать это победой. Менее убыточно — это не "
                "прибыльно.")
    return ("ОТКЛОНЁН: на чистой проверке вариант не оказался лучше базы. "
            "На TRAIN он выигрывал — значит выигрывал у этого куска истории, "
            "а не у рынка.")


def main(argv) -> int:
    max_bars = 0
    workers = min(4, os.cpu_count() or 1)
    символы = []
    # Разбор идёт по порядку, а не поиском по списку. Иначе число ПОСЛЕ ключа
    # («--bars 40000») остаётся в списке и принимается за имя инструмента —
    # программа честно ищет историю пары «40000» и не находит.
    i = 0
    while i < len(argv):
        а = argv[i]
        if а in ("--bars", "--workers"):
            try:
                знач = int(argv[i + 1])
            except (IndexError, ValueError):
                print(f"После {а} нужно число, например: {а} 40000")
                return 2
            if а == "--bars":
                max_bars = знач
            else:
                workers = max(1, знач)
            i += 2
            continue
        if not а.startswith("--"):
            символы.append(а)
        i += 1
    символы = символы or СИМВОЛЫ_ПО_УМОЛЧАНИЮ

    print("=" * 70)
    print("PHASE 3 — ПОДБОР ПАРАМЕТРОВ ПОД ПРИСМОТРОМ")
    print("=" * 70)
    print("Меняются ТОЛЬКО числа настроек. Ни одна строка торговой логики не "
          "трогается, ничего не записывается в программу.")
    print(f"Настройки взяты из: {run_baseline.ОТКУДА_НАСТРОЙКИ}")
    print(f"Терминал: {run_baseline.ОТКУДА_ТЕРМИНАЛ}")
    print(f"Ядер под прогон: {workers}")
    print()
    print("РИСК НЕ ПОДБИРАЕТСЯ. Запрещено трогать: "
          + ", ".join(sorted(optimize.ЗАПРЕЩЕНО)))
    print("Причина: увеличение риска ВСЕГДА улучшает прибыль на истории и "
          "ВСЕГДА ухудшает шанс пережить настоящую просадку.")
    print()
    print(baseline_engine.describe_not_reproducible())

    результаты = [по_инструменту(s, max_bars, workers) for s in символы]

    print()
    print("=" * 70)
    print("ИТОГ PHASE 3")
    print("=" * 70)
    кандидаты = [r for r in результаты if r.get("статус") == "КАНДИДАТ"]
    for r in результаты:
        строка_итога = f"{r['symbol']}: {r['статус']}"
        if r.get("финалист"):
            строка_итога += f" (финалист {r['финалист']} — {r.get('финалист_имя','')})"
        print(строка_итога)

    print()
    if not кандидаты:
        print("Baseline не подтверждает наличие улучшения параметрами.")
        print()
        print("Это не отговорка и не «надо ещё поискать». Проверено семь "
              "вариантов на каждом инструменте, в три этапа, с проверкой "
              "устойчивости. Стратегия НЕ МЕНЯЕТСЯ.")
    else:
        print("ЕСТЬ КАНДИДАТЫ. Ни один из них НЕ ВНЕСЁН в программу:")
        for r in кандидаты:
            print(f"  {r['symbol']}: {r['финалист']} — {r['финалист_имя']}")
            print(f"    на чистой проверке: PF {r['oos']['профит_фактор']}, "
                  f"ожидание {r['oos']['ожидание']}, сделок {r['oos']['сделок']}")
        print()
        print("Решение принимает владелец. Пока он не сказал «внести» — "
              "в программе ничего не меняется.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
