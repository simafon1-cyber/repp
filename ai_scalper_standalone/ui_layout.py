"""ui_layout.py — сколько места занимают вкладки. В пикселях, а не на глаз.

ЗАЧЕМ ЭТОТ ФАЙЛ ПОЯВИЛСЯ

Владелец: «вкладки, кнопки — они выходят за границы, приходится увеличивать
окно. Сделай более компактно».

Причина была простой и арифметической: вкладок стало четырнадцать. Их полоса
шире окна, поэтому названия обрезались, а часть вкладок уезжала за край. Все
предыдущие попытки чинились «на глаз»: сократить название, подвинуть кнопку,
посмотреть на скриншот. На другом мониторе и при другом масштабе шрифта это
разъезжалось заново.

Здесь ширина считается ЧИСЛОМ. Раскладка описана данными, а не разбросана по
пяти тысячам строк окна, и на неё есть тест: полоса вкладок обязана помещаться
в минимальную ширину окна с запасом. Если кто-то добавит пятнадцатую вкладку
или длинное название — тест упадёт до сборки, а не после установки.

ЧЕСТНАЯ ОГОВОРКА ПРО ТОЧНОСТЬ. Ширина знака здесь — ОЦЕНКА сверху: настоящая
ширина зависит от шрифта системы и масштаба экрана, а посчитать её без
запущенного окна нельзя. Поэтому оценка нарочно завышена (см. ЗНАК_ПИКСЕЛЕЙ),
и сверх неё заложен запас. А уже запущенное окно перемеряет полосу настоящим
шрифтом — measure_strip() — и жалуется в журнал, если реальность разошлась
с оценкой.
"""

# Ширина одного знака в шрифте вкладок, пикселей. Segoe UI 9 даёт в среднем
# около 7 пикселей на знак кириллицы; берём 8 — оценка обязана быть СВЕРХУ,
# иначе проверка пропустит раскладку, которая на деле не помещается.
ЗНАК_ПИКСЕЛЕЙ = 8
# Поля слева и справа внутри одной вкладки плюс разделитель между вкладками.
ОТСТУП_ВКЛАДКИ = 24
# Рамки окна и поля вокруг полосы вкладок.
ЗАПАС_ОКНА = 40
# Минимальная ширина окна: меньше этого окно не ужимается (root.minsize).
МИН_ШИРИНА_ОКНА = 900
# Сколько места обязано остаться свободным. Ноль означал бы «впритык», а
# впритык на чужом мониторе превращается в «не помещается».
СВОБОДНО_ДОЛЯ = 0.15

# --------------------------------------------------------------------------
# РАСКЛАДКА: верхняя вкладка -> страницы внутри неё.
#
# Правило группировки — по вопросу, с которым человек открывает программу:
#   «как идут дела?»        -> Обзор
#   «что со счетами?»       -> Счета
#   «чем и как торгуем?»    -> Торговля
#   «что мешает торговать?» -> Новости
#   «что уже произошло?»    -> Журнал
#   «почему не работает?»   -> Система
#   «как этим пользоваться?»-> Помощь
#
# Группа из одной страницы вкладывается в окно напрямую, без второго ряда
# вкладок: лишний ряд ради одной страницы — это та самая ненужная сложность.
# --------------------------------------------------------------------------
ГРУППЫ = {
    "Обзор": ["Обзор"],
    "Счета": ["Счета"],
    "Торговля": ["Символы", "Настройка"],
    "Новости": ["Новости", "Календарь", "Источники", "Сигналы"],
    "Журнал": ["Лог", "Equity"],
    "Система": ["Брокер", "Система"],
    "Помощь": ["Помощь", "Чат"],
}


def tab_width(label: str, знак: int = ЗНАК_ПИКСЕЛЕЙ,
              отступ: int = ОТСТУП_ВКЛАДКИ) -> int:
    """Ширина одной вкладки в пикселях: текст плюс поля."""
    return len(str(label)) * знак + отступ


def strip_width(labels, знак: int = ЗНАК_ПИКСЕЛЕЙ,
                отступ: int = ОТСТУП_ВКЛАДКИ) -> int:
    """Ширина всей полосы вкладок."""
    return sum(tab_width(x, знак, отступ) for x in (labels or ()))


def fits(labels, window_px: int = МИН_ШИРИНА_ОКНА, знак: int = ЗНАК_ПИКСЕЛЕЙ,
         отступ: int = ОТСТУП_ВКЛАДКИ) -> bool:
    """Помещается ли полоса в окно ЗАДАННОЙ ширины, с запасом."""
    доступно = (window_px - ЗАПАС_ОКНА) * (1 - СВОБОДНО_ДОЛЯ)
    return strip_width(labels, знак, отступ) <= доступно


def group_names() -> list:
    """Названия верхних вкладок, в порядке показа."""
    return list(ГРУППЫ.keys())


def pages(group: str) -> list:
    """Страницы внутри группы."""
    return list(ГРУППЫ.get(group, ()))


def all_pages() -> list:
    """Все страницы программы — ни одна не должна потеряться при группировке."""
    out = []
    for имена in ГРУППЫ.values():
        out.extend(имена)
    return out


def group_of(page: str) -> str:
    """В какой группе лежит страница. Пустая строка, если такой страницы нет."""
    for группа, имена in ГРУППЫ.items():
        if page in имена:
            return группа
    return ""


def is_single(group: str) -> bool:
    """Группа из одной страницы: второй ряд вкладок ей не нужен."""
    return len(ГРУППЫ.get(group, ())) == 1


def problems(window_px: int = МИН_ШИРИНА_ОКНА, hidden=()) -> list:
    """Что не так с раскладкой. Пустой список — всё в порядке.

    hidden — страницы, спрятанные в простом режиме. Группа не должна
    опустеть: вкладка без единой страницы — это тупик для человека."""
    беды = []
    верх = group_names()
    if not fits(верх, window_px):
        беды.append(f"Полоса вкладок {strip_width(верх)} px не помещается "
                    f"в окно {window_px} px")

    for группа in верх:
        внутри = [p for p in pages(группа) if p not in set(hidden or ())]
        if not внутри:
            беды.append(f"Группа «{группа}» осталась без страниц")
        # Второй ряд вкладок уже, чем окно, ровно на поля первого ряда.
        elif not is_single(группа) and not fits(внутри, window_px - ЗАПАС_ОКНА):
            беды.append(f"Страницы группы «{группа}» не помещаются в ряд")

    повторы = [p for p in all_pages() if all_pages().count(p) > 1]
    if повторы:
        беды.append(f"Страница лежит сразу в двух группах: {sorted(set(повторы))}")
    return беды


def measure_strip(labels) -> int:
    """Перемерить полосу НАСТОЯЩИМ шрифтом уже открытого окна.

    Оценка выше — приблизительная, и приблизительной она останется: реальный
    шрифт зависит от системы и масштаба экрана. Это единственный способ
    узнать правду, и он требует живого окна, поэтому в тестах не участвует.
    Возвращает 0, если измерить не удалось — молча, потому что ронять окно
    из-за неудачного замера ширины было бы нелепо."""
    try:
        import tkinter.font as tkfont
        шрифт = tkfont.nametofont("TkDefaultFont")
        return sum(шрифт.measure(str(x)) + ОТСТУП_ВКЛАДКИ for x in labels)
    except Exception:  # noqa: BLE001
        return 0
