"""run_h1_study.py — ПРОВЕРКА ПРЕДЗАРЕГИСТРИРОВАННОЙ ГИПОТЕЗЫ H1.

ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ И ЧТО НЕТ

Проверяется ОДНО числовое предсказание, записанное в паспорте до прогона:

    медианная доля издержек в риске сделки на H1 меньше ПОЛОВИНЫ
    от той же доли на M5 — по каждому из семи инструментов,
    при базовом сценарии издержек.

Это узкий механический вопрос. Он НЕ отвечает на вопрос «стала ли
стратегия прибыльной» и не может на него ответить: доля издержек — это
свойство инструмента и размера стопа, а не результата сделок.

ПОЧЕМУ ПРИБЫЛЬ ЗДЕСЬ ПОКАЗЫВАЕТСЯ, НО НЕ ЗАСЧИТЫВАЕТСЯ

Ожидание в R на H1 печатается — прятать числа нельзя. Но засчитывать его
как доказательство преимущества нельзя тоже: старые данные уже участвовали
в том, что мысль про H1 вообще возникла. Для вывода о преимуществе нужен
период, которого мы не видели. Это записано в паспорте и повторяется в
выводе прогона.

Запуск:
    python run_h1_study.py
"""

import json
import logging
import os
import statistics
import sys

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
КОРЕНЬ = os.path.dirname(ЗДЕСЬ)
sys.path.insert(0, ЗДЕСЬ)

import run_baseline  # noqa: E402  (ставит config и заглушку MetaTrader5)

import build_h1           # noqa: E402
import costs              # noqa: E402
import entry_lab          # noqa: E402
import history_data       # noqa: E402
import ledger             # noqa: E402
import research_manifest  # noqa: E402
import run_entry_search as поиск_m5   # noqa: E402

logging.basicConfig(level=logging.ERROR,
                    format="%(levelname)s %(name)s: %(message)s")

ПАСПОРТ = os.path.join(КОРЕНЬ, "preregistration", "manifest_h1.json")
ПАПКА = os.path.join(ЗДЕСЬ, "research")
ЖУРНАЛ_H1 = os.path.join(ПАПКА, "h1_ledger.csv")
РЕЗУЛЬТАТ = os.path.join(ПАПКА, "h1_results.json")

# Всё, что ниже, взято из паспорта и здесь НЕ выбирается заново.
ГОРИЗОНТ_H1 = 24
ДОЛЯ_TRAIN = 0.50
ДОЛЯ_VALIDATION = 0.25


def заголовок(текст, знак="="):
    print()
    print(знак * 100)
    print(текст)
    print(знак * 100)


def отрезки(n: int) -> dict:
    a = int(n * ДОЛЯ_TRAIN)
    b = int(n * (ДОЛЯ_TRAIN + ДОЛЯ_VALIDATION))
    return {"TRAIN": (0, a), "VALIDATION": (a, b), "OOS": (b, n)}


def доли_издержек(ряд, symbol, горизонт) -> list:
    """Доля издержек в риске по каждой сделке всех признаков.

    Берутся сделки ПРИЗНАКОВ (не зеркала и не случайного входа): паспорт
    говорит про долю издержек в риске сделки, а сделки — это то, что
    открывает признак."""
    доли = []
    сделки_всего = []
    for имя, признак in entry_lab.ПРИЗНАКИ.items():
        for гр_имя, (начало, конец) in отрезки(ряд["n"]).items():
            итог = entry_lab.прогнать(ряд, признак, начало, конец, seed=17,
                                      symbol=symbol, горизонт=горизонт)
            for с in итог["признак"]:
                риск = float(с.get("риск_денег", 0.0))
                if риск > 0:
                    доли.append(float(с["издержки_всего"]) / риск)
                    сделки_всего.append(с)
    return доли, сделки_всего


def main() -> int:
    # 1. ПАСПОРТ ЧИТАЕТСЯ ПЕРВЫМ. Прогон без него не начинается, а
    #    изменённый после заверения — отвергается.
    паспорт = research_manifest.прочитать(ПАСПОРТ)

    заголовок("ПРОВЕРКА ПРЕДЗАРЕГИСТРИРОВАННОЙ ГИПОТЕЗЫ H1")
    print(research_manifest.описание(паспорт))
    print()
    print(costs.сводка_сценариев())

    символы = list(паспорт["инструменты"])

    # 2. ДАННЫЕ. Тот же архив, что записан в паспорте.
    заголовок("ДАННЫЕ", "-")
    ряды_m5, ряды_h1, паспорта_данных = {}, {}, {}
    for s in символы:
        try:
            d = history_data.load(s, timeframe="M5")
        except Exception as e:  # noqa: BLE001
            raise SystemExit(f"{s}: история не читается ({e}). "
                             f"Распакуйте data/history_M5.tar.gz")
        bars = d["clean"]
        if not bars or not d["quality"]["usable"]:
            raise SystemExit(f"{s}: данные негодны — прогон недействителен")

        собрано = build_h1.собрать(bars)
        if not собрано["bars"]:
            raise SystemExit(f"{s}: часовых свечей не собралось")

        ряды_m5[s] = entry_lab.подготовить(bars)
        ряды_h1[s] = entry_lab.подготовить(собрано["bars"])
        паспорта_данных[s] = {
            "пятиминуток": собрано["из_пятиминуток"],
            "часов": собрано["часов_получено"],
            "часов_отброшено_неполных": собрано["часов_отброшено_неполных"],
            "хеш_h1": собрано["хеш"],
        }
        print(f"  {s:<8} M5 {собрано['из_пятиминуток']:>6}  →  "
              f"H1 {собрано['часов_получено']:>5}  "
              f"(неполных часов отброшено {собрано['часов_отброшено_неполных']})")
        print(f"           хеш H1: {собрано['хеш']}")

    # 3. ПРОВЕРКА ПРЕДСКАЗАНИЯ — при БАЗОВОМ сценарии, как в паспорте.
    было = costs.выбрать_сценарий(costs.БАЗОВЫЙ)
    try:
        заголовок("ПРЕДСКАЗАНИЕ ПАСПОРТА: ДОЛЯ ИЗДЕРЖЕК ПАДАЕТ БОЛЬШЕ ЧЕМ ВДВОЕ")
        print("Медианная доля издержек в риске сделки, базовый сценарий.")
        print(f"{'инстр':<9}{'M5':>10}{'H1':>10}{'во сколько':>13}"
              f"{'сделок M5':>11}{'сделок H1':>11}   вердикт")

        строки, подтверждений, мало_сделок = [], 0, []
        for s in символы:
            доли_m5, сделки_m5 = доли_издержек(ряды_m5[s], s,
                                               entry_lab.ГОРИЗОНТ)
            доли_h1, сделки_h1 = доли_издержек(ряды_h1[s], s, ГОРИЗОНТ_H1)

            мед_m5 = statistics.median(доли_m5) if доли_m5 else 0.0
            мед_h1 = statistics.median(доли_h1) if доли_h1 else 0.0
            во_сколько = (мед_m5 / мед_h1) if мед_h1 > 0 else 0.0

            хватает = len(сделки_h1) >= int(паспорт["минимум_сделок"])
            подтверждено = хватает and мед_h1 < мед_m5 / 2.0
            подтверждений += 1 if подтверждено else 0
            if not хватает:
                мало_сделок.append(s)

            вердикт = ("подтверждено" if подтверждено
                       else ("МАЛО СДЕЛОК — вывода нет" if not хватает
                             else "не подтверждено"))
            print(f"{s:<9}{мед_m5:>10.4f}{мед_h1:>10.4f}{во_сколько:>12.2f}×"
                  f"{len(сделки_m5):>11}{len(сделки_h1):>11}   {вердикт}")
            строки.append({
                "инструмент": s,
                "доля_издержек_m5": round(мед_m5, 6),
                "доля_издержек_h1": round(мед_h1, 6),
                "во_сколько_раз_меньше": round(во_сколько, 3),
                "сделок_m5": len(сделки_m5),
                "сделок_h1": len(сделки_h1),
                "хватает_сделок": хватает,
                "подтверждено": подтверждено,
            })
    finally:
        costs.выбрать_сценарий(было)

    # 4. ТРИ СЦЕНАРИЯ ОТДЕЛЬНО. Вывод, держащийся на одном, не засчитан.
    заголовок("ТО ЖЕ ПРИ ТРЁХ СЦЕНАРИЯХ ИЗДЕРЖЕК", "-")
    по_сценариям = {}
    print(f"{'сценарий':<10}{'инстр':<9}{'доля M5':>10}{'доля H1':>10}"
          f"{'во сколько':>13}")
    for сценарий in (costs.НИЗКИЙ, costs.БАЗОВЫЙ, costs.ВЫСОКИЙ):
        было = costs.выбрать_сценарий(сценарий)
        try:
            по_сценариям[сценарий] = []
            for s in символы:
                доли_m5, _ = доли_издержек(ряды_m5[s], s, entry_lab.ГОРИЗОНТ)
                доли_h1, _ = доли_издержек(ряды_h1[s], s, ГОРИЗОНТ_H1)
                м5 = statistics.median(доли_m5) if доли_m5 else 0.0
                х1 = statistics.median(доли_h1) if доли_h1 else 0.0
                во = (м5 / х1) if х1 > 0 else 0.0
                print(f"{сценарий:<10}{s:<9}{м5:>10.4f}{х1:>10.4f}{во:>12.2f}×")
                по_сценариям[сценарий].append({
                    "инструмент": s, "доля_m5": round(м5, 6),
                    "доля_h1": round(х1, 6), "во_сколько": round(во, 3)})
        finally:
            costs.выбрать_сценарий(было)

    # 5. ВЕРДИКТ ПО ЗАРАНЕЕ ЗАПИСАННОМУ КРИТЕРИЮ.
    заголовок("ВЕРДИКТ ПО КРИТЕРИЮ ИЗ ПАСПОРТА")
    print(f"Подтверждено на {подтверждений} инструментах из {len(символы)}.")
    if мало_сделок:
        print(f"Сделок не хватило: {', '.join(мало_сделок)} — "
              f"по ним вывода НЕТ.")
        print("Паспорт называет это отсутствием проверки, а не провалом "
              "гипотезы.")
    не_подтверждено = len(символы) - подтверждений - len(мало_сделок)
    if подтверждений == len(символы):
        print("ПРЕДСКАЗАНИЕ ПОДТВЕРЖДЕНО по критерию из паспорта.")
    elif не_подтверждено >= 3:
        print("ПРЕДСКАЗАНИЕ ОПРОВЕРГНУТО: не подтвердилось на "
              f"{не_подтверждено} инструментах (порог провала — три).")
    else:
        print("ПРЕДСКАЗАНИЕ ПОДТВЕРЖДЕНО ЧАСТИЧНО — это не «да» и не «нет».")

    заголовок("ЧЕГО ЭТОТ ПРОГОН НЕ ДОКАЗЫВАЕТ")
    print("Он не показывает, что стратегия на H1 прибыльна, и не может.")
    print("Доля издержек — свойство инструмента и размера стопа, а не")
    print("результата сделок.")
    print()
    print("Старые данные уже участвовали в том, что мысль про H1 возникла.")
    print("Поэтому любой результат по прибыли на них — не доказательство")
    print("преимущества, а материал для НОВОЙ отдельной проверки на")
    print("периоде, которого мы не видели, и затем на демо.")

    os.makedirs(ПАПКА, exist_ok=True)
    with open(РЕЗУЛЬТАТ, "w", encoding="utf-8") as f:
        json.dump({
            "паспорт_хеш": паспорт[research_manifest.ПОЛЕ_ХЕША],
            "данные": паспорта_данных,
            "предсказание_базовый": строки,
            "по_сценариям": по_сценариям,
            "подтверждено_инструментов": подтверждений,
            "мало_сделок": мало_сделок,
        }, f, ensure_ascii=False, indent=2)
    print()
    print(f"Результаты записаны: {РЕЗУЛЬТАТ}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
