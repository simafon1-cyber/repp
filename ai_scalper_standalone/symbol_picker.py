"""symbol_picker.py — сам выбирает пары у брокера.

ЗАЧЕМ
Владелец: «можешь добавить, чтобы список сам подгружался — всё, что есть у
брокера, и он старался работать на всех парах? Если проблематично — выбрать
самые топовые пары, на которых больше всего вариант заработать».

=====================================================================
СРАЗУ ЧЕСТНО: НА ВСЕХ ПАРАХ — НЕЛЬЗЯ, И ВОТ ПОЧЕМУ
=====================================================================
У брокера их сотни. На каждую пару за один проход программа делает несколько
обращений к терминалу: бары рабочего таймфрейма, бары трендового, тик,
описание символа. Осторожная оценка — около 40 мс на пару:

      4 пары ->  0.2 с        100 пар ->  4.0 с
     30 пар ->  1.2 с        300 пар -> 12.0 с

Полный круг задан POLL_SECONDS = 5 секунд. На трёх сотнях пар круг занимал бы
двенадцать — то есть скальпер работал бы по ценам двенадцатисекундной
давности. Для стратегии, где сделка живёт семь минут, это не «чуть медленнее»,
а совсем другая торговля.

ПОПРАВКА, СДЕЛАННАЯ ПОЗЖЕ. Этот расчёт верен, но вывод из него был слишком
поспешным: сначала здесь стоял потолок в 20 пар. Он оказался ненастоящим.
Вход в сделку возможен ТОЛЬКО на новом баре, а таймфрейм M5 — бар раз в 300
секунд; из шестидесяти обходов пары между барами пятьдесят девять
заканчивались ничем. Теперь пары без открытой сделки обходятся по очереди, и
список может быть в разы длиннее без растягивания круга (scan_rotation.py).
Потолок AUTO_PICK_LIMIT по умолчанию снят (0 = все подходящие).

Есть и вторая причина, и вот она никуда не делась. Пары НЕ независимы. EURUSD,
GBPUSD, AUDUSD и NZDUSD — это в основном ставка на доллар. Открыв «десять
разных сделок», можно сделать одну и ту же ставку десять раз и получить
десятикратный убыток там, где казалось, что риск размазан. Поэтому ограничение
осталось, но переехало туда, где ему место — на ОДНОВРЕМЕННО ОТКРЫТЫЕ сделки
(MAX_POSITIONS_PER_CURRENCY, risk_manager.currency_exposure_reason). Смотреть
пары ничего не стоит; платим мы только за открытые.

=====================================================================
ЧТО ДЕЛАЕТСЯ ВМЕСТО ЭТОГО
=====================================================================
Программа берёт ВЕСЬ список брокера и сама отбирает лучшие пары по признакам,
которые можно посчитать, а не угадать:

1. ПО КАРМАНУ ЛИ. Минимальный лот брокера рискует не больше, чем разрешено
   от счёта. Пара, где один минимальный лот стоит 7% депозита, не «рискованная
   — это просто не наш размер.

2. СКОЛЬКО СТОИТ ВХОД. Главная цифра — спред, делённый на ATR: какую долю
   обычного движения инструмента съедает плата за вход. У пары со спредом в
   треть дневного хода заработать нельзя никакой стратегией.

3. ЕСТЬ ЛИ ЧТО ЛОВИТЬ. Совсем неподвижный инструмент бесполезен: движения
   меньше спреда не окупают даже вход.

4. РАЗРЕШЕНА ЛИ ТОРГОВЛЯ. Прямой ответ брокера.

5. НЕ ОДНА И ТА ЖЕ СТАВКА. Ограничение по валютам умеет работать и здесь
   (per_currency), но по умолчанию выключено: список смотреть не жалко.
   По-настоящему оно стоит на одновременно открытых сделках — см. выше.

Ничего из этого не является предсказанием прибыли. Это отсев заведомо
невыгодных инструментов — то есть уменьшение расходов, а не поиск сигналов.
"""

import logging

log = logging.getLogger("symbol_picker")

# Сколько пар брать, если потолок вообще задан. Ноль означает «все
# подходящие» — длинный список круг не растягивает, потому что пары без
# открытой сделки обходятся по очереди (scan_rotation.py).
DEFAULT_LIMIT = 20

# Не больше стольких пар с одной и той же валютой. Три пары с долларом — это
# уже во многом одна ставка, шесть — точно одна.
DEFAULT_PER_CURRENCY = 3


def spread_cost_ratio(spread_points: float, atr_points: float) -> float:
    """Какую долю обычного движения съедает спред. Меньше — лучше.

    Это и есть цена входа, выраженная понятно. Спред в пунктах сам по себе
    ничего не говорит: 20 пунктов на паре, которая ходит 2000, — это дёшево,
    а на паре, которая ходит 60, — это половина хода.

    Большое число (999) означает «считать не по чему»: так пара уходит в
    конец списка, а не наверх."""
    try:
        spread = float(spread_points)
        atr = float(atr_points)
    except (TypeError, ValueError):
        return 999.0
    if atr <= 0 or spread < 0:
        return 999.0
    return spread / atr


def min_lot_risk_percent(min_lot: float, stop_points: float,
                         money_per_point_per_lot: float, equity: float) -> float:
    """Сколько процентов счёта рискует ОДИН минимальный лот брокера.

    Именно минимальный: ниже него объём не опускается, и если он уже слишком
    дорог, то никакая настройка риска не поможет — решает брокер, а не мы."""
    try:
        lot = float(min_lot)
        points = float(stop_points)
        per_point = float(money_per_point_per_lot)
        money = float(equity)
    except (TypeError, ValueError):
        return 999.0
    if money <= 0 or lot <= 0 or points <= 0 or per_point <= 0:
        return 999.0
    return (lot * points * per_point) / money * 100.0


def reject_reason(candidate: dict, equity: float, max_risk_percent: float,
                  max_spread_ratio: float) -> str:
    """Почему эта пара НЕ годится. Пустая строка — годится.

    Причина возвращается текстом, а не флагом: человек должен видеть, почему
    из трёхсот пар осталось двадцать, иначе отбор выглядит произволом."""
    name = candidate.get("symbol", "?")

    if candidate.get("trade_mode") == 0:
        return f"{name}: брокер закрыл торговлю"

    ratio = spread_cost_ratio(candidate.get("spread_points"),
                              candidate.get("atr_points"))
    if ratio >= 999:
        return f"{name}: нет данных для оценки (нет баров или спреда)"
    if max_spread_ratio > 0 and ratio > max_spread_ratio:
        return (f"{name}: спред съедает {ratio * 100:.0f}% обычного движения "
                f"(порог {max_spread_ratio * 100:.0f}%)")

    risk = min_lot_risk_percent(candidate.get("min_lot"),
                                candidate.get("stop_points"),
                                candidate.get("money_per_point"), equity)
    if risk >= 999:
        return f"{name}: не удалось посчитать риск минимального лота"
    if max_risk_percent > 0 and risk > max_risk_percent:
        return (f"{name}: минимальный лот рискует {risk:.1f}% счёта "
                f"(потолок {max_risk_percent:.1f}%)")
    return ""


def currencies_of(symbol: str) -> tuple:
    """Из EURUSD -> ('EUR', 'USD'). Нужно, чтобы не набрать шесть пар, где
    везде одна и та же валюта: это одна ставка, а не шесть.

    Работает только для обычных шестибуквенных валютных пар — для индексов и
    металлов вернёт пусто, и ограничение к ним просто не применится."""
    clean = "".join(ch for ch in str(symbol or "").upper() if ch.isalpha())
    if len(clean) < 6:
        return ()
    return (clean[:3], clean[3:6])


# Грубая мерка стопа для ПЕРВИЧНОГО отсева, в пунктах. Настоящий стоп
# считается из ATR и спреда, но на первом этапе ни того, ни другого ещё нет —
# а отсеять заведомо неподъёмные инструменты надо ДО того, как мы полезем за
# барами. 200 пунктов — обычный порядок величины стопа на M5.
STAGE1_STOP_POINTS = 200

# Сколько пар доводить до настоящего замера. Ограничение существует не ради
# красоты: замер требует добавить пару в «Обзор рынка», после чего терминал
# лезет за историей на сервер. Это и есть та работа, которая при сотнях пар
# превращала запуск в зависание.
DEFAULT_SURVEY_LIMIT = 60


# Разделы брокера, из которых берём инструменты. По умолчанию только валюта.
#
# ПОЧЕМУ ЭТО ВАЖНО. У брокера в списке лежат не только валютные пары, но и
# тысячи АКЦИЙ. Владелец прислал снимок «Обзора рынка»: A, AA, AAA, AAAA... —
# и у AAA покупка 9.99 при продаже 38.95. Акции живут по другим правилам:
# торгуются только в часы своей биржи (несколько часов в сутки), между
# сессиями стоят намертво, спред у неликвидных бумаг шире самой цены, а
# открытие с разрывом делает стоп-лосс приблизительным.
#
# Вся торговая логика здесь считалась и проверялась на валюте: пятиминутный
# бар, ATR, спред, сделка на семь минут, рынок круглосуточно пять дней в
# неделю. Переносить её на акции без переделки — не смелость, а ошибка.
#
# Пустой список означает «брать всё подряд». Оставлять его пустым не советую.
DEFAULT_GROUPS = ("Forex",)


def in_allowed_group(path: str, groups) -> bool:
    """Лежит ли инструмент в разрешённом разделе брокера.

    Раздел приходит строкой вида "Forex\\Majors\\EURUSD". Сравниваем по началу
    и без учёта регистра: у разных брокеров это "Forex", "forex", "FX" —
    точное совпадение отсекало бы половину брокеров молча."""
    if not groups:
        return True                     # ограничения нет
    text = str(path or "").replace("\\", "/").lower()
    if not text:
        return False                    # раздел неизвестен — не рискуем
    return any(text.startswith(str(g).lower()) for g in groups if str(g).strip())


def prefilter(candidates: list, equity: float, max_risk_percent: float,
              assumed_stop_points: float = STAGE1_STOP_POINTS,
              limit: int = DEFAULT_SURVEY_LIMIT,
              groups=DEFAULT_GROUPS) -> dict:
    """ПЕРВЫЙ, ДЕШЁВЫЙ ЭТАП: отсев по постоянным данным контракта.

    ЗАЧЕМ ОН ПОЯВИЛСЯ. Сначала отбор сразу шёл за барами по каждой паре
    брокера. Владелец: «нет отклика от программы, виснет». Так и было:
    чтобы получить бары, пару надо добавить в «Обзор рынка», после чего
    терминал идёт за историей на сервер — и на сотнях пар запуск растягивался
    на минуты. Программа не падала, она честно работала, но выглядело это как
    зависание, а это одно и то же для того, кто на неё смотрит.

    Здесь используются только те данные, которые терминал знает и БЕЗ
    добавления пары в «Обзор рынка»: минимальный лот, цена пункта, разрешение
    на торговлю. Ни баров, ни спреда — они дороги и на этом этапе не нужны.

    Возвращает {"kept": [имена], "rejected": [причины]}. Порядок kept — от
    самых дешёвых для счёта к дорогим: если до настоящего замера дойдут не
    все, дойдут хотя бы посильные."""
    good, rejected = [], []
    for item in candidates or ():
        name = str(item.get("symbol", "?"))

        if item.get("trade_mode") == 0:
            rejected.append(f"{name}: брокер закрыл торговлю")
            continue

        if not in_allowed_group(item.get("path"), groups):
            rejected.append(
                f"{name}: не из разрешённого раздела ({item.get('path') or 'раздел неизвестен'}) — "
                f"вся торговая логика считалась на валютных парах")
            continue

        risk = min_lot_risk_percent(item.get("min_lot"), assumed_stop_points,
                                    item.get("money_per_point"), equity)
        if risk >= 999:
            rejected.append(f"{name}: брокер не дал данных о контракте")
            continue
        if max_risk_percent > 0 and risk > max_risk_percent:
            rejected.append(
                f"{name}: даже минимальный лот рискует около {risk:.1f}% счёта "
                f"(потолок {max_risk_percent:.1f}%)")
            continue
        good.append((risk, name))

    good.sort(key=lambda row: (row[0], row[1]))
    names = [name for _, name in good]
    try:
        cap = int(limit)
    except (TypeError, ValueError):
        cap = DEFAULT_SURVEY_LIMIT
    if cap > 0 and len(names) > cap:
        rejected.append(
            f"ещё {len(names) - cap} пар не проверялись: за один запуск "
            f"замеряется не больше {cap} — иначе запуск растягивается на минуты")
        names = names[:cap]
    return {"kept": names, "rejected": rejected}


def pick(candidates: list, equity: float, limit: int = DEFAULT_LIMIT,
         max_risk_percent: float = 2.0, max_spread_ratio: float = 0.25,
         per_currency: int = DEFAULT_PER_CURRENCY) -> dict:
    """Выбрать лучшие пары. Возвращает {"chosen": [...], "rejected": [...]}.

    Порядок — по цене входа: первыми идут те, где спред съедает меньшую долю
    движения. Это не прогноз прибыли, а отсев дорогих инструментов."""
    good, rejected = [], []
    for item in candidates or ():
        why = reject_reason(item, equity, max_risk_percent, max_spread_ratio)
        if why:
            rejected.append(why)
            continue
        good.append((spread_cost_ratio(item.get("spread_points"),
                                       item.get("atr_points")),
                     str(item.get("symbol"))))

    good.sort(key=lambda row: (row[0], row[1]))

    # limit <= 0 означает «без потолка»: берём все подходящие пары. Обход
    # длинного списка не растягивает круг — пары без открытой сделки идут по
    # очереди, см. scan_rotation.py.
    try:
        cap = int(limit)
    except (TypeError, ValueError):
        cap = DEFAULT_LIMIT

    chosen, used = [], {}
    for ratio, name in good:
        if cap > 0 and len(chosen) >= cap:
            break
        pair = currencies_of(name)
        if per_currency > 0 and pair:
            if any(used.get(cur, 0) >= per_currency for cur in pair):
                rejected.append(
                    f"{name}: уже набрано {per_currency} пар с этой валютой — "
                    f"это была бы та же ставка ещё раз")
                continue
            for cur in pair:
                used[cur] = used.get(cur, 0) + 1
        chosen.append(name)

    return {"chosen": chosen, "rejected": rejected}


def describe(result: dict, total: int = 0, names: bool = True) -> str:
    """Строка о результате отбора.

    names=False — БЕЗ перечисления пар. Это не мелочь: у владельца полный
    список из 497 имён попал в рамку «Внимание» на главной странице и занял
    пол-экрана, вытеснив настоящие предупреждения. Список пар — это не
    предупреждение, его место на вкладке «Символы» и в журнале."""
    chosen = result.get("chosen") or []
    if not chosen:
        return "Подходящих пар не нашлось — проверьте связь с терминалом."
    head = f"Выбрано {len(chosen)} пар"
    if total:
        head += f" из {total} у брокера"
    if not names:
        return head + " — список на вкладке «Символы»."
    return head + ": " + ", ".join(chosen)
