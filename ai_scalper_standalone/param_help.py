def entry(name: str) -> dict:
    """Справка по параметру или пустая заготовка, если её ещё не написали."""
    return HELP.get(name, {"what": "", "more": "", "less": "", "warn": ""})


def has_help(name: str) -> bool:
    return bool(HELP.get(name, {}).get("what"))


_defaults_cache = {}


def default_of(name: str, config_path: str = ""):
    """Значение по умолчанию — читается из config.py.example, единственного
    источника правды. Второй список значений в справке неизбежно разошёлся бы
    с настоящим конфигом."""
    global _defaults_cache
    if not _defaults_cache:
        path = config_path or os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                           "config.py.example")
        try:
            import types
            module = types.ModuleType("cfg_defaults")
            with open(path, "r", encoding="utf-8") as f:
                exec(f.read(), module.__dict__)
            _defaults_cache = {k: v for k, v in module.__dict__.items()
                               if not k.startswith("_")}
        except Exception:
            _defaults_cache = {"__failed__": True}
    return _defaults_cache.get(name)


def describe(name: str) -> str:
    """Готовый текст справки для показа человеку."""
    item = entry(name)
    if not item["what"]:
        return "Описание для этого параметра пока не написано."
    lines = [item["what"]]
    value = default_of(name)
    if value is not None:
        lines.append(f"По умолчанию: {value!r}")
    if item["more"]:
        lines.append("Больше / включить: " + item["more"])
    if item["less"]:
        lines.append("Меньше / выключить: " + item["less"])
    if item["warn"]:
        lines.append("ВНИМАНИЕ: " + item["warn"])
    return "\n\n".join(lines)
