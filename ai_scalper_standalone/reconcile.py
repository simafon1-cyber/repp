"""reconcile.py — ЧТО НА САМОМ ДЕЛЕ НА СЧЁТЕ ПОСЛЕ ИНЦИДЕНТА.

ЗАЧЕМ ЭТОТ МОДУЛЬ

И2 научил программу не забывать о запрете после перезапуска. Но запрет —
это только половина: человеку всё равно приходилось идти в терминал и
разбираться руками, а программа не помогала ничем.

Здесь она помогает: после запуска собирает ФАКТЫ — открытые позиции,
активные заявки, историю заявок и сделок — сопоставляет их с записанным
инцидентом и выносит вердикт.

ЧЕГО ЭТОТ МОДУЛЬ НЕ ДЕЛАЕТ, И ЭТО ГЛАВНОЕ

Он НИКОГДА не снимает инцидент сам. Он только предъявляет доказательства.
Снимает человек, и только если доказательства есть.

    ДОКАЗАНО_НЕ_ОТКРЫЛОСЬ      заявка завершилась ничем, сделок нет
    ДОКАЗАНО_ПОЗИЦИЯ_ЕСТЬ      прослежена цепочка, позиция на счету
    ДОКАЗАНО_ПОЗИЦИЯ_ЗАКРЫТА   прослежена цепочка, позиция уже закрыта
    НЕ_ВЫЯСНЕНО                всё остальное

Первые три разрешают снять инцидент. Последний — нет, и это не
формальность: «не выяснено» значит, что на счету может быть позиция, о
которой программа не знает. Открывать поверх неё новые сделки нельзя.

ПОЧЕМУ НЕЛЬЗЯ ПРОЩЕ

Соблазн такой: «позиций нет — значит, всё чисто». Так рассуждать нельзя
по той же причине, что и в И1-C: отсутствие позиции в момент запроса — это
наблюдение, а не доказательство. Заявка может быть ещё активна. Поэтому
вердикт выносится по цепочке ЗАЯВКА → СДЕЛКА → ПОЗИЦИЯ, а не по тому,
пусто ли сейчас на счёте.
"""

import logging

import config as cfg
import mt5_connector as mt5c

log = logging.getLogger("reconcile")

ДОКАЗАНО_НЕ_ОТКРЫЛОСЬ = "доказано: сделки не было"
ДОКАЗАНО_ПОЗИЦИЯ_ЕСТЬ = "доказано: позиция на счету"
ДОКАЗАНО_ПОЗИЦИЯ_ЗАКРЫТА = "доказано: позиция открывалась и закрыта"
НЕ_ВЫЯСНЕНО = "не выяснено"

ДОКАЗАННЫЕ = (ДОКАЗАНО_НЕ_ОТКРЫЛОСЬ, ДОКАЗАНО_ПОЗИЦИЯ_ЕСТЬ,
              ДОКАЗАНО_ПОЗИЦИЯ_ЗАКРЫТА)


class Вердикт:
    """Что выяснено и на основании чего.

    `факты` — то, что программа увидела своими глазами. Они важнее
    вердикта: вердикт можно оспорить, факты человек проверит в терминале
    сам."""

    __slots__ = ("состояние", "факты", "совет")

    def __init__(self, состояние, факты=None, совет=""):
        self.состояние = состояние
        self.факты = list(факты or [])
        self.совет = совет

    @property
    def доказан(self) -> bool:
        return self.состояние in ДОКАЗАННЫЕ

    def __repr__(self):
        return f"Вердикт({self.состояние}, фактов {len(self.факты)})"

    def рассказ(self) -> str:
        строки = [f"Вердикт: {self.состояние}"]
        строки += [f"  · {ф}" for ф in self.факты]
        if self.совет:
            строки.append(f"Что делать: {self.совет}")
        return "\n".join(строки)


# =====================================================================
def номера_заявок(сведения: dict) -> list:
    """Все номера заявок, какие удалось записать в инцидент.

    Записываются они в разных полях: у невыясненной заявки свой, у
    незакрытой ноги хеджа свой. Читать их надо все — иначе сверка не будет
    знать, что искать."""
    найдено = []
    for ключ in ("заявка_без_ответа", "заявка", "не_закрылись"):
        значение = сведения.get(ключ)
        if значение is None:
            continue
        for кусок in str(значение).replace(";", ",").split(","):
            цифры = "".join(с for с in кусок if с.isdigit())
            if цифры:
                номер = int(цифры)
                if номер > 0 and номер not in найдено:
                    найдено.append(номер)
    return найдено


def выяснить(сведения: dict) -> Вердикт:
    """Собрать факты и вынести вердикт. Инцидент НЕ трогается."""
    symbol = str(сведения.get("символ") or "")
    заявки = номера_заявок(сведения)
    факты = []

    if сведения.get("состояние"):
        # Файл инцидента повреждён: неизвестно даже, что именно случилось.
        return Вердикт(НЕ_ВЫЯСНЕНО,
                       [f"отметка об инциденте повреждена: "
                        f"{сведения.get('причина', '')}"],
                       "разбирайтесь по терминалу вручную: чему верить в "
                       "файле, непонятно")

    позиции = mt5c.positions_or_none(symbol=symbol or None,
                                     magic=cfg.MAGIC_NUMBER)
    if позиции is None:
        return Вердикт(НЕ_ВЫЯСНЕНО,
                       ["список открытых позиций получить не удалось"],
                       "запустите терминал и повторите — без него сверить "
                       "нечего")
    факты.append(f"открытых наших позиций по {symbol or 'счёту'}: "
                 f"{len(позиции)}")
    for p in позиции:
        факты.append(f"  позиция {p.ticket}, объём {float(p.volume):.2f}")

    if not заявки:
        return Вердикт(НЕ_ВЫЯСНЕНО,
                       факты + ["номер заявки в инциденте не записан"],
                       "без номера заявки связь проследить нечем — "
                       "сверьте счёт в терминале вручную")

    вердикты = []
    for номер in заявки:
        в = _по_одной_заявке(номер, позиции, факты)
        вердикты.append(в)

    # Если хоть по одной заявке не выяснено — не выяснено вообще.
    if any(в == НЕ_ВЫЯСНЕНО for в in вердикты):
        return Вердикт(НЕ_ВЫЯСНЕНО, факты,
                       "хотя бы по одной заявке ответа нет — запрет "
                       "остаётся")

    if ДОКАЗАНО_ПОЗИЦИЯ_ЕСТЬ in вердикты:
        return Вердикт(ДОКАЗАНО_ПОЗИЦИЯ_ЕСТЬ, факты,
                       "позиция на счету и видна программе. Решите сами: "
                       "оставить её или закрыть в терминале, — и снимите "
                       "отметку")
    if ДОКАЗАНО_ПОЗИЦИЯ_ЗАКРЫТА in вердикты:
        return Вердикт(ДОКАЗАНО_ПОЗИЦИЯ_ЗАКРЫТА, факты,
                       "сделка была и уже закрыта. Проверьте её результат "
                       "в отчёте и снимите отметку")
    return Вердикт(ДОКАЗАНО_НЕ_ОТКРЫЛОСЬ, факты,
                   "заявка не исполнилась, на счету ничего лишнего нет — "
                   "отметку можно снимать")


def _по_одной_заявке(номер: int, позиции, факты: list) -> str:
    """Чем кончилась одна заявка. Порядок тот же, что и в сверке входа."""
    сделки = mt5c.deals_by_order(номер)
    if сделки is None:
        факты.append(f"заявка {номер}: историю сделок прочитать не удалось")
        return НЕ_ВЫЯСНЕНО

    входы = [d for d in сделки
             if int(getattr(d, "entry", -1)) == mt5c.DEAL_ENTRY_IN]
    if входы:
        номера = {int(getattr(d, "position_id", 0) or 0) for d in входы}
        номера.discard(0)
        if len(номера) != 1:
            факты.append(f"заявка {номер}: сделки указывают на разные "
                         f"позиции {sorted(номера) or '—'}")
            return НЕ_ВЫЯСНЕНО

        позиция_id = номера.pop()
        объём = sum(float(getattr(d, "volume", 0.0) or 0.0) for d in входы)
        есть = any(int(p.ticket) == позиция_id for p in позиции)
        if есть:
            факты.append(f"заявка {номер}: исполнена на {объём:.2f}, "
                         f"позиция {позиция_id} ОТКРЫТА")
            return ДОКАЗАНО_ПОЗИЦИЯ_ЕСТЬ

        выходы = [d for d in сделки
                  if int(getattr(d, "entry", -1)) != mt5c.DEAL_ENTRY_IN]
        по_позиции = mt5c.deals_by_position(позиция_id)
        если_закрыта = bool(выходы) or bool(
            по_позиции and [d for d in по_позиции
                            if int(getattr(d, "entry", -1)) != mt5c.DEAL_ENTRY_IN])
        if если_закрыта:
            факты.append(f"заявка {номер}: исполнена на {объём:.2f}, "
                         f"позиция {позиция_id} уже ЗАКРЫТА")
            return ДОКАЗАНО_ПОЗИЦИЯ_ЗАКРЫТА

        # Позиции нет, а закрытия не видно. Это не «всё чисто».
        факты.append(f"заявка {номер}: исполнена на {объём:.2f}, но позиции "
                     f"{позиция_id} нет и закрытия в истории не видно")
        return НЕ_ВЫЯСНЕНО

    активные = mt5c.order_by_ticket(номер)
    if активные is None:
        факты.append(f"заявка {номер}: список активных заявок недоступен")
        return НЕ_ВЫЯСНЕНО
    if активные:
        состояние = getattr(активные[0], "state", None)
        факты.append(f"заявка {номер}: ЕЩЁ ЖИВА на сервере "
                     f"({mt5c.имя_состояния(состояние)})")
        return НЕ_ВЫЯСНЕНО

    завершённые = mt5c.history_order_by_ticket(номер)
    if завершённые is None:
        факты.append(f"заявка {номер}: историю заявок прочитать не удалось")
        return НЕ_ВЫЯСНЕНО
    if not завершённые:
        факты.append(f"заявка {номер}: не найдена ни среди активных, ни "
                     f"среди завершённых")
        return НЕ_ВЫЯСНЕНО

    состояние = getattr(завершённые[0], "state", None)
    if состояние in mt5c.СОСТОЯНИЯ_БЕЗ_ИСПОЛНЕНИЯ:
        факты.append(f"заявка {номер}: {mt5c.имя_состояния(состояние)}, "
                     f"сделок по ней нет")
        return ДОКАЗАНО_НЕ_ОТКРЫЛОСЬ

    факты.append(f"заявка {номер}: состояние "
                 f"«{mt5c.имя_состояния(состояние)}», а сделок входа не "
                 f"видно — противоречие")
    return НЕ_ВЫЯСНЕНО
