"""quiet_run.py — запуск внешних команд БЕЗ чёрного окна.

ОТКУДА ЭТО ВЗЯЛОСЬ

Владелец, дословно: «Программу постоянно открывают какие-то командную
строку и окна остаются активными, постоянно висят, может, до двадцати
тридцати окон доходить».

ПОЧЕМУ ТАК ПРОИСХОДИТ

Программа собрана как оконная (windowed): своей консоли у неё нет. Когда
такая программа запускает консольную команду — icacls, git, MetaEditor, —
Windows обязана дать этой команде консоль. И даёт: новое окно. На
Windows 11 роль консоли исполняет «Терминал», поэтому в панели задач
появляются окна с этим именем.

Само по себе одно окно мелькнуло бы и исчезло. Но команд у нас много и
зовутся они часто: права на файл настроек переписываются при КАЖДОМ
сохранении, паспорт выгрузки пишется при каждой выгрузке. Отсюда и
двадцать-тридцать окон.

КАК ЧИНИТСЯ

Флагом CREATE_NO_WINDOW. Он говорит Windows: консоль команде дай, окно не
показывай. Плюс STARTUPINFO с SW_HIDE — на случай, если команда попробует
показать окно сама.

ЧЕГО ЗДЕСЬ НАРОЧНО НЕТ

Ни одна команда не становится «тихой» в смысле «ошибки прячем». Прячется
ОКНО, а не результат: коды возврата, вывод и исключения остаются как
были. Спрятать окно и спрятать ошибку — разные вещи, и путать их нельзя.

ОГОВОРКА ПРО DETACHED_PROCESS

CREATE_NO_WINDOW НЕЛЬЗЯ сочетать с DETACHED_PROCESS и CREATE_NEW_CONSOLE —
так написано у Microsoft, и Windows такое сочетание не принимает. У нас
DETACHED_PROCESS стоит ровно в одном месте: установщик новой версии,
который обязан пережить закрытие самой программы. Он и так остаётся без
консоли, и трогать его нельзя.
"""

from __future__ import annotations

import sys

# CREATE_NO_WINDOW. Значение постоянное у Windows и не меняется.
CREATE_NO_WINDOW = 0x08000000
_STARTF_USESHOWWINDOW = 0x00000001
_SW_HIDE = 0


def без_окна() -> dict:
    """Добавка к вызову subprocess, чтобы не мелькало чёрное окно.

    На не-Windows возвращает пустой словарь: там этой беды нет вовсе, а
    подсовывать чужой платформе флаги Windows — верный способ получить
    непонятную ошибку.

    Пользоваться так:

        subprocess.run([...], **quiet_run.без_окна())
    """
    if sys.platform != "win32":
        return {}

    добавка = {"creationflags": CREATE_NO_WINDOW}
    try:
        import subprocess
        начало = subprocess.STARTUPINFO()
        начало.dwFlags |= _STARTF_USESHOWWINDOW
        начало.wShowWindow = _SW_HIDE
        добавка["startupinfo"] = начало
    except Exception:  # noqa: BLE001
        # STARTUPINFO есть не во всех сборках. Один флаг лучше, чем
        # ничего: возвращаем то, что удалось собрать.
        pass
    return добавка
