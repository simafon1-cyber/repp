"""optimize.py — PHASE 3: подбор параметров под присмотром. Без самообмана.

=====================================================================
ЧТО ЭТО И ЧЕГО ЭТО НЕ ДЕЛАЕТ
=====================================================================
Здесь перебираются НАСТРОЙКИ уже существующей стратегии и проверяется,
может ли какая-нибудь из них исправить то, что показал baseline. Ни одна
строка торговой логики не меняется и не добавляется: меняются только числа,
которые и так есть в программе.

НИЧЕГО ОТСЮДА НЕ ПОПАДАЕТ В ПРОГРАММУ САМО. Результат — таблица и вывод.
Решение принимает владелец.

=====================================================================
ПОЧЕМУ ТРИ КУСКА ИСТОРИИ, А НЕ ОДИН
=====================================================================
Подбор параметра по всей истории — это не проверка, а подгонка: из сотни
вариантов какой-нибудь обязательно окажется лучшим на этих данных, даже если
все они одинаково бесполезны. Поэтому история режется ПО ВРЕМЕНИ на три
части, и у каждой своя роль:

  TRAIN (первая половина)      — здесь варианты соревнуются между собой.
  VALIDATION (следующая 1/4)   — здесь выжившие проверяются на данных,
                                 которых при соревновании не было.
  OOS (последняя 1/4)          — сюда допускается только один финалист, и
                                 только один раз. Это последнее слово.

Резать можно ТОЛЬКО по порядку времени. Случайная нарезка подмешала бы
будущее в обучение, и проверка стала бы враньём.

=====================================================================
ДВА ПОРОГА, А НЕ ОДИН — САМОЕ ВАЖНОЕ МЕСТО
=====================================================================
1. ОТНОСИТЕЛЬНЫЙ: стало ли лучше, чем было (ворота validation.py, пять
   способов, минимум три «за»).
2. АБСОЛЮТНЫЙ: а прибыльно ли оно вообще.

Второй порог добавлен потому, что без него получается ловушка. Baseline
убыточен: профит-фактор 0.4. Вариант с профит-фактором 0.7 «лучше» по всем
пяти способам — и остаётся убыточным. Принять такое значит поменять быстрый
убыток на медленный и назвать это победой. Поэтому финалист обязан на OOS
быть ПРИБЫЛЬНЫМ, а не просто менее убыточным.

=====================================================================
ЧТО ЗАПРЕЩЕНО ТРОГАТЬ
=====================================================================
Риск. Владелец: «Не оптимизируй риск». Причина простая: увеличение риска
всегда улучшает прибыль на истории и всегда ухудшает шанс пережить реальную
просадку. Список ЗАПРЕЩЕНО ниже — не пожелание, а проверка: попытка тронуть
любое из этих полей роняет прогон с ошибкой.
"""

import logging

import baseline_engine
import trade_stats
import validation

log = logging.getLogger("optimize")

# =====================================================================
# ЧЕГО КАСАТЬСЯ НЕЛЬЗЯ
# =====================================================================
# Всё, что управляет размером риска и живой торговлей. Подбирать эти числа по
# истории — самый прямой способ получить красивый отчёт и пустой счёт.
ЗАПРЕЩЕНО = frozenset({
    "risk_percent", "max_open_positions", "max_total_risk_pct",
    "daily_loss_limit_pct", "max_drawdown_pct", "max_trades_per_day",
    "MAX_TRADE_RISK_PERCENT_OF_EQUITY", "MAX_TOTAL_RISK_PERCENT",
    "MAX_DAILY_LOSS_PERCENT", "MAX_DRAWDOWN_PERCENT",
    "MAX_LOT", "MIN_LOT", "RISK_PERCENT",
    "LIVE_TRADING", "RISK_PROFILE",
    "UPDATE_REPO", "UPDATE_BRANCH", "UPDATE_ENABLED", "REQUIRE_LOGIN",
})

# Как режется история. Числа не круглые ради красоты: половина на
# соревнование — это минимум, при котором в каждом окне walk-forward
# остаётся осмысленное число сделок.
ДОЛЯ_TRAIN = 0.50
ДОЛЯ_VALIDATION = 0.25

# Сколько сделок должно набраться в куске, чтобы по нему вообще что-то
# говорить. Меньше — пишем UNKNOWN и не делаем вывода.
МИНИМУМ_СДЕЛОК = trade_stats.МАЛО_СДЕЛОК

# АБСОЛЮТНЫЙ ПОРОГ ГОДНОСТИ. Ниже этого вариант не «хуже», он БЕСПОЛЕЗЕН:
# торговать системой с профит-фактором меньше единицы — это платить за право
# нажимать кнопки.
ГОДЕН_ПФ = 1.0
ГОДЕН_ОЖИДАНИЕ = 0.0

# Насколько шевелится число при проверке на устойчивость. Если результат
# держится только при одном значении и рассыпается при сдвиге на пятую часть —
# это не настройка, а совпадение.
СДВИГ_УСТОЙЧИВОСТИ = 0.2


# =====================================================================
# ПРАВКА НАСТРОЕК — ВРЕМЕННАЯ И ОБРАТИМАЯ
# =====================================================================
class Правка:
    """Временно подменяет настройки. Возвращает всё на место всегда.

    Именно всегда: если бы правка пережила прогон, следующий вариант считался
    бы уже по чужим настройкам, и вся таблица оказалась бы враньём. Поэтому
    возврат стоит в finally, а не в конце удачного пути."""

    def __init__(self, профиль: dict = None, настройки: dict = None):
        for имя in list((профиль or {}).keys()) + list((настройки or {}).keys()):
            if имя in ЗАПРЕЩЕНО:
                raise ValueError(
                    f"Параметр {имя} трогать запрещено: это риск или режим "
                    f"работы, а не качество входа. Подбор риска по истории "
                    f"всегда улучшает отчёт и всегда ухудшает счёт.")
        self.профиль = dict(профиль or {})
        self.настройки = dict(настройки or {})
        self._было_профиль = {}
        self._было_настройки = {}

    def __enter__(self):
        import config as cfg
        import risk_manager as rm
        п = rm.get_profile()
        for имя, знач in self.профиль.items():
            self._было_профиль[имя] = п.get(имя)
            п[имя] = знач
        for имя, знач in self.настройки.items():
            self._было_настройки[имя] = getattr(cfg, имя, None)
            setattr(cfg, имя, знач)
        return self

    def __exit__(self, *_):
        import config as cfg
        import risk_manager as rm
        п = rm.get_profile()
        for имя, знач in self._было_профиль.items():
            п[имя] = знач
        for имя, знач in self._было_настройки.items():
            setattr(cfg, имя, знач)
        self._было_профиль = {}
        self._было_настройки = {}
        return False


# =====================================================================
# НАРЕЗКА ИСТОРИИ ПО ВРЕМЕНИ
# =====================================================================
def segments(bars) -> dict:
    """Границы TRAIN / VALIDATION / OOS. Только по порядку времени."""
    n = len(bars or ())
    a = int(n * ДОЛЯ_TRAIN)
    b = int(n * (ДОЛЯ_TRAIN + ДОЛЯ_VALIDATION))
    return {"TRAIN": (0, a), "VALIDATION": (a, b), "OOS": (b, n)}


def slice_for(bars, отрезок):
    """Кусок истории вместе с разгоном индикаторов.

    Разгон берётся из свечей ПЕРЕД куском — они в прошлом относительно первого
    решения, и заглядыванием вперёд не являются. Без разгона первые триста
    решений куска считались бы по недосчитанным индикаторам, то есть по другим
    числам, чем у живой программы."""
    начало, конец = отрезок
    старт = max(0, начало - baseline_engine.ОКНО_БАРОВ)
    return list(bars[старт:конец])


# =====================================================================
# ОДИН ПРОГОН ОДНОГО ВАРИАНТА
# =====================================================================
def run_variant(symbol: str, bars, meta: dict, вариант: dict,
                отрезок, equity: float = 0.0, m1_bars=None) -> dict:
    """Прогнать один вариант на одном куске истории.

    Возвращает {"вариант", "отрезок", "trades", "money", "сводка", "rejects"}."""
    кусок = slice_for(bars, отрезок)
    правка = Правка(вариант.get("профиль"), вариант.get("настройки"))
    with правка:
        итог = baseline_engine.run(
            symbol, кусок, meta, equity_start=equity,
            only_direction=int(вариант.get("направление", 0) or 0),
            m1_bars=m1_bars if вариант.get("по_минуткам") else None)
    сделки = итог.get("trades", [])
    деньги = [float(t["money"]) for t in сделки]
    return {
        "вариант": вариант.get("код", "?"),
        "имя": вариант.get("имя", ""),
        "trades": сделки,
        "money": деньги,
        "сводка": trade_stats.summarize(сделки, вариант.get("код", "?")),
        "rejects": итог.get("rejects", {}),
        "error": итог.get("error", ""),
    }


# =====================================================================
# СУЖДЕНИЕ
# =====================================================================
def profitable(сводка: dict) -> bool:
    """Абсолютный порог: это вообще прибыльно?

    Отдельно от сравнения «лучше/хуже» намеренно. «Лучше убыточного» —
    по-прежнему убыточно, и путать эти два вопроса нельзя."""
    return (float(сводка.get("профит_фактор", 0) or 0) > ГОДЕН_ПФ
            and float(сводка.get("ожидание", 0) or 0) > ГОДЕН_ОЖИДАНИЕ)


def enough(сводка: dict) -> bool:
    return int(сводка.get("сделок", 0) or 0) >= МИНИМУМ_СДЕЛОК


def compare(база: dict, вариант: dict, seed: int = 0) -> dict:
    """Сравнить вариант с базой воротами validation.py — всеми пятью способами."""
    решение = validation.gate(база["money"], вариант["money"], seed=seed)
    return {
        "вариант": вариант["вариант"],
        "имя": вариант["имя"],
        "решение": решение["решение"],
        "способов_за": решение["способов_за"],
        "причина": решение["причина"],
        "способы": решение["способы"],
        "прибылен": profitable(вариант["сводка"]),
        "достаточно_сделок": enough(вариант["сводка"]),
        "сводка": вариант["сводка"],
    }


def survivors(сравнения) -> list:
    """Кто идёт дальше: ворота пропустили И сделок достаточно.

    Прибыльность здесь ещё НЕ требуется: на первом куске истории вариант может
    быть убыточным и всё равно заслуживать проверки. Требование прибыли стоит
    на последнем рубеже (OOS), где обмануться уже нечем."""
    return [с for с in сравнения
            if с["решение"] == "принять" and с["достаточно_сделок"]]


def sensitivity(symbol: str, bars, meta: dict, вариант: dict, отрезок,
                сдвиг: float = СДВИГ_УСТОЙЧИВОСТИ) -> list:
    """Пошевелить число варианта в обе стороны.

    Настройка, которая работает только при одном значении и рассыпается при
    сдвиге на пятую часть, — это не найденная закономерность, а совпадение,
    попавшее в сетку перебора. Такое принимать нельзя.

    Возвращает список прогонов соседей; двигаются только числовые поля."""
    соседи = []
    for источник in ("профиль", "настройки"):
        for имя, знач in (вариант.get(источник) or {}).items():
            if not isinstance(знач, (int, float)) or isinstance(знач, bool):
                continue
            for доля, метка in ((1 - сдвиг, "меньше"), (1 + сдвиг, "больше")):
                новое = round(знач * доля, 4)
                if новое == знач:
                    continue
                сосед = {
                    "код": f"{вариант['код']}~{имя}{метка}",
                    "имя": f"{вариант['имя']}: {имя} {метка} на "
                           f"{int(сдвиг * 100)}% ({знач} -> {новое})",
                    "направление": вариант.get("направление", 0),
                    "профиль": dict(вариант.get("профиль") or {}),
                    "настройки": dict(вариант.get("настройки") or {}),
                }
                сосед[источник][имя] = новое
                соседи.append(сосед)
    return [run_variant(symbol, bars, meta, с, отрезок) for с in соседи]


def robust(база: dict, соседи, seed: int = 0) -> dict:
    """Держится ли результат у соседей.

    Требование строгое: КАЖДЫЙ сосед обязан остаться лучше базы. Достаточно
    одного провалившегося — и это уже не настройка, а точка на графике шума."""
    подробно = []
    все_держатся = True
    for сосед in соседи:
        м_база = validation.metrics(база["money"])
        м_сосед = validation.metrics(сосед["money"])
        лучше = validation.improved(м_база, м_сосед)
        счёт = sum(1 for v in лучше.values() if v)
        держится = счёт >= validation.МИНИМУМ_МЕТРИК
        все_держатся = все_держатся and держится
        подробно.append({"имя": сосед["имя"], "метрик_лучше": счёт,
                         "держится": держится,
                         "сводка": сосед["сводка"]})
    return {"устойчив": bool(соседи) and все_держатся,
            "соседей": len(соседи), "подробно": подробно}


