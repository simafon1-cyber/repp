# ДИАГНОСТИКА: А ДОСТИЖИМА ЛИ ЦЕЛЬ ВООБЩЕ
# =====================================================================
def reach_report(trades) -> dict:
    """Сравнить, КУДА поставлена цель и КУДА сделка реально доходит.

    ПОЧЕМУ ЭТО СЧИТАЕТСЯ ОТДЕЛЬНО. Проверка вариантов отвечает на вопрос
    «какая настройка лучше». Она не отвечает на вопрос «а не бессмысленна ли
    сама конструкция». Здесь считается именно это.

    Мера — R, то есть размер стопа. Сделка, дошедшая до +1R, прошла ровно
    столько, сколько потеряла бы при стопе. Если цель стоит на 4R, а половина
    сделок не доходит и до 0.6R, то цель не «редко срабатывает» — она не
    срабатывает никогда, и выйти сделка может только через стоп.

    Возвращает {"сделок", "цель_R", "медиана_MFE_R", "лучший_MFE_R",
    "дошли_бы", "доля_дошедших"}."""
    ряд = [t for t in (trades or ()) if float(t.get("risk_points", 0) or 0) > 0]
    if not ряд:
        return {"сделок": 0, "цель_R": 0.0, "медиана_MFE_R": 0.0,
                "лучший_MFE_R": 0.0, "дошли_бы": 0, "доля_дошедших": 0.0}

    цели = [float(t.get("tp_r", 0) or 0) for t in ряд if float(t.get("tp_r", 0) or 0) > 0]
    цель = round(sum(цели) / len(цели), 2) if цели else 0.0
    ходы = sorted(float(t["mfe_points"]) / float(t["risk_points"]) for t in ряд)
    медиана = round(ходы[len(ходы) // 2], 2)
    дошли = sum(1 for x in ходы if цель > 0 and x >= цель)
    return {
        "сделок": len(ряд),
        "цель_R": цель,
        "медиана_MFE_R": медиана,
        "лучший_MFE_R": round(ходы[-1], 2),
        "дошли_бы": дошли,
        "доля_дошедших": round(дошли / len(ходы), 3),
    }


def describe_reach(r: dict) -> str:
    """Диагностика словами. Пишется в отчёт всегда, а не только при провале."""
    if not r.get("сделок"):
        return "Достижимость цели: судить не по чему — сделок нет."
    строки = [
        f"Сделок в замере: {r['сделок']}",
        f"Цель стоит на:            {r['цель_R']} R "
        f"(R — это размер стопа: сколько сделка потеряла бы, если бы её выбило)",
        f"Половина сделок доходит:  {r['медиана_MFE_R']} R и не дальше",
        f"Лучшая сделка дошла до:   {r['лучший_MFE_R']} R",
        f"Дошли бы до цели:         {r['дошли_бы']} из {r['сделок']} "
        f"({r['доля_дошедших'] * 100:.1f}%)",
    ]
    if r["цель_R"] <= 0:
        строки.append("У сделки НЕТ ЦЕЛИ ВОВСЕ: выйти можно только по стопу — "
                      "своему или подтянутому трейлингом.")
    elif r["дошли_бы"] == 0:
        строки.append("ЦЕЛЬ НЕДОСТИЖИМА. Ни одна сделка за весь период до неё "
                      "не дошла. Значит она не «редко срабатывает» — она не "
                      "срабатывает никогда, и выйти сделка всё равно может "
                      "только по стопу.")
    return "\n".join("  " + с for с in строки)
