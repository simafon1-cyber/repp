# СНИМКИ: КАЖДАЯ ВЫГРУЗКА — ОТДЕЛЬНЫЙ НЕИЗМЕНЯЕМЫЙ КАТАЛОГ
# =====================================================================
# ПОЧЕМУ ЭТО ПОЯВИЛОСЬ. Терминал отдаёт не «всю историю», а ФИКСИРОВАННОЕ
# ЧИСЛО ПОСЛЕДНИХ баров: 50 000 на M5, 25 000 на M1 и M15. Числа не
# зависят от того, сколько просить.
#
# Следствие неочевидное и дорогое: каждая новая выгрузка не углубляет
# историю, а СДВИГАЕТ ОКНО ВПЕРЁД. Начало теряется. Проверено на живых
# данных: EURUSD_M5 при повторной выгрузке потерял шесть дней начала,
# EURUSD_M15 — четыре. Вернуть их нельзя ничем: окно уже уехало.
#
# А писала выгрузка в постоянное имя, в режиме "w". То есть повторный
# запуск затирал невосстановимое.
#
# Теперь каждая выгрузка кладётся в свой каталог с датой и временем и
# НИКОГДА не трогает предыдущие. Если каталог с таким именем уже есть —
# выгрузка отказывается работать, а не дописывает в него.
СНИМКИ_FOLDER = os.path.join("history", "snapshots")
МАНИФЕСТ = "manifest.json"


def метка_времени(когда=None) -> str:
    """Имя каталога снимка: время по UTC, без двоеточий.

    Двоеточия убраны не для красоты: в именах файлов Windows они
    запрещены, и каталог просто не создался бы."""
    когда = когда or datetime.now(timezone.utc)
    return когда.strftime("%Y-%m-%dT%H-%M-%SZ")


def новый_снимок(folder: str = "", когда=None) -> str:
    """Создать НОВЫЙ каталог снимка. Отказ, если такой уже есть.

    Отказ, а не «допишем туда же»: одинаковое имя означает, что рядом
    лежит чужая выгрузка, и дописывать в неё — тот же способ потерять
    данные, только медленнее."""
    корень = folder or os.path.join(base_dir(), СНИМКИ_FOLDER)
    путь = os.path.join(корень, метка_времени(когда))
    if os.path.exists(путь):
        raise FileExistsError(
            f"Каталог снимка уже существует: {путь}. "
            f"Выгрузка ничего не перезаписывает — подождите минуту или "
            f"уберите этот каталог сами, если он точно лишний.")
    os.makedirs(путь)
    return путь


def записать_манифест(папка: str) -> str:
    """Список файлов снимка с отпечатком каждого.

    Нужен затем, чтобы потом можно было доказать: этот снимок с тех пор
    не менялся. Без отпечатков «неизменяемый каталог» — только слово."""
    записи = {}
    for имя in sorted(os.listdir(папка)):
        if имя == МАНИФЕСТ:
            continue
        полный = os.path.join(папка, имя)
        if not os.path.isfile(полный):
            continue
        h = hashlib.sha256()
        with open(полный, "rb") as f:
            for кусок in iter(lambda: f.read(1 << 20), b""):
                h.update(кусок)
        записи[имя] = {"sha256": h.hexdigest(),
                       "байт": os.path.getsize(полный)}
    путь = os.path.join(папка, МАНИФЕСТ)
    with open(путь, "w", encoding="utf-8") as f:
        json.dump({"снят_utc": datetime.now(timezone.utc).isoformat(),
                   "файлов": len(записи), "файлы": записи},
                  f, ensure_ascii=False, indent=1)
    return путь

