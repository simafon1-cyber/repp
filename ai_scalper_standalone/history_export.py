def _разбор(аргументы=None):
    р = argparse.ArgumentParser(
        description="Выгрузка истории из MetaTrader 5 в неизменяемый снимок.")
    р.add_argument("--timeframe", "-t", action="append", required=True,
                   metavar="ТФ",
                   help="какой таймфрейм выгружать: M1, M5, M15, H1. "
                        "Можно повторять. Обязателен НАРОЧНО: выгрузка "
                        "всего подряд занимает минуты и место, а нужен "
                        "обычно один.")
    р.add_argument("--symbol", "-s", action="append", metavar="ПАРА",
                   help="инструмент. Можно повторять. "
                        "По умолчанию — обычный список.")
    р.add_argument("--bars", type=int, default=None,
                   help="сколько баров просить (по умолчанию — по таблице)")
    р.add_argument("--folder", default="",
                   help="куда класть снимки (по умолчанию history/snapshots)")
    return р.parse_args(аргументы)


def main(аргументы=None) -> int:
    """Возвращает КОД: 0 — выгрузилось, иначе — нет.

    Ненулевой код при пустом отчёте обязателен: без него сценарий,
    вызвавший выгрузку, не отличит «ничего не вышло» от «всё хорошо»."""
    а = _разбор(аргументы)

    тфы = [т.upper() for т in а.timeframe]
    неизвестные = [т for т in тфы if т not in БАРОВ_ПО_ТФ]
    if неизвестные:
        print(f"Неизвестный таймфрейм: {', '.join(неизвестные)}. "
              f"Известные: {', '.join(sorted(БАРОВ_ПО_ТФ))}")
        return 2

    символы = tuple(а.symbol) if а.symbol else DEFAULT_SYMBOLS

    import mt5_connector as mt5c
    try:
        mt5c.connect()
    except Exception as e:  # noqa: BLE001
        print(f"Не удалось подключиться к терминалу: {e}")
        print("Запустите MetaTrader 5, войдите в счёт и повторите.")
        return 3

    try:
        папка = новый_снимок(а.folder)
    except FileExistsError as e:
        print(str(e))
        mt5c.disconnect()
        return 4

    отчёты = []
    try:
        print(f"Снимок: {папка}")
        отчёты = export_all(symbols=символы, timeframe=тфы, bars=а.bars,
                            folder=папка,
                            progress=lambda т: print(т, flush=True))
        for р in отчёты:
            if р.get("error"):
                print(f"  ОШИБКА  {р['symbol']} {р['timeframe']}: {р['error']}")
            else:
                print(f"  {р['symbol']} {р['timeframe']}: {р['bars']} свечей "
                      f"-> {р['csv']}")
        манифест = записать_манифест(папка)
        print(f"Манифест снимка: {манифест}")
    finally:
        # ОТКЛЮЧЕНИЕ В finally. Оборвалась выгрузка или нет, терминал
        # отпустить надо: иначе следующий запуск наткнётся на занятое
        # подключение и объяснит это как-нибудь иначе.
        try:
            mt5c.disconnect()
        except Exception:  # noqa: BLE001
            pass

    если_пусто = not отчёты
    ошибок = sum(1 for р in отчёты if р.get("error"))
    удачных = sum(1 for р in отчёты if not р.get("error") and р.get("bars"))

    if если_пусто:
        print("Не выгружено НИЧЕГО. Отчёт пуст.")
        return 5
    if not удачных:
        print(f"Ни одного инструмента не выгрузилось (ошибок: {ошибок}).")
        return 6
    if ошибок:
        print(f"Выгружено {удачных}, с ошибками {ошибок}.")
        return 7

    print(f"Выгружено инструментов: {удачных}. Ошибок нет.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
