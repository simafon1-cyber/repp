# СКОЛЬКО ПРОСИТЬ НА КАЖДОМ ТАЙМФРЕЙМЕ — И ПОЧЕМУ ЧИСЛА РАЗНЫЕ.
#
# Одинаковое число баров означает РАЗНЫЙ отрезок времени: 200 000 баров M5 —
# два года, а M1 — всего сто сорок дней. Считать «поровну» тут не значит
# «справедливо».
#
# M1 = 100 000 (около семидесяти дней). Этого с запасом хватает на весь
#   период настоящей торговли счёта, ради сверки с которым M1 и нужен.
#   Просить два года минуток незачем: файл вырос бы в пять раз, а сверять
#   его не с чем.
# M5 = 200 000 (около двух лет) — основной таймфрейм, на нём считается
#   baseline, и ему нужен полный запас на walk-forward.
# M15 = 100 000 (около трёх лет) — старший таймфрейм тренда, ему достаточно.
# H1 = 100 000 (около одиннадцати лет по торговым часам) — и вот зачем.
#
#   ДО ЭТОЙ ПРАВКИ H1 НЕ ВЫГРУЖАЛСЯ ВООБЩЕ. Часовые свечи в исследованиях
#   собирались из пятиминутных склейкой по двенадцать (build_h1.py). Сборка
#   честная и проверенная, но это всё-таки РЕКОНСТРУКЦИЯ — так и записано
#   ограничением в отчёте по И8.
#
#   Вторая, более важная причина. Пятиминутная выгрузка дала только
#   50 000 баров, то есть примерно восемь месяцев. Весь этот период уже
#   участвовал во всех прогонах — поиске входов, версиях выходов, модели
#   издержек, проверке H1. Невиданных данных на M5 не осталось ни одного
#   дня, а без них проверять наличие преимущества нечем: любая проверка
#   на виденном периоде — пересказ, а не проверка.
#
#   На часовом таймфрейме то же число баров покрывает во много раз больший
#   отрезок времени. Значит, у брокера можно попросить годы истории, из
#   которых виден лишь последний кусок. Остальное — настоящий невиданный
#   период, и только на нём вопрос о преимуществе имеет смысл задавать.
#
#   Файл при этом маленький: час содержит столько же строк, сколько час на
#   M5 делённый на двенадцать.
#
# ЧЕСТНО О ЦЕНЕ: файлы уезжают в репозиторий и остаются в его истории
# навсегда. Каждая лишняя сотня тысяч баров — это мегабайты, которые уже не
# удалить. Поэтому берётся столько, сколько нужно делу, а не «побольше».
