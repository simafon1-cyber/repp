"""Прогон по паспорту В-001 «Фиксация вверху».

ВОПРОС, НА КОТОРЫЙ ОТВЕЧАЕТ ЭТОТ ФАЙЛ

Владелец: «вывесела сделка плюс двадцать долларов, и она просто
откатилась до минус пять. То есть это фиксировать прибыль максимально
вверху».

Проверяется правило выхода: цели нет вовсе, сделка закрывается, когда
прибыль откатилась от своего ЛУЧШЕГО значения на заданную долю этого
пика. Вход, стоп, горизонт, признаки, срезы и издержки — те же, что у
родительского прогона. Меняется ОДНО: как выходим.

ДОГОВОРЁННОСТЬ ВНУТРИ БАРА — ПЕССИМИСТИЧНАЯ И ЗАПИСАНА ДО РАСЧЁТА

Часовой бар даёт open/high/low/close и не говорит, в каком порядке
внутри часа были максимум и минимум. Поэтому в каждом баре сначала
проверяется НЕБЛАГОПРИЯТНЫЙ край — стоп и откат от ПРЕЖНЕГО пика, — и
только потом бар обновляет пик. Сомнение толкуется против гипотезы.

Считать иначе (сначала обновить пик, потом проверять откат) значило бы
позволить одному и тому же бару сперва «дать» прибыль, а потом отдать
её лишь частично. Так результат стал бы красивее, а правда — нет.

Коды возврата те же, что у родительского прогона.

Запуск:  python3 ai_scalper_standalone/run_peak_exit_study.py
"""

