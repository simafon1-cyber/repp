# =====================================================================
def проверка_паспорта() -> dict:
    if not os.path.exists(ПАСПОРТ):
        raise Стоп(f"Паспорт В-001 не найден: {ПАСПОРТ}")
    паспорт = json.loads(open(ПАСПОРТ, encoding="utf-8").read())
    печать = паспорт.get("хеш_паспорта")
    если_бы = research_manifest.хеш_поля(паспорт, "хеш_паспорта")
    if not печать:
        raise Стоп("В паспорте В-001 не стоит печать")
    if печать != если_бы:
        raise Стоп("Печать паспорта В-001 НЕ СХОДИТСЯ с содержимым: "
                   f"{печать} против {если_бы}")
    # Сетка в коде обязана совпадать с объявленной в паспорте.
    объявлено = tuple((паспорт.get("заранее_объявленная_сетка") or {})
                      .get("доля_отката_от_пика") or ())
    if tuple(float(x) for x in объявлено) != ОТКАТЫ:
        raise Стоп(f"Сетка в коде {ОТКАТЫ} не совпадает с объявленной в "
                   f"паспорте {объявлено}. Подбор после запечатывания.")
    print(f"  1. Паспорт В-001 сверен, печать {печать[:16]}…; "
          f"сетка совпала: {ОТКАТЫ}")
    return паспорт


