def сделка_по_откату(ряд, i: int, направление: int, symbol: str,
                     доля_отката: float, горизонт: int = ГОРИЗОНТ):
    """Одна сделка. Цели нет; выход по откату от пика, стопу или горизонту.

    Возвращает ту же запись, что entry_lab.сделка, — чтобы издержки,
    R и всё остальное считалось ОДНИМ И ТЕМ ЖЕ кодом, а не второй его
    копией. Здесь определяется только ГДЕ и ПОЧЕМУ мы вышли."""
    n = ряд["n"]
    if i + 1 >= n or ряд["atr"][i] <= 0:
        return None
    риск_цены = ряд["atr"][i] * entry_lab.СТОП_ATR
    if риск_цены <= 0:
        return None

    вход = ряд["open"][i + 1]
    стоп = вход - направление * риск_цены
    конец = min(n, i + 1 + горизонт)

    пик_цены = вход          # лучшая достигнутая цена в нашу сторону
    выход = None
    причина = ""
    индекс = конец - 1

    def _исполнение(уровень, откр):
        """По какой цене на самом деле закроется стоп на этом уровне.

        ДЕФЕКТ, КОТОРЫЙ ЭТО ЧИНИТ, БЫЛ МОИМ И БЫЛ РЕШАЮЩИМ. Раньше здесь
        стояла цена уровня — как будто стоп всегда исполняется ровно там,
        где стоит. На деле стоп — это рыночная заявка при касании: если
        бар ОТКРЫЛСЯ уже за уровнем, исполнение будет по открытию, а не
        по уровню.

        Замер на train: так открывались 77,7 % выходов по откату, и
        средний недоучёт составлял 0,208 R на сделку. Это БОЛЬШЕ, чем
        весь найденный «плюс» в 0,088 R. То есть прежний прогон измерял
        не правило выхода, а невозможное исполнение."""
        if направление == 1:
            return min(уровень, откр)
        return max(уровень, откр)

    for j in range(i + 1, конец):
        h, l, откр = ряд["high"][j], ряд["low"][j], ряд["open"][j]

        # --- НЕБЛАГОПРИЯТНЫЙ КРАЙ ПЕРВЫМ (договорённость из паспорта) ---
        стоп_задет = (l <= стоп) if направление == 1 else (h >= стоп)
        if стоп_задет:
            выход, причина, индекс = _исполнение(стоп, откр), "стоп", j
            break

        # Откат считается от ПРЕЖНЕГО пика, ещё не обновлённого этим баром.
        пик_прибыли = (пик_цены - вход) * направление
        if пик_прибыли > 0:
            порог_прибыли = пик_прибыли * (1.0 - доля_отката)
            уровень = вход + направление * порог_прибыли
            откат_задет = (l <= уровень) if направление == 1 else (h >= уровень)
            if откат_задет:
                выход, причина, индекс = _исполнение(уровень, откр), "откат", j
                break

        # --- и только теперь бар обновляет пик ---
        лучшая = h if направление == 1 else l
        if (лучшая - вход) * направление > (пик_цены - вход) * направление:
            пик_цены = лучшая

    if выход is None:
        выход = ряд["close"][конец - 1]
        причина = "горизонт"
        индекс = конец - 1

    # Дальше — тот же расчёт денег и издержек, что у entry_lab.сделка.
    # Повторять его здесь нельзя: две копии однажды разойдутся. Поэтому
    # собирается запись через общий код, а найденный выход подставляется.
    запись = entry_lab.сделка(ряд, i, направление, symbol=symbol,
                              горизонт=горизонт)
    if запись is None:
        return None
    return _пересчитать(запись, ряд, i, направление, symbol,
                        вход, выход, стоп, причина, индекс, риск_цены)


def _пересчитать(запись, ряд, i, направление, symbol, вход, выход, стоп,
                 причина, индекс, риск_цены):
    """Подставить наш выход в запись и пересчитать деньги ТЕМ ЖЕ способом."""
    пункт = costs.пункт(symbol)
    if пункт <= 0:
        return None
    л = запись["лот"]
    цена_пункта = costs.стоимость_пункта(symbol, вход, л)
    риск_денег = (риск_цены / пункт) * цена_пункта
    if риск_денег <= 0:
        return None
    грязная = ((выход - вход) * направление / пункт) * цена_пункта

    запись = dict(запись)
    запись.update({
        "время_выхода": ряд["time"][индекс],
        "выход": выход,
        "стоп": стоп,
        "цель": None,
        "баров_в_сделке": индекс - i,
        "причина_выхода": причина,
        "r_грязный": ((выход - вход) * направление) / риск_цены,
        "риск_денег": риск_денег,
        "грязная_прибыль": грязная,
    })
    # Своп зависит от того, сколько ночей сделка прожила, а прожила она
    # теперь другое время. Пересчитываем — иначе издержки были бы от
    # чужой сделки.
    ночей = costs.ночей(запись["время_входа"], запись["время_выхода"])
    своп = costs.своп(symbol, направление, ночей, л)
    издержки = запись["спред"] + запись["комиссия"] - своп
    чистая = грязная - издержки
    запись.update({"ночей": ночей, "своп": своп,
                   "издержки_всего": издержки, "чистая_прибыль": чистая,
                   "r_чистый": чистая / риск_денег})
    return запись


def сделки_среза(папка_h1: str, инструмент: str, часть: dict) -> dict:
    """{доля отката: [сделки]} по одному срезу, все доли за один проход."""
    пусто = {д: [] for д in ОТКАТЫ}
    if not часть["баров"]:
        return пусто
    путь = os.path.join(папка_h1, f"{инструмент}_H1.csv")
    начало = datetime.fromisoformat(часть["начало_utc"]).timestamp()
    конец = datetime.fromisoformat(часть["конец_utc"]).timestamp()
    кусок = база._ряд_среза(путь, начало, конец, int(часть["баров"]))
    ряд = entry_lab.подготовить(кусок)

    итог = {д: [] for д in ОТКАТЫ}
    предел = ряд["n"] - ГОРИЗОНТ - 1
    for имя, признак in entry_lab.ПРИЗНАКИ.items():
        for i in range(предел):
            направление = признак(ряд, i)
            if not направление:
                continue
            for доля in ОТКАТЫ:
                запись = сделка_по_откату(ряд, i, направление, инструмент,
                                          доля, горизонт=ГОРИЗОНТ)
                if запись is None:
                    continue
                if float(запись.get("риск_денег", 0)) <= 0:
                    continue
                запись["инструмент"] = инструмент
                запись["признак"] = имя
                запись["день"] = datetime.fromtimestamp(
                    ряд["time"][i + 1], timezone.utc).strftime("%Y-%m-%d")
                итог[доля].append(запись)
    return итог


def свод(сделки) -> dict:
    return база.бутстрэп(сделки, повторов=ПОВТОРОВ, зерно=ЗЕРНО) if сделки else {}


def _печать(имя: str, по_долям: dict):
    for доля in ОТКАТЫ:
        с = по_долям.get(доля) or {}
        if not с:
            print(f"  {имя:11} откат {доля:.0%}: сделок нет")
            continue
        print(f"  {имя:11} откат {доля:.0%}: сделок {с['сделок']:>6}, дней "
              f"{с['дней']:>4}, среднее R {с['среднее_r']:+.5f}, "
              f"интервал [{с['нижняя_граница']:+.5f}; "
              f"{с['верхняя_граница']:+.5f}]")


# =====================================================================
def main(аргументы=None) -> int:
    р = argparse.ArgumentParser(
        description="Единственный прогон по паспорту В-001.",
        epilog="Аргументов нет намеренно: путь результата задан в коде.")
    р.parse_args(аргументы)

    база.заголовок("ПРОВЕРКИ ДО РАСЧЁТА (каждая fail-closed)")
    временный = tempfile.mkdtemp(prefix="peak_exit_")
    try:
        паспорт = проверка_паспорта()
        родитель = json.loads(open(база.ПАСПОРТ, encoding="utf-8").read())
        база.проверка_2_хеши_данных(родитель)
        папка = база.проверка_3_распаковка(временный)
        границы = база.проверка_4_видимые_срезы(папка)
        costs.выбрать_сценарий(costs.БАЗОВЫЙ)
        if costs.текущий_сценарий() != costs.БАЗОВЫЙ:
            raise Стоп("Не удалось включить базовый сценарий издержек")
        print(f"  4. Сценарий издержек выбран ДО расчёта: "
              f"{costs.текущий_сценарий()}")
        проверка_одноразовости(паспорт)
    except УжеОткрывали as e:
        print(f"\nПРОГОН ОСТАНОВЛЕН ДО ЧТЕНИЯ OOS: {e}")
        return 5
    except Стоп as e:
        print(f"\nПРОГОН ОСТАНОВЛЕН: {e}")
        return 2
    except SystemExit as e:
        print(f"\nПРОГОН ОСТАНОВЛЕН: {e}")
        return 2
    except Exception as e:  # noqa: BLE001
        print(f"\nПРОГОН ОСТАНОВЛЕН: {type(e).__name__}: {e}")
        return 3

    база.заголовок("6. TRAIN и VALIDATION (все три доли отката)")
    диагностика = {}
    for часть in ("train", "validation"):
        собрано = {д: [] for д in ОТКАТЫ}
        for инструмент, з in границы["инструменты"].items():
            по_долям = сделки_среза(папка, инструмент, з["части"][часть])
            for д in ОТКАТЫ:
                собрано[д] += по_долям[д]
        диагностика[часть] = {f"{д:.2f}": свод(собрано[д]) for д in ОТКАТЫ}
        _печать(часть, {д: диагностика[часть][f"{д:.2f}"] for д in ОТКАТЫ})

    база.заголовок("7. OOS — ЕДИНСТВЕННЫЙ ФИНАЛЬНЫЙ ШАГ")
    try:
        отметка = занять_oos(паспорт)
    except FileExistsError:
        print(f"\nПРОГОН ОСТАНОВЛЕН: отметка {МАРКЕР} уже есть.")
        return 5
    print(f"  Отметка об открытии OOS создана: {МАРКЕР}")
    try:
        база.проверка_7_срезы_oos(папка, границы)
    except Стоп as e:
        print(f"\nПРОГОН ОСТАНОВЛЕН: {e}")
        return 2

    собрано = {д: [] for д in ОТКАТЫ}
    for инструмент, з in границы["инструменты"].items():
        по_долям = сделки_среза(папка, инструмент, з["части"]["oos"])
        for д in ОТКАТЫ:
            собрано[д] += по_долям[д]
    итог = {f"{д:.2f}": свод(собрано[д]) for д in ОТКАТЫ}
    _печать("oos", {д: итог[f"{д:.2f}"] for д in ОТКАТЫ})

    ответ = {
        "хеш_паспорта": паспорт["хеш_паспорта"],
        "архив_h1": база._отпечаток_файла(база.АРХИВ),
        "границы": база._отпечаток_файла(база.ГРАНИЦЫ),
        "ревизия": отметка["ревизия"],
        "когда_utc": отметка["когда_utc"],
        "сценарий_издержек": costs.текущий_сценарий(),
        "зерно": ЗЕРНО,
        "горизонт_баров": ГОРИЗОНТ,
        "доли_отката": list(ОТКАТЫ),
        "train": диагностика.get("train", {}),
        "validation": диагностика.get("validation", {}),
        "oos": итог,
    }

    # КРИТЕРИЙ ИЗ ПАСПОРТА: одна и та же доля, обе границы выше нуля.
    подтверждено = []
    for д in ОТКАТЫ:
        ключ = f"{д:.2f}"
        val = (диагностика.get("validation", {}).get(ключ) or {})
        oos = (итог.get(ключ) or {})
        if oos.get("сделок", 0) < МИНИМУМ_СДЕЛОК:
            continue
        if float(val.get("нижняя_граница", 0)) > 0 and \
           float(oos.get("нижняя_граница", 0)) > 0:
            подтверждено.append(д)

    ответ["решение"] = ("ГИПОТЕЗА ПОДТВЕРЖДЕНА" if подтверждено
                        else "ГИПОТЕЗА ОТКЛОНЕНА")
    ответ["подтвердившиеся_доли"] = подтверждено
    ответ["почему"] = (
        "нижние границы интервалов: " + "; ".join(
            f"{д:.0%} val "
            f"{float((диагностика.get('validation', {}).get(f'{д:.2f}') or {}).get('нижняя_граница', 0)):+.5f} / "
            f"oos {float((итог.get(f'{д:.2f}') or {}).get('нижняя_граница', 0)):+.5f}"
            for д in ОТКАТЫ))
    ответ["оговорка"] = (
        "Проверялись ТРИ доли отката — об этом сказано в паспорте до "
        "расчёта. Срезы используются уже третий раз (H1-edge, З-001, "
        "В-001), поэтому OOS здесь не нетронутый. Подтверждение не "
        "является доказательством прибыльности.")

