# ГРУППА 1. Вызовы, которые ДВИГАЮТ ДЕНЬГИ. Каждый бросает ошибку.
# Список намеренно короткий: сюда попадает только то, что способно
# создать или изменить позицию.
ТОРГОВЫЕ = ("order_send", "order_check")

# ГРУППА 2. Вызовы ПОДКЛЮЧЕНИЯ. Отдают False — «подключиться не удалось».
# Это не выдумка: подключиться действительно не удалось. Программа уже
# умеет так себя вести, когда терминал закрыт.
ПОДКЛЮЧЕНИЕ = ("initialize", "login")

# ГРУППА 2б. Завершение работы. Закрывать нечего — тихо ничего не делаем.
ЗАВЕРШЕНИЕ = ("shutdown",)

# ГРУППА 3. Вызовы, которые только СПРАШИВАЮТ. Отдают пустоту — и это
# правда: ничего не известно, потому что спросить не у кого.
# order_calc_margin и order_calc_profit здесь, а не в ТОРГОВЫЕ: они
# ничего не отправляют брокеру, они только считают по его данным.
ЧИТАЮЩИЕ = ("symbol_info", "symbol_info_tick", "symbol_select",
            "copy_rates_from_pos", "copy_rates_range", "positions_get",
            "orders_get", "history_deals_get", "history_orders_get",
            "symbols_get", "account_info", "terminal_info", "last_error",
            "version", "symbols_total",
            "order_calc_margin", "order_calc_profit")


def поставить_заглушку():
    """Подставить заглушку MetaTrader5, если настоящего пакета нет.

    Возвращает True, если заглушка поставлена."""
    if настоящий_терминал_есть():
        return False
    if getattr(sys.modules.get("MetaTrader5"), "_это_заглушка", False):
        return True

    m = types.ModuleType("MetaTrader5")
    m._это_заглушка = True
    m.__doc__ = ("Заглушка. Настоящего MetaTrader5 на этой машине нет — "
                 "он существует только под Windows.")
    # ПАСПОРТ МОДУЛЯ. Без него `importlib.util.find_spec("MetaTrader5")`
    # не отвечает «нет», а бросает ValueError: «__spec__ is None». Именно
    # так и случилось: вкладка «Диагностика» падала на проверке
    # установленных библиотек — там, где всего-то хотели узнать, есть
    # пакет или нет. Обычный модуль такой паспорт получает от загрузчика;
    # модуль, созданный руками, — не получает, его надо выписать самому.
    m.__spec__ = importlib.machinery.ModuleSpec("MetaTrader5", None)

    for имя, знач in ПОСТОЯННЫЕ.items():
        setattr(m, имя, знач)

    объяснение = почему_нельзя()

    def торговый(имя):
        def нельзя(*a, **k):
            raise ТорговляНедоступна(
                f"Вызов {имя}() невозможен на этом компьютере.\n"
                f"{объяснение}")
        нельзя.__name__ = имя
        return нельзя

    for имя in ТОРГОВЫЕ:
        setattr(m, имя, торговый(имя))

    # Подключение честно не удаётся. Именно False, а не ошибка: программа
    # уже проверяет этот ответ и говорит человеку «терминал недоступен».
    for имя in ПОДКЛЮЧЕНИЕ:
        setattr(m, имя, lambda *a, **k: False)

    # Закрывать нечего.
    for имя in ЗАВЕРШЕНИЕ:
        setattr(m, имя, lambda *a, **k: None)

    # Справочные отдают пустоту. Не выдумывают числа: пустой ответ означает
    # «неизвестно», и это ровно то, что есть на самом деле.
    for имя in ЧИТАЮЩИЕ:
        setattr(m, имя, lambda *a, **k: None)

    sys.modules["MetaTrader5"] = m
    return True


def подготовить() -> str:
    """Вызывается ОДИН раз при старте, до импорта торговых модулей.

    Возвращает строку о состоянии — её показывают человеку."""
    if настоящий_терминал_есть():
        return "Терминал MetaTrader 5 доступен: торговля возможна."
    поставить_заглушку()
    return почему_нельзя()
