def _построчно(путь):
    """Строки файла ПО ОДНОЙ, лениво, без заголовка.

    Отдельная функция нужна не для красоты. Тест подменяет её и
    записывает каждую ВЫДАННУЮ строку. Пока читатель не попросил
    следующую — она физически не прочитана. Так «OOS не читали»
    становится проверяемым фактом, а не обещанием в комментарии.

    Раньше здесь был загрузчик, читавший ВЕСЬ файл целиком, а срез
    отбирался уже из готового списка. Формально порядок соблюдался: за
    train звали train. Фактически строки OOS оказывались в памяти в
    первую же секунду прогона. Аудит поймал это (P1-E3) и был прав."""
    with open(путь, encoding="utf-8") as f:
        next(f, None)          # заголовок
        for строка in f:
            yield строка


def _ряд_среза(путь: str, начало: float, конец: float, сколько: int):
    """Свечи ТОЛЬКО внутри [начало; конец], ровно «сколько» штук.

    CSV упорядочен по времени, поэтому чтение обрывается, а файл
    закрывается, как только срез набран. Для train и validation это
    значит, что байты OOS не читаются вообще — не «не используются», а
    именно не читаются.

    Почему остановка по СЧЁТУ, а не по «первой свече правее конца».
    Второе выглядит естественнее, но чтобы увидеть свечу правее конца,
    её надо прочитать — а для validation эта свеча и есть первая свеча
    OOS. Ровно одна строка невиданных данных утекала бы на каждом
    инструменте. Число баров среза заранее записано в файле границ и
    сверено проверкой 4, поэтому считать можно по нему.

    Условие «правее конца» оставлено вторым рубежом: если данные всё же
    разойдутся с границами, лучше оборваться, чем набрать чужое."""
    бары = []
    поток = _построчно(путь)
    try:
        for строка in поток:
            строка = строка.strip()
            if not строка:
                continue
            ч = строка.split(";")
            t = int(ч[0])
            if t < начало:
                continue
            if t > конец:
                break          # запасной рубеж: данные разошлись с границами
            бары.append({"time": t, "open": float(ч[1]),
                         "high": float(ч[2]), "low": float(ч[3]),
                         "close": float(ч[4]), "spread": int(float(ч[6]))})
            if len(бары) >= сколько:
                break          # срез набран — дальше файл нас не касается
    finally:
        # Закрываем поток СРАЗУ, а не когда до него доберётся сборщик
        # мусора: открытый файл — это ещё не прочитанные байты, но
        # проверяющему приходится верить на слово, а не смотреть.
        закрыть = getattr(поток, "close", None)
        if закрыть is not None:
            закрыть()
    return бары


def сделки_среза(папка_h1: str, инструмент: str, часть: dict) -> list:
    """Чистые сделки внутри одного среза.

    Берутся только те, у кого сигнальная свеча И ВЕСЬ ГОРИЗОНТ умещаются
    внутри среза: иначе исход досчитывался бы по данным за его пределами."""
    if not часть["баров"]:
        return []
    путь = os.path.join(папка_h1, f"{инструмент}_H1.csv")
    начало = datetime.fromisoformat(часть["начало_utc"]).timestamp()
    конец = datetime.fromisoformat(часть["конец_utc"]).timestamp()
    кусок = _ряд_среза(путь, начало, конец, int(часть["баров"]))
    ряд = entry_lab.подготовить(кусок)

    итог = []
    предел = ряд["n"] - ГОРИЗОНТ - 1
    for имя, признак in entry_lab.ПРИЗНАКИ.items():
        for i in range(предел):
            направление = признак(ряд, i)
            if not направление:
                continue
            запись = entry_lab.сделка(ряд, i, направление, symbol=инструмент,
                                      горизонт=ГОРИЗОНТ)
            if запись is None:
                continue
            # ЧИСТАЯ СДЕЛКА: риск строго больше нуля. Нулевые не
            # засчитываются нулём — ноль тянул бы среднее к нулю.
            if float(запись.get("риск_денег", 0)) <= 0:
                continue
            запись["инструмент"] = инструмент
            запись["признак"] = имя
            запись["день"] = datetime.fromtimestamp(
                ряд["time"][i + 1], timezone.utc).strftime("%Y-%m-%d")
            итог.append(запись)
    return итог


def бутстрэп(сделки, повторов=ПОВТОРОВ, зерно=ЗЕРНО) -> dict:
    """Блочный бутстрэп по календарным дням.

    Блок — один день ПО ВСЕМ инструментам сразу. Ресемплинг отдельных
    сделок считал бы их независимыми и занизил бы неопределённость, то
    есть облегчил бы подтверждение гипотезы."""
    по_дням = {}
    for с in сделки:
        по_дням.setdefault(с["день"], []).append(float(с["r_чистый"]))
    дни = sorted(по_дням)
    K = len(дни)
    if K == 0:
        return {}

    все_r = [r for д in дни for r in по_дням[д]]
    средние = []
    ген = random.Random(зерно)
    for _ in range(повторов):
        сумма = 0.0
        сколько = 0
        for _ in range(K):
            день = дни[ген.randrange(K)]
            значения = по_дням[день]
            сумма += sum(значения)
            сколько += len(значения)
        средние.append(сумма / сколько if сколько else 0.0)
    средние.sort()

    def процентиль(p):
        место = (len(средние) - 1) * p / 100.0
        низ = int(место)
        верх = min(низ + 1, len(средние) - 1)
        доля = место - низ
        return средние[низ] * (1 - доля) + средние[верх] * доля

    return {
        "сделок": len(все_r),
        "дней": K,
        "среднее_r": statistics.fmean(все_r),
        "нижняя_граница": процентиль(НИЖНИЙ_ПРОЦЕНТИЛЬ),
        "верхняя_граница": процентиль(ВЕРХНИЙ_ПРОЦЕНТИЛЬ),
        "повторов": повторов,
        "зерно": зерно,
    }


