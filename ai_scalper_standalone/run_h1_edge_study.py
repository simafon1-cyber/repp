"""run_h1_edge_study.py — ЕДИНСТВЕННЫЙ ПРОГОН ПО ПАСПОРТУ H1-EDGE.

ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ

Одна гипотеза, записанная в preregistration/manifest_h1_edge.json ДО
всякого расчёта:

    на невиданном участке часовой истории зафиксированная стратегия
    имеет ПОЛОЖИТЕЛЬНОЕ ожидание на сделку после полной модели издержек

Решает одно число: 2,5-й процентиль распределения бутстрэп-средних
чистого результата в R на срезе OOS. Больше нуля — гипотеза
подтверждена. Не больше — отклонена окончательно.

ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ПРАВКА СТАРОГО ПРОГОНА

Старый run_h1_study.py привязан к другому паспорту, строит часовые свечи
из пятиминутных и проверяет другую гипотезу — про долю издержек. Запуск
его под видом проверки H1-edge был бы недействителен: другой архив,
другой паспорт, другой OOS.

Править его тоже нельзя: тогда пропала бы возможность повторить прежний
принятый результат.

ПОРЯДОК, КОТОРЫЙ НЕЛЬЗЯ ОБОЙТИ

Девять проверок выполняются ДО первого вычисления результата, и каждая
fail-closed: не сошлось — прогон останавливается с ненулевым кодом, а не
продолжается «на всякий случай».

Главная из них — седьмая: OOS не читается, пока не посчитаны train и
validation. Это не формальность. Открыть OOS первым и потом сказать «а
теперь посмотрим train» технически возможно, а честно — нет.

Запуск:
    python3 run_h1_edge_study.py
"""

