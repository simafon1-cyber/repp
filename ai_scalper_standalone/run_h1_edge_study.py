def _ревизия() -> str:
    try:
        return subprocess.check_output(
            ["git", "-C", КОРЕНЬ, "rev-parse", "HEAD"],
            stderr=subprocess.DEVNULL).decode().strip()
    except Exception:  # noqa: BLE001
        return "неизвестна"


def _записать(путь: str, ответ: dict):
    """Результат пишется ТОЛЬКО в новый файл.

    Режим "w" молча затирал бы прошлый результат — то есть позволял бы
    переписать неудобное число, не оставив следа. O_EXCL превращает это
    в ошибку."""
    os.makedirs(os.path.dirname(путь), exist_ok=True)
    ф = os.open(путь, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o444)
    with os.fdopen(ф, "w", encoding="utf-8") as f:
        json.dump(ответ, f, ensure_ascii=False, indent=1)
    print(f"\nЗаписано: {путь}")


