def _ряд_из_файла(путь):
    """Свечи в том виде, который понимает entry_lab."""
    бары = []
    with open(путь, encoding="utf-8") as f:
        next(f, None)
        for строка in f:
            строка = строка.strip()
            if not строка:
                continue
            ч = строка.split(";")
            бары.append({"time": int(ч[0]), "open": float(ч[1]),
                         "high": float(ч[2]), "low": float(ч[3]),
                         "close": float(ч[4]), "spread": int(float(ч[6]))})
    return бары


def сделки_среза(папка_h1: str, инструмент: str, часть: dict) -> list:
    """Чистые сделки внутри одного среза.

    Берутся только те, у кого сигнальная свеча И ВЕСЬ ГОРИЗОНТ умещаются
    внутри среза: иначе исход досчитывался бы по данным за его пределами."""
    if not часть["баров"]:
        return []
    путь = os.path.join(папка_h1, f"{инструмент}_H1.csv")
    все = _ряд_из_файла(путь)
    начало = datetime.fromisoformat(часть["начало_utc"]).timestamp()
    конец = datetime.fromisoformat(часть["конец_utc"]).timestamp()
    кусок = [б for б in все if начало <= б["time"] <= конец]
    ряд = entry_lab.подготовить(кусок)

    итог = []
    предел = ряд["n"] - ГОРИЗОНТ - 1
    for имя, признак in entry_lab.ПРИЗНАКИ.items():
        for i in range(предел):
            направление = признак(ряд, i)
            if not направление:
                continue
            запись = entry_lab.сделка(ряд, i, направление, symbol=инструмент,
                                      горизонт=ГОРИЗОНТ)
            if запись is None:
                continue
            # ЧИСТАЯ СДЕЛКА: риск строго больше нуля. Нулевые не
            # засчитываются нулём — ноль тянул бы среднее к нулю.
            if float(запись.get("риск_денег", 0)) <= 0:
                continue
            запись["инструмент"] = инструмент
            запись["признак"] = имя
            запись["день"] = datetime.fromtimestamp(
                ряд["time"][i + 1], timezone.utc).strftime("%Y-%m-%d")
            итог.append(запись)
    return итог


def бутстрэп(сделки, повторов=ПОВТОРОВ, зерно=ЗЕРНО) -> dict:
    """Блочный бутстрэп по календарным дням.

    Блок — один день ПО ВСЕМ инструментам сразу. Ресемплинг отдельных
    сделок считал бы их независимыми и занизил бы неопределённость, то
    есть облегчил бы подтверждение гипотезы."""
    по_дням = {}
    for с in сделки:
        по_дням.setdefault(с["день"], []).append(float(с["r_чистый"]))
    дни = sorted(по_дням)
    K = len(дни)
    if K == 0:
        return {}

    все_r = [r for д in дни for r in по_дням[д]]
    средние = []
    ген = random.Random(зерно)
    for _ in range(повторов):
        сумма = 0.0
        сколько = 0
        for _ in range(K):
            день = дни[ген.randrange(K)]
            значения = по_дням[день]
            сумма += sum(значения)
            сколько += len(значения)
        средние.append(сумма / сколько if сколько else 0.0)
    средние.sort()

    def процентиль(p):
        место = (len(средние) - 1) * p / 100.0
        низ = int(место)
        верх = min(низ + 1, len(средние) - 1)
        доля = место - низ
        return средние[низ] * (1 - доля) + средние[верх] * доля

    return {
        "сделок": len(все_r),
        "дней": K,
        "среднее_r": statistics.fmean(все_r),
        "нижняя_граница": процентиль(НИЖНИЙ_ПРОЦЕНТИЛЬ),
        "верхняя_граница": процентиль(ВЕРХНИЙ_ПРОЦЕНТИЛЬ),
        "повторов": повторов,
        "зерно": зерно,
    }


# =====================================================================
# ПРОГОН
# =====================================================================
def main(аргументы=None) -> int:
    р = argparse.ArgumentParser(
        description="Единственный прогон по паспорту H1-edge.")
    р.add_argument("--вывод", default=os.path.join(КОРЕНЬ, "research",
                                                   "h1_edge_results.json"))
    а = р.parse_args(аргументы)

    заголовок("ПРОВЕРКИ ДО РАСЧЁТА (каждая fail-closed)")
    временный = tempfile.mkdtemp(prefix="h1_edge_")
    try:
        паспорт = проверка_1_паспорт()
        проверка_2_хеши_данных(паспорт)
        папка = проверка_3_распаковка(временный)
        границы = проверка_4_срезы(папка)
        проверка_5_сценарий_издержек(паспорт)
    except Стоп as e:
        print(f"\nПРОГОН ОСТАНОВЛЕН: {e}")
        return 2
    except SystemExit as e:
        # research_manifest.прочитать() бросает именно SystemExit, а он НЕ
        # ловится обычным except Exception: SystemExit наследуется от
        # BaseException. Без этой ветки процесс умирал, минуя обработку, и
        # прогон нельзя было вызвать как обычную функцию — что и вскрыл
        # собственный тест.
        print(f"\nПРОГОН ОСТАНОВЛЕН: {e}")
        return 2
    except Exception as e:  # noqa: BLE001
        print(f"\nПРОГОН ОСТАНОВЛЕН: {type(e).__name__}: {e}")
        return 3

    # ПОРЯДОК: сначала train и validation, OOS — последним и один раз.
    заголовок("6. TRAIN и VALIDATION (для сравнения, решения не принимают)")
    диагностика = {}
    for часть in ("train", "validation"):
        сделки = []
        for инструмент, з in границы["инструменты"].items():
            сделки += сделки_среза(папка, инструмент, з["части"][часть])
        сводка = бутстрэп(сделки) if сделки else {}
        диагностика[часть] = сводка
        if сводка:
            print(f"  {часть:11} сделок {сводка['сделок']:>6}, дней "
                  f"{сводка['дней']:>4}, среднее R {сводка['среднее_r']:+.5f}, "
                  f"интервал [{сводка['нижняя_граница']:+.5f}; "
                  f"{сводка['верхняя_граница']:+.5f}]")
        else:
            print(f"  {часть:11} сделок нет")

    заголовок("7. OOS — ЕДИНСТВЕННЫЙ ФИНАЛЬНЫЙ ШАГ")
    сделки_oos = []
    for инструмент, з in границы["инструменты"].items():
        сделки_oos += сделки_среза(папка, инструмент, з["части"]["oos"])
    итог = бутстрэп(сделки_oos)

    ответ = {
        "хеш_паспорта": паспорт["хеш_паспорта"],
        "архив_h1": _отпечаток_файла(АРХИВ),
        "границы": _отпечаток_файла(ГРАНИЦЫ),
        "ревизия": _ревизия(),
        "когда_utc": datetime.now(timezone.utc).isoformat(),
        "сценарий_издержек": costs.текущий_сценарий(),
        "train": диагностика.get("train", {}),
        "validation": диагностика.get("validation", {}),
        "oos": итог,
    }

    if not итог or итог["сделок"] < МИНИМУМ_СДЕЛОК:
        ответ["решение"] = "НЕТ ВЫВОДА"
        ответ["почему"] = (
            f"чистых сделок на OOS {итог.get('сделок', 0)}, а требуется "
            f"не менее {МИНИМУМ_СДЕЛОК}. Это НЕ провал гипотезы, а "
            f"отсутствие проверки.")
        print(f"  Сделок: {итог.get('сделок', 0)} — меньше {МИНИМУМ_СДЕЛОК}")
        print(f"\n  РЕШЕНИЕ: {ответ['решение']}. {ответ['почему']}")
        _записать(а.вывод, ответ)
        return 4

    print(f"  Сделок: {итог['сделок']}, дней: {итог['дней']}")
    print(f"  Среднее чистое R: {итог['среднее_r']:+.5f}")
    print(f"  95 % интервал: [{итог['нижняя_граница']:+.5f}; "
          f"{итог['верхняя_граница']:+.5f}]")
    print(f"  Решающее число (2,5-й процентиль): {итог['нижняя_граница']:+.5f}")

    подтверждено = итог["нижняя_граница"] > 0
    ответ["решение"] = "ГИПОТЕЗА ПОДТВЕРЖДЕНА" if подтверждено else "ГИПОТЕЗА ОТКЛОНЕНА"
    ответ["почему"] = (
        "нижняя граница интервала строго больше нуля" if подтверждено else
        "нижняя граница интервала не превышает нуля")

    заголовок(f"РЕШЕНИЕ: {ответ['решение']}")
    print(ответ["почему"] + ".")
    if not подтверждено:
        print("\nОтклонение окончательно. Перебирать другие признаки, "
              "горизонты,\nинструменты или период по итогам этого прогона "
              "ЗАПРЕЩЕНО паспортом.")
    else:
        print("\nЭто НЕ разрешение перейти на H1 и НЕ разрешение торговать.\n"
              "Переход на H1 — изменение стратегии, а оно требует отдельной\n"
              "процедуры по разделу 3 правил проекта. LIVE_TRADING остаётся False.")

    _записать(а.вывод, ответ)
    return 0


def _ревизия() -> str:
    try:
        return subprocess.check_output(
            ["git", "-C", КОРЕНЬ, "rev-parse", "HEAD"],
            stderr=subprocess.DEVNULL).decode().strip()
    except Exception:  # noqa: BLE001
        return "неизвестна"


def _записать(путь: str, ответ: dict):
    os.makedirs(os.path.dirname(путь), exist_ok=True)
    with open(путь, "w", encoding="utf-8") as f:
        json.dump(ответ, f, ensure_ascii=False, indent=1)
    print(f"\nЗаписано: {путь}")


if __name__ == "__main__":
    sys.exit(main())
