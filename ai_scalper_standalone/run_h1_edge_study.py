class Стоп(RuntimeError):
    """Проверка не прошла. Прогон обязан остановиться, а не продолжиться."""


def _отпечаток_файла(путь) -> str:
    h = hashlib.sha256()
    with open(путь, "rb") as f:
        for кусок in iter(lambda: f.read(1 << 20), b""):
            h.update(кусок)
    return h.hexdigest()


def заголовок(текст, знак="="):
    print("\n" + знак * 70)
    print(текст)
    print(знак * 70)


