def проверка_1_паспорт() -> dict:
    """Паспорт читается и не менялся после заверения."""
    паспорт = research_manifest.прочитать(ПАСПОРТ)
    print(f"  1. Паспорт прочитан, заверение целое. "
          f"Хеш: {паспорт['хеш_паспорта'][:16]}...")
    return паспорт


def проверка_2_хеши_данных(паспорт: dict):
    """sha256 архива и файла границ совпадают с записанными в паспорте."""
    версия = паспорт["версия_данных"]
    факт_архив = _отпечаток_файла(АРХИВ)
    факт_границы = _отпечаток_файла(ГРАНИЦЫ)
    for имя, значение in (("архива H1", факт_архив), ("файла границ", факт_границы)):
        if значение not in версия:
            raise Стоп(
                f"Отпечаток {имя} НЕ СОВПАЛ с записанным в паспорте.\n"
                f"  сейчас: {значение}\n"
                f"Данные изменились после заверения условий — прогон по ним "
                f"ничего не доказывает.")
    print(f"  2. Отпечатки данных совпали с паспортом "
          f"(архив {факт_архив[:16]}..., границы {факт_границы[:16]}...)")


def проверка_3_распаковка(куда: str) -> str:
    """Архив распакован во временный каталог; исходные данные не трогаются."""
    with tarfile.open(АРХИВ) as t:
        небезопасные = [ч.name for ч in t.getmembers()
                        if ч.name.startswith("/") or ".." in ч.name.split("/")]
        if небезопасные:
            raise Стоп(f"В архиве небезопасные пути: {небезопасные[:3]}")
        t.extractall(куда)
    снимки = os.path.join(куда, "snapshots")
    каталоги = sorted(os.listdir(снимки))
    if len(каталоги) != 1:
        raise Стоп(f"В архиве ожидался один снимок, найдено {len(каталоги)}")
    папка = os.path.join(снимки, каталоги[0])
    print(f"  3. Архив распакован во временный каталог: снимок {каталоги[0]}")
    return папка


def проверка_4_срезы(папка_h1: str) -> dict:
    """24 отпечатка срезов пересчитаны и сверены с файлом границ."""
    записано = json.loads(open(ГРАНИЦЫ, encoding="utf-8").read())
    прежние = os.path.join(КОРЕНЬ, "data", "_прежние")
    if not os.path.isdir(прежние):
        прежние = _распаковать_прежние()
    посчитано = unseen_split.посчитать(папка_h1, прежние)

    расхождения = []
    сверено = 0
    for инструмент, з in записано["инструменты"].items():
        новое = посчитано["инструменты"].get(инструмент)
        if новое is None:
            расхождения.append(f"{инструмент}: пропал из расчёта")
            continue
        if новое.get("граница_секунды") != з.get("граница_секунды"):
            расхождения.append(f"{инструмент}: граница разошлась")
        for часть in unseen_split.ЧАСТИ:
            сверено += 1
            было = з["части"][часть]["sha256"]
            стало = новое["части"][часть]["sha256"]
            if было != стало:
                расхождения.append(f"{инструмент}/{часть}: отпечаток среза разошёлся")
    if расхождения:
        raise Стоп("Срезы не совпали с зафиксированными:\n  "
                   + "\n  ".join(расхождения[:6]))
    print(f"  4. Пересчитано и сверено отпечатков срезов: {сверено} из 24")
    return посчитано


def _распаковать_прежние() -> str:
    """Прежние M1/M5/M15 нужны, чтобы пересчитать границы."""
    архив = os.path.join(КОРЕНЬ, "data", "history_all.tar.gz")
    куда = tempfile.mkdtemp(prefix="прежние_")
    with tarfile.open(архив) as t:
        t.extractall(куда)
    return os.path.join(куда, "raw")


def проверка_5_сценарий_издержек(паспорт: dict):
    """Базовый сценарий выбирается ДО расчёта, а не после."""
    if "БАЗОВЫЙ" not in паспорт["сценарий_издержек"].upper():
        raise Стоп("В паспорте решающий сценарий издержек не назван базовым")
    costs.выбрать_сценарий(costs.БАЗОВЫЙ)
    if costs.текущий_сценарий() != costs.БАЗОВЫЙ:
        raise Стоп("Не удалось включить базовый сценарий издержек")
    print(f"  5. Сценарий издержек выбран ДО расчёта: {costs.текущий_сценарий()}")


