def проверка_6_одноразовость(паспорт: dict):
    """OOS открывают ОДИН раз. Отметка об этом лежит на диске.

    Паспорт разрешал один раз словами. Слова не мешают запустить прогон
    снова после неудобного числа — аудит указал на это (P1-E4). Теперь
    мешает файл.

    Разбирается ЧЕТЫРЕ состояния, и три из них — отказ:

    * отметки нет, результата нет  — первая попытка, можно;
    * отметка есть и совпала       — уже смотрели, нельзя;
    * отметка есть, но от других входов — не про этот прогон, нельзя;
    * отметки нет, а результат есть — отметку удалили, это ИНЦИДЕНТ.

    Последнее важнее всего. Удаление файла не должно работать как
    разрешение начать заново: иначе вся защита стоит одну команду."""
    свои = _отпечатки(паспорт)
    if os.path.exists(МАРКЕР):
        try:
            был = json.loads(open(МАРКЕР, encoding="utf-8").read())
        except Exception as e:  # noqa: BLE001
            raise УжеОткрывали(
                f"Отметка об открытии OOS есть, но нечитаема ({e}).\n"
                f"  {МАРКЕР}\n"
                f"Пока не доказано обратное — считаем, что OOS открывали.")
        if all(был.get(к) == з for к, з in свои.items()):
            raise УжеОткрывали(
                f"OOS по этому паспорту и этим данным УЖЕ открывали.\n"
                f"  когда: {был.get('когда_utc')}\n"
                f"  ревизия: {был.get('ревизия')}\n"
                f"  отметка: {МАРКЕР}\n"
                f"Паспорт разрешает ровно один раз. Повторный прогон "
                f"недействителен, каким бы ни был прошлый результат.")
        raise УжеОткрывали(
            f"Отметка об открытии OOS есть, но она от ДРУГИХ входных "
            f"данных.\n  {МАРКЕР}\n"
            f"Либо подменены данные, либо отметка чужая. И то и другое "
            f"разбирают руками, а не молча продолжают прогон.")
    if os.path.exists(РЕЗУЛЬТАТ):
        raise УжеОткрывали(
            f"Результат прошлого прогона есть, а отметки об открытии OOS "
            f"нет.\n  результат: {РЕЗУЛЬТАТ}\n  отметка: {МАРКЕР}\n"
            f"Отметку удалили. Это ИНЦИДЕНТ, а не разрешение повторить.")
    print("  6. Отметки об открытии OOS нет — это первая и единственная попытка")


def _занять_oos(паспорт: dict) -> dict:
    """Атомарно застолбить единственное открытие OOS.

    O_EXCL — не украшение. «Проверить, что файла нет» и «создать файл» —
    два разных действия, и между ними файл может появиться. Здесь
    создание либо происходит целиком, либо падает FileExistsError. Файл
    создаётся ДО первого чтения OOS, а не после расчёта: иначе прогон,
    прерванный на середине, оставлял бы OOS «неоткрытым»."""
    отметка = dict(_отпечатки(паспорт))
    отметка["ревизия"] = _ревизия()
    отметка["когда_utc"] = datetime.now(timezone.utc).isoformat()
    os.makedirs(os.path.dirname(МАРКЕР), exist_ok=True)
    ф = os.open(МАРКЕР, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o444)
    with os.fdopen(ф, "w", encoding="utf-8") as f:
        json.dump(отметка, f, ensure_ascii=False, indent=1)
    return отметка


