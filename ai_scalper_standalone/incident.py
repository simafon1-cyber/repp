"""incident.py — НЕЗАКРЫТЫЙ ИНЦИДЕНТ ИСПОЛНЕНИЯ, ПЕРЕЖИВАЮЩИЙ ПЕРЕЗАПУСК.

ЗАЧЕМ ЭТОТ МОДУЛЬ ПОЯВИЛСЯ

Работа И1 научила программу останавливаться, когда положение заявки не
выяснено: возможно, позиция открыта, а возможно, нет. Остановка делалась
так:

    control.set_paused(True)

Это переменная в памяти. Программа перезапустилась — переменная исчезла, и
торговля пошла дальше как ни в чём не бывало. То есть защита работала
ровно до первого перезапуска, а перезапуск в такой момент как раз и
вероятен: программу перезапускают, когда с ней что-то не так.

Здесь остановка кладётся на диск и переживает перезапуск.

ЧЕТЫРЕ ПРАВИЛА, ПО КОТОРЫМ ЭТО УСТРОЕНО

1. ЗАПИСЬ ЦЕЛИКОМ ИЛИ НИКАК. Файл пишется атомарно (см. safe_files):
   промежуточного «наполовину записанного» состояния не бывает.

2. СОМНЕНИЕ ТОЛКУЕТСЯ В СТОРОНУ ОСТАНОВКИ. Файл не читается, испорчен,
   изменён снаружи программы — считаем, что инцидент ЕСТЬ. Ошибка в эту
   сторону стоит простоя. Ошибка в другую — торговли поверх неучтённой
   позиции.

3. САМА ПРОГРАММА ИНЦИДЕНТ НЕ СНИМАЕТ. Ни при старте, ни по времени, ни
   обычной кнопкой «снять паузу». Снять может только человек отдельным
   действием, и это записывается в журнал.

4. ФАЙЛ ЗАЩИЩЁН, НАСКОЛЬКО ПОЗВОЛЯЕТ СИСТЕМА. Доступ ограничивается
   текущим пользователем, целостность проверяется хэшем.

ЧЕГО ЭТОТ МОДУЛЬ НЕ ДЕЛАЕТ

Он не выясняет, что на самом деле произошло на счёте. Это работа И3
(сверка при старте). Здесь только одно: не дать программе продолжить
торговлю, пока человек не разобрался.
"""

import json
import logging
import os
import sys
from datetime import datetime

import safe_files

log = logging.getLogger("incident")

ФАЙЛ = "incident.json"
ЖУРНАЛ = "incident_log.txt"
ВЕРСИЯ = 1

# Суффикс файла с хэшем. Должен совпадать с тем, что пишет safe_files —
# проверяется тестом, иначе строгая проверка ниже искала бы не тот файл и
# всегда говорила «хэша нет».
ХЭШ_СУФФИКС = ".sha256"

# Что записано, когда файл есть, но прочитать его не вышло. Инцидент при
# этом считается ОТКРЫТЫМ: см. правило 2.
ПОВРЕЖДЁН = "повреждён"


def путь(folder: str = "") -> str:
    """Файл РЯДОМ С ПРОГРАММОЙ, а не в служебной подпапке.

    У собранной версии код лежит в _internal, и путь по __file__ увёл бы
    отметку об инциденте туда, где человек её не найдёт."""
    if folder:
        base = folder
    elif getattr(sys, "frozen", False):
        base = os.path.dirname(sys.executable)
    else:
        base = os.path.dirname(os.path.abspath(__file__))
    return os.path.join(base, ФАЙЛ)


def путь_журнала(folder: str = "") -> str:
    return os.path.join(os.path.dirname(путь(folder)), ЖУРНАЛ)


# =====================================================================
def открыть(сведения: dict, folder: str = "") -> bool:
    """Записать незакрытый инцидент. True — записан на диск.

    False означает, что на диск записать НЕ УДАЛОСЬ. Это не повод
    продолжать торговлю: вызывающий обязан остановиться в памяти и сказать
    об этом человеку. Просто такая остановка не переживёт перезапуск."""
    цель = путь(folder)
    запись = {
        "version": ВЕРСИЯ,
        "открыт": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        "сведения": dict(сведения or {}),
    }
    try:
        safe_files.atomic_write_text(
            цель, json.dumps(запись, ensure_ascii=False, indent=2),
            backup=False)
    except Exception as e:  # noqa: BLE001
        log.error("НЕ УДАЛОСЬ записать инцидент в %s: %s. Остановка "
                  "действует только до перезапуска.", цель, e)
        return False

    safe_files.restrict_to_current_user(цель)
    _в_журнал(folder, "ОТКРЫТ", сведения.get("причина", ""))
    log.error("Открыт незакрытый инцидент исполнения: %s",
              сведения.get("причина", ""))
    return True


def открыт(folder: str = "") -> bool:
    """Есть ли незакрытый инцидент.

    Файл есть — инцидент есть. Читаемость содержимого на этот ответ не
    влияет: испорченный файл тоже значит «есть» (правило 2)."""
    return os.path.exists(путь(folder))


def подробности(folder: str = "") -> dict:
    """Что именно записано. Пустой словарь — инцидента нет.

    Если файл не читается или изменён снаружи, возвращается пометка о
    повреждении, а НЕ пустой словарь: инцидент остаётся открытым."""
    цель = путь(folder)
    if not os.path.exists(цель):
        return {}

    целостен, беда = _целостность_строго(цель)
    try:
        with open(цель, "r", encoding="utf-8") as f:
            данные = json.load(f)
    except Exception as e:  # noqa: BLE001
        log.error("Файл инцидента %s не читается (%s) — считаю инцидент "
                  "открытым", цель, e)
        return {"состояние": ПОВРЕЖДЁН,
                "причина": f"файл инцидента не читается: {e}"}

    if not isinstance(данные, dict) or "сведения" not in данные:
        return {"состояние": ПОВРЕЖДЁН,
                "причина": "файл инцидента не той формы"}

    итог = dict(данные.get("сведения") or {})
    итог["открыт"] = данные.get("открыт", "")
    if not целостен:
        # Доверять содержимому уже нельзя. Само по себе это не обязательно
        # злой умысел — файл могли тронуть руками, — но и не «всё в порядке».
        итог["состояние"] = ПОВРЕЖДЁН
        итог["причина"] = f"{итог.get('причина', '')} [{беда}]".strip()
        log.error("Файл инцидента %s: %s", цель, беда)
    return итог


def _целостность_строго(цель: str):
    """Совпадает ли файл со своим хэшем. (True, "") — да.

    ЗДЕСЬ СТРОЖЕ, ЧЕМ В ОБЩЕЙ ПРОВЕРКЕ safe_files.check_integrity(). Та
    считает отсутствующий хэш-файл нормой и молча создаёт его заново — для
    обычных журналов это удобно. Для отметки об остановке — нет: тогда
    достаточно удалить хэш-файл, и подмена содержимого пройдёт незамеченной.

    Поэтому отсутствующий и нечитаемый хэш здесь считаются повреждением."""
    сайдкар = цель + ХЭШ_СУФФИКС
    if not os.path.exists(сайдкар):
        return False, "хэш-файл отсутствует — содержимое подтвердить нечем"
    try:
        with open(сайдкар, encoding="utf-8") as f:
            ожидаемый = f.read().strip()
    except OSError as e:
        return False, f"хэш-файл не читается: {e}"
    if not ожидаемый:
        return False, "хэш-файл пуст"
    фактический = safe_files.sha256_of_file(цель)
    if not фактический:
        return False, "файл не прочитать для сверки хэша"
    if фактический != ожидаемый:
        return False, "файл изменён снаружи программы"
    return True, ""


def снять(кто: str, комментарий: str = "", folder: str = "") -> bool:
    """Закрыть инцидент. ТОЛЬКО по явному действию человека.

    Программа сама эту функцию не вызывает нигде — ни при старте, ни по
    времени. Проверяется отдельным тестом.

    `кто` обязателен: закрытие инцидента должно быть именным, иначе через
    месяц никто не вспомнит, кто разрешил торговать дальше."""
    if not str(кто or "").strip():
        log.error("Попытка снять инцидент без указания, кто это сделал — "
                  "отказано")
        return False

    цель = путь(folder)
    if not os.path.exists(цель):
        return True

    _в_журнал(folder, "СНЯТ", f"{кто}: {комментарий}".strip(": "))
    try:
        os.remove(цель)
    except OSError as e:
        log.error("Не удалось удалить файл инцидента %s: %s", цель, e)
        return False
    try:
        os.remove(цель + ".sha256")
    except OSError:
        pass
    log.warning("Инцидент снят человеком (%s): %s", кто, комментарий)
    return True


def _в_журнал(folder: str, что: str, текст: str):
    """Журнал открытий и снятий. Дозапись, чтобы история не терялась."""
    строка = (f"{datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\t{что}\t"
              f"{текст}\n")
    try:
        safe_files.append_line_safely(
            путь_журнала(folder), lambda f: f.write(строка))
    except Exception as e:  # noqa: BLE001
        log.warning("Не удалось записать в журнал инцидентов: %s", e)
