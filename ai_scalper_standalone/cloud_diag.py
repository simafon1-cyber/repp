"""cloud_diag.py — СОСТОЯНИЕ ПРОГРАММЫ, ВЫЛОЖЕННОЕ ТУДА, ГДЕ ЕГО ПРОЧТУТ.

=====================================================================
ЗАЧЕМ ЭТОТ ФАЙЛ СУЩЕСТВУЕТ
=====================================================================
Владелец, дословно: «все ошибки, которые появляются, пускай он
записывает где-то в логи на GitHub, чтобы ты его сам непосредственно мог
прочитать этот файл, чтобы я тебе не скидывал каждый раз скриншот».

За неделю разбирательств причина «почему нет сделок» трижды оказывалась
не той, что предполагал исполнитель, и каждый раз её находил СНИМОК
ЭКРАНА владельца. То есть человек работал глазами вместо программы.

Здесь программа рассказывает о себе сама: раз в несколько минут кладёт
в репозиторий короткий текст — что с барьером, сколько пар, почему по
каждой не входили, какие ошибки были в журнале.

=====================================================================
ЧЕГО ЗДЕСЬ НЕТ И НЕ БУДЕТ
=====================================================================
Секретов. Токены, пароли и ключи вычищаются ПЕРЕД отправкой, а не
«стараемся не писать»: файл уезжает в репозиторий, и одна утёкшая строка
там останется навсегда. Вычистка — не украшение, а условие работы.

Денег и сделок: для них есть cloud_journal. Здесь только состояние
машины.
"""

from __future__ import annotations

import logging
import os
import re
import sys
from datetime import datetime, timezone

log = logging.getLogger("cloud_diag")

# Сколько последних строк журнала прикладывать. Больше — файл распухает и
# перестаёт читаться; меньше — не видно, что предшествовало беде.
СТРОК_ЖУРНАЛА = 120

# Что вычищаем перед отправкой. Список нарочно шире необходимого: лучше
# затереть лишнее, чем однажды не затереть нужное.
СЕКРЕТЫ = (
    re.compile(r"gh[pousr]_[A-Za-z0-9]{16,}"),          # токены GitHub
    re.compile(r"github_pat_[A-Za-z0-9_]{20,}"),
    re.compile(r"(?i)(token|password|пароль|secret|ключ)\s*[:=]\s*\S+"),
    re.compile(r"(?i)authorization:\s*\S+"),
)


def вычистить(текст: str) -> str:
    """Убрать из текста всё, что похоже на секрет."""
    очищено = str(текст or "")
    for правило in СЕКРЕТЫ:
        очищено = правило.sub("<вырезано>", очищено)
    return очищено


def _хвост_журнала(путь: str, строк: int = СТРОК_ЖУРНАЛА) -> list:
    """Последние строки файла журнала. Ошибка чтения — не беда."""
    try:
        with open(путь, "r", encoding="utf-8", errors="replace") as f:
            return f.readlines()[-строк:]
    except OSError:
        return []


def собрать(снимок: dict = None, барьер=None, инцидент: dict = None,
            ожидающих: int = 0, путь_журнала: str = "",
            версия: str = "") -> str:
    """Короткий текст о состоянии программы. Ничего не отправляет.

    Отделено от отправки нарочно: собрать состояние должно быть
    безопасно и проверяемо тестом, без сети и без репозитория."""
    снимок = снимок or {}
    счёт = снимок.get("account") or {}
    строки = [
        "СОСТОЯНИЕ ПРОГРАММЫ",
        f"время UTC: {datetime.now(timezone.utc).isoformat(timespec='seconds')}",
        f"версия: {версия or 'неизвестна'}",
        "",
        "СЧЁТ",
        f"  номер: {счёт.get('login', '—')}   сервер: {счёт.get('server', '—')}",
        f"  баланс: {счёт.get('balance', '—')}   эквити: {счёт.get('equity', '—')}",
        f"  режим счёта (trade_mode): {счёт.get('trade_mode', '—')}",
        f"  реальная торговля включена: {снимок.get('live_trading', '—')}",
        f"  профиль риска: {снимок.get('risk_profile', '—')}",
        f"  сделок сегодня: {снимок.get('trades_today', '—')}",
        "",
        "БАРЬЕР",
    ]
    if барьер is None:
        строки.append("  спросить не удалось")
    else:
        строки.append(f"  открыт: {барьер.get('открыт', '—')}")
        if барьер.get("причина_отказа"):
            строки.append(f"  причина отказа: {барьер['причина_отказа']}")
        if барьер.get("разрешение"):
            строки.append(f"  открыт для: {барьер['разрешение']}")

    строки += ["", "ПРОИСШЕСТВИЕ",
               f"  открыто: {bool(инцидент)}",
               f"  причина: {(инцидент or {}).get('причина', '—')}",
               f"  неподтверждённых заявок: {ожидающих}", ""]

    пары = снимок.get("symbols") or []
    строки.append(f"ПАРЫ ({len(пары)})")
    if not пары:
        строки.append("  НИ ОДНОЙ — сделок не будет по этой причине")
    for п in пары[:40]:
        if not isinstance(п, dict):
            continue
        строки.append(
            f"  {str(п.get('symbol', '?')):12} отказ: "
            f"{п.get('reject_reason', '—')}")

    хвост = _хвост_журнала(путь_журнала) if путь_журнала else []
    беды = [с for с in хвост
            if "ERROR" in с or "WARNING" in с or "CRITICAL" in с]
    строки += ["", f"ОШИБКИ И ПРЕДУПРЕЖДЕНИЯ ИЗ ЖУРНАЛА ({len(беды)})"]
    строки += ["  " + с.rstrip() for с in беды[-40:]] or ["  нет"]

    строки += ["", "ЧЕГО ЗДЕСЬ НЕТ",
               "  токенов, паролей и ключей — вычищены перед отправкой",
               "  сделок и денег — они в отдельном журнале"]
    return вычистить("\n".join(строки))


def имя_файла(снимок: dict = None) -> str:
    """Куда класть в репозитории. По счёту — чтобы не путать машины."""
    счёт = (снимок or {}).get("account") or {}
    номер = str(счёт.get("login") or "неизвестный")
    return f"diag/состояние_{номер}.txt"


def выгрузить(текст: str, снимок: dict = None) -> tuple:
    """(получилось, пояснение). Ошибка выгрузки НЕ должна ломать торговлю."""
    try:
        import cloud_journal
    except ImportError as e:      # pragma: no cover
        return False, f"облачный журнал недоступен: {e}"
    if not cloud_journal.enabled():
        return False, "выгрузка состояния выключена (JOURNAL_CLOUD_ENABLED)"
    готов, почему = cloud_journal.ready()
    if not готов:
        return False, почему
    try:
        коммит = cloud_journal.put_file(
            имя_файла(снимок), вычистить(текст),
            "состояние программы")
    except Exception as e:  # noqa: BLE001
        return False, f"{type(e).__name__}: {e}"
    return True, f"выложено, коммит {коммит}"
