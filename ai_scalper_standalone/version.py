"""version.py — какая версия программы сейчас установлена.

ЗАЧЕМ ЭТО ЕСТЬ
Владелец: «прописывай где-то версию, чтобы было видно, обновилось или нет».
Без этого понять, работает ли новая сборка, можно было только косвенно — по
тому, изменилось ли поведение. Несколько раз получалось так: исправление
давно выпущено, а программа запущена старая, и мы искали ошибку, которой
в новой версии уже нет.

ОТКУДА БЕРУТСЯ ЗНАЧЕНИЯ
Файл переписывается сборочным сценарием (.github/workflows/build-exe.yml)
прямо перед упаковкой .exe: туда подставляются номер сборки, короткий номер
коммита и дата. В исходниках, запущенных как есть, значения остаются
«разработка» — это честно: такой запуск и правда не является выпущенной
сборкой.

Файл намеренно простой (только строки, никаких зависимостей): его
переписывает сценарий сборки, и любая логика здесь означала бы риск
получить .exe, который не запускается.
"""

# --- заполняется при сборке, не редактировать вручную ---
BUILD_NUMBER = ""      # номер сборки на GitHub, например "11"
COMMIT = ""            # короткий номер правки, например "92a52c7"
BUILT_AT = ""          # дата сборки, например "2026-08-06"
# ---------------------------------------------------------


def is_release() -> bool:
    """True — это выпущенная сборка, False — запуск из исходников."""
    return bool(BUILD_NUMBER)


def short() -> str:
    """Коротко, для заголовка окна: «сборка 11» или «разработка»."""
    if not is_release():
        return "разработка"
    return f"сборка {BUILD_NUMBER}"


def full() -> str:
    """Подробно, для вкладки «Система»: сборка, дата и номер правки.

    Дата и номер правки нужны не для красоты: по ним видно, ТА ЛИ это
    версия, о которой шла речь. Номер сборки сам по себе можно спутать,
    а «сборка 11 · 06.08.2026 · 92a52c7» ни с чем не спутаешь."""
    if not is_release():
        return ("разработка (запуск из исходников, а не собранная программа)")
    parts = [f"сборка {BUILD_NUMBER}"]
    if BUILT_AT:
        parts.append(BUILT_AT)
    if COMMIT:
        parts.append(COMMIT)
    return " · ".join(parts)


def number() -> int:
    """Номер сборки числом. 0 — не выпущенная сборка. Нужен, чтобы сравнить
    установленное с тем, что лежит в GitHub Releases."""
    try:
        return int(str(BUILD_NUMBER).strip())
    except (TypeError, ValueError):
        return 0
