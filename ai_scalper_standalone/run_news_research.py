def разрезать(события, доли=(ДОЛЯ_TRAIN, ДОЛЯ_VALID)):
    n = len(события)
    a = int(n * доли[0])
    b = int(n * (доли[0] + доли[1]))
    return {"TRAIN": события[:a], "VALIDATION": события[a:b], "OOS": события[b:]}


