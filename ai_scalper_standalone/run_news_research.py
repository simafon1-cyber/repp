        ряд = данные.get(s) or []
        if not ряд:
            continue
        print(f"\n  {s}: средний |ход| бара по часам сервера (в единицах ATR)")
        по_часам = {}
        for i in range(30, len(ряд)):
            atr = nr.atr_до(ряд, i)
            if atr <= 0:
                continue
            import datetime as dt
            час = dt.datetime.utcfromtimestamp(ряд[i]["t"]).hour
            мин = dt.datetime.utcfromtimestamp(ряд[i]["t"]).minute
