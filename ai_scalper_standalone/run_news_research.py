def раздел_доходимость(итоги):
    шапка("5. РАСПРЕДЕЛЕНИЕ ХОДА: P(MFE >= X)")
    print("  MFE и MAE меряются от цены выпуска, R = ATR ДО события.")
    for (s, окно), (соб, замеры) in sorted(итоги.items()):
        mfe = [з["MFE"] for з in замеры]
        mae = [з["MAE"] for з in замеры]
        доли = []
        for порог in (0.5, 1.0, 1.5, 2.0):
            п = sum(1 for x in mfe if x >= порог) / len(mfe) * 100
            # И отдельно: дошли до цели, НЕ задев стоп в 1R раньше.
            чисто = sum(1 for з in замеры if з["MFE"] >= порог and з["MAE"] < 1.0)
            доли.append(f"{порог}R: {п:4.1f}% (чисто {чисто/len(mfe)*100:4.1f}%)")
        print(f"  {s} {окно:<16} " + "  ".join(доли))


def раздел_варианты(данные, итоги):
    шапка("6. ЧЕТЫРЕ ВАРИАНТА ВХОДА x ЧЕТЫРЕ ВЫХОДА")
    print("  Правила заданы заранее и не подбираются. Степеней свободы:")
    print("  4 входа x 4 выхода x 3 окна x 2 инструмента = 96 клеток.")
    print("  Это МНОГО, и поправка на множественность обязательна — см. ниже.")
    print("  Выбор делается ТОЛЬКО на TRAIN.")

    результаты = {}
    for s in СИМВОЛЫ:
        ряд = данные.get(s) or []
        point = 1e-05 if s == "EURUSD" else 0.01
        for окно in ("US_0830", "US_1000", "US_1400"):
            пара = итоги.get((s, окно))
            if not пара:
                continue
            соб, _ = пара
            куски = разрезать(соб)
            for имя_вх, вход in nr.ВХОДЫ.items():
                for имя_вых, (sl, tp, предел) in nr.ВЫХОДЫ.items():
                    по_кускам = {}
                    for кусок, список in куски.items():
                        r = []
                        for e in список:
                            atr = nr.atr_до(ряд, e["i"])
                            if atr <= 0:
                                continue
                            вх = вход(ряд, e["i"])
                            if not вх:
                                continue
                            начало, цена, знак = вх
                            # Спред платится один раз, из самих данных.
                            спред_r = (ряд[e["i"]]["s"] * point) / (sl * atr)
                            итог, _, _ = nr.выход(ряд, начало, цена, знак, sl,
                                                  tp, atr, предел, спред_r)
                            r.append(итог)
                        по_кускам[кусок] = r
                    результаты[(s, окно, имя_вх, имя_вых)] = по_кускам

    # Печатаем только TRAIN, и только клетки, где хоть что-то набралось.
    print()
    print("  TRAIN (по нему выбираем):")
    годные = []
    for ключ, по_кускам in sorted(результаты.items()):
        s, окно, вх, вых = ключ
        c = nr.сводка(по_кускам["TRAIN"])
        if c["n"] < МИНИМУМ_СДЕЛОК:
            continue
        годные.append((ключ, c))
    годные.sort(key=lambda x: -x[1]["ожидание"])
    for (s, окно, вх, вых), c in годные[:12]:
        строка(f"{s[:6]} {окно[3:]} {вх[0]} {вых}", c)
    if not годные:
        print(f"    Ни в одной клетке не набралось {МИНИМУМ_СДЕЛОК} сделок.")
    return результаты, годные


def раздел_семейство(данные, итоги, результаты):
    """САМАЯ ВАЖНАЯ ПРОВЕРКА: работает ли тот же вход в спокойную минуту.

    Если да — это не новостной эффект, а просто откатная стратегия, и
    новости тут ни при чём."""
    шапка("7. РЕШАЮЩАЯ ПРОВЕРКА: тот же вход в СПОКОЙНУЮ минуту")
    print("  Если правило работает и в 05:30, когда никаких данных США не")
    print("  выходит, значит дело не в новостях. Сравнение парное: одни и те")
    print("  же дни, одни и те же правила, разное время суток.")

    для_отчёта = {}
    for s_ in СИМВОЛЫ:
        ряд = данные.get(s_) or []
        point = 1e-05 if s_ == "EURUSD" else 0.01
        for имя_вх, вход in nr.ВХОДЫ.items():
            for имя_вых, (sl, tp, предел) in nr.ВЫХОДЫ.items():
                пары = {}
                for метка, окно in (("новость", "US_0830"),
                                    ("контроль", "КОНТРОЛЬ 05:30")):
                    пара = итоги.get((s_, окно))
                    if not пара:
                        continue
                    соб, _ = пара
                    r = []
                    for e in соб:
                        atr = nr.atr_до(ряд, e["i"])
                        if atr <= 0:
                            continue
                        вх = вход(ряд, e["i"])
                        if not вх:
                            continue
                        начало, цена, знак = вх
                        спред_r = (ряд[e["i"]]["s"] * point) / (sl * atr)
                        итог, _, _ = nr.выход(ряд, начало, цена, знак, sl, tp,
                                              atr, предел, спред_r)
                        r.append(итог)
                    пары[метка] = r
                if len(пары) == 2 and min(len(v) for v in пары.values()) >= 30:
                    p = nr.перестановка(пары["новость"], пары["контроль"])
                    для_отчёта[(s_, имя_вх, имя_вых)] = (
                        nr.сводка(пары["новость"]), nr.сводка(пары["контроль"]), p)

    print()
    значимых = 0
    for (s_, вх, вых), (нов, контр, p) in sorted(
            для_отчёта.items(), key=lambda kv: -(kv[1][0]["ожидание"] - kv[1][1]["ожидание"])):
        разница = нов["ожидание"] - контр["ожидание"]
        знак = "ЗНАЧИМО" if p <= 0.05 else "не значимо"
        if p <= 0.05:
            значимых += 1
        print(f"  {s_[:6]} {вх:<14} {вых:<10} новость {нов['ожидание']:>8}R "
              f"(n={нов['n']:>3})  контроль {контр['ожидание']:>8}R "
              f"(n={контр['n']:>3})  разница {разница:+.4f}R  p={p:.4f}  {знак}")
    print()
    print(f"  Клеток, где новость значимо отличается от спокойной минуты: "
          f"{значимых} из {len(для_отчёта)}")
    print(f"  При 5% уровне и {len(для_отчёта)} проверках случайность даёт "
          f"около {len(для_отчёта) * 0.05:.1f} таких находок сама по себе.")
    return для_отчёта


def раздел_издержки(данные, результаты, годные):
    шапка("8. ИЗДЕРЖКИ: сколько пунктов выдерживает результат")
    if not годные:
        print("  Нечего проверять: ни одна клетка не набрала "
              f"{МИНИМУМ_СДЕЛОК} сделок.")
        return None
    (s_, окно, вх, вых), _ = годные[0]
    ряд = данные[s_]
    point = 1e-05 if s_ == "EURUSD" else 0.01
    sl_atr, tp_r, предел = nr.ВЫХОДЫ[вых]
    print(f"  Лучшая клетка TRAIN при n >= {МИНИМУМ_СДЕЛОК}: "
          f"{s_} {окно} / {вх} / {вых}")

    # Сколько ПУНКТОВ стоит один R — без этого числа издержки не с чем сравнить.
    пара = результаты.get((s_, окно, вх, вых))
    соб = _события_кэш.get((s_, окно), [])
    r_в_пунктах = []
    for e in соб:
        atr = nr.atr_до(ряд, e["i"])
        if atr > 0:
            r_в_пунктах.append(sl_atr * atr / point)
    if r_в_пунктах:
        медиана_r = nr.перцентиль(r_в_пунктах, 0.5)
        print(f"  1R = {медиана_r:.0f} пунктов (медиана). Это и есть мерка, с")
        print(f"  которой надо сравнивать спред и проскальзывание.")

    print()
    print("  Ожидание при разном проскальзывании (в пунктах на сделку):")
    for пунктов in ИЗДЕРЖКИ_ПУНКТОВ[s_]:
        по_кускам = {}
        for кусок, список in разрезать(соб).items():
            r = []
            for e in список:
                atr = nr.atr_до(ряд, e["i"])
                if atr <= 0:
                    continue
                вх_ф = nr.ВХОДЫ[вх](ряд, e["i"])
                if not вх_ф:
                    continue
                начало, цена, знак = вх_ф
                издержки_r = (пунктов * point) / (sl_atr * atr)
                итог, _, _ = nr.выход(ряд, начало, цена, знак, sl_atr, tp_r,
                                      atr, предел, издержки_r)
                r.append(итог)
            по_кускам[кусок] = r
        c = nr.сводка(по_кускам["TRAIN"])
        строка(f"+{пунктов} пунктов", c)
