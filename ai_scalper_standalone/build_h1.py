"""build_h1.py — СОБРАТЬ ЧАСОВЫЕ СВЕЧИ ИЗ ПЯТИМИНУТНЫХ.

ЗАЧЕМ

Часовой истории у нас нет — есть пятиминутная. Двенадцать пятиминуток
складываются в один час, и это не приближение: часовая свеча по
определению есть открытие первой, максимум и минимум по всем, закрытие
последней.

ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ПАРА СТРОК В ПРОГОНЕ

Потому что сборка должна быть ДЕТЕРМИНИРОВАННОЙ и проверяемой. Аудит
потребовал: H1 формируется только детерминированной агрегацией, а хеш
полученных данных попадает в паспорт прогона. Значит, у сборки должен
быть свой хеш, который можно сравнить.

ГЛАВНОЕ ПРАВИЛО СБОРКИ: НЕПОЛНЫЙ ЧАС НЕ БЕРЁТСЯ

Если в часе оказалось меньше двенадцати пятиминуток — а так бывает на
границах выходных, на праздниках и в разрывах данных, — такой час
выбрасывается целиком.

Соблазн «взять что есть» здесь опасен: неполный час это час с другим
диапазоном, а на диапазоне (ATR) стоит весь расчёт риска. Пара таких
часов на границе выходных сместила бы ATR, а вместе с ним и размер стопа,
и долю издержек — то есть ровно то, что мы измеряем.

СПРЕД БЕРЁТСЯ МАКСИМАЛЬНЫЙ ИЗ ДВЕНАДЦАТИ

Не средний. Вход в часовую свечу происходит в какой-то момент внутри неё,
и какой именно спред был в ту секунду, мы не знаем. Брать средний значило
бы предполагать удачу. Максимум — осторожная оценка, а осторожность в
издержках здесь принципиальна.
"""

import hashlib
import logging

log = logging.getLogger("build_h1")

СВЕЧЕЙ_В_ЧАСЕ = 12          # 12 × 5 минут
СЕКУНД_В_ЧАСЕ = 3600


def собрать(bars_m5) -> dict:
    """Пятиминутки → часы. Возвращает {"bars": [...], "пропущено": N, ...}.

    Группировка идёт по НОМЕРУ ЧАСА, а не по счёту свечей подряд: если в
    данных дыра, счёт «по двенадцать штук» слепил бы вместе куски разных
    часов и получил бы свечу, которой не было."""
    по_часам = {}
    for b in bars_m5:
        час = int(b["time"]) // СЕКУНД_В_ЧАСЕ
        по_часам.setdefault(час, []).append(b)

    готовые = []
    неполных = 0
    # ПО ВРЕМЕНИ, А НЕ ПО ПОРЯДКУ ПОЯВЛЕНИЯ В ФАЙЛЕ. Часовой ряд обязан
    # идти хронологически: на нём считается ATR, а он смотрит на предыдущие
    # свечи. Перепутанный порядок дал бы бессмысленный ATR, и это не
    # заметили бы — числа получились бы правдоподобные.
    for час in sorted(по_часам):
        куски = по_часам[час]
        if len(куски) != СВЕЧЕЙ_В_ЧАСЕ:
            неполных += 1
            continue
        куски = sorted(куски, key=lambda x: int(x["time"]))
        готовые.append({
            "time": час * СЕКУНД_В_ЧАСЕ,
            "open": float(куски[0]["open"]),
            "high": max(float(k["high"]) for k in куски),
            "low": min(float(k["low"]) for k in куски),
            "close": float(куски[-1]["close"]),
            "tick_volume": sum(int(k.get("tick_volume", 0) or 0) for k in куски),
            # Максимальный, а не средний: какой спред был в момент входа
            # внутри часа, мы не знаем, и предполагать удачу нельзя.
            "spread": max(int(k.get("spread", 0) or 0) for k in куски),
            "real_volume": sum(int(k.get("real_volume", 0) or 0) for k in куски),
        })

    return {
        "bars": готовые,
        "из_пятиминуток": len(bars_m5),
        "часов_получено": len(готовые),
        "часов_отброшено_неполных": неполных,
        "хеш": хеш_свечей(готовые),
    }


def хеш_свечей(bars) -> str:
    """Отпечаток собранных данных.

    По нему проверяющий убеждается, что считал ровно те же свечи. Формат
    строки зафиксирован: любое изменение сборки меняет хеш."""
    h = hashlib.sha256()
    for b in bars:
        h.update(f"{b['time']}|{b['open']:.8f}|{b['high']:.8f}|"
                 f"{b['low']:.8f}|{b['close']:.8f}|{b['spread']}\n"
                 .encode("utf-8"))
    return h.hexdigest()
