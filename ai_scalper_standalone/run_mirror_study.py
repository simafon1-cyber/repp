ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
КОРЕНЬ = os.path.dirname(ЗДЕСЬ)
sys.path.insert(0, ЗДЕСЬ)

import run_h1_edge_study as база   # noqa: E402
import costs                        # noqa: E402
import entry_lab                    # noqa: E402
import research_manifest            # noqa: E402

ПАСПОРТ = os.path.join(КОРЕНЬ, "preregistration", "strategy_mirror.json")
РЕЗУЛЬТАТ = os.path.join(КОРЕНЬ, "research", "mirror_results.json")
МАРКЕР = os.path.join(КОРЕНЬ, "research", "mirror_oos_открыт.json")

# Те же, что у родительского прогона. Меняем ОДНО — сторону входа.
ГОРИЗОНТ = база.ГОРИЗОНТ
ПОВТОРОВ = база.ПОВТОРОВ
МИНИМУМ_СДЕЛОК = база.МИНИМУМ_СДЕЛОК

# Зерно СВОЁ и записано в паспорте до расчёта. Взять чужое зерно значило
# бы, что числа зависят от прошлой работы, а не только от данных.
ЗЕРНО = 20260903

Стоп = база.Стоп
УжеОткрывали = база.УжеОткрывали


# =====================================================================
def проверка_паспорта() -> dict:
    """Паспорт на месте, печать сходится с содержимым.

    Без сверки печати паспорт можно было бы поправить в блокноте после
    того, как числа увидены, — и «зафиксированный заранее» критерий
    перестал бы что-либо значить."""
    if not os.path.exists(ПАСПОРТ):
        raise Стоп(f"Паспорт З-001 не найден: {ПАСПОРТ}")
    паспорт = json.loads(open(ПАСПОРТ, encoding="utf-8").read())
    печать = паспорт.get("хеш_паспорта")
    если_бы = research_manifest.хеш_поля(паспорт, "хеш_паспорта")
    if not печать:
        raise Стоп("В паспорте З-001 не стоит печать")
    if печать != если_бы:
        raise Стоп(
            "Печать паспорта З-001 НЕ СХОДИТСЯ с его содержимым.\n"
            f"  в файле:  {печать}\n"
            f"  по факту: {если_бы}\n"
            "Паспорт правили после запечатывания. Прогон недействителен.")
    print(f"  1. Паспорт З-001 сверен, печать {печать[:16]}…")
    return паспорт


def _отпечатки(паспорт: dict) -> dict:
    return {
        "хеш_паспорта": паспорт["хеш_паспорта"],
        "архив_h1": база._отпечаток_файла(база.АРХИВ),
        "границы": база._отпечаток_файла(база.ГРАНИЦЫ),
    }


def проверка_одноразовости(паспорт: dict):
    """OOS по ЭТОМУ паспорту открывают один раз.

    Своя отметка, а не родительская: это другая гипотеза, и смешивать их
    отметки — значит однажды решить, что OOS «уже смотрели», когда его по
    этому вопросу не смотрели вовсе, или наоборот."""
    свои = _отпечатки(паспорт)
    if os.path.exists(МАРКЕР):
        try:
            был = json.loads(open(МАРКЕР, encoding="utf-8").read())
        except Exception as e:  # noqa: BLE001
            raise УжеОткрывали(
                f"Отметка есть, но нечитаема ({e}): {МАРКЕР}. "
                f"Пока не доказано обратное — считаем, что OOS открывали.")
        if all(был.get(к) == з for к, з in свои.items()):
            raise УжеОткрывали(
                f"OOS по паспорту З-001 и этим данным УЖЕ открывали.\n"
                f"  когда: {был.get('когда_utc')}\n"
                f"  ревизия: {был.get('ревизия')}\n"
                f"Паспорт разрешает ровно один раз.")
        raise УжеОткрывали(
            f"Отметка есть, но она от ДРУГИХ входных данных: {МАРКЕР}. "
            f"Разбирают руками, а не продолжают прогон.")
    if os.path.exists(РЕЗУЛЬТАТ):
        raise УжеОткрывали(
            f"Результат есть, а отметки нет: {РЕЗУЛЬТАТ}. "
            f"Отметку удалили — это ИНЦИДЕНТ, а не разрешение повторить.")
    print("  5. Отметки об открытии OOS по З-001 нет — первая попытка")


def занять_oos(паспорт: dict) -> dict:
    отметка = dict(_отпечатки(паспорт))
    отметка["ревизия"] = база._ревизия()
    отметка["когда_utc"] = datetime.now(timezone.utc).isoformat()
    os.makedirs(os.path.dirname(МАРКЕР), exist_ok=True)
    ф = os.open(МАРКЕР, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o444)
    with os.fdopen(ф, "w", encoding="utf-8") as f:
        json.dump(отметка, f, ensure_ascii=False, indent=1)
    return отметка


