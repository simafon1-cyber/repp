#!/usr/bin/env python3
"""Прогон по паспорту З-001 «Зеркало».

ВОПРОС, НА КОТОРЫЙ ОТВЕЧАЕТ ЭТОТ ФАЙЛ

Владелец, дословно: «может просто попробовать сделать все в зеркале, то
есть сигнал приходит на покупку пусть ставит на продажу».

Замысел понятный: если вход теряет деньги, значит надо входить наоборот.
Проверить это можно только счётом, потому что арифметика «поменяем знак»
здесь НЕ РАБОТАЕТ. Три причины записаны в паспорте и видны прямо в коде:

  1. Спред и комиссия вычитаются в ОБЕ стороны и знак не меняют.
  2. Своп зависит от стороны: costs.своп(symbol, направление, ...).
  3. Внутри одного бара стоп проверяется РАНЬШЕ цели (entry_lab.сделка).
     Бар, задевший обе цены, засчитывается стопом И исходному входу, И
     зеркалу. На таких барах проигрывают ОБА, и сумма двух зеркальных
     результатов строго меньше нуля.

ЧТО ЗДЕСЬ СДЕЛАНО ИНАЧЕ, ЧЕМ В РОДИТЕЛЬСКОМ ПРОГОНЕ

Ровно одно: направление умножается на −1. Данные, срезы, признаки, стоп,
цель, горизонт, модель издержек и вид интервала — те же. Чтобы сравнение
было честным, обе стороны считаются В ОДНОМ ПРОХОДЕ по одним и тем же
барам: разница между ними тогда не может объясняться разными данными.

ПОЧЕМУ ВСЕ ПРОВЕРКИ ВЗЯТЫ ИЗ РОДИТЕЛЬСКОГО ПРОГОНА

Они уже прошли аудит: сверка отпечатков данных, сверка границ срезов,
чтение OOS последним и ровно один раз. Переписывать их заново — значит
завести вторую, непроверенную копию защиты.

Коды возврата:
    0  прогон закончен, решение записано
    2  проверка не сошлась (данные, паспорт, срезы, издержки)
    3  непредвиденная ошибка
    4  сделок слишком мало — вывода нет
    5  OOS по этому паспорту уже открывали, либо результат уже записан

Запуск:  python3 ai_scalper_standalone/run_mirror_study.py
"""

