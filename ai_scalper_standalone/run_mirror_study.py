def обе_стороны(папка_h1: str, инструмент: str, часть: dict) -> tuple:
    """([сделки как есть], [сделки в зеркале]) по одному срезу.

    ОДИН проход по барам, ОДИН и тот же набор сигналов. Каждый сигнал
    считается дважды: как он есть и с направлением −1. Разница между
    двумя списками не может объясняться разными данными или разным
    отбором — только стороной входа."""
    if not часть["баров"]:
        return [], []
    путь = os.path.join(папка_h1, f"{инструмент}_H1.csv")
    начало = datetime.fromisoformat(часть["начало_utc"]).timestamp()
    конец = datetime.fromisoformat(часть["конец_utc"]).timestamp()
    кусок = база._ряд_среза(путь, начало, конец, int(часть["баров"]))
    ряд = entry_lab.подготовить(кусок)

    как_есть, зеркало = [], []
    предел = ряд["n"] - ГОРИЗОНТ - 1
    for имя, признак in entry_lab.ПРИЗНАКИ.items():
        for i in range(предел):
            направление = признак(ряд, i)
            if not направление:
                continue
            for сторона, копилка in ((направление, как_есть),
                                     (-направление, зеркало)):
                запись = entry_lab.сделка(ряд, i, сторона, symbol=инструмент,
                                          горизонт=ГОРИЗОНТ)
                if запись is None:
                    continue
                # Чистая сделка: риск строго больше нуля. Нулевые не
                # засчитываются нулём — ноль тянул бы среднее к нулю.
                if float(запись.get("риск_денег", 0)) <= 0:
                    continue
                запись["инструмент"] = инструмент
                запись["признак"] = имя
                запись["день"] = datetime.fromtimestamp(
                    ряд["time"][i + 1], timezone.utc).strftime("%Y-%m-%d")
                копилка.append(запись)
    return как_есть, зеркало


def свод(сделки) -> dict:
    return база.бутстрэп(сделки, повторов=ПОВТОРОВ, зерно=ЗЕРНО) if сделки else {}


def _печать_среза(имя: str, как_есть: dict, зеркало: dict):
    for подпись, с in (("как есть", как_есть), ("ЗЕРКАЛО ", зеркало)):
        if not с:
            print(f"  {имя:11} {подпись}: сделок нет")
            continue
        print(f"  {имя:11} {подпись}: сделок {с['сделок']:>6}, дней "
              f"{с['дней']:>4}, среднее R {с['среднее_r']:+.5f}, "
              f"интервал [{с['нижняя_граница']:+.5f}; "
              f"{с['верхняя_граница']:+.5f}]")


# =====================================================================
def main(аргументы=None) -> int:
    р = argparse.ArgumentParser(
        description="Единственный прогон по паспорту З-001 «Зеркало».",
        epilog="Аргументов нет намеренно: путь результата задан в коде.")
    р.parse_args(аргументы)

    база.заголовок("ПРОВЕРКИ ДО РАСЧЁТА (каждая fail-closed)")
    временный = tempfile.mkdtemp(prefix="mirror_")
    try:
        паспорт = проверка_паспорта()
        # Отпечатки данных берём из РОДИТЕЛЬСКОГО паспорта: данные те же
        # самые, и держать их в двух местах — значит однажды разойтись.
        база.проверка_2_хеши_данных(_паспорт_с_хешами())
        папка = база.проверка_3_распаковка(временный)
        границы = база.проверка_4_видимые_срезы(папка)
        _сценарий_издержек()
        проверка_одноразовости(паспорт)
    except УжеОткрывали as e:
        print(f"\nПРОГОН ОСТАНОВЛЕН ДО ЧТЕНИЯ OOS: {e}")
        return 5
    except Стоп as e:
        print(f"\nПРОГОН ОСТАНОВЛЕН: {e}")
        return 2
    except SystemExit as e:
        print(f"\nПРОГОН ОСТАНОВЛЕН: {e}")
        return 2
    except Exception as e:  # noqa: BLE001
        print(f"\nПРОГОН ОСТАНОВЛЕН: {type(e).__name__}: {e}")
        return 3

    база.заголовок("6. TRAIN и VALIDATION (обе стороны на одних барах)")
    диагностика = {}
    for часть in ("train", "validation"):
        все_как_есть, все_зеркало = [], []
        for инструмент, з in границы["инструменты"].items():
            а, б = обе_стороны(папка, инструмент, з["части"][часть])
            все_как_есть += а
            все_зеркало += б
        диагностика[часть] = {"как_есть": свод(все_как_есть),
                              "зеркало": свод(все_зеркало)}
        _печать_среза(часть, диагностика[часть]["как_есть"],
                      диагностика[часть]["зеркало"])

    база.заголовок("7. OOS — ЕДИНСТВЕННЫЙ ФИНАЛЬНЫЙ ШАГ")
    try:
        отметка = занять_oos(паспорт)
    except FileExistsError:
        print(f"\nПРОГОН ОСТАНОВЛЕН ДО ЧТЕНИЯ OOS: отметка {МАРКЕР} уже есть.")
        return 5
    print(f"  Отметка об открытии OOS создана: {МАРКЕР}")
    try:
        база.проверка_7_срезы_oos(папка, границы)
    except Стоп as e:
        print(f"\nПРОГОН ОСТАНОВЛЕН: {e}")
        return 2

    oos_как_есть, oos_зеркало = [], []
    for инструмент, з in границы["инструменты"].items():
        а, б = обе_стороны(папка, инструмент, з["части"]["oos"])
        oos_как_есть += а
        oos_зеркало += б
    итог = {"как_есть": свод(oos_как_есть), "зеркало": свод(oos_зеркало)}
    _печать_среза("oos", итог["как_есть"], итог["зеркало"])

    ответ = {
        "хеш_паспорта": паспорт["хеш_паспорта"],
        "архив_h1": база._отпечаток_файла(база.АРХИВ),
        "границы": база._отпечаток_файла(база.ГРАНИЦЫ),
        "ревизия": отметка["ревизия"],
        "когда_utc": отметка["когда_utc"],
        "сценарий_издержек": costs.текущий_сценарий(),
        "зерно": ЗЕРНО,
        "горизонт_баров": ГОРИЗОНТ,
        "train": диагностика.get("train", {}),
        "validation": диагностика.get("validation", {}),
        "oos": итог,
    }

    зерк_val = диагностика.get("validation", {}).get("зеркало") or {}
    зерк_oos = итог.get("зеркало") or {}

    if зерк_oos.get("сделок", 0) < МИНИМУМ_СДЕЛОК:
        ответ["решение"] = "НЕТ ВЫВОДА"
        ответ["почему"] = (
            f"чистых сделок зеркала на OOS {зерк_oos.get('сделок', 0)}, "
            f"а требуется не менее {МИНИМУМ_СДЕЛОК}. Это НЕ провал "
            f"гипотезы, а отсутствие проверки.")
        _записать(ответ)
        print(f"\n  РЕШЕНИЕ: {ответ['решение']}. {ответ['почему']}")
        return 4

    # КРИТЕРИЙ ИЗ ПАСПОРТА, ЗАФИКСИРОВАННЫЙ ДО РАСЧЁТА:
    # нижняя граница выше нуля ОДНОВРЕМЕННО на validation И на OOS.
    низ_val = float(зерк_val.get("нижняя_граница", 0.0))
    низ_oos = float(зерк_oos.get("нижняя_граница", 0.0))
    подтверждено = низ_val > 0 and низ_oos > 0

    ответ["решение"] = ("ГИПОТЕЗА ПОДТВЕРЖДЕНА" if подтверждено
                        else "ГИПОТЕЗА ОТКЛОНЕНА")
    ответ["почему"] = (
        f"нижняя граница интервала зеркала: validation {низ_val:+.5f}, "
        f"oos {низ_oos:+.5f}. Критерий из паспорта — обе выше нуля."
        + ("" if подтверждено else
           " Хотя бы одна не превышает нуля, значит гипотеза отклонена."))
    ответ["оговорка"] = (
        "Эти срезы уже использовались для родительской гипотезы. Даже "
        "подтверждение здесь НЕ является доказательством прибыльности: "
        "это вторая гипотеза на тех же данных. Записано в паспорте ДО "
        "расчёта.")

    _записать(ответ)
    print(f"\n  РЕШЕНИЕ: {ответ['решение']}")
    print(f"  {ответ['почему']}")
    print(f"  ОГОВОРКА: {ответ['оговорка']}")
    return 0


def _паспорт_с_хешами() -> dict:
    """Отпечатки данных берём из РОДИТЕЛЬСКОГО паспорта.

    Данные те же самые, и держать их отпечатки в двух местах — значит
    однажды разойтись. Читаем один источник."""
    родитель = json.loads(open(база.ПАСПОРТ, encoding="utf-8").read())
    return родитель


def _сценарий_издержек():
    """Базовый сценарий издержек — тот же, что у родительского прогона."""
    costs.выбрать_сценарий(costs.БАЗОВЫЙ)
    if costs.текущий_сценарий() != costs.БАЗОВЫЙ:
        raise Стоп("Не удалось включить базовый сценарий издержек")
    print(f"  4. Сценарий издержек выбран ДО расчёта: "
          f"{costs.текущий_сценарий()}")


def _записать(ответ: dict):
    os.makedirs(os.path.dirname(РЕЗУЛЬТАТ), exist_ok=True)
    ф = os.open(РЕЗУЛЬТАТ, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o444)
    with os.fdopen(ф, "w", encoding="utf-8") as f:
        json.dump(ответ, f, ensure_ascii=False, indent=1)


if __name__ == "__main__":
    sys.exit(main())
