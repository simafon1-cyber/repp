"""pretrade_gate.py — ПРЕДТОРГОВЫЙ БАРЬЕР: НА КАКОМ СЧЁТЕ ВООБЩЕ МОЖНО ТОРГОВАТЬ.

ПОЧЕМУ ЭТОТ ФАЙЛ ПОЯВИЛСЯ

Аудит демо-приёмки нашёл дыру и назвал её блокирующей (P0-1).

Протокол прогона требует работать только на демо-счёте MetaQuotes-Demo.
Но требование это жило В ДОКУМЕНТЕ, а в коде — нет. Единственным
барьером перед отправкой заявки был флаг `LIVE_TRADING`. Поставили
`True` — и заявки уходят на тот счёт, к которому программа подключилась.

А к какому она подключилась, заранее не известно. Если логин в настройках
не заполнен, adapter сам входит в ПЕРВЫЙ готовый счёт из локального
хранилища терминала. Первым может оказаться не тот. В том числе
настоящий.

Ручная инструкция «проверьте счёт перед запуском» барьером не является:
она защищает ровно до первой невнимательности.

ЧТО ЭТОТ БАРЬЕР ДЕЛАЕТ

До любого вызова, способного отправить, изменить или закрыть заявку,
спрашивается одно: разрешение получено или нет. По умолчанию —
НЕ ПОЛУЧЕНО. Это и называется fail-closed: чтобы торговать, нужно
доказать право, а не забыть его отобрать.

Разрешение выдаётся один раз при запуске и только если СРАЗУ ВСЁ:

  1. терминал ответил на вопрос о счёте — не пустотой и не ошибкой;
  2. номер счёта совпал с заранее заданным;
  3. сервер совпал с заранее заданным;
  4. режим счёта — демонстрационный.

Не выполнено что угодно одно — разрешения нет, торговых вызовов нет,
причина названа словами в журнале.

ПОЧЕМУ «НЕ СМОГЛИ СПРОСИТЬ» = «НЕЛЬЗЯ»

Раздел 5 правил проекта: неясный исход — не отказ, а запрет. Здесь то же
самое, только на входе. Если `account_info()` вернул пустоту или бросил
ошибку, мы НЕ ЗНАЕМ, на каком мы счёте. Разрешать торговлю в этом
состоянии — то же самое, что стрелять в темноту.

ЧЕГО ЭТОТ БАРЬЕР НЕ ДЕЛАЕТ

Не заменяет `LIVE_TRADING` и не отменяет ни одной существующей проверки.
Он добавляется ПЕРЕД ними и только запрещает — разрешить что-либо, что
было запрещено раньше, он не может.

Не меняет стратегию, риск, объём, стопы и тейк-профиты. Он вообще не
знает, что это такое.

Не следит за подменой счёта в середине работы. Разрешение выдаётся при
запуске по тому счёту, который тогда ответил. Это ограничение записано в
отчёте честно, а не замолчано.
"""

from __future__ import annotations

import logging

log = logging.getLogger("pretrade_gate")

# Режимы счёта в MetaTrader 5. Числа определены платформой.
СЧЁТ_ДЕМО = 0
СЧЁТ_КОНКУРС = 1
СЧЁТ_РЕАЛЬНЫЙ = 2

ИМЯ_РЕЖИМА = {СЧЁТ_ДЕМО: "демо", СЧЁТ_КОНКУРС: "конкурсный",
              СЧЁТ_РЕАЛЬНЫЙ: "РЕАЛЬНЫЙ"}


class БарьерЗакрыт(RuntimeError):
    """Попытка торгового вызова без выданного разрешения."""


# Состояние процесса. None — разрешения нет. Это НАЧАЛЬНОЕ значение, и
# именно поэтому барьер fail-closed: чтобы торговать, надо что-то сделать;
# чтобы не торговать, достаточно ничего не делать.
_разрешение = None

# ПОЧЕМУ БАРЬЕР ЗАКРЫТ — ПОСЛЕДНЕЙ ПОПЫТКОЙ, СЛОВАМИ.
#
# Причина писалась только в лог при запуске. На «Обзоре» из-за этого стояло
# «точная причина в логе при запуске», и владельцу приходилось искать файл
# журнала, чтобы узнать, что именно не совпало — номер счёта, имя сервера
# или признак «демо». Это ровно та же беда, что была с самими настройками
# барьера: программа знает ответ и не говорит его.
_причина_отказа = ""



# =====================================================================
# ЧТЕНИЕ НАСТРОЕК
# =====================================================================
def включён(cfg) -> bool:
    """Действует ли режим демо-приёмки.

    Выключенный режим означает обычную работу программы: барьер не
    вмешивается и ничего не запрещает сверх того, что было раньше."""
    return bool(getattr(cfg, "DEMO_ACCEPTANCE_MODE", False))


def ожидаемый_счёт(cfg) -> tuple:
    """(номер, сервер, нужен_ли_демо) из настроек. Номер 0 — не задан."""
    try:
        номер = int(getattr(cfg, "DEMO_ACCEPTANCE_LOGIN", 0) or 0)
    except (TypeError, ValueError):
        номер = -1          # заполнено мусором — считаем «не задан»
    сервер = str(getattr(cfg, "DEMO_ACCEPTANCE_SERVER", "") or "").strip()
    только_демо = bool(getattr(cfg, "DEMO_ACCEPTANCE_REQUIRE_DEMO", True))
    return номер, сервер, только_демо


def _поле(счёт, имя):
    """Достать поле из ответа терминала. Ответ бывает объектом и словарём."""
    if счёт is None:
        return None
    if isinstance(счёт, dict):
        return счёт.get(имя)
    return getattr(счёт, имя, None)


# =====================================================================
# САМА ПРОВЕРКА
# =====================================================================
def проверить(cfg, счёт) -> tuple:
    """(можно_ли, причина). Ничего не меняет — только смотрит.

    `счёт` — то, что вернул account_info(). None означает «не спросилось»,
    и это ЗАПРЕТ, а не «наверное всё в порядке»."""
    if not включён(cfg):
        return True, "режим демо-приёмки выключен — барьер не вмешивается"

    номер, сервер, только_демо = ожидаемый_счёт(cfg)

    if номер <= 0:
        return False, (
            "режим демо-приёмки включён, но ожидаемый счёт не задан "
            "(DEMO_ACCEPTANCE_LOGIN). Пока не задан — торговать нельзя: "
            "иначе барьер сравнивал бы счёт неизвестно с чем.")
    if not сервер:
        return False, (
            "режим демо-приёмки включён, но ожидаемый сервер не задан "
            "(DEMO_ACCEPTANCE_SERVER).")

    if счёт is None:
        return False, (
            "терминал не ответил на вопрос о счёте. Мы НЕ ЗНАЕМ, к какому "
            "счёту подключены. Торговать вслепую нельзя.")

    факт_номер = _поле(счёт, "login")
    факт_сервер = _поле(счёт, "server")
    факт_режим = _поле(счёт, "trade_mode")

    if факт_номер is None:
        return False, "в ответе терминала нет номера счёта (login) — неясно, где мы"
    try:
        факт_номер = int(факт_номер)
    except (TypeError, ValueError):
        return False, f"номер счёта нечитаем: {факт_номер!r}"

    if факт_номер != номер:
        return False, (
            f"счёт НЕ ТОТ: подключены к {факт_номер}, а разрешён только "
            f"{номер}. Заявки могли бы уйти на чужой счёт.")

    if факт_сервер is None:
        return False, "в ответе терминала нет имени сервера — неясно, где мы"
    if str(факт_сервер).strip() != сервер:
        return False, (
            f"сервер НЕ ТОТ: подключены к «{факт_сервер}», а разрешён "
            f"только «{сервер}». Номер счёта может совпасть у разных "
            f"брокеров — само по себе совпадение номера ничего не значит.")

    if только_демо:
        if факт_режим is None:
            return False, ("терминал не сказал режим счёта (trade_mode). "
                           "Демонстрационный он или реальный — неизвестно.")
        try:
            факт_режим = int(факт_режим)
        except (TypeError, ValueError):
            return False, f"режим счёта нечитаем: {факт_режим!r}"
        if факт_режим != СЧЁТ_ДЕМО:
            имя = ИМЯ_РЕЖИМА.get(факт_режим, f"неизвестный ({факт_режим})")
            return False, (
                f"режим счёта — {имя}, а разрешён только демонстрационный. "
                f"Демо-приёмка на реальных деньгах не проводится.")

    return True, (f"счёт {факт_номер} ({факт_сервер}), режим демонстрационный "
                  f"— совпало с заданным")


# =====================================================================
# ВЫДАЧА И ОТЗЫВ РАЗРЕШЕНИЯ
# =====================================================================
def открыть(cfg, спросить_счёт) -> tuple:
    """Спросить счёт и выдать разрешение, если всё сошлось.

    `спросить_счёт` — то, чем спрашивают (обычно mt5_connector.get_account_info).
    Передаётся снаружи нарочно: барьер не должен сам решать, откуда брать
    ответ, иначе его нельзя проверить тестом.

    Возвращает (можно_ли, причина). Ничего не бросает: решение принимает
    тот, кто вызвал."""
    global _разрешение

    try:
        счёт = спросить_счёт()
    except Exception as e:  # noqa: BLE001
        _разрешение = None
        причина = (f"спросить счёт не удалось: {type(e).__name__}: {e}. "
                   f"Разрешения нет.")
        globals()["_причина_отказа"] = причина
        log.error("ПРЕДТОРГОВЫЙ БАРЬЕР ЗАКРЫТ. %s", причина)
        return False, причина

    можно, причина = проверить(cfg, счёт)
    if not можно:
        _разрешение = None
        globals()["_причина_отказа"] = причина
        log.error("ПРЕДТОРГОВЫЙ БАРЬЕР ЗАКРЫТ. %s", причина)
        return False, причина

    globals()["_причина_отказа"] = ""
    _разрешение = {
        "номер": _поле(счёт, "login"),
        "сервер": _поле(счёт, "server"),
        "режим": _поле(счёт, "trade_mode"),
        "причина": причина,
    }
    log.info("Предторговый барьер открыт: %s", причина)
    return True, причина


def причина_отказа() -> str:
    """Чем именно закрыт барьер по последней попытке. Пусто — отказа не было.

    Нужна окну: человек должен видеть причину там же, где видит запрет, а
    не искать её в файле журнала."""
    return _причина_отказа


def закрыть() -> None:
    """Отозвать разрешение. После этого торговые вызовы снова запрещены."""
    global _разрешение
    _разрешение = None


def открыт() -> bool:
    return _разрешение is not None


def разрешение() -> dict:
    """Чем именно открыт барьер. Пустой словарь — закрыт."""
    return dict(_разрешение) if _разрешение else {}


def требовать(что: str = "торговый вызов") -> None:
    """Пропустить дальше или остановить. Зовётся ПЕРЕД отправкой.

    Бросает, а не возвращает False, нарочно: возвращённое значение можно
    не проверить, брошенную ошибку — нельзя.

    ПОЧЕМУ ЗДЕСЬ ПЕРЕЧИТЫВАЮТСЯ НАСТРОЙКИ

    Барьер не имеет права менять поведение программы у тех, кто демо-
    приёмку не проводит. Раздел 4 правил проекта: торговую логику не
    трогать без отдельного согласования. Поэтому при выключенном режиме
    вызов проходит ровно так же, как проходил раньше.

    А вот если настройки прочитать НЕ УДАЛОСЬ — запрет. Мы в этом случае
    не знаем даже, включён режим или нет, и «наверное выключен» — не тот
    вывод, который можно делать перед отправкой заявки."""
    if _разрешение is not None:
        return

    try:
        import config as cfg
    except Exception as e:  # noqa: BLE001
        raise БарьерЗакрыт(
            f"{что} запрещён: настройки прочитать не удалось "
            f"({type(e).__name__}: {e}).\n"
            "Неизвестно даже, идёт ли демо-приёмка. Отправлять заявку "
            "в таком состоянии нельзя.") from e

    if not включён(cfg):
        return          # режим выключен — ведём себя как до появления барьера

    raise БарьерЗакрыт(
        f"{что} запрещён: предторговый барьер закрыт.\n"
        "Идёт режим демо-приёмки, а разрешение на торговлю не выдавалось — "
        "значит не доказано, что мы на том самом демо-счёте. Пока не "
        "доказано, ни одна заявка отсюда уйти не может.")
