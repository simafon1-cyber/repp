"""run_components.py — РАЗБОР ВХОДА ПО ЧАСТЯМ. Что помогает, что мешает.

=====================================================================
ГЛАВНОЕ ПРАВИЛО ЭТОГО ЗАМЕРА
=====================================================================
Качество ВХОДА измеряется при ОДНОМ И ТОМ ЖЕ выходе для всех вариантов.

Иначе сравнение бессмысленно: убрали фильтр — изменились входы — изменилось
и то, как трейлинг их вёл, и непонятно, что именно поменяло результат. Здесь
выход зафиксирован (эталонный: стоп 2 ATR, цель 1R, худший порядок внутри
бара), и разница между вариантами — это разница ВХОДОВ, и только их.

Вторая мера — MFE без цензуры: сколько хода в нашу сторону даёт рынок после
входа, независимо от того, когда мы вышли. Она вообще не зависит от правил
выхода, и потому честнее всех.

=====================================================================
ЧЕГО ЭТОТ ЗАМЕР НЕ ДЕЛАЕТ
=====================================================================
Не рекомендует ничего выключать. «Без этого фильтра лучше» на истории и
«этот фильтр вреден» — разные утверждения; второе требует подтверждения на
куске, которого при замере не было. Поэтому всё показано отдельно по
TRAIN / VALIDATION / OOS, и вывод делается только при совпадении.

Новых индикаторов здесь не добавляется ни одного. Владелец: «если выходы не
спасают систему, НЕ добавляй новые индикаторы».
"""

