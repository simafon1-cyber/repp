КОРЗИНЫ_SCORE = ((0, 60), (60, 65), (65, 70), (70, 75), (75, 80), (80, 101))


def заголовок(текст, знак="="):
    print()
    print(знак * 78)
    print(текст)
    print(знак * 78)


def строка_R(имя, св, добавка=""):
    print(f"  {имя:<34} входов {св['сделок']:>5}  PF {св['профит_фактор']:>6}  "
          f"ожидание {св['ожидание']:>8}R  винрейт {св['винрейт']:>5}%  "
          f"ср.выигрыш {св['средний_выигрыш']:>6}R  ср.проигрыш "
          f"{св['средний_проигрыш']:>6}R  просадка {св['просадка']:>7}R  "
          f"восст. {св['восстановление']:>6}{добавка}")


_ЗАДАЧА = {"symbol": "", "bars": [], "meta": {}}


def _прогон(вариант):
    """Один вариант: собрать пути при выключенном (или включённом) компоненте."""
    имя, значение = вариант
    try:
        правка = optimize.Правка(настройки={имя: значение}) if имя else optimize.Правка()
        with правка:
            пути = exit_lab.collect(_ЗАДАЧА["symbol"], _ЗАДАЧА["bars"],
                                    _ЗАДАЧА["meta"])
        return {"имя": имя or "БАЗА", "пути": пути, "error": ""}
    except Exception as e:  # noqa: BLE001
        return {"имя": имя or "БАЗА", "пути": [], "error": f"{type(e).__name__}: {e}"}


def прогнать(варианты, workers):
    if workers <= 1:
        return [_прогон(в) for в in варианты]
    import multiprocessing as mp
    with mp.get_context("fork").Pool(processes=workers) as pool:
        return pool.map(_прогон, варианты)


def оценить(пути, границы_времени):
    """Эталонный выход, отдельно по кускам времени."""
    t1, t2 = границы_времени
    куски = {
        "ВСЁ": пути,
        "TRAIN": [п for п in пути if п["entry_time"] < t1],
        "VALIDATION": [п for п in пути if t1 <= п["entry_time"] < t2],
        "OOS": [п for п in пути if п["entry_time"] >= t2],
    }
    итог = {}
    for имя, кусок in куски.items():
        прогон = exit_lab.simulate(кусок, ЭТАЛОН_SL, ЭТАЛОН_TP, "worst")
        итог[имя] = exit_lab.stats_r(прогон["r"])
    замеры = exit_lab.excursions(пути)
    итог["MFE"] = exit_lab.distribution([з["mfe_r"] for з in замеры])
    return итог


def вердикт(база, вариант) -> str:
    """HELPFUL / NEUTRAL / HARMFUL — и только при совпадении кусков.

    Вариант — это система БЕЗ компонента. Значит если без него ЛУЧШЕ, то
    компонент ВРЕДЕН. Знаки здесь легко перепутать, поэтому проговорено."""
    if вариант["ВСЁ"]["сделок"] < 100:
        return "UNKNOWN (мало входов)"
    куски = ["TRAIN", "VALIDATION", "OOS"]
    годные = [к for к in куски if вариант[к]["сделок"] >= 30
              and база[к]["сделок"] >= 30]
    if len(годные) < 2:
        return "UNKNOWN (мало входов в кусках)"
    лучше = sum(1 for к in годные
                if вариант[к]["ожидание"] > база[к]["ожидание"])
    хуже = sum(1 for к in годные
               if вариант[к]["ожидание"] < база[к]["ожидание"])
    if лучше == len(годные):
        return "HARMFUL (без него лучше во всех кусках)"
    if хуже == len(годные):
        return "HELPFUL (без него хуже во всех кусках)"
    return "NEUTRAL (в разных кусках по-разному)"


def по_инструменту(symbol, max_bars, workers):
    заголовок(f"РАЗБОР ВХОДА ПО ЧАСТЯМ: {symbol}")

    данные = history_data.load(symbol)
    if not данные["clean"] or not данные["quality"]["usable"]:
        print("СТАТУС: INSUFFICIENT DATA")
        return {"symbol": symbol, "статус": "INSUFFICIENT DATA"}

    bars = данные["clean"]
    if max_bars and len(bars) > max_bars:
        bars = bars[-int(max_bars):]
    _ЗАДАЧА["symbol"], _ЗАДАЧА["bars"], _ЗАДАЧА["meta"] = symbol, bars, данные["meta"]
    границы = optimize.segments(bars)
    границы_времени = (int(bars[границы["VALIDATION"][0]]["time"]),
                       int(bars[границы["OOS"][0]]["time"]))

    print(f"Свечей: {len(bars)}. Эталонный выход для ВСЕХ вариантов: "
          f"стоп {ЭТАЛОН_SL} ATR, цель {ЭТАЛОН_TP}R, худший порядок в баре.")
    print("Разница между строками — это разница ВХОДОВ, и только их.")

    варианты = [(None, None)] + [(имя, False if имя != "USE_VOLUME_FILTER" else True)
                                 for имя, _, _ in КОМПОНЕНТЫ]
    прогоны = прогнать(варианты, workers)

    база_путей = прогоны[0]["пути"]
    if not база_путей:
        print(f"СТАТУС: базовый прогон не дал входов. {прогоны[0]['error']}")
        return {"symbol": symbol, "статус": "НЕТ ВХОДОВ"}
    база = оценить(база_путей, границы_времени)

    # ------------------------------------------------ есть ли сила у score
    заголовок(f"ЕСТЬ ЛИ ПРЕДСКАЗАТЕЛЬНАЯ СИЛА У БАЛЛА ВХОДА. {symbol}", "-")
    print("  Если балл что-то значит, у высоких баллов ход цены должен быть")
    print("  больше, а результат лучше. Если нет — балл не различает сделки,")
    print("  и поднимать порог входа бессмысленно.")
    for низ, верх in КОРЗИНЫ_SCORE:
        в_корзине = [п for п in база_путей if низ <= float(п["score"]) < верх]
        if not в_корзине:
            continue
        з = exit_lab.excursions(в_корзине)
        d = exit_lab.distribution([x["mfe_r"] for x in з])
        прогон = exit_lab.simulate(в_корзине, ЭТАЛОН_SL, ЭТАЛОН_TP, "worst")
        св = exit_lab.stats_r(прогон["r"])
        мало = "" if d["n"] >= 100 else "  [UNKNOWN: мало входов]"
        print(f"  балл {низ}-{верх if верх <= 100 else 100:<4} входов {d['n']:>5}  "
              f"медиана MFE {d['медиана']:>6}R  P90 {d['P90']:>6}R  ->  "
              f"ожидание {св['ожидание']:>8}R  PF {св['профит_фактор']:>6}{мало}")

    # ------------------------------------------------------- база по кускам
    заголовок(f"БАЗА ПРИ ЭТАЛОННОМ ВЫХОДЕ. {symbol}", "-")
    for кусок in ("ВСЁ", "TRAIN", "VALIDATION", "OOS"):
        строка_R(f"БАЗА / {кусок}", база[кусок])
    print(f"  MFE базы: медиана {база['MFE']['медиана']}R, "
          f"P75 {база['MFE']['P75']}R, P90 {база['MFE']['P90']}R")

    # ------------------------------------------------------- компоненты
    заголовок(f"КАЖДЫЙ КОМПОНЕНТ ОТДЕЛЬНО. {symbol}", "-")
    print("  Строка = система БЕЗ этого компонента (кроме фильтра объёма —")
    print("  он сейчас выключен, и там строка = система С НИМ).")
    итоги = []
    for прогон, (имя, подпись, почему) in zip(прогоны[1:], КОМПОНЕНТЫ):
        if прогон["error"] or not прогон["пути"]:
            print(f"\n  {подпись}: нет входов. {прогон['error']}")
            итоги.append({"имя": имя, "подпись": подпись,
                          "вердикт": "UNKNOWN (нет входов)"})
            continue
        оценка = оценить(прогон["пути"], границы_времени)
        в = вердикт(база, оценка)
        print(f"\n  {подпись}  [{имя}]")
        if почему:
            print(f"    {почему}")
        print(f"    ВЕРДИКТ: {в}")
        строка_R("    без него / ВСЁ", оценка["ВСЁ"])
        for кусок in ("TRAIN", "VALIDATION", "OOS"):
            разница = (оценка[кусок]["ожидание"] - база[кусок]["ожидание"])
            строка_R(f"    без него / {кусок}", оценка[кусок],
                     f"   разница {разница:+.4f}R")
        print(f"    MFE без него: медиана {оценка['MFE']['медиана']}R "
              f"(у базы {база['MFE']['медиана']}R)")
        итоги.append({"имя": имя, "подпись": подпись, "вердикт": в,
                      "оценка": оценка})

    return {"symbol": symbol, "статус": "OK", "база": база, "компоненты": итоги}


def main(argv) -> int:
    max_bars = 0
    workers = min(4, os.cpu_count() or 1)
    символы = []
    i = 0
    while i < len(argv):
        а = argv[i]
        if а in ("--bars", "--workers"):
            try:
                знач = int(argv[i + 1])
            except (IndexError, ValueError):
                print(f"После {а} нужно число.")
                return 2
            if а == "--bars":
                max_bars = знач
            else:
                workers = max(1, знач)
            i += 2
            continue
        if not а.startswith("--"):
            символы.append(а)
        i += 1
    символы = символы or СИМВОЛЫ

    заголовок("РАЗБОР ВХОДА: ЧТО ПОМОГАЕТ, ЧТО МЕШАЕТ, ЧТО БЕЗРАЗЛИЧНО")
    print("Ни один индикатор не добавляется. Проверяются только те")
    print("переключатели, которые в программе уже есть.")
    print(f"Настройки: {run_baseline.ОТКУДА_НАСТРОЙКИ}")
    print(f"Ядер: {workers}")

    результаты = [по_инструменту(s, max_bars, workers) for s in символы]

    заголовок("СВОДКА ПО КОМПОНЕНТАМ")
    for r in результаты:
        if r.get("статус") != "OK":
            print(f"{r['symbol']}: {r['статус']}")
            continue
        print(f"\n{r['symbol']}:")
        for к in r["компоненты"]:
            print(f"  {к['вердикт']:<42} {к['подпись']}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
