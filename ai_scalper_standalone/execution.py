"""execution.py — ЧЕМ НА САМОМ ДЕЛЕ ЗАКОНЧИЛАСЬ ЗАЯВКА.

ЗАЧЕМ ЭТОТ МОДУЛЬ ВООБЩЕ ПОЯВИЛСЯ

Программа спрашивала у ответа брокера ровно одно: «retcode равен DONE?».
Да — успех, нет — отказ. Такой вопрос предполагает, что ответов бывает
два. Их четыре.

    ПОЛНОЕ      просили 0.10, дали 0.10;
    ЧАСТИЧНОЕ   просили 0.10, дали 0.06, остаток отменён;
    ОТКАЗ       не дали ничего, и это точно известно;
    НЕИЗВЕСТНО  ответа нет. Позиция может быть, а может не быть.

Двух средних состояний код не различал, и оба он записывал в «отказ».

Чем это плохо на деньгах:

  * ЧАСТИЧНОЕ, записанное как отказ. Позиция открыта, программа считает,
    что нет. Она не попадёт в учёт риска, для хеджа не будет закрыта
    встречной ногой, а компенсировать будет нечего — по мнению программы
    компенсировать нечего.

  * НЕИЗВЕСТНО, записанное как отказ. Программа отправляет заявку
    повторно. Если первая всё-таки дошла — на счету две позиции вместо
    одной, то есть двойной риск, о котором никто не просил.

Разница между «отказ» и «неизвестно» — не философская. «Отказ» разрешает
идти дальше. «Неизвестно» не разрешает НИЧЕГО, пока не сверились с
терминалом (см. trade_manager.сверить_вход).

ПОЧЕМУ У ИТОГА НЕТ ПРАВДЫ И ЛЖИ

`if итог:` здесь намеренно ЗАПРЕЩЁН и бросает ошибку. У четырёх состояний
нет верного перевода в «да/нет»: любой выбор для НЕИЗВЕСТНО оказывается
враньём в одну из двух сторон. Пусть лучше код упадёт на разработке, чем
молча решит за нас на реальном счёте.
"""

ПОЛНОЕ = "полное"
ЧАСТИЧНОЕ = "частичное"
ОТКАЗ = "отказ"
НЕИЗВЕСТНО = "неизвестно"

# Открылось, но номер позиции брокер не прислал. Это не отказ: сделка есть.
ТИКЕТ_НЕИЗВЕСТЕН = -1

# Объёмы у брокера дробные (0.01 лота), сравнивать их «==» нельзя.
ДОПУСК_ОБЪЁМА = 1e-9

# Коды ответа торгового сервера MT5. Значения заданы платформой и не
# меняются; здесь они записаны числами, чтобы модуль можно было проверять
# без установленного терминала. Совпадение с mt5_connector проверяется
# тестом test_partial_fill.test_retcode_numbers_match_the_terminal.
КОД_DONE = 10009
КОД_DONE_PARTIAL = 10010
КОД_PLACED = 10008
КОД_TIMEOUT = 10012
КОД_CONNECTION = 10031

# Ответы, после которых положение дел неизвестно и нужна сверка.
НЕОПРЕДЕЛЁННЫЕ = (КОД_PLACED, КОД_TIMEOUT, КОД_CONNECTION)


class Итог:
    """Что произошло с одной заявкой. Не «да/нет», а состояние."""

    __slots__ = ("статус", "тикет", "заказано", "исполнено", "код", "пояснение")

    def __init__(self, статус, тикет=0, заказано=0.0, исполнено=0.0,
                 код=None, пояснение=""):
        self.статус = статус
        self.тикет = int(тикет or 0)
        self.заказано = float(заказано or 0.0)
        self.исполнено = float(исполнено or 0.0)
        self.код = код
        self.пояснение = пояснение

    # --- вопросы, на которые отвечать МОЖНО --------------------------
    @property
    def открылось(self) -> bool:
        """Позиция на счету точно есть (целиком или частью)."""
        return self.статус in (ПОЛНОЕ, ЧАСТИЧНОЕ)

    @property
    def решено(self) -> bool:
        """Положение дел известно — неважно, хорошее или плохое."""
        return self.статус != НЕИЗВЕСТНО

    @property
    def недобор(self) -> float:
        """Сколько объёма не досталось."""
        return max(0.0, self.заказано - self.исполнено)

    # --- вопрос, на который отвечать НЕЛЬЗЯ --------------------------
    def __bool__(self):
        raise TypeError(
            "У итога заявки четыре состояния, а не два. "
            "Проверяйте .открылось / .решено / .статус, а не сам итог. "
            f"Здесь было: {self!r}")

    def __repr__(self):
        return (f"Итог({self.статус}, тикет={self.тикет}, "
                f"{self.исполнено:.2f}/{self.заказано:.2f}, код={self.код})")


# =====================================================================
def _число(значение) -> float:
    """Объём из ответа брокера. Нечитаемое значение — это ноль, а не сбой."""
    try:
        return float(значение or 0.0)
    except (TypeError, ValueError):
        return 0.0


def разобрать(result, заказано: float) -> Итог:
    """Ответ брокера → одно из четырёх состояний.

    result — то, что вернул mt5.order_send(). None значит, что ответа не
    было вовсе, а не что заявка отклонена: заявка могла уйти на сервер и
    исполниться."""
    if result is None:
        return Итог(НЕИЗВЕСТНО, заказано=заказано,
                    пояснение="терминал не ответил на заявку")

    коммент = str(getattr(result, "comment", "") or "")
    try:
        код = int(getattr(result, "retcode", 0) or 0)
    except (TypeError, ValueError):
        # Ответ есть, но код в нём не читается. Это не отказ и не успех:
        # что произошло на счету — неизвестно. Падать здесь нельзя, это
        # торговый цикл, а врать в любую сторону — тем более.
        return Итог(НЕИЗВЕСТНО, заказано=заказано,
                    пояснение=f"код ответа не читается: "
                              f"{getattr(result, 'retcode', None)!r}")
    исполнено = _число(getattr(result, "volume", 0.0))
    try:
        тикет = int(getattr(result, "order", 0) or 0) or ТИКЕТ_НЕИЗВЕСТЕН
    except (TypeError, ValueError):
        тикет = ТИКЕТ_НЕИЗВЕСТЕН

    if код == КОД_DONE:
        # Брокер сказал «исполнено». Объём всё равно сверяем: встречается
        # DONE с урезанным объёмом, и верить на слово тут нечему.
        if 0 < исполнено < заказано - ДОПУСК_ОБЪЁМА:
            return Итог(ЧАСТИЧНОЕ, тикет, заказано, исполнено, код,
                        "код DONE, но объём меньше заказанного")
        # Нулевой объём в ответе — не повод считать сделку меньше: многие
        # сборки поля volume не заполняют. Берём заказанный.
        return Итог(ПОЛНОЕ, тикет, заказано, исполнено or заказано, код)

    if код == КОД_DONE_PARTIAL:
        if исполнено <= 0:
            # «Исполнено частично» без указания, сколько именно. Сколько
            # на счету — неизвестно, а гадать здесь нечем.
            return Итог(НЕИЗВЕСТНО, тикет, заказано, 0.0, код,
                        "частичное исполнение, но объём не сообщён")
        if исполнено >= заказано - ДОПУСК_ОБЪЁМА:
            return Итог(ПОЛНОЕ, тикет, заказано, исполнено, код)
        return Итог(ЧАСТИЧНОЕ, тикет, заказано, исполнено, код)

    if код in НЕОПРЕДЕЛЁННЫЕ:
        return Итог(НЕИЗВЕСТНО, тикет, заказано, исполнено, код,
                    f"ответ {код} {коммент}".strip())

    return Итог(ОТКАЗ, 0, заказано, 0.0, код, коммент)


def отказ(пояснение: str, заказано: float = 0.0) -> Итог:
    """Отказ, о котором мы знаем точно (не от брокера, а от себя):
    слишком близкий стоп, нет цены, выключенная торговля."""
    return Итог(ОТКАЗ, 0, заказано, 0.0, None, пояснение)


def неизвестно(пояснение: str, заказано: float = 0.0) -> Итог:
    return Итог(НЕИЗВЕСТНО, 0, заказано, 0.0, None, пояснение)


def полное(тикет=ТИКЕТ_НЕИЗВЕСТЕН, объём: float = 0.0, пояснение="") -> Итог:
    return Итог(ПОЛНОЕ, тикет, объём, объём, None, пояснение)
