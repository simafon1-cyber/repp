def проверить_признак(имя, признак, ряды, отрезок_имя, порог):
    """Один признак на всех инструментах, на одном отрезке времени."""
    строки = []
    за_признак = 0          # на скольких инструментах он лучше зеркала
    всего_годных = 0

    for symbol, (ряд, гр) in ряды.items():
        начало, конец = гр[отрезок_имя]
        итог = entry_lab.прогнать(ряд, признак, начало, конец, seed=17)
        свои = entry_lab.сводка(итог["признак"])
        зерк = entry_lab.сводка(итог["зеркало"])
        случ = entry_lab.сводка(итог["случай"])

        если_мало = свои["сделок"] < entry_lab.МИНИМУМ_СДЕЛОК
        p_зерк = (1.0 if если_мало
                  else entry_lab.перестановка(итог["признак"], итог["зеркало"]))
        p_случ = (1.0 if если_мало
                  else entry_lab.перестановка(итог["признак"], итог["случай"]))

        лучше = (not если_мало
                 and свои["ожидание"] > зерк["ожидание"]
                 and p_зерк <= порог)
        if not если_мало:
            всего_годных += 1
            за_признак += 1 if лучше else 0

        строки.append((symbol, свои, зерк, случ, p_зерк, p_случ, если_мало, лучше))

    return строки, за_признак, всего_годных


def печать_признака(имя, строки, за, годных, порог):
    print(f"\n  {имя}")
    print(f"  {'инструмент':<10}{'сделок':>8}{'ожид.R':>9}{'зеркало':>9}"
          f"{'случай':>9}{'PF':>7}{'p зерк':>9}{'p случ':>9}   вердикт")
    for symbol, свои, зерк, случ, p1, p2, мало, лучше in строки:
        if мало:
            print(f"  {symbol:<10}{свои['сделок']:>8}"
                  f"{'  мало сделок — вывода нет':>44}")
            continue
        знак = "ЛУЧШЕ ЗЕРКАЛА" if лучше else "не отличим"
        print(f"  {symbol:<10}{свои['сделок']:>8}{свои['ожидание']:>9.4f}"
              f"{зерк['ожидание']:>9.4f}{случ['ожидание']:>9.4f}"
              f"{свои['профит_фактор']:>7.2f}{p1:>9.4f}{p2:>9.4f}   {знак}")
    if годных:
        print(f"  ИТОГ: лучше зеркала на {за} инструментах из {годных} "
              f"(порог значимости {порог:.4f})")
    else:
        print("  ИТОГ: годных инструментов нет")


def main():
    аргументы = sys.argv[1:]
    max_bars = 0
    символы = []
    i = 0
    while i < len(аргументы):
        а = аргументы[i]
        if а == "--bars" and i + 1 < len(аргументы):
            max_bars = int(аргументы[i + 1])
            i += 2
            continue
        if not а.startswith("-"):
            символы.append(а)
        i += 1
    символы = символы or list(СИМВОЛЫ)

    заголовок("ПОИСК ПРЕИМУЩЕСТВА ВО ВХОДЕ")
    порог = entry_lab.порог_с_поправкой(len(entry_lab.ПРИЗНАКИ))
    print(f"Признаков проверяется: {len(entry_lab.ПРИЗНАКИ)}")
    print(f"Порог значимости с поправкой на это число: {порог:.4f}")
    print(f"Эталонный выход у всех один: стоп {entry_lab.СТОП_ATR} ATR, "
          f"цель {entry_lab.ЦЕЛЬ_R}R, горизонт {entry_lab.ГОРИЗОНТ} свечей")
    print()

    ряды = {}
    for s in символы:
        bars = загрузить(s, max_bars)
        if bars is None:
            continue
        ряд = entry_lab.подготовить(bars)
        ряды[s] = (ряд, отрезки(ряд["n"]))
        print(f"  {s}: {ряд['n']} свечей готовы")

    if not ряды:
        print("Данных нет — проверять нечего.")
        return

    сводный = {}
    for отрезок_имя in ("TRAIN", "VALIDATION", "OOS"):
        заголовок(f"ОТРЕЗОК {отрезок_имя}", "-")
        for имя, признак in entry_lab.ПРИЗНАКИ.items():
            строки, за, годных = проверить_признак(
                имя, признак, ряды, отрезок_имя, порог)
            печать_признака(имя, строки, за, годных, порог)
            сводный.setdefault(имя, {})[отрезок_имя] = (за, годных)

    # =================================================================
    заголовок("СВОДКА: НА СКОЛЬКИХ ИНСТРУМЕНТАХ ПРИЗНАК ЛУЧШЕ ЗЕРКАЛА")
    print(f"  {'признак':<24}{'TRAIN':>12}{'VALIDATION':>14}{'OOS':>10}")
    выжившие = []
    for имя in entry_lab.ПРИЗНАКИ:
        клетки = []
        for о in ("TRAIN", "VALIDATION", "OOS"):
            за, годных = сводный.get(имя, {}).get(о, (0, 0))
            клетки.append(f"{за}/{годных}")
        print(f"  {имя:<24}{клетки[0]:>12}{клетки[1]:>14}{клетки[2]:>10}")
        # Кандидат — тот, кто прошёл больше чем на половине инструментов
        # НА ВСЕХ ТРЁХ отрезках. Это намеренно строго.
        годен = True
        for о in ("TRAIN", "VALIDATION", "OOS"):
            за, годных = сводный.get(имя, {}).get(о, (0, 0))
            if не_большинство(за, годных):
                годен = False
        if годен:
            выжившие.append(имя)

    заголовок("ВЕРДИКТ")
    if выжившие:
        print("КАНДИДАТЫ, прошедшие на большинстве инструментов и на всех")
        print("трёх отрезках времени:")
        for имя in выжившие:
            print(f"    * {имя}")
        print()
        print("Это НЕ означает «можно включать». Это означает «стоит")
        print("проверить дальше»: на реальных издержках, с walk-forward и")
        print("Monte Carlo, и только потом — на демо.")
    else:
        print("НИ ОДИН из проверенных признаков не прошёл.")
        print()
        print("Что это значит: шесть простых и общеизвестных идей входа не")
        print("отличаются от собственного зеркала на этих данных. Это НЕ")
        print("доказывает, что преимущества не существует в природе, — это")
        print("значит, что дешёвыми способами оно здесь не находится.")
        print()
        print("Чего делать НЕ надо после такого результата:")
        print("  * подбирать пороги признаков, пока что-нибудь не сработает")
        print("    — это подгонка, и она не переживает следующий месяц;")
        print("  * добавлять признаки в список задним числом;")
        print("  * увеличивать лот, чтобы «отыграться».")


def не_большинство(за: int, годных: int) -> bool:
    """Прошёл ли признак больше чем на половине годных инструментов."""
    return годных == 0 or за * 2 <= годных


if __name__ == "__main__":
    main()
