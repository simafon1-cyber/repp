"""run_entry_search.py — ЕСТЬ ЛИ ХОТЬ У ОДНОГО ВХОДА ПРЕИМУЩЕСТВО?

Отвечает на один вопрос, и ответ «нет» здесь такой же полноценный, как
«да»:

    ЕСТЬ ЛИ ПРОСТОЙ ПРИЗНАК ВХОДА, КОТОРЫЙ ОТЛИЧАЕТСЯ ОТ СЛУЧАЙНОГО
    И ОТ СВОЕГО ЗЕРКАЛА — НА НЕСКОЛЬКИХ ИНСТРУМЕНТАХ СРАЗУ?

Как устроена проверка:

  * шесть признаков, список зафиксирован ДО прогона (entry_lab.ПРИЗНАКИ);
  * семь инструментов по 50 000 свечей;
  * три отрезка по времени: TRAIN, VALIDATION, OOS;
  * у каждого признака два контроля — зеркало и случайный вход;
  * порог значимости с поправкой на число проверенных признаков.

ПОЧЕМУ СЕМЬ ИНСТРУМЕНТОВ, А НЕ ОДИН. Признак, работающий на одном
инструменте, — совпадение: инструментов много, и что-нибудь где-нибудь
всегда выстрелит. Признак, работающий на семи, — это уже свойство рынка,
а не выборки.

Запуск:
    python run_entry_search.py                 # всё
    python run_entry_search.py EURUSD XAUUSD   # выбранные инструменты
    python run_entry_search.py --bars 20000    # по последним свечам
"""

import logging
import os
import sys

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, ЗДЕСЬ)

import run_baseline  # noqa: E402  (ставит config и заглушку MetaTrader5)

import entry_lab     # noqa: E402
import history_data  # noqa: E402

logging.basicConfig(level=logging.ERROR,
                    format="%(levelname)s %(name)s: %(message)s")

СИМВОЛЫ = ("EURUSD", "GBPUSD", "USDJPY", "USDCHF", "USDCAD", "AUDUSD", "XAUUSD")

# Как режется история — те же доли, что и везде в проекте.
ДОЛЯ_TRAIN = 0.50
ДОЛЯ_VALIDATION = 0.25


def заголовок(текст, знак="="):
    print()
    print(знак * 100)
    print(текст)
    print(знак * 100)


def отрезки(n: int) -> dict:
    a = int(n * ДОЛЯ_TRAIN)
    b = int(n * (ДОЛЯ_TRAIN + ДОЛЯ_VALIDATION))
    return {"TRAIN": (0, a), "VALIDATION": (a, b), "OOS": (b, n)}


def загрузить(symbol: str, max_bars: int):
    try:
        d = history_data.load(symbol, timeframe="M5")
    except Exception as e:
        print(f"  {symbol}: не читается ({e})")
        return None
    if not d["clean"] or not d["quality"]["usable"]:
        print(f"  {symbol}: данные негодны")
        return None
    bars = d["clean"]
    if max_bars and len(bars) > max_bars:
        bars = bars[-int(max_bars):]
    return bars


