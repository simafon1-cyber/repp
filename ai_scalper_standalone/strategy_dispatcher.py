def пустое_состояние() -> dict:
    return {"версия_каталога": 0, "текущий": "", "остановлена": "", "шаги": {}}


def прочитать_состояние(folder: str = "") -> dict:
    путь = путь_состояния(folder)
    try:
        with open(путь, "r", encoding="utf-8") as f:
            состояние = json.load(f)
    except (OSError, ValueError):
        return пустое_состояние()
    if not isinstance(состояние, dict) or "шаги" not in состояние:
        return пустое_состояние()
    return состояние


def записать_состояние(состояние: dict, folder: str = "") -> bool:
    """Запись атомарная: половина файла состояния хуже, чем его отсутствие."""
    путь = путь_состояния(folder)
    try:
        safe_files.atomic_write_text(
            путь, json.dumps(состояние, ensure_ascii=False, indent=2))
        return True
    except OSError as e:
        log.error("Состояние диспетчера не записано: %s", e)
        return False


def _день(состояние: dict, id_шага: str, дата: str) -> dict:
    шаги = состояние.setdefault("шаги", {})
    шаг = шаги.setdefault(str(id_шага), {"дни": {}, "завершён": "", "почему": ""})
    дни = шаг.setdefault("дни", {})
    return дни.setdefault(str(дата), {"минут_без_помех": 0, "сделок": 0})


def отметить_работу(состояние: dict, id_шага: str, дата: str,
                    минут: int) -> dict:
    """Прибавить минуты РАБОТЫ БЕЗ ПОМЕХ за этот день.

    Минуты, когда на «Обзоре» висела строка «СДЕЛОК НЕ БУДЕТ», сюда не
    попадают: их прибавляет тот, кто видит состояние помех, и только за
    время, когда помех не было."""
    д = _день(состояние, id_шага, дата)
    д["минут_без_помех"] = int(д.get("минут_без_помех", 0)) + max(0, int(минут))
    return состояние


def отметить_сделку(состояние: dict, id_шага: str, дата: str,
                    сколько: int = 1) -> dict:
    """Прибавить ЗАКРЫТЫЕ сделки. Прибыль не передаётся и не хранится."""
    д = _день(состояние, id_шага, дата)
    д["сделок"] = int(д.get("сделок", 0)) + max(0, int(сколько))
    return состояние


def полных_дней(состояние: dict, id_шага: str, минут_для_дня: int = 0) -> int:
    порог = int(минут_для_дня or МИНУТ_ДЛЯ_ПОЛНОГО_ДНЯ)
    шаг = (состояние.get("шаги") or {}).get(str(id_шага)) or {}
    return len([1 for д in (шаг.get("дни") or {}).values()
                if int((д or {}).get("минут_без_помех", 0)) >= порог])


def закрытых_сделок(состояние: dict, id_шага: str) -> int:
    шаг = (состояние.get("шаги") or {}).get(str(id_шага)) or {}
    return sum(int((д or {}).get("сделок", 0))
               for д in (шаг.get("дни") or {}).values())


