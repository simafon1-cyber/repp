def _корень_данных() -> str:
    """Где искать preregistration. То же правило, что в strategies.py."""
    meipass = getattr(sys, "_MEIPASS", None)
    if meipass:
        return meipass
    return os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def путь_каталога(folder: str = "") -> str:
    if folder:
        return os.path.join(folder, "strategy_catalog.json")
    return os.path.join(_корень_данных(), "preregistration",
                        "strategy_catalog.json")


def путь_состояния(folder: str = "") -> str:
    if folder:
        return os.path.join(folder, ФАЙЛ_СОСТОЯНИЯ)
    if getattr(sys, "frozen", False):
        база = os.path.dirname(sys.executable)
    else:
        база = os.path.dirname(os.path.abspath(__file__))
    return os.path.join(база, ФАЙЛ_СОСТОЯНИЯ)


