def прочитать_каталог(folder: str = "") -> dict:
    """Очередь версий. Пустой словарь — прочитать не вышло.

    Отсутствие каталога НЕ означает «работай как хочешь»: без каталога
    диспетчер вообще ничего не разрешает (см. решение())."""
    путь = путь_каталога(folder)
    try:
        with open(путь, "r", encoding="utf-8") as f:
            каталог = json.load(f)
    except (OSError, ValueError) as e:
        log.error("Каталог стратегий не прочитан (%s): %s", путь, e)
        return {}
    return каталог if isinstance(каталог, dict) else {}


def замечания_каталога(каталог: dict) -> list:
    """Что в каталоге мешает работать. Пустой список — годен.

    Проверяется то, отсутствие чего однажды уже стоило дорого:
    неоднозначное «дни или сделки», неназванный признак полного дня,
    паспорт-черновик вместо заверённого."""
    беды = []
    if not каталог:
        return ["каталог не прочитан"]

    очередь = каталог.get("очередь")
    if not isinstance(очередь, list) or not очередь:
        беды.append("в каталоге нет очереди")
        return беды

    порядки = []
    for шаг in очередь:
        if not isinstance(шаг, dict):
            беды.append("шаг очереди не является записью")
            continue
        имя = str(шаг.get("id") or "?")
        порядки.append(шаг.get("порядок"))

        паспорт = str(шаг.get("паспорт") or "")
        if not паспорт:
            беды.append(f"{имя}: не указан файл паспорта")
        elif "_draft" in паспорт or "черновик" in паспорт.lower():
            беды.append(
                f"{имя}: в каталоге указан ЧЕРНОВИК паспорта ({паспорт}). "
                f"Заверенный паспорт — отдельный файл, иначе диспетчер "
                f"может пустить непроверенную версию")

        окно = шаг.get("окно") or {}
        for ключ in ("минимум_полных_торговых_дней", "минимум_закрытых_сделок"):
            if not isinstance(окно.get(ключ), int) or окно.get(ключ) <= 0:
                беды.append(f"{имя}: в окне не задано «{ключ}» числом")

    if len(set(порядки)) != len(порядки):
        беды.append("в очереди повторяется «порядок»")

    правила = каталог.get("правила_диспетчера") or {}
    if правила.get("смена_по_pnl") is not False:
        беды.append("в правилах не запрещена смена версии по прибыли/убытку")
    if правила.get("смена_по_мало_входов") is not False:
        беды.append("в правилах не запрещена смена версии из-за малого числа входов")
    if not каталог.get("минут_для_полного_дня"):
        беды.append(
            "не сказано, сколько минут работы без помех делают день "
            "«полным». Без этого три дня в запрете зачтутся как выполненное окно")
    return беды


def шаг_по_id(каталог: dict, id_шага: str) -> dict:
    for шаг in (каталог.get("очередь") or ()):
        if isinstance(шаг, dict) and str(шаг.get("id")) == str(id_шага):
            return шаг
    return {}


def порядок_очереди(каталог: dict) -> list:
    очередь = [ш for ш in (каталог.get("очередь") or ()) if isinstance(ш, dict)]
    return sorted(очередь, key=lambda ш: int(ш.get("порядок") or 0))


