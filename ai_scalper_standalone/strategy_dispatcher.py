def текущий_шаг(каталог: dict, состояние: dict) -> dict:
    """Чей сейчас ход. Первый незавершённый шаг очереди."""
    завершённые = {i for i, ш in (состояние.get("шаги") or {}).items()
                   if (ш or {}).get("завершён")}
    for шаг in порядок_очереди(каталог):
        if str(шаг.get("id")) not in завершённые:
            return шаг
    return {}


def решение(каталог: dict, состояние: dict) -> dict:
    """Что делать сейчас. Прибыль сюда не передаётся и передаваться не может.

    Возвращает {"что": ..., "шаг": id, "почему": ...}, где «что» одно из:
        ЖДАТЬ_ВЛАДЕЛЬЦА  очередь остановлена или каталог негоден
        НЕ_ГОТОВ         шаг есть, но паспорта/кода нет
        ПРОДОЛЖАТЬ       окно идёт
        ОКНО_ЗАВЕРШЕНО   набрано; переход делает человек
        ОЧЕРЕДЬ_ПУСТА    все шаги завершены
    """
    беды = замечания_каталога(каталог)
    if беды:
        return {"что": "ЖДАТЬ_ВЛАДЕЛЬЦА", "шаг": "",
                "почему": "каталог не годится: " + "; ".join(беды[:3])}
    if состояние.get("остановлена"):
        return {"что": "ЖДАТЬ_ВЛАДЕЛЬЦА", "шаг": состояние.get("текущий", ""),
                "почему": f"очередь остановлена: {состояние['остановлена']}"}

    шаг = текущий_шаг(каталог, состояние)
    if not шаг:
        return {"что": "ОЧЕРЕДЬ_ПУСТА", "шаг": "",
                "почему": "все шаги очереди завершены"}

    id_шага = str(шаг.get("id"))
    можно, почему = шаг_готов(шаг)
    if not можно:
        return {"что": "НЕ_ГОТОВ", "шаг": id_шага, "почему": почему}

    минут = int(каталог.get("минут_для_полного_дня") or МИНУТ_ДЛЯ_ПОЛНОГО_ДНЯ)
    набрано, пояснение = окно_завершено(шаг, состояние, минут)
    if набрано:
        return {"что": "ОКНО_ЗАВЕРШЕНО", "шаг": id_шага, "почему": пояснение}
    return {"что": "ПРОДОЛЖАТЬ", "шаг": id_шага, "почему": пояснение}


# =====================================================================
# ЗАВЕРШЕНИЕ ШАГА
# =====================================================================
def завершить_шаг(состояние: dict, id_шага: str, причина: str,
                  кто: str, комментарий: str = "",
                  подтверждено_владельцем: bool = False,
                  folder: str = "") -> tuple:
    """(получилось, пояснение). Причина — только из закрытого списка.

    ПРОВАЛ ТЕХНИКИ ОСТАНАВЛИВАЕТ ОЧЕРЕДЬ ЦЕЛИКОМ. Идти к следующей
    версии на неисправной машине бессмысленно: её результат ничего не
    будет значить, а выяснится это через неделю."""
    if причина not in ПРИЧИНЫ_ЗАВЕРШЕНИЯ:
        return False, (f"причина «{причина}» не из списка. Разрешены: "
                       + ", ".join(ПРИЧИНЫ_ЗАВЕРШЕНИЯ))
    if not str(кто or "").strip():
        return False, "не указано, кто завершает шаг"
    if причина in (ВРУЧНУЮ, ПРОВАЛ_ТЕХНИКИ) and not подтверждено_владельцем:
        return False, (f"«{причина}» требует подтверждения владельца — "
                       f"диспетчер сам такого не решает")

    шаг = (состояние.setdefault("шаги", {})
           .setdefault(str(id_шага), {"дни": {}, "завершён": "", "почему": ""}))
    шаг["завершён"] = datetime.now(timezone.utc).isoformat()
    шаг["почему"] = причина
    шаг["кто"] = кто
    шаг["комментарий"] = комментарий
    if причина == ПРОВАЛ_ТЕХНИКИ:
        состояние["остановлена"] = (
            f"ПРОВАЛ ТЕХНИКИ на шаге {id_шага}: {комментарий or 'без пояснения'}. "
            f"Следующая версия не начинается, пока владелец не разберётся.")
    записать_состояние(состояние, folder)
    log.warning("Шаг %s завершён (%s) — %s", id_шага, причина, кто)
    return True, f"шаг {id_шага} завершён: {причина}"


def отчёт_шага(каталог: dict, состояние: dict, id_шага: str,
               замороженные_пары=None, folder: str = "") -> str:
    """Записать отчёт шага. Возвращает путь или пустую строку.

    Список пар кладётся В ОТЧЁТ намеренно: паспорт требует заморозить
    его снимком «до», и через месяц надо будет доказать, на чём считали."""
    шаг = шаг_по_id(каталог, id_шага)
    состояние_шага = (состояние.get("шаги") or {}).get(str(id_шага)) or {}
    минут = int(каталог.get("минут_для_полного_дня") or МИНУТ_ДЛЯ_ПОЛНОГО_ДНЯ)
    метка = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    имя = f"dispatcher_step_{id_шага}_{метка}.json"
    корень = folder or os.path.dirname(путь_состояния())
