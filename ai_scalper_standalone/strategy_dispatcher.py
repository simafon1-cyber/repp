def шаг_готов(шаг: dict) -> tuple:
    """(можно_ли_начинать, почему_нет). Паспорт проверяется по печати."""
    if not шаг:
        return False, "шага нет в очереди"
    готовность = str(шаг.get("статус_готовности") or "")
    if готовность.upper().startswith("НЕ ГОТОВ"):
        return False, f"шаг помечен как не готовый: {готовность}"

    ключ = str(шаг.get("стратегия_в_коде") or "")
    if not ключ:
        return False, "не указана стратегия в коде"
    try:
        import strategies
    except ImportError as e:      # pragma: no cover
        return False, f"модуль стратегий не загрузился: {e}"
    можно, почему = strategies.паспорт_заверен(ключ)
    if not можно:
        return False, f"паспорт не пускает: {почему}"
    return True, ""


def окно_завершено(шаг: dict, состояние: dict, минут_для_дня: int = 0) -> tuple:
    """(завершено_ли, пояснение).

    ОБА условия сразу, а не любое из них. Если засчитывать по одному,
    три дня с пятью сделками закрыли бы окно, и судить было бы не по
    чему. В паспорте С-001 это записано так же: не набралось сделок —
    окно продлевается, версия не меняется, параметры не крутятся."""
    окно = (шаг or {}).get("окно") or {}
    нужно_дней = int(окно.get("минимум_полных_торговых_дней") or 0)
    нужно_сделок = int(окно.get("минимум_закрытых_сделок") or 0)
    id_шага = str((шаг or {}).get("id") or "")

    есть_дней = полных_дней(состояние, id_шага, минут_для_дня)
    есть_сделок = закрытых_сделок(состояние, id_шага)

    чего_не_хватает = []
    if есть_дней < нужно_дней:
        чего_не_хватает.append(f"дней {есть_дней} из {нужно_дней}")
    if есть_сделок < нужно_сделок:
        чего_не_хватает.append(f"сделок {есть_сделок} из {нужно_сделок}")
    if чего_не_хватает:
        return False, "окно продолжается: " + ", ".join(чего_не_хватает)
    return True, (f"окно набрано: дней {есть_дней} из {нужно_дней}, "
                  f"сделок {есть_сделок} из {нужно_сделок}")


