"""strategy_dispatcher.py — ОЧЕРЕДЬ ВЕРСИЙ СТРАТЕГИИ, А НЕ ПОИСК ЛУЧШЕЙ.

=====================================================================
ЗАЧЕМ ЭТОТ ФАЙЛ СУЩЕСТВУЕТ
=====================================================================
Владелец, дословно: «работать день-два, мониторить входы, выходы,
смотреть, сколько минусовых сделок, и изменять либо стратегию, либо
корректировать данные этой стратегии».

Так делать нельзя, и это не мнение исполнителя. За два дня выходит
20-70 сделок. При винрейте около 49% разброс на таком числе больше
разницы между любыми двумя настройками — подкрутив по двум дням, мы
подгоняем под шум и через неделю крутим обратно. Замер 27 сочетаний
настроек (docs/НА_ПРОВЕРКУ_СЕТКА_НАСТРОЕК.md) показал ровно это: ни
одно не выходит в плюс, а разница между ними меньше собственного шума.

Поэтому очередь версий задаётся ЗАРАНЕЕ и в репозитории, а не решается
по ходу. Диспетчер ведёт шаг до конца окна и не имеет права сменить
версию потому, что она в минусе. Так решил владелец: в каталоге стоит
"смена_по_pnl": false.

=====================================================================
ГЛАВНОЕ ПРАВИЛО: ПРИБЫЛЬ НЕ ВХОДИТ В РЕШЕНИЕ
=====================================================================
Ни одна функция здесь не принимает и не читает прибыль, убыток, баланс
или эквити. Это не забывчивость, а условие: то, чего нет на входе,
нельзя случайно учесть. Проверяется отдельным тестом.

Решение о смене версии принимается ровно по трём причинам:

    окно завершено      дни И сделки набраны — обе величины сразу
    владелец вручную    явное действие человека с причиной
    провал техники      и ТОЛЬКО с подтверждением владельца

=====================================================================
ЧЕГО ЭТОТ МОДУЛЬ НЕ ДЕЛАЕТ
=====================================================================
Не торгует и не считает деньги. Не выбирает стратегию. Не заверяет
паспорта. Не решает, была ли версия удачной — это работа отчёта и
человека. Здесь только: чей сейчас ход, набралось ли окно, и можно ли
двигаться дальше.
"""

from __future__ import annotations

import json
import logging
import os
import sys
from datetime import datetime, timezone

import safe_files

log = logging.getLogger("dispatcher")

# Файл состояния лежит РЯДОМ С ПРОГРАММОЙ, как отметка об инциденте: у
# собранной версии код распакован в _internal, и путь по __file__ увёл бы
# состояние туда, где человек его не найдёт.
ФАЙЛ_СОСТОЯНИЯ = "strategy_run_state.json"
ПАПКА_ОТЧЁТОВ = "research"

# СКОЛЬКО МИНУТ БЕЗ ПОМЕХ ДЕЛАЮТ ДЕНЬ «ПОЛНЫМ».
#
# Без этого числа окно закрывается само собой: бот простоял три дня в
# запрете — «три дня прошло», сделок ноль, окно «выполнено». Ровно это и
# случилось у владельца на прошлой неделе. Час работы и полный день — не
# одно и то же, и разница должна быть записана числом, а не подразумеваться.
#
# Шесть часов выбраны как половина активной сессии. Число предложено
# исполнителем и ждёт подтверждения владельца — так и помечено в каталоге.
МИНУТ_ДЛЯ_ПОЛНОГО_ДНЯ = 360

# Причины, по которым шаг может завершиться. Список закрытый: причина не
# из списка не принимается вовсе, чтобы «потому что минус» нельзя было
# протащить свободным текстом.
ОКНО_ЗАВЕРШЕНО = "окно завершено"
ВРУЧНУЮ = "владелец вручную"
ПРОВАЛ_ТЕХНИКИ = "провал техники"
ПРИЧИНЫ_ЗАВЕРШЕНИЯ = (ОКНО_ЗАВЕРШЕНО, ВРУЧНУЮ, ПРОВАЛ_ТЕХНИКИ)


