# 5. ЖИЗНЕННЫЙ ПУТЬ PROFIT LOCK И ЛЕСТНИЦЫ
# ---------------------------------------------------------------------
def лестница_и_лок(сделки, cfg, tm):
    """Где включается защита и сколько запирает — по фактическим MFE сделок."""
    print(f"\nЛЕСТНИЦА R: пик -> сколько заперто (по настройке R_TRAIL_LADDER)")
    ladder = getattr(cfg, "R_TRAIL_LADDER", None) or []
    giveback = float(getattr(cfg, "R_TRAIL_GIVEBACK_R", 0) or 0)
    print(f"{'пик R':>8}{'заперто R':>12}{'отдаётся':>11}{'сделок дошло':>14}")
    for пик in (0.0, 0.25, 0.30, 0.50, 0.60, 1.00, 1.50, 2.00, 2.50, 3.00):
        замок = tm.r_ladder_lock_points(пик, 1.0, ladder, giveback)
        дошло = sum(1 for t in сделки if t.get("mfe_r", 0.0) >= пик)
        замок_т = "—" if замок is None else f"{замок:.2f}"
        отдано = "—" if замок is None else f"{пик - замок:.2f}"
        print(f"{пик:>8.2f}{замок_т:>12}{отдано:>11}{дошло:>14}")

    доля = getattr(cfg, "PROFIT_LOCK_START_R_FRACTION", 1.0)
    tiers = getattr(cfg, "PROFIT_LOCK_TIERS", None) or []
    print(f"\nPROFIT LOCK: включается с пика {доля:.2f}R, ступени {tiers}")
    print(f"{'пик R':>8}{'% заперт':>10}{'заперто R':>12}{'отдаётся R':>12}")
    for пик in (0.5, 1.0, 1.5, 2.0, 3.0):
        if пик < доля:
            print(f"{пик:>8.2f}{'выключен':>10}")
            continue
        pct = tm._tiered_lock_percent(пик, доля) if getattr(
            cfg, "USE_TIERED_PROFIT_LOCK", False) else cfg.PROFIT_LOCK_PERCENT
        print(f"{пик:>8.2f}{pct:>9.0f}%{пик * pct / 100.0:>12.2f}"
              f"{пик * (1 - pct / 100.0):>12.2f}")


def трейлинг(сделки, cfg):
    """Насколько ATR-трейлинг отстаёт от цены — в единицах риска сделки.

    ATR в пунктах берётся из самих сделок, а не из отдельного ряда: почти
    всегда стоп упирается в пол MIN_SL_ATR_FRACTION, то есть риск сделки
    равен ему же, умноженному на ATR. Так число получается тем самым, что
    видела сделка, а не средним по истории."""
    риски = [t["risk_points"] for t in сделки if t["risk_points"] > 0]
    if not риски:
        return
    риск = медиана(риски)
    пол = float(getattr(cfg, "MIN_SL_ATR_FRACTION", 1.5) or 1.5)
    atr_пт = риск / пол
    шаг = max(atr_пт * 0.3, atr_пт * cfg.TRAILING_ATR_MULTIPLIER)
    print(f"\nATR-ТРЕЙЛИНГ")
    print(f"  медианный риск сделки (1R)      {риск:>10.1f} пт")
    print(f"  он же в ATR (пол MIN_SL_ATR_FRACTION){пол:>6.2f} ATR"
          f"  ->  ATR = {atr_пт:.1f} пт")
    print(f"  отступ трейлинга {cfg.TRAILING_ATR_MULTIPLIER:.2f}×ATR"
          f"{шаг:>13.1f} пт = {шаг / риск:.2f}R")
    print(f"  включается с прибыли             {шаг / риск:>10.2f}R")
    if шаг / риск > 0.6:
        print(f"  то есть подтянувшись, отдаёт назад {шаг / риск:.2f}R — "
              f"почти весь стоп; поэтому он почти никогда и не выигрывает "
              f"у лестницы по R")


# ---------------------------------------------------------------------
def прогон(symbol: str):
    import baseline_engine
    import config as cfg
    import trade_manager as tm

    бары, мета = загрузить(symbol)
    if бары is None:
        print(f"{symbol}: нет файла истории")
        return None
    итог = baseline_engine.run(symbol, бары, мета)
    сделки = итог["trades"]
    if not сделки:
        print(f"{symbol}: сделок нет")
        return None

    print("=" * 96)
    print(f"{symbol} — АУДИТ ВЫХОДОВ. Сделок {len(сделки)}, "
          f"итог {sum(t['r'] for t in сделки):.1f}R / "
          f"{sum(t['money'] for t in сделки):.2f}$")
    print("=" * 96)

    печать_причин(по_причинам(сделки), len(сделки))
    асимметрия(сделки)
    печать_корзин(корзины_по_деньгам(сделки, +1, КОРЗИНЫ_ПЛЮС),
                  "ПРИБЫЛЬНЫЕ СДЕЛКИ ПО КОРЗИНАМ ДЕНЕГ")
    печать_корзин(корзины_по_деньгам(сделки, -1, КОРЗИНЫ_МИНУС),
                  "УБЫТОЧНЫЕ СДЕЛКИ ПО КОРЗИНАМ ДЕНЕГ")
    дошли_до(сделки)
    раннее_распознавание(сделки)
    лестница_и_лок(сделки, cfg, tm)

    трейлинг(сделки, cfg)
    return сделки


def ab_время(symbol: str):
    """A/B ровно одной пары: механизмы, зависящие ОТ ВРЕМЕНИ, включены и
    выключены. Отдельного «выхода по времени» в системе нет (см. раздел 1
    аудита), поэтому время влияет только через эти два механизма:

        USE_TP_TIGHTEN        — цель ужимается на 18% за каждую минуту
        USE_BREAK_EVEN_RESCUE — после 10-й минуты цель прибивается к нулю

    Меняются ТОЛЬКО эти два выключателя. Ни риск, ни лот, ни стоп, ни
    индикаторы не трогаются."""
    import config as cfg
    было = (getattr(cfg, "USE_TP_TIGHTEN", False),
            getattr(cfg, "USE_BREAK_EVEN_RESCUE", False))
    итоги = {}
    for имя, вкл in (("ВРЕМЯ ВКЛ", True), ("ВРЕМЯ ВЫКЛ", False)):
        cfg.USE_TP_TIGHTEN, cfg.USE_BREAK_EVEN_RESCUE = вкл, вкл
        print(f"\n{'#' * 96}\n### {symbol}: {имя}\n{'#' * 96}")
        итоги[имя] = прогон(symbol)
    cfg.USE_TP_TIGHTEN, cfg.USE_BREAK_EVEN_RESCUE = было

    print(f"\n{'=' * 96}\nA/B ПО {symbol}: механизмы, зависящие от времени\n{'=' * 96}")
    print(f"{'':<14}{'сделок':>8}{'итог R':>10}{'ожидание':>11}{'PF':>8}"
          f"{'винрейт':>9}{'в ноль':>9}{'ср.плюс':>10}{'мед.мин':>9}")
    for имя, сделки in итоги.items():
        if not сделки:
            continue
        плюс = [t["r"] for t in сделки if t["r"] > 0]
        минус = [t["r"] for t in сделки if t["r"] < 0]
        ноль = [t for t in сделки if t["r"] == 0]
        pf = (sum(плюс) / abs(sum(минус))) if минус else float("inf")
        print(f"{имя:<14}{len(сделки):>8}{sum(t['r'] for t in сделки):>10.1f}"
              f"{средн([t['r'] for t in сделки]):>11.4f}{pf:>8.3f}"
              f"{len(плюс) / len(сделки) * 100:>8.1f}%"
              f"{len(ноль) / len(сделки) * 100:>8.1f}%"
              f"{средн(плюс):>10.3f}"
              f"{медиана([t['held_seconds'] / 60.0 for t in сделки]):>9.1f}")
    print("\nВНИМАНИЕ, ЧЕСТНАЯ ОГОВОРКА. История одна и та же, и правило входа "
          "одно и то же, но САМИ ВХОДЫ РАЗНЫЕ: пока сделка открыта, новая по "
          "этой паре не берётся, поэтому более быстрый выход освобождает место "
          "и добавляет сделок. Сравнивать поэтому можно ОЖИДАНИЕ НА СДЕЛКУ, а "
          "итог в R — только с оглядкой на разное число сделок.")


def main():
    флаги = [a for a in sys.argv[1:] if a.startswith("-")]
    символы = [a for a in sys.argv[1:] if not a.startswith("-")] or list(ПО_УМОЛЧАНИЮ)
    for s in символы:
        if "--ab" in флаги:
            ab_время(s)
        else:
            прогон(s)
        print()


if __name__ == "__main__":
    main()
