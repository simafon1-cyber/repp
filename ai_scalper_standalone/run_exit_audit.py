"""run_exit_audit.py — АУДИТ УПРАВЛЕНИЯ ОТКРЫТЫМИ СДЕЛКАМИ.

Отвечает ровно на один вопрос владельца:

    «Прибыль закрывается маленькой (+0.30…+0.50), а убыткам даётся
     гораздо больше места (-1, -2, -3). Почему?»

Ничего не оптимизирует и не подбирает. Только считает по фактическим
сделкам прогона:

  * кто именно закрыл каждую сделку (безубыток / ATR-трейлинг / лестница R /
    Profit Lock / начальный стоп / цель);
  * корзины по деньгам — отдельно прибыльные, отдельно убыточные, и по
    каждой: время жизни, причина выхода, MFE, MAE, R, лот;
  * сколько сделок дошло до +0.25R, +0.5R, +1R, +2R и что с ними стало;
  * жизненный путь Profit Lock: где он включается и сколько запирает;
  * трейлинг: на сколько он реально отодвигает стоп и что отдаёт обратно.

Запуск:
    python run_exit_audit.py                 # EURUSD и XAUUSD
    python run_exit_audit.py EURUSD          # только один инструмент
"""

