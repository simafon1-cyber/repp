"""backtest.py — проверка настроек на истории, а не на словах.

ЗАЧЕМ ЭТО ПОЯВИЛОСЬ

Владелец: «анализируй, что можно улучшить, где мы живём в прошлом».

Вот главное, где живём. За эти дни я поменял десятки настроек: ступени
трейлинг-стопа, поджим тейка, пол стопа, потолок риска, отбор пар. Каждое
изменение я обосновывал РАССУЖДЕНИЕМ — «так логичнее», «по отчёту видно, что».
Ни одно не было ИЗМЕРЕНО. Для торговой системы это и есть жизнь в прошлом:
спорить о настройках вместо того, чтобы посчитать.

Здесь настройки прогоняются по реальной истории баров, и на выходе числа:
сколько сделок, сколько выигрышных, средний плюс, средний минус и главное —
профит-фактор (сумма плюсов, делённая на сумму минусов). Меньше единицы
означает, что система в минусе, сколько её ни настраивай.

=====================================================================
ЧЕГО ЭТА ПРОВЕРКА НЕ УМЕЕТ — ЧИТАТЬ ОБЯЗАТЕЛЬНО
=====================================================================
Числа отсюда НЕ равны будущей прибыли, и вот почему — по-честному:

1. ФИТИЛИ ВНУТРИ БАРА. Известны только четыре цены бара: открытие, максимум,
   минимум, закрытие. Если внутри одного бара задет и стоп, и цель — что
   сработало раньше, неизвестно. Здесь принимается ХУДШИЙ вариант: сначала
   стоп. Это занижает результат, и так и надо: обманывать себя в свою пользу
   на своих же деньгах — плохая привычка.

2. СПРЕД БЕРЁТСЯ ПОСТОЯННЫМ, а на деле он расширяется ночью и на новостях —
   ровно тогда, когда сделки и получаются худшими. То есть реальный результат
   БУДЕТ ХУЖЕ показанного.

3. НЕТ ПРОСКАЛЬЗЫВАНИЯ, комиссии и своп-платы. Их надо вычитать сверх того.

4. ПОДГОНКА. Покрутить настройки до красивого числа на одном отрезке истории
   можно всегда. Это не улучшение стратегии, это её заучивание. Поэтому
   проверять изменение стоит на РАЗНЫХ отрезках и на разных парах, а
   улучшением считать только то, что помогает везде.

Правильное применение здесь одно: СРАВНИТЬ ДВА НАБОРА НАСТРОЕК на одних и тех
же данных (compare). Абсолютное число обманчиво, разница — гораздо честнее.
"""

import logging

log = logging.getLogger("backtest")

# Дробная пыль двоичной арифметики. Меньше миллионной доли пункта — то есть
# на порядки меньше любого движения, которое существует на рынке.
ПЫЛЬ = 1e-6


def simulate(bars, entries, stop_points: float, target_points: float,
             point: float, spread_points: float = 0.0,
             trail=None) -> list:
    """Провести сделки по истории. Возвращает список исходов в ПУНКТАХ.

    bars    — последовательность (high, low, close) в порядке времени.
    entries — {индекс бара: направление}, 1 покупка, -1 продажа.
    trail   — функция (пик в пунктах) -> куда подтянуть стоп (в пунктах),
              или None. Ровно та же ступенчатая логика, что в торговле.

    Считаем в пунктах, а не в деньгах: пункты не зависят от размера счёта и
    от объёма, и потому сравнимы между парами и между настройками."""
    if point <= 0 or stop_points <= 0:
        return []

    сделки = []
    ряд = list(bars or ())
    for i, direction in sorted((entries or {}).items()):
        if not (0 <= i < len(ряд)) or direction not in (1, -1):
            continue
        _, _, close = ряд[i]
        # Вход по цене закрытия сигнального бара плюс спред: платим его сразу,
        # как и в жизни.
        вход = close + direction * spread_points * point
        стоп = стоп_старт = stop_points
        пик = 0.0
        исход = None

        for high, low, _c in ряд[i + 1:]:
            # Прибыль в пунктах, если бы закрылись по лучшей цене этого бара
            лучший = ((high - вход) if direction == 1 else (вход - low)) / point
            худший = ((вход - low) if direction == 1 else (high - вход)) / point

            # СНАЧАЛА СТОП. Внутри бара порядок неизвестен, и берём худший
            # для себя вариант — см. оговорку 1 в начале файла.
            #
            # ДОПУСК В СРАВНЕНИИ. Расстояние в пунктах считается делением
            # дробных цен, и ровно 50 пунктов легко превращается в
            # 49.999999999998934. Без допуска выигрышная сделка молча
            # потерялась бы — именно это и поймал тест на первом прогоне.
            # Допуск в миллионную долю пункта на порядки меньше любого
            # реального движения цены, поэтому подыграть себе им нельзя.
            if худший >= стоп - ПЫЛЬ:
                исход = -стоп
                break
            if target_points > 0 and лучший >= target_points - ПЫЛЬ:
                исход = target_points
                break

            пик = max(пик, лучший)
            if trail is not None:
                подтянуть = trail(пик)
                if подтянуть is not None:
                    # Стоп только ужимается, никогда не расширяется
                    стоп = min(стоп, -подтянуть) if подтянуть > 0 else min(стоп, стоп_старт)
        if исход is None:
            # Сделка не закрылась до конца истории — считаем по последней цене
            _, _, последняя = ряд[-1]
            исход = ((последняя - вход) if direction == 1 else (вход - последняя)) / point
        сделки.append(исход)
    return сделки


def summarize(trades) -> dict:
    """Числа, по которым видно, работает система или нет."""
    сделки = [float(t) for t in (trades or ())]
    плюсы = [t for t in сделки if t > 0]
    минусы = [-t for t in сделки if t < 0]
    сумма_плюсов = sum(плюсы)
    сумма_минусов = sum(минусы)

    return {
        "сделок": len(сделки),
        "выигрышных": len(плюсы),
        "винрейт": round(len(плюсы) / len(сделки) * 100, 1) if сделки else 0.0,
        "средний_плюс": round(сумма_плюсов / len(плюсы), 1) if плюсы else 0.0,
        "средний_минус": round(сумма_минусов / len(минусы), 1) if минусы else 0.0,
        # Профит-фактор: сумма выигрышей / сумма проигрышей. Ниже единицы —
        # система в минусе. Бесконечности не выдаём: «минусов не было» на
        # коротком отрезке означает мало данных, а не безубыточность.
        "профит_фактор": (round(сумма_плюсов / сумма_минусов, 2)
                          if сумма_минусов > 0 else 0.0),
        "итог_пунктов": round(sum(сделки), 1),
        # Ожидание на сделку — самое честное одно число: сколько в среднем
        # приносит одна сделка. Отрицательное означает, что каждая следующая
        # сделка в среднем отнимает деньги.
        "ожидание": round(sum(сделки) / len(сделки), 2) if сделки else 0.0,
    }


def compare(before: dict, after: dict) -> str:
    """Стало лучше или хуже — словами, с числами и с оговоркой.

    Смысл всей затеи именно здесь. Абсолютное число из проверки на истории
    обманчиво (см. оговорки в начале файла), а РАЗНИЦА между двумя наборами
    настроек на одних и тех же данных — гораздо надёжнее."""
    было = float(before.get("ожидание", 0) or 0)
    стало = float(after.get("ожидание", 0) or 0)
    n = int(after.get("сделок", 0) or 0)

    if not before.get("сделок") or not n:
        return "Сравнивать не по чему: на этих данных сделок не было."

    разница = стало - было
    if abs(разница) < 1e-9:
        вывод = "Разницы нет вовсе."
    elif разница > 0:
        вывод = f"Лучше на {разница:.2f} пункта на сделку."
    else:
        вывод = f"ХУЖЕ на {abs(разница):.2f} пункта на сделку."

    строка = (f"Было: ожидание {было:.2f}, профит-фактор "
              f"{before.get('профит_фактор')}, сделок {before.get('сделок')}. "
              f"Стало: ожидание {стало:.2f}, профит-фактор "
              f"{after.get('профит_фактор')}, сделок {n}. {вывод}")

    # Малая выборка — главная ловушка. На двух десятках сделок «улучшение»
    # чаще означает везение, чем работу настройки.
    if n < 100:
        строка += (f" ВНИМАНИЕ: сделок всего {n} — этого мало, чтобы отличить "
                   f"работу настройки от везения. Нужна хотя бы сотня, и лучше "
                   f"на разных отрезках истории.")
    return строка
