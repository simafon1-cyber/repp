"""migrate_meta.py — ПЕРЕНОС ПАСПОРТОВ СНИМКА НА ВЕРНОЕ СМЕЩЕНИЕ ВРЕМЕНИ.

ЗАЧЕМ ЭТОТ ФАЙЛ

Смещение времени сервера в паспортах часовой выгрузки записано неверно:
−1 у валютных пар и −2 у золота вместо +3. Причина разобрана в
history_export.py — считалось по последнему тику, а выгрузка шла в
субботу, когда рынок закрыт и тик протух.

Расчёт исправлен. Но данные выгружены ДО правки, и в опубликованном
снимке остаются старые числа. Приёмочный аудит указал на это отдельно
(P1-H4): исправленный код доказан тестами для будущих выгрузок, но уже
лежащий артефакт он не чинит. А `baseline_engine.session_of()` читает
именно это поле — значит предстоящий прогон получил бы неверные ярлыки
сессий.

ГЛАВНОЕ ПРАВИЛО ЭТОГО ФАЙЛА: СВЕЧИ НЕ ТРОГАЮТСЯ

Заново выгружать нельзя: окно терминала уехало бы вперёд и начало
истории потерялось бы. Значит правится только паспорт, а сами свечи
обязаны остаться байт в байт теми же.

Это не обещание, а проверка: отпечаток каждого CSV снимается ДО правки и
сверяется ПОСЛЕ. Разошёлся хоть один — перенос отменяется целиком.

ЧТО ОСТАЁТСЯ ПОСЛЕ ПЕРЕНОСА

Рядом со снимком появляется журнал `migration.json`: что было, что стало,
какие файлы изменены и — отдельной строкой — что CSV не менялись. Через
год разбираться будут по нему, а не по памяти.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
from datetime import datetime, timezone

import history_export

ЖУРНАЛ = "migration.json"
ПОЛЕ = "server_utc_offset_hours"
ПОЛЕ_ПОЯСНЕНИЕ = "server_utc_offset_note"


def отпечаток(путь) -> str:
    h = hashlib.sha256()
    with open(путь, "rb") as f:
        for кусок in iter(lambda: f.read(1 << 20), b""):
            h.update(кусок)
    return h.hexdigest()


def свечи_из_файла(путь) -> list:
    """Только время — больше для расчёта смещения ничего не нужно."""
    бары = []
    with open(путь, encoding="utf-8") as f:
        next(f, None)                       # заголовок
        for строка in f:
            строка = строка.strip()
            if строка:
                бары.append({"time": int(строка.split(";")[0])})
    return бары


def _тф(имя_файла: str) -> str:
    """H1 из «EURUSD_H1.csv»."""
    основа = os.path.basename(имя_файла)
    return основа.rsplit(".", 1)[0].rsplit("_", 1)[-1]


ЧАСОВ_РАЗБЕГА = 24 * 3600


def _смещение_снимка(папка: str, файлы) -> tuple:
    """Смещение сервера для ВСЕГО снимка — по его часовым файлам.

    Требуется согласие: если часовые файлы дают разные значения, значит
    что-то не так с данными, и общее смещение не выводится.

    Ещё требуется, чтобы снимок был снят за один заход: паспорта с сильно
    разным временем выгрузки могли застать разные состояния сервера, и
    переносить смещение между ними нельзя."""
    значения, времена = {}, []
    for имя in файлы:
        путь_меты = os.path.join(папка, имя.replace(".csv", ".meta.json"))
        try:
            мета = json.loads(open(путь_меты, encoding="utf-8").read())
        except Exception:  # noqa: BLE001
            continue
        когда = str(мета.get("exported_utc", "") or "")
        if когда:
            времена.append(когда)
        if _тф(имя) != "H1":
            continue
        бары = свечи_из_файла(os.path.join(папка, имя))
        см, _ = history_export.смещение_по_свечам(бары, "H1")
        if см is not None:
            значения[см] = значения.get(см, 0) + 1

    if not значения:
        return None, "часовых файлов в снимке нет"
    if len(значения) > 1:
        return None, f"часовые файлы дают разные смещения: {значения}"

    if len(времена) >= 2:
        разбег = _разбег_секунд(времена)
        if разбег is not None and разбег > ЧАСОВ_РАЗБЕГА:
            return None, (f"снимок собран не за один заход: между первой и "
                          f"последней выгрузкой {разбег/3600:.1f} ч")

    смещение = next(iter(значения))
    return смещение, f"по {значения[смещение]} часовым файлам"


def _разбег_секунд(времена) -> float:
    """Сколько прошло между самой ранней и самой поздней выгрузкой."""
    метки = []
    for т in времена:
        try:
            метки.append(datetime.strptime(т, "%Y-%m-%d %H:%M:%S")
                         .replace(tzinfo=timezone.utc).timestamp())
        except ValueError:
            continue
    if len(метки) < 2:
        return None
    return max(метки) - min(метки)


def перенести(папка: str, применять: bool = True) -> dict:
    """Пересчитать смещение по свечам и записать в паспорта.

    применять=False — только посмотреть, ничего не меняя.

    Возвращает журнал переноса."""
    файлы = sorted(f for f in os.listdir(папка) if f.endswith(".csv"))
    если_нет = [f for f in файлы
                if not os.path.exists(os.path.join(папка, f.replace(".csv", ".meta.json")))]
    if если_нет:
        raise FileNotFoundError(f"нет паспортов для: {', '.join(если_нет)}")

    # ОТПЕЧАТКИ СВЕЧЕЙ ДО. С ними сверяемся после — это и есть доказательство,
    # что данные не тронуты.
    до = {f: отпечаток(os.path.join(папка, f)) for f in файлы}

    журнал = {
        "когда_utc": datetime.now(timezone.utc).isoformat(),
        "папка": os.path.abspath(папка),
        "что_сделано": ("пересчитано смещение времени сервера по свечам; "
                        "сами свечи не менялись"),
        "паспорта": [],
        "csv_не_менялись": None,
        "применено": применять,
    }

    # СМЕЩЕНИЕ — СВОЙСТВО СЕРВЕРА, А НЕ ТАЙМФРЕЙМА.
    #
    # Считать его можно только по часовым свечам: на M1, M5 и M15 граница
    # недели размыта пропусками. Но это не значит, что для них смещение
    # другое — сервер один, и снимок снят за несколько минут.
    #
    # Поэтому смещение берётся из часовых файлов и применяется ко всем
    # паспортам снимка. Обнулять их было бы хуже: сейчас там ЗАВЕДОМО
    # НЕВЕРНОЕ число, и заменить его верным полезнее, чем пустотой.
    общее, откуда = _смещение_снимка(папка, файлы)

    for имя in файлы:
        тф = _тф(имя)
        путь_меты = os.path.join(папка, имя.replace(".csv", ".meta.json"))
        мета = json.loads(open(путь_меты, encoding="utf-8").read())
        было = мета.get(ПОЛЕ)

        бары = свечи_из_файла(os.path.join(папка, имя))
        стало, пояснение = history_export.смещение_по_свечам(бары, тф)

        if стало is None and общее is not None:
            стало = общее
            пояснение = (f"смещение взято из часовых файлов этого же снимка "
                         f"({откуда}): оно свойство сервера, а не "
                         f"таймфрейма. Прежнее значение {было} получено по "
                         f"последнему тику на закрытом рынке и неверно.")
        elif стало is None:
            пояснение = (f"{пояснение}. Прежнее значение {было} получено по "
                         f"последнему тику на закрытом рынке и неверно — "
                         f"оставлять его нельзя, поэтому поле очищено.")

        запись = {"файл": имя, "таймфрейм": тф, "было": было, "стало": стало,
                  "пояснение": пояснение, "изменено": False}

        if применять:
            мета[ПОЛЕ] = запись["стало"]
            мета[ПОЛЕ_ПОЯСНЕНИЕ] = запись["пояснение"]
            with open(путь_меты, "w", encoding="utf-8") as f:
                json.dump(мета, f, ensure_ascii=False, indent=1)
            запись["изменено"] = было != запись["стало"]
        else:
            запись["изменено"] = было != запись["стало"]

        журнал["паспорта"].append(запись)

    # ОТПЕЧАТКИ СВЕЧЕЙ ПОСЛЕ.
    после = {f: отпечаток(os.path.join(папка, f)) for f in файлы}
    разошлись = [f for f in файлы if до[f] != после[f]]
    журнал["csv_не_менялись"] = not разошлись
    журнал["csv_разошлись"] = разошлись
    журнал["csv_отпечатки"] = после
    журнал["изменено_паспортов"] = sum(1 for з in журнал["паспорта"] if з["изменено"])

    if разошлись:
        raise RuntimeError(
            f"ПЕРЕНОС ИСПОРТИЛ СВЕЧИ: {разошлись}. Это никогда не должно "
            f"происходить — перенос правит только паспорта. Снимок больше "
            f"нельзя считать достоверным.")

    if применять:
        history_export.записать_манифест(папка)
        with open(os.path.join(папка, ЖУРНАЛ), "w", encoding="utf-8") as f:
            json.dump(журнал, f, ensure_ascii=False, indent=1)
        # Манифест пересобран ПОСЛЕ журнала быть не может: журнал сам
        # обязан попасть в манифест, иначе его можно подменить незаметно.
        history_export.записать_манифест(папка)

    return журнал


def _человеку(журнал: dict) -> str:
    строки = [f"Папка: {журнал['папка']}"]
    for з in журнал["паспорта"]:
        знак = "изменено" if з["изменено"] else "без изменений"
        строки.append(f"  {з['файл']:22} {з['было']} -> {з['стало']}  ({знак})")
    строки.append("")
    строки.append(f"Паспортов изменено: {журнал['изменено_паспортов']} "
                  f"из {len(журнал['паспорта'])}")
    строки.append("Свечи не менялись: "
                  + ("ДА, отпечатки всех CSV совпали"
                     if журнал["csv_не_менялись"] else "НЕТ — см. csv_разошлись"))
    return "\n".join(строки)


def main(аргументы=None) -> int:
    р = argparse.ArgumentParser(
        description="Пересчитать смещение времени сервера в паспортах снимка. "
                    "Свечи не трогаются.")
    р.add_argument("папка", help="каталог снимка")
    р.add_argument("--посмотреть", action="store_true",
                   help="ничего не менять, только показать, что получится")
    а = р.parse_args(аргументы)

    if not os.path.isdir(а.папка):
        print(f"Нет такого каталога: {а.папка}")
        return 2
    try:
        журнал = перенести(а.папка, применять=not а.посмотреть)
    except Exception as e:  # noqa: BLE001
        print(f"Перенос не выполнен: {type(e).__name__}: {e}")
        return 3
    print(_человеку(журнал))
    if not журнал["csv_не_менялись"]:
        return 4
    return 0


if __name__ == "__main__":
    sys.exit(main())
