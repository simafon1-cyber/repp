"""research_manifest.py — ПАСПОРТ ГИПОТЕЗЫ, ЗАПОЛНЯЕМЫЙ ДО ПРОГОНА.

ЗАЧЕМ

Внешний аудит разрешил следующий этап только как НОВОЕ ПРЕДЗАРЕГИСТРИРОВАННОЕ
исследование, а не как подкрутку прежнего «до плюса». Разница между этими
двумя вещами не в намерениях, а в порядке действий:

    предрегистрация    сначала записал условия, потом посмотрел результат
    подгонка           сначала посмотрел результат, потом записал условия

Отличить их постфактум по тексту отчёта невозможно — оба выглядят
одинаково. Отличить можно только по времени: если условия лежат в
репозитории коммитом РАНЬШЕ, чем появились результаты, подкрутить их
задним числом нельзя, не переписав историю.

ЧТО ЗДЕСЬ ЛЕЖИТ

Структура паспорта и его заверение хешем. Сам паспорт — отдельный файл,
который коммитится ДО прогона. Прогон отказывается работать, если паспорт
изменился с момента заверения.

ЧЕГО ЭТОТ МОДУЛЬ НЕ МОЖЕТ

Он не мешает написать новый паспорт после того, как результаты увидены, и
выдать его за старый. От этого защищает только история коммитов — на неё
и надо смотреть проверяющему. Поэтому в отчёте указывается коммит, в
котором паспорт появился, и он обязан быть раньше коммита с результатами.
"""

import hashlib
import json
import os

# Поля, без которых паспорт неполон. Список из требований аудита: данные,
# инструменты, таймфрейм, правила решения, смысл сигнала, фиксированный
# выход, сценарий издержек, критерий успеха и OOS, не участвовавший в
# выборе гипотезы.
ОБЯЗАТЕЛЬНЫЕ = (
    "гипотеза",            # что именно утверждается, одним предложением
    "почему",              # на чём основана — и что из этого пост-фактум
    "версия_данных",       # какой архив истории, с контрольной суммой
    "инструменты",
    "таймфрейм",
    "правила_входа",       # когда открываем
    "смысл_сигнала",       # что означает направление
    "выход",               # фиксированный, одинаковый для всех
    "сценарий_издержек",
    "критерий_успеха",     # что считать подтверждением, ЧИСЛОМ
    "критерий_провала",    # и что считать опровержением
    "разделение",          # как режется история
    "oos",                 # какой кусок не участвовал в выборе гипотезы
    "минимум_сделок",
)

ПОЛЕ_ХЕША = "хеш_паспорта"


def хеш(паспорт: dict) -> str:
    """Хеш содержимого паспорта без самого поля хеша.

    Сортировка ключей обязательна: иначе один и тот же паспорт давал бы
    разные хеши в зависимости от порядка записи."""
    без_хеша = {к: v for к, v in паспорт.items() if к != ПОЛЕ_ХЕША}
    строка = json.dumps(без_хеша, ensure_ascii=False, sort_keys=True,
                        separators=(",", ":"))
    return hashlib.sha256(строка.encode("utf-8")).hexdigest()


def заверить(паспорт: dict) -> dict:
    """Проставить хеш. Делается один раз, до прогона."""
    проверить_полноту(паспорт)
    готовый = dict(паспорт)
    готовый[ПОЛЕ_ХЕША] = хеш(паспорт)
    return готовый


def проверить_полноту(паспорт: dict):
    """Все ли обязательные поля заполнены.

    Пустое поле — это не «пока не решили», а незаполненный паспорт.
    Прогон по неполному паспорту ничего не доказывает: недостающее
    условие всегда можно дописать после того, как результат увиден."""
    нет = [п for п in ОБЯЗАТЕЛЬНЫЕ
           if not str(паспорт.get(п, "")).strip()]
    if нет:
        raise ValueError(
            "паспорт гипотезы неполон, не заполнено: " + ", ".join(нет))


def прочитать(путь: str) -> dict:
    """Паспорт с диска, с проверкой заверения.

    Бросает ошибку, если паспорт изменился после заверения. Это и есть вся
    защита: подкрутить условия под увиденный результат нельзя, не сломав
    хеш, а хеш лежит в том же коммите."""
    if not os.path.exists(путь):
        raise SystemExit(
            f"НЕТ ПАСПОРТА ГИПОТЕЗЫ: {путь}\n"
            f"Исследование без предрегистрации ничего не доказывает — "
            f"условия можно дописать после того, как результат увиден.\n"
            f"Сначала заполните паспорт и закоммитьте его, потом запускайте.")

    with open(путь, "r", encoding="utf-8") as f:
        паспорт = json.load(f)

    проверить_полноту(паспорт)

    записан = паспорт.get(ПОЛЕ_ХЕША, "")
    настоящий = хеш(паспорт)
    if not записан:
        raise SystemExit(f"Паспорт {путь} не заверен: нет поля {ПОЛЕ_ХЕША}")
    if записан != настоящий:
        raise SystemExit(
            f"ПАСПОРТ ИЗМЕНЁН ПОСЛЕ ЗАВЕРЕНИЯ: {путь}\n"
            f"  записан:  {записан}\n"
            f"  на деле:  {настоящий}\n"
            f"Условия исследования правились после того, как их заверили. "
            f"Такой прогон недействителен.")
    return паспорт


def описание(паспорт: dict) -> str:
    """Паспорт человеческим текстом. Печатается перед результатами."""
    строки = ["ПАСПОРТ ГИПОТЕЗЫ (заполнен ДО прогона)", ""]
    подписи = {
        "гипотеза": "Гипотеза",
        "почему": "На чём основана",
        "версия_данных": "Данные",
        "инструменты": "Инструменты",
        "таймфрейм": "Таймфрейм",
        "правила_входа": "Когда входим",
        "смысл_сигнала": "Что означает направление",
        "выход": "Выход (одинаковый для всех)",
        "сценарий_издержек": "Сценарий издержек",
        "разделение": "Разделение истории",
        "oos": "OOS",
        "минимум_сделок": "Минимум сделок",
        "критерий_успеха": "ЧТО СЧИТАЕМ ПОДТВЕРЖДЕНИЕМ",
        "критерий_провала": "ЧТО СЧИТАЕМ ОПРОВЕРЖЕНИЕМ",
    }
    for ключ, подпись in подписи.items():
        значение = паспорт.get(ключ, "")
        if isinstance(значение, (list, tuple)):
            значение = ", ".join(str(x) for x in значение)
        строки.append(f"  {подпись}:")
        for кусок in str(значение).split("\n"):
            строки.append(f"      {кусок}")
    строки.append("")
    строки.append(f"  Хеш паспорта: {паспорт.get(ПОЛЕ_ХЕША, '—')}")
    строки.append("  Проверяющему: этот хеш и коммит, в котором паспорт")
    строки.append("  появился, обязаны быть РАНЬШЕ коммита с результатами.")
    return "\n".join(строки)
