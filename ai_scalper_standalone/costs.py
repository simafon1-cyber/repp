"""costs.py — ЕДИНАЯ МОДЕЛЬ ИЗДЕРЖЕК. ФИКСИРУЕТСЯ ДО ПРОГОНА.

ЗАЧЕМ ЭТОТ МОДУЛЬ ПОЯВИЛСЯ

Это исправление моей собственной ошибки, и назвать её надо прямо.

В `docs/ENTRY_SEARCH.md` есть таблица «после вычета издержек», и на ней
построен главный вывод всей работы по входам: ноль инструментов из семи.
Так вот, **эту таблицу посчитал я вручную**. Скрипт `run_entry_search.py`
вызывал `entry_lab.прогнать()` БЕЗ параметра издержек, то есть считал без
них вовсе, а вычитание я проделал в уме и записал результат.

Числа, скорее всего, верные: там простое вычитание одного числа. Но
проверить их нельзя, повторить прогоном нельзя, и ошибку в моей
арифметике никто бы не поймал. Правило «результат, который нельзя
воспроизвести, — не результат» я нарушил сам.

ЧТО ЗДЕСЬ ЛЕЖИТ

Одна модель издержек на весь расчёт: спред, комиссия, своп. Она передаётся
в расчёт КАЖДОЙ СДЕЛКИ, а не приписывается к итоговой таблице.

ПОЧЕМУ ВЕРСИЯ И ДАТА ЗАПИСАНЫ В КОДЕ

Чтобы нельзя было подкрутить издержки после того, как результат увиден.
Версия печатается перед каждым прогоном и попадает в журнал сделок. Если
модель менялась — это видно, и старые результаты с новыми не сравнить по
недосмотру.

ЧЕГО ЗДЕСЬ НЕТ

Проскальзывания и реквотов. Их нельзя восстановить из свечей, и выдумывать
число не буду: это делало бы модель хуже, а не лучше. Поэтому все оценки
ниже — **оценки сверху**: настоящие издержки не меньше посчитанных.
"""

ВЕРСИЯ = "1.0 (2026-08-20)"

# =====================================================================
# СЦЕНАРИИ ИЗДЕРЖЕК. ЭТО ДОПУЩЕНИЯ, А НЕ УСЛОВИЯ ВАШЕГО СЧЁТА.
# =====================================================================
# Внешний аудит потребовал называть вещи своими именами: комиссия, свопы и
# спецификации инструментов здесь — ТИПОВЫЕ значения розничного счёта, а
# не выгрузка условий счёта 5054028014 за исследуемый период. Выдавать их
# за факт нельзя.
#
# Поэтому вместо одного числа — три явно названных сценария. Вывод,
# который держится только при одном из них, — это не вывод, а совпадение.
#
# Если условия счёта удастся выгрузить у брокера (см. capture_broker_terms.py),
# появится четвёртый вариант — «фактический», и вот он уже будет фактом.
НИЗКИЙ = "низкий"
БАЗОВЫЙ = "базовый"
ВЫСОКИЙ = "высокий"
ФАКТИЧЕСКИЙ = "фактический"

СЦЕНАРИИ = {
    # Комиссия за круг на лот; множитель к нижней границе спреда;
    # множитель к свопам.
    НИЗКИЙ:   {"комиссия": 3.0, "спред": 1.0, "своп": 0.5,
               "что это": "льготные условия: комиссия 3 доллара за круг"},
    БАЗОВЫЙ:  {"комиссия": 7.0, "спред": 1.0, "своп": 1.0,
               "что это": "типовой розничный ECN-счёт"},
    ВЫСОКИЙ:  {"комиссия": 10.0, "спред": 1.5, "своп": 1.5,
               "что это": "неблагоприятные условия: шире спред, дороже своп"},
}

# Какой сценарий действует сейчас. Меняется только явно — функцией
# выбрать_сценарий(), и выбор печатается перед прогоном.
_текущий = БАЗОВЫЙ

# Лот в исследовании ФИКСИРОВАННЫЙ. Здесь не проверяется управление
# капиталом и не подбирается размер позиции — сравниваются входы. Один и
# тот же лот у признака, зеркала и случайного входа делает сравнение
# честным, а перевод в деньги — понятным.
ЛОТ = 1.0

# Комиссия за круг (вход + выход) на один лот, в валюте счёта.
# Значение базового сценария; занижать его нельзя — вся работа про то,
# переживает ли преимущество издержки.
КОМИССИЯ_ЗА_КРУГ = 7.0

# Своп за ночь на один лот, в валюте счёта. Отрицательное — списание.
# Тройной своп в среду здесь НЕ моделируется: это сделало бы оценку
# издержек чуть больше, то есть в консервативную сторону, а точных
# значений у брокера мы не знаем.
СВОП_ЗА_НОЧЬ = {
    "EURUSD": {1: -7.0, -1: 1.5},
    "GBPUSD": {1: -6.0, -1: 1.0},
    "USDJPY": {1: 3.0, -1: -9.0},
    "USDCHF": {1: 8.0, -1: -14.0},
    "USDCAD": {1: 2.0, -1: -8.0},
    "AUDUSD": {1: -8.0, -1: 2.0},
    "XAUUSD": {1: -18.0, -1: 6.0},
}
СВОП_ПО_УМОЛЧАНИЮ = {1: -8.0, -1: -8.0}

# НИЖНЯЯ ГРАНИЦА СПРЕДА, В ПУНКТАХ.
#
# В выгруженной истории у части свечей спред записан НУЛЁМ: у EURUSD таких
# 67 %, у золота 9 %. Нулевого спреда не бывает — это значит «не
# записано», а не «бесплатно». Считать по нулю значило бы занизить
# издержки ровно там, где их больше всего.
#
# Поэтому берётся БОЛЬШЕЕ из двух: фактический спред свечи и это число.
# Числа — медианы НЕнулевых спредов из той же истории, то есть не
# выдуманные, а измеренные. Они зафиксированы здесь до прогона и
# печатаются перед ним.
СПРЕД_НЕ_МЕНЬШЕ = {
    "EURUSD": 2,
    "GBPUSD": 4,
    "USDJPY": 3,
    "USDCHF": 9,
    "USDCAD": 3,
    "AUDUSD": 4,
    "XAUUSD": 4,
}
СПРЕД_ПО_УМОЛЧАНИЮ = 5

# Размер контракта и шаг цены. Нужны, чтобы перевести движение цены в
# деньги. Значения стандартные для розничных счетов MetaTrader 5.
ИНСТРУМЕНТЫ = {
    "EURUSD": {"контракт": 100_000.0, "пункт": 0.00001},
    "GBPUSD": {"контракт": 100_000.0, "пункт": 0.00001},
    "USDJPY": {"контракт": 100_000.0, "пункт": 0.001},
    "USDCHF": {"контракт": 100_000.0, "пункт": 0.00001},
    "USDCAD": {"контракт": 100_000.0, "пункт": 0.00001},
    "AUDUSD": {"контракт": 100_000.0, "пункт": 0.00001},
    "XAUUSD": {"контракт": 100.0, "пункт": 0.01},
}
ПО_УМОЛЧАНИЮ = {"контракт": 100_000.0, "пункт": 0.00001}

# Сколько секунд в сутках — для подсчёта ночей, за которые берётся своп.
СУТКИ = 86_400


def выбрать_сценарий(имя: str):
    """Переключить сценарий издержек. Возвращает прежний.

    Явная функция, а не переменная: переключение должно быть видно в коде
    и попадать в паспорт прогона."""
    global _текущий
    if имя not in СЦЕНАРИИ and имя != ФАКТИЧЕСКИЙ:
        raise ValueError(f"неизвестный сценарий издержек: {имя!r}. "
                         f"Есть: {', '.join(СЦЕНАРИИ)}")
    было, _текущий = _текущий, имя
    return было


def текущий_сценарий() -> str:
    return _текущий


def _множитель(что: str) -> float:
    правила = СЦЕНАРИИ.get(_текущий)
    if правила is None:
        return 1.0
    return float(правила.get(что, 1.0))


def инструмент(symbol: str) -> dict:
    return ИНСТРУМЕНТЫ.get(symbol.upper(), ПО_УМОЛЧАНИЮ)


def пункт(symbol: str) -> float:
    return инструмент(symbol)["пункт"]


def стоимость_пункта(symbol: str, цена: float, лот: float = ЛОТ) -> float:
    """Сколько денег даёт движение цены на один пункт.

    ПОЧЕМУ ЭТО НЕ ОДНО ЧИСЛО НА ВСЕХ. У пар, где доллар стоит справа
    (EURUSD, GBPUSD, AUDUSD, XAUUSD), пункт стоит одинаково всегда. У пар,
    где доллар слева (USDJPY, USDCHF, USDCAD), цена пункта зависит от
    самого курса — потому что прибыль получается в чужой валюте и её надо
    перевести в доллары.

    Считать их одинаково значило бы ошибиться в разы: на USDJPY при курсе
    150 пункт стоит в 150 раз меньше, чем кажется."""
    с = инструмент(symbol)
    в_валюте_котировки = с["контракт"] * с["пункт"] * лот
    if symbol.upper().startswith("USD") and цена > 0:
        # Прибыль получается в валюте котировки — переводим в доллары.
        return в_валюте_котировки / цена
    return в_валюте_котировки


def спред_пунктов(symbol: str, из_данных) -> float:
    """Сколько пунктов спреда считать по этой свече.

    Берётся БОЛЬШЕЕ из фактического и нижней границы: ноль в данных
    означает «не записано», а не «бесплатно»."""
    try:
        факт = float(из_данных or 0.0)
    except (TypeError, ValueError):
        факт = 0.0
    пол = float(СПРЕД_НЕ_МЕНЬШЕ.get(symbol.upper(), СПРЕД_ПО_УМОЛЧАНИЮ))
    return max(факт, пол) * _множитель("спред")


def спред_деньгами(symbol: str, спред_пунктов_: float, цена: float,
                   лот: float = ЛОТ) -> float:
    """Спред платится ОДИН РАЗ, при входе.

    Второй раз вычитать его нельзя: это была бы двойная плата за одну
    сделку. Такая ошибка в проекте уже попадалась."""
    return max(0.0, float(спред_пунктов_)) * стоимость_пункта(symbol, цена, лот)


def комиссия(лот: float = ЛОТ) -> float:
    """За круг, то есть за вход и выход вместе. Зависит от сценария."""
    правила = СЦЕНАРИИ.get(_текущий)
    за_круг = (float(правила["комиссия"]) if правила
               else КОМИССИЯ_ЗА_КРУГ)
    return за_круг * лот


def ночей(время_входа: float, время_выхода: float) -> int:
    """Сколько раз сделка пережила полночь по времени сервера.

    Своп берётся за переход через полночь, а не за каждые 24 часа: сделка
    может прожить два часа и всё равно заплатить своп, если эти два часа
    пришлись на полночь."""
    if время_выхода <= время_входа:
        return 0
    return int(время_выхода // СУТКИ) - int(время_входа // СУТКИ)


def своп(symbol: str, направление: int, ночей_: int,
         лот: float = ЛОТ) -> float:
    """Своп за всё время удержания. Отрицательное — списание."""
    таблица = СВОП_ЗА_НОЧЬ.get(symbol.upper(), СВОП_ПО_УМОЛЧАНИЮ)
    за_ночь = таблица.get(1 if направление == 1 else -1, 0.0)
    # Множитель сценария делает своп ХУЖЕ, а не просто больше по модулю:
    # положительный своп при высоком сценарии не должен становиться ещё
    # выгоднее, иначе «неблагоприятный» сценарий местами оказался бы
    # выгоднее базового.
    м = _множитель("своп")
    если_хуже = м if за_ночь < 0 else (1.0 / м if м > 0 else 1.0)
    return за_ночь * если_хуже * лот * max(0, int(ночей_))


def описание() -> str:
    """Что именно зафиксировано. Печатается перед прогоном."""
    правила = СЦЕНАРИИ.get(_текущий, {})
    строки = [
        f"МОДЕЛЬ ИЗДЕРЖЕК, версия {ВЕРСИЯ}",
        f"  СЦЕНАРИЙ: {_текущий} — {правила.get('что это', 'условия счёта')}",
        "",
        "  ЭТО ДОПУЩЕНИЕ, А НЕ УСЛОВИЯ ВАШЕГО СЧЁТА. Комиссия, свопы и",
        "  спецификации инструментов взяты типовыми для розничного счёта;",
        "  выгрузки условий счёта 5054028014 за исследуемый период нет.",
        "",
        f"  лот в исследовании: {ЛОТ}",
        f"  комиссия за круг: {комиссия(1.0):.2f} на лот",
        "  спред: по свече входа, но не меньше нижней границы "
        "(ноль в данных = «не записано»):",
    ]
    строки.append("      " + "  ".join(
        f"{и} {п}" for и, п in sorted(СПРЕД_НЕ_МЕНЬШЕ.items())))
    if _множитель("спред") != 1.0:
        строки.append(f"      множитель сценария: ×{_множитель('спред'):.2f}")
    строки.append("  своп: за переход через полночь, на лот за ночь:")
    for имя in sorted(СВОП_ЗА_НОЧЬ):
        д = СВОП_ЗА_НОЧЬ[имя]
        строки.append(f"      {имя:<8} покупка {своп(имя, 1, 1):+6.2f}   "
                      f"продажа {своп(имя, -1, 1):+6.2f}")
    строки.append("  проскальзывание и реквоты НЕ моделируются — поэтому "
                  "оценка издержек ЗАНИЖЕНА,")
    строки.append("  а значит, итоговый результат — оценка СВЕРХУ.")
    return "\n".join(строки)


def сводка_сценариев() -> str:
    """Все сценарии рядом. Нужна, чтобы читатель видел разброс допущений."""
    строки = ["СЦЕНАРИИ ИЗДЕРЖЕК (допущения, не факты):"]
    for имя in (НИЗКИЙ, БАЗОВЫЙ, ВЫСОКИЙ):
        п = СЦЕНАРИИ[имя]
        строки.append(
            f"  {имя:<9} комиссия {п['комиссия']:>5.2f}  "
            f"спред ×{п['спред']:.2f}  своп ×{п['своп']:.2f}   {п['что это']}")
    return "\n".join(строки)
