"""validation.py — ВОРОТА. Ни одно изменение не входит в программу без доказательства.

ПРАВИЛО ВЛАДЕЛЬЦА, РАДИ КОТОРОГО НАПИСАН ЭТОТ ФАЙЛ

    «НИКОГДА не считать, что новая функция улучшает систему. Любая новая
    функция считается бесполезной, пока не доказано обратное.»

Это правило легко пообещать и невозможно соблюсти на честном слове: через
неделю обещание забывается, а «ну тут же очевидно лучше» — нет. Поэтому
правило здесь не обещание, а КОД, который отвечает «принять» или «отклонить».

ПЯТЬ СПОСОБОВ ПРОВЕРКИ (все требуются владельцем):

  1. BACKTEST — вся история целиком. Самый слабый способ: именно под всю
     историю настройку и подгоняют.
  2. OUT OF SAMPLE — настройку смотрят ТОЛЬКО на том куске истории, который
     при её подборе не использовался. Подгонка здесь разваливается.
  3. WALK FORWARD — история режется на несколько окон подряд, и улучшение
     должно быть в БОЛЬШИНСТВЕ окон, а не в одном удачном месяце.
  4. MONTE CARLO — сделки многократно пересобираются случайной выборкой.
     Отвечает на вопрос «а если бы те же сделки выпали в другом порядке и
     в другом составе?». Убивает результаты, которые держатся на двух-трёх
     везучих сделках.
  5. A/B (перестановочный тест) — а не могла ли разница получиться просто
     случайно? Метки «до» и «после» тасуются тысячи раз, и смотрится, как
     часто случайность даёт разницу не меньше наблюдаемой.

ЧЕТЫРЕ МЕТРИКИ, ПО КОТОРЫМ СУДЯТ (тоже заданы владельцем):
     профит-фактор, просадка, фактор восстановления, ожидание на сделку.

КАК ЧИТАЕТСЯ РЕШЕНИЕ. Внутри одного способа изменение засчитывается, только
если стало лучше минимум по трём метрикам из четырёх. Само изменение
принимается, только если так высказались минимум ТРИ способа из пяти. Ровно
или хуже — это не улучшение: ничья засчитывается против изменения, потому
что по умолчанию изменение отклоняется.

ЧЕГО ЭТИ ВОРОТА НЕ УМЕЮТ — ЧИТАТЬ ОБЯЗАТЕЛЬНО

  * Они работают со списком исходов сделок в пунктах. Все оговорки проверки
    на истории (фитили внутри бара, постоянный спред, отсутствие
    проскальзывания) остаются в силе — см. backtest.py.
  * Они проверяют ТОРГОВЫЕ изменения: фильтры, сигналы, настройки риска.
    Изменение внешнего вида окна или текста подсказки прогонять здесь
    бессмысленно: у него нет сделок, и притвориться, что есть, значит
    подделать доказательство.
  * Мало сделок — не «слабое доказательство», а ОТСУТСТВИЕ доказательства.
    При выборке меньше сотни сделок ворота отвечают «отклонить» независимо
    от того, насколько красивы числа.
"""

import logging
import random

from backtest import МАЛО_СДЕЛОК, summarize

log = logging.getLogger("validation")

# ---------------------------------------------------------------- пороги ---
# Сколько способов из пяти обязаны сказать «лучше». Требование владельца.
МИНИМУМ_СПОСОБОВ = 3
# Сколько метрик из четырёх обязаны улучшиться внутри одного способа.
МИНИМУМ_МЕТРИК = 3
# На сколько окон режется история для walk forward. Четыре — компромисс:
# больше окон означает более строгую проверку, но в каждом окне остаётся
# слишком мало сделок, чтобы отличить работу настройки от шума.
ОКОН_WALK_FORWARD = 4
# Доля истории, отдаваемая «на подбор». Остаток — чистая проверка.
ДОЛЯ_ОБУЧЕНИЯ = 0.7
# Сколько раз пересобирать сделки в Monte Carlo.
ПРОГОНОВ_MONTE_CARLO = 1000
# Сколько раз тасовать метки «до»/«после» в A/B.
ПЕРЕСТАНОВОК = 2000
# Насколько редкой должна быть случайность, чтобы разнице поверили.
# 0.05 означает: случайность даёт такую же разницу реже чем в 5 случаях из 100.
ПОРОГ_СЛУЧАЙНОСТИ = 0.05
# Нижняя граница доверия в Monte Carlo: улучшение засчитывается, только если
# оно сохраняется в 95 прогонах из 100.
ДОВЕРИЕ = 0.95
# Дробная пыль двоичной арифметики — чтобы ничья не притворилась улучшением.
ПЫЛЬ = 1e-9

# Метрики и направление «лучше»: True — больше лучше, False — меньше лучше.
МЕТРИКИ = {
    "профит_фактор": True,
    "просадка": False,
    "восстановление": True,
    "ожидание": True,
}


# ------------------------------------------------------------- измерения ---
def max_drawdown(trades) -> float:
    """Самое глубокое падение от достигнутого пика, в пунктах.

    Считается по нарастающему итогу: запоминается лучший результат за всё
    время, и меряется, насколько глубоко счёт проваливался ниже него. Это то
    число, которое владелец видит на своём счёте как «минус», и то, из-за
    которого систему выключают руками, даже если она в итоге прибыльна."""
    итог = 0.0
    пик = 0.0
    просадка = 0.0
    for t in (trades or ()):
        итог += float(t)
        пик = max(пик, итог)
        просадка = max(просадка, пик - итог)
    return round(просадка, 1)


def recovery_factor(trades) -> float:
    """Итог, делённый на самую глубокую просадку.

    Отвечает на вопрос «сколько система заработала на каждый пункт боли».
    Две системы с одинаковой прибылью не равны: та, что заработала её без
    глубоких провалов, лучше. Бесконечности не выдаём — «просадки не было»
    на коротком отрезке означает мало данных, а не безрисковость."""
    просадка = max_drawdown(trades)
    if просадка <= 0:
        return 0.0
    return round(sum(float(t) for t in trades) / просадка, 2)


def metrics(trades) -> dict:
    """Четыре метрики решения плюс число сделок."""
    сводка = summarize(trades)
    return {
        "профит_фактор": сводка["профит_фактор"],
        "просадка": max_drawdown(trades),
        "восстановление": recovery_factor(trades),
        "ожидание": сводка["ожидание"],
        "сделок": сводка["сделок"],
    }


def improved(before: dict, after: dict) -> dict:
    """По каким метрикам стало лучше. Ничья засчитывается ПРОТИВ изменения."""
    лучше = {}
    for имя, больше_лучше in МЕТРИКИ.items():
        было = float(before.get(имя, 0) or 0)
        стало = float(after.get(имя, 0) or 0)
        лучше[имя] = (стало > было + ПЫЛЬ) if больше_лучше else (стало < было - ПЫЛЬ)
    return лучше


def _вердикт_по_метрикам(before_trades, after_trades) -> dict:
    """Общий кусок для способов, которые просто сравнивают два набора сделок."""
    было = metrics(before_trades)
    стало = metrics(after_trades)
    лучше = improved(было, стало)
    счёт = sum(1 for v in лучше.values() if v)
    return {
        "улучшение": счёт >= МИНИМУМ_МЕТРИК,
        "метрик_лучше": счёт,
        "было": было,
        "стало": стало,
        "по_метрикам": лучше,
    }


# --------------------------------------------------------------- способы ---
def backtest_check(before_trades, after_trades) -> dict:
    """Способ 1: вся история целиком. Самый слабый, потому что под неё и
    подгоняют. Идёт первым только для того, чтобы отсеять изменения, которые
    не помогают даже там, где им подыгрывают."""
    итог = _вердикт_по_метрикам(before_trades, after_trades)
    итог["способ"] = "backtest"
    return итог


def split_out_of_sample(trades, train_fraction: float = ДОЛЯ_ОБУЧЕНИЯ):
    """Разрезать сделки на «подбор» и «чистую проверку», сохраняя порядок.

    Резать надо строго по времени. Случайная выборка здесь была бы подделкой:
    будущее подмешалось бы в обучение."""
    ряд = list(trades or ())
    доля = min(max(float(train_fraction), 0.0), 1.0)
    граница = int(len(ряд) * доля)
    return ряд[:граница], ряд[граница:]


def out_of_sample_check(before_trades, after_trades,
                        train_fraction: float = ДОЛЯ_ОБУЧЕНИЯ) -> dict:
    """Способ 2: смотрим только тот кусок, который при подборе не трогали."""
    _, было = split_out_of_sample(before_trades, train_fraction)
    _, стало = split_out_of_sample(after_trades, train_fraction)
    итог = _вердикт_по_метрикам(было, стало)
    итог["способ"] = "out of sample"
    итог["сделок_в_проверке"] = len(стало)
    return итог


def windows(trades, count: int = ОКОН_WALK_FORWARD) -> list:
    """Порезать сделки на равные окна ПО ПОРЯДКУ, не перемешивая."""
    ряд = list(trades or ())
    n = max(int(count), 1)
    if len(ряд) < n:
        return [ряд] if ряд else []
    шаг = len(ряд) / n
    куски = []
    for i in range(n):
        начало = int(round(i * шаг))
        конец = int(round((i + 1) * шаг))
        куски.append(ряд[начало:конец])
    return куски


def walk_forward_check(before_trades, after_trades,
                       count: int = ОКОН_WALK_FORWARD) -> dict:
    """Способ 3: улучшение обязано повторяться в большинстве окон подряд.

    Изменение, которое выигрывает один месяц и проигрывает три, — это
    везение, а не улучшение. Здесь оно и отсекается."""
    было_окна = windows(before_trades, count)
    стало_окна = windows(after_trades, count)
    пар = min(len(было_окна), len(стало_окна))
    выигранных = 0
    подробно = []
    for i in range(пар):
        окно = _вердикт_по_метрикам(было_окна[i], стало_окна[i])
        подробно.append(окно["метрик_лучше"])
        if окно["улучшение"]:
            выигранных += 1
    return {
        "способ": "walk forward",
        # Большинство окон, а не половина: ровно половина — это ничья, а
        # ничья засчитывается против изменения.
        "улучшение": пар > 0 and выигранных * 2 > пар,
        "окон": пар,
        "окон_лучше": выигранных,
        "метрик_по_окнам": подробно,
    }


def _выборка(rnd, ряд, размер):
    return [ряд[rnd.randrange(len(ряд))] for _ in range(размер)]


def monte_carlo_check(before_trades, after_trades,
                      runs: int = ПРОГОНОВ_MONTE_CARLO, seed: int = 0) -> dict:
    """Способ 4: а если бы те же сделки выпали в другом составе и порядке?

    Каждый прогон случайно пересобирает обе истории (с возвратом) и считает
    разницу ожиданий. Улучшение засчитывается, только если разница осталась
    положительной в 95 прогонах из 100. Так отсеиваются результаты, которые
    держатся на двух-трёх везучих сделках."""
    было = [float(t) for t in (before_trades or ())]
    стало = [float(t) for t in (after_trades or ())]
    if not было or not стало:
        return {"способ": "monte carlo", "улучшение": False, "прогонов": 0,
                "доля_лучше": 0.0, "худший_случай": 0.0}

    rnd = random.Random(seed)
    n = max(int(runs), 1)
    разницы = []
    for _ in range(n):
        a = _выборка(rnd, было, len(было))
        b = _выборка(rnd, стало, len(стало))
        разницы.append(sum(b) / len(b) - sum(a) / len(a))
    разницы.sort()
    # Нижняя граница доверия: отступаем от худшего конца на (1 - ДОВЕРИЕ).
    край = разницы[min(int((1 - ДОВЕРИЕ) * n), n - 1)]
    доля = sum(1 for d in разницы if d > 0) / n
    return {
        "способ": "monte carlo",
        "улучшение": край > ПЫЛЬ,
        "прогонов": n,
        "доля_лучше": round(доля, 3),
        "худший_случай": round(край, 3),
    }


def ab_check(before_trades, after_trades,
             shuffles: int = ПЕРЕСТАНОВОК, seed: int = 0) -> dict:
    """Способ 5: а не случайность ли это?

    Метки «до» и «после» тасуются тысячи раз на объединённом наборе сделок.
    Если случайное деление даёт такую же разницу не реже чем в 5 случаях из
    100 — разница ничего не значит, сколько бы красиво она ни выглядела."""
    было = [float(t) for t in (before_trades or ())]
    стало = [float(t) for t in (after_trades or ())]
    if not было or not стало:
        return {"способ": "A/B", "улучшение": False, "случайность": 1.0,
                "разница": 0.0}

    наблюдаемая = sum(стало) / len(стало) - sum(было) / len(было)
    общий = было + стало
    rnd = random.Random(seed)
    n = max(int(shuffles), 1)
    не_хуже = 0
    for _ in range(n):
        rnd.shuffle(общий)
        a = общий[:len(было)]
        b = общий[len(было):]
        разница = sum(b) / len(b) - sum(a) / len(a)
        # Двусторонний счёт: случайность одинаково легко даёт разницу в любую
        # сторону, и считать только удобную нам сторону — это самообман.
        if abs(разница) >= abs(наблюдаемая) - ПЫЛЬ:
            не_хуже += 1
    # +1 в числителе и знаменателе: наблюдаемое деление тоже одно из
    # возможных, и без этой поправки при нуле совпадений получилась бы
    # «вероятность случайности 0», чего не бывает.
    случайность = (не_хуже + 1) / (n + 1)
    return {
        "способ": "A/B",
        "улучшение": наблюдаемая > ПЫЛЬ and случайность <= ПОРОГ_СЛУЧАЙНОСТИ,
        "случайность": round(случайность, 4),
        "разница": round(наблюдаемая, 3),
    }


# ----------------------------------------------------------------- ворота ---
def gate(before_trades, after_trades, seed: int = 0) -> dict:
    """Пропустить изменение или отклонить. Решение принимает КОД, не мнение.

    Возвращает подробности всех пяти способов и итог «принять»/«отклонить»."""
    было = list(before_trades or ())
    стало = list(after_trades or ())

    # Мало сделок — это не слабое доказательство, это его отсутствие.
    # Проверка идёт ДО способов: считать проценты по двадцати сделкам можно,
    # верить им нельзя.
    если_мало = min(len(было), len(стало))
    if если_мало < МАЛО_СДЕЛОК:
        return {
            "решение": "отклонить",
            "причина": (f"Мало сделок: {если_мало}. Нужно хотя бы "
                        f"{МАЛО_СДЕЛОК}, иначе числа означают везение, а не "
                        f"работу изменения."),
            "способов_за": 0,
            "способы": [],
        }

    способы = [
        backtest_check(было, стало),
        out_of_sample_check(было, стало),
        walk_forward_check(было, стало),
        monte_carlo_check(было, стало, seed=seed),
        ab_check(было, стало, seed=seed),
    ]
    за = sum(1 for с in способы if с.get("улучшение"))
    принять = за >= МИНИМУМ_СПОСОБОВ
    return {
        "решение": "принять" if принять else "отклонить",
        "причина": (f"За изменение {за} способов из {len(способы)}; "
                    f"нужно {МИНИМУМ_СПОСОБОВ}."),
        "способов_за": за,
        "способы": способы,
    }


def describe(result: dict) -> str:
    """Решение словами — для журнала и для владельца."""
    строки = [f"РЕШЕНИЕ: {result.get('решение', '?').upper()}. "
              f"{result.get('причина', '')}"]
    for с in result.get("способы", ()):
        знак = "+" if с.get("улучшение") else "-"
        строки.append(f"  [{знак}] {с.get('способ')}")
    return "\n".join(строки)
