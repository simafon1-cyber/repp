"""manifest.py — ПАСПОРТ ПРОГОНА.

ЗАЧЕМ

Отчёт по И6 утверждал: «все числа получены прогоном». Внешний
проверяющий взял чистую копию ветки, запустил прогон — и получил
«данных нет». То есть проверить утверждение было НЕЧЕМ: истории в
репозитории не было, журнала не было, и никакого способа убедиться, что
цифры вообще из этих данных, тоже не было.

Слова «получено прогоном» без возможности этот прогон повторить стоят
ровно столько же, сколько посчитанная вручную таблица, которую И6 и
исправлял. Тот же порок, только на другом уровне.

ЧТО ЗАПИСЫВАЕТСЯ

Паспорт пишется ДО прогона и содержит всё, чем один прогон отличается от
другого:

  * ревизия кода (git commit) и время запуска в UTC;
  * инструменты, таймфрейм, период и число свечей;
  * SHA-256 КАЖДОГО файла данных — сырого и очищенного;
  * параметры выхода и зерно случайности;
  * версия модели издержек и SHA-256 самого файла costs.py.

После прогона рядом ложится файл результатов и SHA-256 журнала сделок.

СМЫСЛ ХЭШЕЙ

Хэш — это отпечаток файла. Если данные подменили хоть одной свечой,
отпечаток изменится, и совпадение чисел станет невозможно объяснить
совпадением. Без хэшей «те самые данные» — это слова.
"""

import hashlib
import json
import os
import subprocess
from datetime import datetime, timezone

ИМЯ = "research_manifest.json"
ИМЯ_РЕЗУЛЬТАТОВ = "research_results.json"
ВЕРСИЯ = 1


def хэш(путь: str) -> str:
    """SHA-256 файла. Пусто — файла нет или не читается."""
    h = hashlib.sha256()
    try:
        with open(путь, "rb") as f:
            for кусок in iter(lambda: f.read(1 << 20), b""):
                h.update(кусок)
    except OSError:
        return ""
    return h.hexdigest()


def ревизия() -> dict:
    """Какая версия кода считала. Без неё повтор бессмыслен."""
    def команда(*аргументы):
        try:
            из = subprocess.run(аргументы, capture_output=True, timeout=10,
                                text=True, check=False)
            return из.stdout.strip()
        except Exception:  # noqa: BLE001
            return ""

    грязно = команда("git", "status", "--porcelain")
    return {
        "commit": команда("git", "rev-parse", "HEAD"),
        "ветка": команда("git", "rev-parse", "--abbrev-ref", "HEAD"),
        # Если в рабочей копии есть незакоммиченные правки, прогон уже НЕ
        # соответствует ни одной ревизии. Это надо видеть сразу.
        "рабочая_копия_чистая": не_пусто(грязно) is False,
        "изменённых_файлов": len([с for с in грязно.splitlines() if с.strip()]),
    }


def не_пусто(текст) -> bool:
    return bool(str(текст or "").strip())


def файлы_данных(папка: str, символы, таймфрейм: str) -> list:
    """Отпечатки всех файлов, из которых читались свечи."""
    записи = []
    for имя in символы:
        for вид, шаблон in (("сырые", "raw/{s}_{tf}.csv"),
                            ("описание", "raw/{s}_{tf}.meta.json"),
                            ("очищенные", "clean/{s}_{tf}.csv")):
            путь = os.path.join(папка, шаблон.format(s=имя, tf=таймфрейм))
            записи.append({
                "инструмент": имя,
                "вид": вид,
                "файл": os.path.relpath(путь, os.path.dirname(папка)),
                "есть": os.path.exists(путь),
                "байт": os.path.getsize(путь) if os.path.exists(путь) else 0,
                "sha256": хэш(путь),
            })
    return записи


def собрать(папка_данных: str, символы, таймфрейм: str, ряды: dict,
            параметры: dict, модель_издержек: dict) -> dict:
    """Паспорт целиком. Собирается ДО прогона."""
    периоды = {}
    for имя, значение in (ряды or {}).items():
        ряд = значение[0] if isinstance(значение, tuple) else значение
        периоды[имя] = {
            "свечей": ряд["n"],
            "первая_свеча_utc": _время(ряд["time"][0]),
            "последняя_свеча_utc": _время(ряд["time"][-1]),
            "первая_метка": int(ряд["time"][0]),
            "последняя_метка": int(ряд["time"][-1]),
        }

    return {
        "версия_паспорта": ВЕРСИЯ,
        "запуск_utc": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S"),
        "код": ревизия(),
        "таймфрейм": таймфрейм,
        "инструменты": list(символы),
        "период": периоды,
        "параметры": параметры,
        "модель_издержек": модель_издержек,
        "данные": файлы_данных(папка_данных, символы, таймфрейм),
    }


def _время(метка) -> str:
    try:
        return datetime.fromtimestamp(int(метка), tz=timezone.utc).strftime(
            "%Y-%m-%d %H:%M")
    except (TypeError, ValueError, OSError, OverflowError):
        return str(метка)


def записать(паспорт: dict, путь: str) -> str:
    папка = os.path.dirname(os.path.abspath(путь))
    if папка:
        os.makedirs(папка, exist_ok=True)
    with open(путь, "w", encoding="utf-8") as f:
        json.dump(паспорт, f, ensure_ascii=False, indent=2, sort_keys=False)
    return путь


def кратко(паспорт: dict) -> str:
    """Что показать человеку перед прогоном."""
    код = паспорт.get("код", {})
    строки = [
        f"Ревизия кода: {код.get('commit', '?')[:12]} "
        f"({код.get('ветка', '?')})",
    ]
    if not код.get("рабочая_копия_чистая", True):
        строки.append(
            f"  ВНИМАНИЕ: в рабочей копии {код.get('изменённых_файлов', '?')} "
            f"изменённых файлов — прогон НЕ соответствует ни одной ревизии")
    строки.append(f"Запуск (UTC): {паспорт.get('запуск_utc', '?')}")

    данные = паспорт.get("данные", [])
    нет = [д["файл"] for д in данные if not д["есть"]]
    строки.append(f"Файлов данных: {len(данные)}, "
                  f"из них отсутствует {len(нет)}")
    for д in данные:
        if д["есть"] and д["вид"] == "очищенные":
            строки.append(f"    {д['инструмент']:<8} {д['sha256'][:16]}…  "
                          f"{д['байт'] // 1024} КБ")
    return "\n".join(строки)
