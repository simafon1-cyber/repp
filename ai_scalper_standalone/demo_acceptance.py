"""demo_acceptance.py — СНИМКИ СОСТОЯНИЯ СЧЁТА ДЛЯ ПРОГОНА НА ДЕМО.

ЗАЧЕМ ЭТО НУЖНО

Всё, что проверено в И1–И5 — частичное исполнение, неясные ответы
брокера, аварийная остановка, сверка после перезапуска, — проверено на
ПОДДЕЛЬНОМ брокере. Подделка вела настоящий счёт и отвечала как
настоящая, но настоящей она не была. В каждом отчёте это записано
отдельной строкой, и это не формальность: подделка отвечает так, как я
её научил, а брокер — как ему вздумается.

Прогон на демо — первое настоящее свидетельство. Но свидетельство
годится только тогда, когда его можно перепроверить. «Я посмотрел, всё
было нормально» — не свидетельство. Скриншот — тоже: на нём не видно ни
времени по UTC, ни номера заявки, ни того, что было за секунду до.

Поэтому здесь снимаются СНИМКИ: полное состояние счёта на момент
времени, записанное в файл с хешем. До прогона, после прогона, и в любой
момент между. Потом их можно сравнить и увидеть, что именно произошло —
а не вспоминать.

ЧТО ЭТОТ МОДУЛЬ НЕ ДЕЛАЕТ

Не торгует. Совсем. Он только СПРАШИВАЕТ терминал.

Это не обещание, а устройство: в модуле нет ни одного вызова order_send
или order_check, и на это есть отдельная проверка, которая разбирает
дерево кода и падает, если такой вызов появится
(tests/test_demo_acceptance.py).

Он также не запускает и не останавливает бота — прогон ведёт человек,
обычным окном программы. Снимки снимаются рядом.

ГЛАВНОЕ ПРАВИЛО ЭТОГО ФАЙЛА: «НЕ СПРОСИЛОСЬ» — НЕ «НЕТ»

Раздел 5 правил проекта: неясный исход — не отказ. То же и здесь. Если
терминал не ответил на вопрос о позициях, записать «позиций нет» —
значит соврать в самом опасном месте: по такому снимку потом решат, что
сделка не открылась.

Поэтому каждый раздел снимка имеет одно из двух состояний: ОТВЕТ (пусть
даже пустой) или НЕИЗВЕСТНО. Пустой список и «спросить не удалось» —
разные вещи, и в файле они выглядят по-разному.

ВТОРОЕ ПРАВИЛО: ФИЛЬТР НЕ ВЫБРАСЫВАЕТ, А ПОМЕЧАЕТ

Аудит нашёл здесь блокирующую ошибку (P0-2). Снимок спрашивал позиции
сразу с фильтром по своему magic — то есть чужие позиции физически не
попадали в файл. А одно из заранее записанных условий приёмки звучит
«ни одной позиции с чужим magic». Проверить его по такому снимку
нельзя: в нём чужих позиций нет ПО УСТРОЙСТВУ, а не по факту. Условие
отчиталось бы выполненным на счёте, где чужая позиция есть.

Теперь спрашивается ВСЁ, без фильтра, и записывается целиком. Разделение
на «свои» и «чужие» делается уже по записанному — и обе части лежат в
файле рядом.

ТРЕТЬЕ ПРАВИЛО: СВЯЗЬ ДОКАЗЫВАЕТСЯ ПО НОМЕРУ, А НЕ ПО СОВПАДЕНИЮ ВРЕМЕНИ

Там же (P0-2) нашлось второе. Условие «ни одной позиции без сделки в
истории» проверялось так: появились ли позиции и появились ли вообще
хоть какие-то сделки за то же окно. Это не доказательство связи. Одна
посторонняя сделка в том же окне прикрывала бы позицию, у которой своей
истории нет вовсе. А сделка, открывшая позицию раньше окна, вообще не
попадала в запрос.

Теперь для КАЖДОЙ своей позиции отдельно спрашивается её собственная
история по номеру позиции. Ответов три: сделки нашлись, ответ пуст,
спросить не удалось. Если связь не доказана — так и пишется
«НЕ ДОКАЗАНО». Не «успех» и не «провал»: не доказано.
"""

from __future__ import annotations

import argparse
import hashlib
import hmac
import json
import os
import sys
from datetime import datetime, timedelta, timezone

# НЕИЗВЕСТНО — не «пусто». См. шапку файла.
НЕИЗВЕСТНО = "НЕИЗВЕСТНО: спросить у терминала не удалось"


def _просто(значение):
    """Превратить ответ терминала в то, что ложится в JSON.

    Терминал отдаёт свои собственные объекты (namedtuple-подобные). Класть
    в файл их repr() бессмысленно: прочитать потом нельзя. Разворачиваем в
    обычный словарь."""
    if значение is None:
        return None
    if isinstance(значение, (str, int, float, bool)):
        return значение
    if isinstance(значение, (list, tuple)):
        return [_просто(э) for э in значение]
    if isinstance(значение, dict):
        return {str(к): _просто(з) for к, з in значение.items()}
    if hasattr(значение, "_asdict"):
        return _просто(значение._asdict())
    # Объекты терминала: собираем открытые поля.
    поля = {}
    for имя in dir(значение):
        if имя.startswith("_"):
            continue
        try:
            з = getattr(значение, имя)
        except Exception:  # noqa: BLE001
            continue
        if callable(з):
            continue
        поля[имя] = _просто(з)
    return поля or str(значение)


def _спросить(что, вопрос):
    """Задать терминалу вопрос и честно записать, чем это кончилось.

    Возвращает (ответ, получилось). `получилось` False означает ровно
    одно: мы не знаем. Не «нет», не «пусто» — НЕ ЗНАЕМ."""
    try:
        ответ = вопрос()
    except Exception as e:  # noqa: BLE001
        return f"{НЕИЗВЕСТНО} ({что}: {type(e).__name__}: {e})", False
    if ответ is None:
        return f"{НЕИЗВЕСТНО} ({что}: терминал вернул пустоту)", False
    return _просто(ответ), True


ДОКАЗАНО = "ДОКАЗАНО"
НЕ_ДОКАЗАНО = "НЕ ДОКАЗАНО"
ВЫПОЛНЕНО = "ВЫПОЛНЕНО"
НЕ_ВЫПОЛНЕНО = "НЕ ВЫПОЛНЕНО"


def _строгий_терминал():
    """Прямой доступ к терминалу — БЕЗ защитных значений по умолчанию.

    Зачем отдельно от mt5_connector. В торговом коде осторожные значения по
    умолчанию правильны: get_spread_points() отдаёт 999999, когда спросить
    не вышло, и программа из-за огромного спреда просто не входит в сделку.
    Это хорошая защита.

    Но в СНИМКЕ такое значение — ложь. Оно выглядит как полученный ответ:
    в файле окажется число, и по нему потом будут судить, каким был спред.
    Аудит назвал это P1-1. Поэтому здесь спрашивается напрямую, и «не
    ответил» остаётся «не ответил».

    Ни одно значение по умолчанию в торговой логике при этом не меняется —
    там всё остаётся как было."""
    import MetaTrader5 as mt5
    return mt5


def _спросить_строго(что, вопрос):
    """То же, что _спросить, но для прямых вопросов терминалу."""
    try:
        ответ = вопрос()
    except Exception as e:  # noqa: BLE001
        return f"{НЕИЗВЕСТНО} ({что}: {type(e).__name__}: {e})", False
    if ответ is None:
        return f"{НЕИЗВЕСТНО} ({что}: терминал вернул пустоту)", False
    return _просто(ответ), True


def _свои_и_чужие(записи, magic):
    """Разделить записи по magic, ничего не выбрасывая.

    Возвращает (свои, чужие). Если спросить не удалось — (None, None):
    из «неизвестно» ничего не выделишь."""
    if not isinstance(записи, list):
        return None, None
    свои, чужие = [], []
    for з in записи:
        if not isinstance(з, dict):
            чужие.append(з)
            continue
        (свои if з.get("magic") == magic else чужие).append(з)
    return свои, чужие


def история_позиции(mt5c, позиция) -> dict:
    """Собственная история КОНКРЕТНОЙ позиции — по её номеру.

    Это и есть доказательство связи «позиция ↔ сделка». Совпадение по
    времени, инструменту или направлению доказательством не является: в то
    же окно попадает и чужая сделка, и сделка второго экземпляра
    программы.

    Три исхода, и они разные:
      ДОКАЗАНО     — история нашлась, номера сделок записаны;
      НЕ ДОКАЗАНО  — терминал ответил пустотой либо не ответил вовсе.

    Пустой ответ НЕ считается доказательством отсутствия. Он считается
    отсутствием доказательства — это разные вещи, и вторая безопаснее."""
    номер = позиция.get("ticket") if isinstance(позиция, dict) else None
    итог = {
        "номер_позиции": номер,
        "identifier": позиция.get("identifier") if isinstance(позиция, dict) else None,
        "magic": позиция.get("magic") if isinstance(позиция, dict) else None,
        "symbol": позиция.get("symbol") if isinstance(позиция, dict) else None,
        "volume": позиция.get("volume") if isinstance(позиция, dict) else None,
    }
    # У позиции есть свой номер (ticket) и номер, под которым она живёт в
    # истории (identifier). Обычно они совпадают, но не обязаны: после
    # частичного закрытия или на неттинговом счёте бывает иначе. Спрашиваем
    # по обоим и записываем, что откуда пришло.
    ключ = итог["identifier"] or номер
    if not ключ:
        итог["состояние"] = НЕ_ДОКАЗАНО
        итог["почему"] = "у позиции нет номера — спросить нечем"
        итог["сделки"] = НЕИЗВЕСТНО
        return итог

    ответ, получилось = _спросить(f"deals_by_position({ключ})",
                                  lambda: mt5c.deals_by_position(ключ))
    if not получилось:
        итог["состояние"] = НЕ_ДОКАЗАНО
        итог["почему"] = "спросить историю этой позиции не удалось"
        итог["сделки"] = ответ
        return итог
    if not ответ:
        итог["состояние"] = НЕ_ДОКАЗАНО
        итог["почему"] = ("терминал ответил пустотой: своей истории у этой "
                          "позиции не видно. Это НЕ доказывает, что её нет — "
                          "история может отставать.")
        итог["сделки"] = []
        return итог

    итог["состояние"] = ДОКАЗАНО
    итог["сделки"] = ответ
    итог["номера_сделок"] = [с.get("ticket") for с in ответ
                             if isinstance(с, dict)]
    итог["номера_ордеров"] = sorted({с.get("order") for с in ответ
                                     if isinstance(с, dict) and с.get("order")})
    return итог


def снимок(символы=None, magic=None, часов_истории: int = 24) -> dict:
    """Полное состояние счёта на сейчас.

    Ничего не отправляет. Только спрашивает."""
    import mt5_connector as mt5c
    import config as cfg

    if символы is None:
        символы = list(getattr(cfg, "SYMBOLS", []))
    if magic is None:
        magic = getattr(cfg, "MAGIC_NUMBER", None)

    сейчас = datetime.now(timezone.utc)
    с_какого = сейчас - timedelta(hours=часов_истории)

    данные = {
        "время_utc": сейчас.isoformat(),
        "окно_истории_utc": [с_какого.isoformat(), сейчас.isoformat()],
        "magic": magic,
        "символы_из_настроек": символы,
        "не_спросилось": [],
    }

    def записать(ключ, что, вопрос):
        ответ, получилось = _спросить(что, вопрос)
        данные[ключ] = ответ
        if not получилось:
            данные["не_спросилось"].append(ключ)
        return ответ, получилось

    записать("счёт", "account_info", mt5c.get_account_info)

    # ПОЗИЦИИ И ЗАЯВКИ — БЕЗ ФИЛЬТРА. Фильтр по magic выбрасывал бы чужие
    # записи ещё до записи в файл, и условие «нет чужих позиций» стало бы
    # непроверяемым (P1 аудита стал P0-2). Спрашиваем всё, делим потом.
    все_позиции, поз_есть = записать(
        "позиции_все", "positions_get(без фильтра)",
        lambda: mt5c.positions_or_none())
    все_заявки, зая_есть = записать(
        "активные_заявки_все", "orders_get(без фильтра)",
        lambda: mt5c.orders_or_none())

    свои_п, чужие_п = _свои_и_чужие(все_позиции if поз_есть else None, magic)
    свои_з, чужие_з = _свои_и_чужие(все_заявки if зая_есть else None, magic)
    данные["позиции_свои"] = свои_п if свои_п is not None else НЕИЗВЕСТНО
    данные["позиции_чужие"] = чужие_п if чужие_п is not None else НЕИЗВЕСТНО
    данные["активные_заявки_свои"] = свои_з if свои_з is not None else НЕИЗВЕСТНО
    данные["активные_заявки_чужие"] = чужие_з if чужие_з is not None else НЕИЗВЕСТНО

    записать("сделки_за_окно", "history_deals_get",
             lambda: mt5c.deals_or_none(с_какого, сейчас))

    # ИСТОРИЯ КАЖДОЙ СВОЕЙ ПОЗИЦИИ ПО ЕЁ НОМЕРУ. Именно это доказывает
    # связь «позиция ↔ сделка». Окно истории здесь не при чём: спрашиваем
    # по номеру, а не по времени, поэтому сделка, открывшая позицию до
    # начала окна, тоже находится.
    if isinstance(свои_п, list):
        истории = [история_позиции(mt5c, п) for п in свои_п]
        данные["история_своих_позиций"] = истории
        не_доказаны = [и["номер_позиции"] for и in истории
                       if и.get("состояние") != ДОКАЗАНО]
        if не_доказаны:
            данные["не_спросилось"].append(
                f"история позиций {не_доказаны}")
    else:
        данные["история_своих_позиций"] = НЕИЗВЕСТНО

    # РАЗРЕШЕНИЕ ТОРГОВАТЬ — СТРОГО. trading_permission_status() при
    # молчании терминала отвечает {"ok": true, "problems": []}, то есть
    # «всё в порядке». В торговой логике это терпимо, в доказательном
    # снимке — нет (P1-1). Спрашиваем напрямую.
    try:
        mt5 = _строгий_терминал()
    except Exception as e:  # noqa: BLE001
        данные["разрешение_торговать"] = f"{НЕИЗВЕСТНО} (терминал недоступен: {e})"
        данные["не_спросилось"].append("разрешение_торговать")
        mt5 = None

    if mt5 is not None:
        терм, т_есть = _спросить_строго("terminal_info", mt5.terminal_info)
        сч, с_есть = _спросить_строго("account_info", mt5.account_info)
        if т_есть and с_есть:
            данные["разрешение_торговать"] = {
                "терминалу_разрешено": терм.get("trade_allowed"),
                "счёту_разрешено": сч.get("trade_allowed"),
                "эксперты_разрешены": терм.get("trade_expert"),
            }
        else:
            данные["разрешение_торговать"] = {
                "терминал": терм if т_есть else терм,
                "счёт": сч if с_есть else сч,
                "итог": НЕИЗВЕСТНО,
            }
            данные["не_спросилось"].append("разрешение_торговать")

    инструменты = {}
    for символ in символы:
        по_символу = {}
        if mt5 is None:
            по_символу["сведения"] = f"{НЕИЗВЕСТНО} (терминал недоступен)"
            данные["не_спросилось"].append(f"{символ}/сведения")
            инструменты[символ] = по_символу
            continue

        # СВЕДЕНИЯ ОБ ИНСТРУМЕНТЕ — СТРОГО, одним ответом. Раньше спред и
        # пункт брались через торговые обёртки, которые при молчании
        # терминала подставляют 999999 и 0.0001. В файле это выглядело как
        # настоящие числа (P1-1).
        сведения, есть = _спросить_строго(f"{символ}/symbol_info",
                                          lambda с=символ: mt5.symbol_info(с))
        if есть:
            по_символу["спред_пунктов"] = сведения.get("spread")
            по_символу["пункт"] = сведения.get("point")
            по_символу["цифр"] = сведения.get("digits")
            по_символу["шаг_объёма"] = сведения.get("volume_step")
            по_символу["режим_торговли"] = сведения.get("trade_mode")
        else:
            по_символу["спред_пунктов"] = сведения
            по_символу["пункт"] = сведения
            данные["не_спросилось"].append(f"{символ}/сведения")

        цена, ц_есть = _спросить_строго(f"{символ}/symbol_info_tick",
                                        lambda с=символ: mt5.symbol_info_tick(с))
        по_символу["цена"] = цена
        if not ц_есть:
            данные["не_спросилось"].append(f"{символ}/цена")

        инструменты[символ] = по_символу
    данные["инструменты"] = инструменты

    # Итог одной строкой — чтобы человек увидел главное, не читая JSON.
    данные["всё_ли_спросилось"] = not данные["не_спросилось"]
    данные["условия"] = проверить_условия(данные)
    return данные


def проверить_условия(данные: dict) -> dict:
    """Заранее записанные условия О1 и О2 — по фактам снимка.

    Оба условия имеют ТРИ исхода, а не два. «Не доказано» — отдельный
    исход, и он не считается выполнением. Иначе молчание терминала
    засчитывалось бы как успех, а это ровно тот способ обмануть себя,
    против которого написан весь протокол."""
    итог = {}

    # О1: у каждой своей позиции есть своя история по номеру.
    истории = данные.get("история_своих_позиций")
    if not isinstance(истории, list):
        итог["О1"] = {
            "состояние": НЕ_ДОКАЗАНО,
            "пояснение": "список своих позиций не получен — проверять нечего и не на чем",
        }
    elif not истории:
        итог["О1"] = {
            "состояние": ВЫПОЛНЕНО,
            "пояснение": "своих открытых позиций нет — нечему быть без истории",
            "позиций": 0,
        }
    else:
        без_истории = [и.get("номер_позиции") for и in истории
                       if и.get("состояние") != ДОКАЗАНО]
        итог["О1"] = {
            "состояние": ВЫПОЛНЕНО if not без_истории else НЕ_ДОКАЗАНО,
            "позиций": len(истории),
            "без_доказанной_истории": без_истории,
            "пояснение": ("у каждой позиции найдена своя история по номеру"
                          if not без_истории else
                          "для этих позиций связь с историей НЕ доказана"),
        }

    # О2: чужих позиций нет.
    чужие = данные.get("позиции_чужие")
    if not isinstance(чужие, list):
        итог["О2"] = {
            "состояние": НЕ_ДОКАЗАНО,
            "пояснение": "полный список позиций не получен — о чужих ничего не известно",
        }
    else:
        итог["О2"] = {
            "состояние": ВЫПОЛНЕНО if not чужие else НЕ_ВЫПОЛНЕНО,
            "чужих_позиций": len(чужие),
            "номера": [п.get("ticket") for п in чужие if isinstance(п, dict)],
            "пояснение": ("чужих позиций на счёте нет" if not чужие else
                          "на счёте есть позиции с чужим magic — они перечислены "
                          "в разделе «позиции_чужие» снимка"),
        }

    итог["всё_ли_выполнено"] = all(
        з.get("состояние") == ВЫПОЛНЕНО for з in итог.values()
        if isinstance(з, dict))
    return итог


# Имя переменной окружения с ключом подписи. Сам ключ НЕ хранится ни в
# репозитории, ни в config.py, ни в файле снимка — иначе подпись теряет
# смысл: кто может править файл, тот прочитает и ключ рядом.
ПЕРЕМЕННАЯ_КЛЮЧА = "DEMO_ACCEPTANCE_KEY"

ОБЫЧНЫЙ = "sha256"
ПОДПИСЬ = "hmac-sha256"


def ключ_подписи() -> str:
    """Ключ из окружения. Пусто — подписи не будет, только отпечаток."""
    return os.environ.get(ПЕРЕМЕННАЯ_КЛЮЧА, "").strip()


# Версия формата подписи. Входит В ПОДПИСЬ — иначе завтрашнее изменение
# правил подсчёта можно будет выдать за вчерашний файл.
ВЕРСИЯ_ФОРМАТА = 2


def _подписываемое(данные: dict, защита: str) -> bytes:
    """Что именно уходит под подпись.

    ПОЧЕМУ СЮДА ВХОДЯТ НЕ ТОЛЬКО ДАННЫЕ

    Первая версия подписывала один лишь снимок. Тип защиты («обычный
    отпечаток» или «подпись») лежал в том же файле, но САМ НЕ ПОДПИСЫВАЛСЯ,
    а чтение брало алгоритм проверки именно оттуда.

    Из этого получалась дыра, которую аудит воспроизвёл на факте. Тот, у
    кого ключа нет, мог: поправить данные → переставить тип защиты с
    «подпись» на «обычный отпечаток» → посчитать обычный SHA-256. Чтение
    послушно переключалось на обычную проверку и принимало файл. Подпись
    защищала данные, но не защищала запись о том, чем они защищены.

    Теперь тип защиты и версия формата входят в подписываемые байты.
    Переставить их, не зная ключа, нельзя."""
    тело = json.dumps(данные, ensure_ascii=False, sort_keys=True,
                      separators=(",", ":"))
    return f"{ВЕРСИЯ_ФОРМАТА}\n{защита}\n{тело}".encode("utf-8")


def хеш(данные: dict, ключ: str = "", защита: str = "") -> str:
    """Отпечаток снимка.

    ЧЕСТНО О ТОМ, ЧТО ЭТО ЗАЩИЩАЕТ, А ЧТО НЕТ.

    Без ключа это обычный SHA-256, посчитанный из тех же данных и лежащий
    в том же файле. Он ловит СЛУЧАЙНУЮ или НЕСОГЛАСОВАННУЮ правку: открыли
    файл, поправили число, забыли пересчитать отпечаток — и чтение
    откажется. Этого достаточно, чтобы снимок не «поплыл» незаметно.

    Но от УМЫШЛЕННОЙ подмены он не защищает, и говорить обратное нельзя.
    Кто правит файл, тот пересчитает и отпечаток — считается он из
    открытых данных, без секрета. Аудит указал на это отдельно (P1-2), и
    формулировка здесь сужена до правды.

    С ключом (переменная окружения DEMO_ACCEPTANCE_KEY) считается HMAC —
    подпись, которую без ключа не подделать. Ключ в файл не попадает."""
    if not защита:
        защита = ПОДПИСЬ if ключ else ОБЫЧНЫЙ
    текст = _подписываемое(данные, защита)
    if ключ:
        return hmac.new(ключ.encode("utf-8"), текст, hashlib.sha256).hexdigest()
    return hashlib.sha256(текст).hexdigest()


def записать_снимок(папка: str, метка: str, данные: dict) -> str:
    """Положить снимок в файл вместе с его отпечатком.

    Имя файла содержит время: снимки не перезаписывают друг друга, даже
    если метку повторили. Потерять снимок «до» из-за опечатки нельзя."""
    os.makedirs(папка, exist_ok=True)
    когда = данные["время_utc"].replace(":", "-").replace("+00-00", "Z")
    имя = f"снимок_{метка}_{когда}.json"
    путь = os.path.join(папка, имя)

    ключ = ключ_подписи()
    защита = ПОДПИСЬ if ключ else ОБЫЧНЫЙ
    завёрнутый = {
        "метка": метка,
        "снимок": данные,
        "версия_формата": ВЕРСИЯ_ФОРМАТА,
        "хеш_снимка": хеш(данные, ключ, защита),
        # Чем именно защищён файл — написано в самом файле, чтобы читающий
        # не гадал и не принимал отпечаток за подпись.
        "защита": защита,
        "защита_от": ("умышленной подмены (ключ хранится вне файла)" if ключ
                      else "случайной или несогласованной правки; "
                           "от умышленной подмены НЕ защищает"),
    }
    текст = json.dumps(завёрнутый, ensure_ascii=False, indent=2)

    временный = путь + ".tmp"
    with open(временный, "w", encoding="utf-8") as f:
        f.write(текст)
        f.flush()
        os.fsync(f.fileno())
    os.replace(временный, путь)
    try:
        d = os.open(папка, os.O_RDONLY)
        try:
            os.fsync(d)
        finally:
            os.close(d)
    except (OSError, AttributeError):
        # На некоторых системах папку синхронизировать нельзя. Сам файл
        # уже записан и переименован — этого достаточно.
        pass
    return путь


def прочитать_снимок(путь: str) -> dict:
    """Прочитать снимок и сверить его отпечаток.

    Что именно сверяется, зависит от того, чем файл был защищён:

      * обычный отпечаток — ловит случайную или несогласованную правку;
      * подпись (HMAC) — ловит и умышленную, но только если ключ на месте.

    Если файл подписан, а ключа нет, чтение НЕ делает вид, что всё
    хорошо: оно отказывается. Сказать «сходится», не проверив, — хуже,
    чем сказать «проверить нечем»."""
    with open(путь, encoding="utf-8") as f:
        завёрнутый = json.load(f)
    данные = завёрнутый["снимок"]
    было = завёрнутый.get("хеш_снимка", "")
    защита = завёрнутый.get("защита", ОБЫЧНЫЙ)

    ключ = ключ_подписи()

    if защита == ПОДПИСЬ and not ключ:
        raise ValueError(
            f"Снимок {путь} подписан ключом, а ключа нет.\n"
            f"Задайте переменную окружения {ПЕРЕМЕННАЯ_КЛЮЧА} тем же "
            f"значением, каким снимок подписывали.\n"
            "Без ключа подпись не проверяется — и делать вид, что она "
            "сошлась, нельзя.")

    # ЗАПРЕТ ПОНИЖЕНИЯ ЗАЩИТЫ.
    #
    # Ключ задан — значит идёт доказательная приёмка, и в ней принимаются
    # ТОЛЬКО подписанные снимки. Отказ происходит ДО подсчёта хеша: иначе
    # мы посчитали бы обычный SHA-256 по подделанному файлу и признали его
    # сошедшимся. Ровно так дыра и работала.
    #
    # Если надо прочитать старый неподписанный снимок — уберите ключ из
    # окружения. Это осознанное действие, а не молчаливое послабление.
    if ключ and защита != ПОДПИСЬ:
        raise ValueError(
            f"Снимок {путь} НЕ подписан (защита: «{защита}»), а ключ задан.\n"
            "Идёт доказательная приёмка — в ней принимаются только "
            "подписанные снимки.\n"
            "Так выглядела бы подмена: правим данные, переставляем тип "
            "защиты на обычный отпечаток и пересчитываем его без ключа.\n"
            f"Чтобы прочитать неподписанный снимок намеренно, уберите "
            f"переменную окружения {ПЕРЕМЕННАЯ_КЛЮЧА}.")

    if защита != ПОДПИСЬ:
        ключ = ""      # файл без подписи проверяем обычным отпечатком

    # Версия формата тоже входит в подпись — сверяем ту, что записана.
    версия = завёрнутый.get("версия_формата", 1)
    if версия != ВЕРСИЯ_ФОРМАТА:
        raise ValueError(
            f"Снимок {путь} записан по другой версии формата "
            f"({версия}, сейчас {ВЕРСИЯ_ФОРМАТА}).\n"
            "Сверить его этой программой нельзя — правила подсчёта "
            "отпечатка изменились.")

    стало = хеш(данные, ключ, защита)
    if было != стало:
        raise ValueError(
            f"Снимок {путь} изменён после записи.\n"
            f"  записан с отпечатком: {было}\n"
            f"  сейчас отпечаток:     {стало}\n"
            "Такой снимок доказательством быть не может.")
    return завёрнутый


def _номера(записи, поле):
    """Номера из списка записей. Пусто, если спросить не удалось."""
    if not isinstance(записи, list):
        return None
    номера = set()
    for з in записи:
        if isinstance(з, dict) and поле in з:
            номера.add(з[поле])
    return номера


def сверить(до: dict, после: dict) -> dict:
    """Что изменилось между двумя снимками.

    Если хотя бы в одном снимке нужный раздел не спросился, разница по
    нему НЕ вычисляется: из «неизвестно» вычесть нельзя. В таком случае
    так и пишется, а не выдаётся ноль."""
    итог = {"неизвестно": [], "предупреждения": []}

    for ключ, поле, имя in (("позиции_свои", "ticket", "позиции"),
                            ("активные_заявки_свои", "ticket", "заявки"),
                            ("сделки_за_окно", "ticket", "сделки"),
                            ("позиции_чужие", "ticket", "чужие_позиции")):
        было = _номера(до.get(ключ), поле)
        стало = _номера(после.get(ключ), поле)
        if было is None or стало is None:
            итог["неизвестно"].append(имя)
            итог[f"{имя}_появились"] = НЕИЗВЕСТНО
            итог[f"{имя}_исчезли"] = НЕИЗВЕСТНО
            continue
        итог[f"{имя}_появились"] = sorted(стало - было)
        итог[f"{имя}_исчезли"] = sorted(было - стало)

    for ключ, имя in (("balance", "баланс"), ("equity", "средства")):
        сч_до = до.get("счёт")
        сч_после = после.get("счёт")
        if isinstance(сч_до, dict) and isinstance(сч_после, dict) \
                and ключ in сч_до and ключ in сч_после:
            итог[f"{имя}_было"] = сч_до[ключ]
            итог[f"{имя}_стало"] = сч_после[ключ]
            итог[f"{имя}_разница"] = round(сч_после[ключ] - сч_до[ключ], 2)
        else:
            итог["неизвестно"].append(имя)
            итог[f"{имя}_разница"] = НЕИЗВЕСТНО

    # СВЯЗНОСТЬ БЕРЁТСЯ ИЗ СНИМКА, А НЕ ИЗ РАЗНИЦЫ.
    #
    # Раньше здесь стояла проверка «появились позиции, но не появилось
    # сделок». Она выглядела как проверка связи, но связью не была: одна
    # посторонняя сделка в том же окне делала предупреждение молчаливым,
    # а позиция без собственной истории проходила незамеченной. Аудит
    # назвал это блокирующим (P0-2).
    #
    # Настоящая связь доказывается по номеру каждой позиции — это делает
    # сам снимок (история_своих_позиций). Здесь мы только переносим его
    # вывод наружу, ничего не досочиняя.
    итог["условия_после"] = после.get("условия", НЕИЗВЕСТНО)
    условия = после.get("условия")
    if isinstance(условия, dict):
        for имя, з in условия.items():
            if not isinstance(з, dict):
                continue
            if з.get("состояние") != ВЫПОЛНЕНО:
                итог["предупреждения"].append(
                    f"{имя}: {з.get('состояние')} — {з.get('пояснение')}")
    else:
        итог["предупреждения"].append(
            "В снимке «после» нет раздела условий — проверить О1 и О2 нечем.")

    чужие = итог.get("чужие_позиции_появились")
    if isinstance(чужие, list) and чужие:
        итог["предупреждения"].append(
            f"За время прогона появились ЧУЖИЕ позиции: {чужие}. "
            "Программа их не открывала — разберитесь, откуда они.")

    итог["всё_ли_известно"] = not итог["неизвестно"]
    return итог


def _человеку(данные: dict) -> str:
    """Короткий пересказ снимка обычными словами."""
    строки = []
    счёт = данные.get("счёт")
    if isinstance(счёт, dict):
        строки.append(
            f"Счёт {счёт.get('login')} ({счёт.get('server')}), "
            f"баланс {счёт.get('balance')} {счёт.get('currency')}, "
            f"средства {счёт.get('equity')}")
        if счёт.get("trade_mode") is not None:
            строки.append(f"Режим счёта (trade_mode): {счёт.get('trade_mode')} "
                          "— 0 демо, 1 конкурс, 2 реальный")
    else:
        строки.append(f"Счёт: {счёт}")

    for ключ, имя in (("позиции_свои", "Своих открытых позиций"),
                      ("позиции_чужие", "ЧУЖИХ открытых позиций"),
                      ("активные_заявки_свои", "Своих активных заявок"),
                      ("активные_заявки_чужие", "ЧУЖИХ активных заявок"),
                      ("сделки_за_окно", "Сделок за окно истории")):
        значение = данные.get(ключ)
        строки.append(f"{имя}: "
                      f"{len(значение) if isinstance(значение, list) else значение}")

    условия = данные.get("условия")
    if isinstance(условия, dict):
        строки.append("")
        строки.append("Заранее записанные условия:")
        for имя in ("О1", "О2"):
            з = условия.get(имя)
            if isinstance(з, dict):
                строки.append(f"  {имя}: {з.get('состояние')} — {з.get('пояснение')}")

    if данные.get("не_спросилось"):
        строки.append("НЕ СПРОСИЛОСЬ: " + ", ".join(данные["не_спросилось"]))
        строки.append("Такой снимок неполон. Пустота в нём НЕ означает «ничего нет».")
    else:
        строки.append("Спросилось всё.")
    return "\n".join(строки)


def main(аргументы=None) -> int:
    разбор = argparse.ArgumentParser(
        description="Снимки состояния счёта для прогона на демо. Не торгует.")
    под = разбор.add_subparsers(dest="команда", required=True)

    с = под.add_parser("снимок", help="снять состояние счёта сейчас")
    с.add_argument("метка", help="например: до, после, середина")
    с.add_argument("--папка", default="demo_acceptance")
    с.add_argument("--часов-истории", type=int, default=24)

    в = под.add_parser("сверка", help="сравнить два снимка")
    в.add_argument("до")
    в.add_argument("после")

    а = разбор.parse_args(аргументы)

    if а.команда == "снимок":
        import mt5_connector as mt5c
        try:
            mt5c.connect()
        except Exception as e:  # noqa: BLE001
            print(f"Не удалось подключиться к терминалу: {e}")
            print("Снимок не снят. Запустите терминал MetaTrader 5 и "
                  "повторите — пустой снимок хуже, чем никакого.")
            return 2
        try:
            данные = снимок(часов_истории=а.часов_истории)
        finally:
            try:
                mt5c.disconnect()
            except Exception:  # noqa: BLE001
                pass
        путь = записать_снимок(а.папка, а.метка, данные)
        print(_человеку(данные))
        print(f"\nЗаписано: {путь}")
        ключ = ключ_подписи()
        print(f"Отпечаток: {хеш(данные, ключ)}")
        if ключ:
            print("Файл ПОДПИСАН: без ключа подделать не выйдет.")
        else:
            print(f"Файл без подписи: отпечаток ловит случайную правку, но "
                  f"НЕ умышленную подмену. Чтобы подписывать — задайте "
                  f"переменную окружения {ПЕРЕМЕННАЯ_КЛЮЧА}.")
        return 0 if данные["всё_ли_спросилось"] else 1

    до = прочитать_снимок(а.до)["снимок"]
    после = прочитать_снимок(а.после)["снимок"]
    итог = сверить(до, после)
    print(json.dumps(итог, ensure_ascii=False, indent=2))
    return 0 if итог["всё_ли_известно"] else 1


if __name__ == "__main__":
    sys.exit(main())
