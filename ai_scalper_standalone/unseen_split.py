"""unseen_split.py — ГДЕ ПРОХОДИТ ГРАНИЦА ВИДЕННОГО И КАК РЕЖЕТСЯ ИСТОРИЯ.

ЗАЧЕМ ЭТОТ ФАЙЛ

Приёмочный аудит поймал меня на том, что опубликованное число невиданных
баров не воспроизводится (P1-H5). В отчёте стояло 149 389 (74,7 %), а
пересчёт давал 149 640 при одной границе и 149 422 при другой. Ни одно не
совпало.

Причина простая и стыдная: я считал по ОКРУГЛЁННЫМ ДАТАМ («2025-08-15»),
а не по точным отметкам времени самых ранних сохранённых свечей.
Расхождение невелико числом, но велико по сути: до предрегистрации
граница обязана вычисляться программой, а не описываться словами.

ЧТО ДЕЛАЕТ ЭТОТ ФАЙЛ

Одна явно выбранная договорённость, одна программа, воспроизводимый
результат. По каждому инструменту печатает: границу, число баров в
train / validation / OOS и отпечаток каждого среза.

ВЫБРАННАЯ ДОГОВОРЁННОСТЬ: ПОКОМПОНЕНТНАЯ СТРОГАЯ

Для КАЖДОГО инструмента граница — время самой ранней уже сохранённой
свечи ЭТОГО ЖЕ инструмента на любом таймфрейме (M1, M5, M15).

Почему именно она (так же советует и аудит):

* она не объявляет виденной историю одного инструмента из-за того, что
  по другому инструменту данные начинались раньше;
* и при этом запрещает любой бар, который когда-либо был у нас по этому
  инструменту.

Общая граница для всех (самая ранняя среди валютных пар) строже, но
строже не туда: она вычёркивает часы, которых мы по этой паре не видели
никогда. Числа обеих договорённостей печатаются рядом — чтобы выбор был
виден, а не подразумевался.

ГРАНИЦА — ЭТО НЕ «ПРИМЕРНО ТРИ ГОДА»

Это точная отметка времени в секундах, взятая из данных. Всё, что
печатает этот файл, воспроизводится запуском на тех же двух архивах.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
from datetime import datetime, timezone

ТАЙМФРЕЙМЫ_ПРЕЖНИЕ = ("M1", "M5", "M15")
ДОЛИ_ПО_УМОЛЧАНИЮ = (0.50, 0.25, 0.25)
ЧАСТИ = ("train", "validation", "oos")


def _времена(путь) -> list:
    времена = []
    with open(путь, encoding="utf-8") as f:
        next(f, None)
        for строка in f:
            строка = строка.strip()
            if строка:
                времена.append(int(строка.split(";")[0]))
    return времена


def _строки(путь) -> list:
    with open(путь, encoding="utf-8") as f:
        return [с.strip() for с in f.read().splitlines()[1:] if с.strip()]


def отпечаток_среза(строки) -> str:
    """Отпечаток куска данных — чтобы срез нельзя было подменить незаметно.

    Считается по самим строкам, а не по числу баров: одинаковое число
    баров бывает у разных кусков."""
    h = hashlib.sha256()
    for с in строки:
        h.update(с.encode("utf-8"))
        h.update(b"\n")
    return h.hexdigest()


def границы_по_инструментам(папка_прежних: str) -> dict:
    """{инструмент: самая ранняя уже сохранённая свеча}.

    Берётся минимум по ВСЕМ прежним таймфреймам этого инструмента."""
    границы = {}
    for имя in sorted(os.listdir(папка_прежних)):
        if not имя.endswith(".csv"):
            continue
        основа = имя[:-4]
        if "_" not in основа:
            continue
        инструмент, тф = основа.rsplit("_", 1)
        if тф not in ТАЙМФРЕЙМЫ_ПРЕЖНИЕ:
            continue
        времена = _времена(os.path.join(папка_прежних, имя))
        if not времена:
            continue
        было = границы.get(инструмент)
        границы[инструмент] = min(времена) if было is None else min(было, min(времена))
    return границы


def разрезать(времена_и_строки, доли=ДОЛИ_ПО_УМОЛЧАНИЮ) -> dict:
    """Поделить НЕВИДАННУЮ часть по времени, без перемешивания.

    Порядок сохраняется: train — самое раннее, oos — самое позднее. Резать
    вперемешку нельзя: тогда «будущее» попадёт в обучение."""
    всего = len(времена_и_строки)
    к1 = int(всего * доли[0])
    к2 = к1 + int(всего * доли[1])
    куски = {"train": времена_и_строки[:к1],
             "validation": времена_и_строки[к1:к2],
             "oos": времена_и_строки[к2:]}
    return куски


def посчитать(папка_h1: str, папка_прежних: str, доли=ДОЛИ_ПО_УМОЛЧАНИЮ) -> dict:
    границы = границы_по_инструментам(папка_прежних)
    итог = {
        "договорённость": ("покомпонентная строгая: для каждого инструмента "
                           "граница — время самой ранней уже сохранённой "
                           "свечи ЭТОГО инструмента на M1, M5 или M15"),
        "доли": {"train": доли[0], "validation": доли[1], "oos": доли[2]},
        "инструменты": {},
    }

    всего_баров = всего_невидено = 0
    for имя in sorted(os.listdir(папка_h1)):
        if not имя.endswith("_H1.csv"):
            continue
        инструмент = имя[:-7]
        путь = os.path.join(папка_h1, имя)
        строки = _строки(путь)
        времена = [int(с.split(";")[0]) for с in строки]
        граница = границы.get(инструмент)

        запись = {"баров_всего": len(строки)}
        if граница is None:
            запись["граница_utc"] = None
            запись["почему"] = ("прежних данных по этому инструменту нет — "
                                "виденным считать нечего")
            запись["невидено"] = len(строки)
            невиданные = list(zip(времена, строки))
        else:
            запись["граница_секунды"] = граница
            запись["граница_utc"] = datetime.fromtimestamp(
                граница, timezone.utc).isoformat()
            невиданные = [(t, с) for t, с in zip(времена, строки) if t < граница]
            запись["невидено"] = len(невиданные)

        запись["доля_невиданного"] = round(запись["невидено"] / len(строки), 6)
        куски = разрезать(невиданные, доли)
        запись["части"] = {}
        for часть in ЧАСТИ:
            кусок = куски[часть]
            запись["части"][часть] = {
                "баров": len(кусок),
                "начало_utc": (datetime.fromtimestamp(кусок[0][0], timezone.utc)
                               .isoformat() if кусок else None),
                "конец_utc": (datetime.fromtimestamp(кусок[-1][0], timezone.utc)
                              .isoformat() if кусок else None),
                "sha256": отпечаток_среза([с for _, с in кусок]),
            }
        итог["инструменты"][инструмент] = запись
        всего_баров += len(строки)
        всего_невидено += запись["невидено"]

    итог["итого"] = {
        "баров_всего": всего_баров,
        "невидено": всего_невидено,
        "доля": round(всего_невидено / всего_баров, 6) if всего_баров else 0,
    }

    # ВТОРАЯ ДОГОВОРЁННОСТЬ — ДЛЯ СРАВНЕНИЯ, А НЕ ДЛЯ ИСПОЛЬЗОВАНИЯ.
    # Печатается затем, чтобы выбор был виден. Числа двух договорённостей
    # различаются, и молчать об этом нельзя.
    итог["для_сравнения_общая_граница"] = _общая_граница(
        папка_h1, границы)
    return итог


def _общая_граница(папка_h1: str, границы: dict) -> dict:
    """Одна граница на все валютные пары плюс отдельная для золота."""
    валютные = {и: г for и, г in границы.items() if и != "XAUUSD"}
    if not валютные:
        return {}
    общая = min(валютные.values())
    золото = границы.get("XAUUSD")
    невидено = всего = 0
    for имя in sorted(os.listdir(папка_h1)):
        if not имя.endswith("_H1.csv"):
            continue
        инструмент = имя[:-7]
        граница = золото if инструмент == "XAUUSD" else общая
        времена = _времена(os.path.join(папка_h1, имя))
        всего += len(времена)
        if граница is not None:
            невидено += sum(1 for t in времена if t < граница)
    return {
        "описание": ("самая ранняя граница среди валютных пар, отдельно "
                     "золото — строже, но вычёркивает часы, которых по "
                     "этой паре мы не видели никогда"),
        "граница_валютных_utc": datetime.fromtimestamp(общая, timezone.utc).isoformat(),
        "граница_золота_utc": (datetime.fromtimestamp(золото, timezone.utc).isoformat()
                               if золото else None),
        "невидено": невидено,
        "доля": round(невидено / всего, 6) if всего else 0,
    }


def _человеку(итог: dict) -> str:
    строки = [f"Договорённость: {итог['договорённость']}", ""]
    строки.append(f"{'инструмент':10} {'граница UTC':20} {'невидено':>9} "
                  f"{'train':>7} {'valid':>7} {'oos':>7}")
    for имя, з in итог["инструменты"].items():
        ч = з["части"]
        граница = (з["граница_utc"] or "прежних данных нет")[:19]
        строки.append(f"{имя:10} {граница:20} {з['невидено']:>9} "
                      f"{ч['train']['баров']:>7} {ч['validation']['баров']:>7} "
                      f"{ч['oos']['баров']:>7}")
    и = итог["итого"]
    строки.append("")
    строки.append(f"ИТОГО невидено: {и['невидено']} из {и['баров_всего']} = "
                  f"{и['доля']*100:.4f}%")
    с = итог.get("для_сравнения_общая_граница") or {}
    if с:
        строки.append(f"Для сравнения, общая граница: {с['невидено']} = "
                      f"{с['доля']*100:.4f}%  (НЕ используется)")
    строки.append("")
    строки.append("Отпечатки срезов (первые 16 знаков):")
    for имя, з in итог["инструменты"].items():
        части = "  ".join(f"{ч}={з['части'][ч]['sha256'][:16]}" for ч in ЧАСТИ)
        строки.append(f"  {имя:10} {части}")
    return "\n".join(строки)


def main(аргументы=None) -> int:
    р = argparse.ArgumentParser(
        description="Границы виденного и разбиение истории. "
                    "Одна договорённость, воспроизводимый результат.")
    р.add_argument("--h1", required=True, help="каталог с часовыми файлами")
    р.add_argument("--прежние", required=True,
                   help="каталог с прежними M1/M5/M15")
    р.add_argument("--вывод", default="",
                   help="куда записать итог в JSON (по умолчанию не писать)")
    а = р.parse_args(аргументы)

    for путь in (а.h1, а.прежние):
        if not os.path.isdir(путь):
            print(f"Нет такого каталога: {путь}")
            return 2

    итог = посчитать(а.h1, а.прежние)
    if not итог["инструменты"]:
        print("Часовых файлов не найдено — считать нечего.")
        return 3
    print(_человеку(итог))
    if а.вывод:
        with open(а.вывод, "w", encoding="utf-8") as f:
            json.dump(итог, f, ensure_ascii=False, indent=1)
        print(f"\nЗаписано: {а.вывод}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
