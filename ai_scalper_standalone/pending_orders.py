"""pending_orders.py — ЗАЯВКИ, ПРО КОТОРЫЕ МЫ ЗНАЕМ, А СЧЁТ ЕЩЁ НЕТ.

ЗАЧЕМ ЭТОТ ФАЙЛ

Между «мы отправили заявку» и «позиция видна в терминале» проходит время,
и оно ничем не гарантировано. В этом промежутке программа может:

  * не получить ответа брокера (TIMEOUT, обрыв связи);
  * получить ответ и тут же быть закрытой владельцем или упасть;
  * увидеть свежий список позиций, в котором новой сделки ещё нет.

Во всех трёх случаях позиция может СУЩЕСТВОВАТЬ, а программа про неё не
знает. Дальше она считает свободный риск так, будто её нет, и открывает
новую сделку поверх.

ЧТО БЫЛО НЕ ТАК

Резервы (reservations.py) закрывали ровно эту дыру, но только внутри
одного прохода: в начале следующего они стираются, «потому что свежий
список позиций к тому времени уже содержит настоящие позиции». В
документации того файла прямо было написано, что рассинхронизация
невозможна. Это неверно. Список приходит от терминала, а терминал
отвечает не мгновенно — именно поэтому резервы и понадобились. Стереть
их и поверить списку — значит поверить тому самому источнику, чья
задержка и создала проблему.

И отдельно: резервы живут в памяти. Перезапуск стирает их полностью.

ЧТО ДЕЛАЕТ ЭТОТ ФАЙЛ

Пишет на диск ДО отправки заявки: инструмент, направление, объём, риск,
время UTC. После подтверждения связывает запись с номером позиции. При
запуске сверяется с терминалом.

ГЛАВНОЕ ПРАВИЛО

Запись снимается только по ДОКАЗАННОМУ исходу: позиция найдена, или
брокер внятно отказал. Молчание, обрыв и «не вижу позиции» доказательством
не являются — запись остаётся, и риск учитывается консервативно.

ЧЕГО ЭТОТ ФАЙЛ НЕ ДЕЛАЕТ

Не торгует, не отменяет заявки, не закрывает позиции и не решает, входить
ли. Он только помнит и отвечает на вопрос «что мы отправляли, но так и не
увидели».
"""

from __future__ import annotations

import json
import logging
import os
import sys
import uuid
from datetime import datetime, timezone

import safe_files

log = logging.getLogger("pending_orders")

ФАЙЛ = "ожидаемые_заявки.json"
ВЕРСИЯ = 1

# Исходы записи.
ОЖИДАЕТ = "ожидает"          # отправлено, исход не доказан
ПОДТВЕРЖДЕНА = "подтверждена"
ОТМЕНЕНА = "отменена"        # брокер отказал ВНЯТНО


# Куда писать, когда folder не задан. Пустая строка означает «рядом с
# программой» — обычный рабочий режим.
#
# Существует ради тестов, и это не удобство, а исправление настоящего
# дефекта. Торговый путь зовёт записать() БЕЗ folder, поэтому любой тест,
# доходящий до отправки заявки, писал файл прямо в исходный каталог
# программы. Один такой файл я потом смёл в репозиторий командой
# git add -A: 76 синтетических записей со статусом «ожидает». Свежая
# копия программы нашла бы их при первом запуске, открыла инцидент и
# отказалась торговать — защита сработала бы на пустом месте.
ПАПКА_ПО_УМОЛЧАНИЮ = ""


def путь(folder: str = "") -> str:
    """Файл РЯДОМ С ПРОГРАММОЙ, как и отметка об инциденте.

    У собранной версии код лежит в _internal, и путь по __file__ увёл бы
    файл туда, где человек его не найдёт."""
    folder = folder or ПАПКА_ПО_УМОЛЧАНИЮ
    if folder:
        base = folder
    elif getattr(sys, "frozen", False):
        base = os.path.dirname(sys.executable)
    else:
        base = os.path.dirname(os.path.abspath(__file__))
    return os.path.join(base, ФАЙЛ)


def _прочитать(folder: str = "") -> list:
    try:
        with open(путь(folder), encoding="utf-8") as f:
            данные = json.load(f)
    except FileNotFoundError:
        return []
    except Exception as e:  # noqa: BLE001
        # Испорченный файл — НЕ пустой список. Пустой означал бы «ничего
        # не отправляли», а это ровно то утверждение, которое мы не можем
        # сделать. Возвращаем особую запись, чтобы вызывающий остановился.
        log.error("Файл ожидаемых заявок не читается (%s). Считаем, что "
                  "неподтверждённые заявки ЕСТЬ.", e)
        return [{"ид": "повреждён", "статус": ОЖИДАЕТ, "символ": "?",
                 "направление": 0, "лот": 0.0, "риск_денег": 0.0,
                 "когда_utc": "", "почему": f"файл повреждён: {e}"}]
    return list(данные.get("записи", []))


def _записать(записи: list, folder: str = "") -> bool:
    тело = {"version": ВЕРСИЯ, "записи": записи}
    try:
        safe_files.atomic_write_text(
            путь(folder), json.dumps(тело, ensure_ascii=False, indent=1),
            backup=False)
        return True
    except Exception as e:  # noqa: BLE001
        log.error("Журнал ожидаемых заявок НЕ записан: %s", e)
        return False


def записать(symbol: str, direction: int, lot: float,
             risk_money: float = 0.0, folder: str = "") -> str:
    """Отметить заявку ДО отправки. Возвращает её внутренний номер.

    Пишется ДО order_send, а не после. После — поздно: между отправкой и
    ответом программа может перестать существовать, и тогда следа не
    останется вовсе.

    ПУСТАЯ СТРОКА ОЗНАЧАЕТ «ЗАПИСАТЬ НЕ УДАЛОСЬ», и это НЕ мелочь.

    Раньше здесь возвращался номер в любом случае, даже когда файл на
    диск не лёг. Вызывающий получал номер, отправлял заявку — и следа не
    оставалось. То есть весь смысл журнала («след есть всегда») терялся
    ровно в том случае, ради которого журнал и написан: когда с машиной
    что-то не так.

    Вызывающий обязан НЕ отправлять заявку, получив пустую строку.
    Ложная пауза неприятна, но новой позиции она не создаёт; заявка без
    следа — создаёт."""
    ид = uuid.uuid4().hex[:12]
    записи = _прочитать(folder)
    записи.append({
        "ид": ид,
        "статус": ОЖИДАЕТ,
        "символ": str(symbol or ""),
        "направление": int(direction or 0),
        "лот": float(lot or 0.0),
        "риск_денег": max(0.0, float(risk_money or 0.0)),
        "когда_utc": datetime.now(timezone.utc).isoformat(),
        "тикет": 0,
    })
    if not _записать(записи, folder):
        log.error("Заявка по %s НЕ отмечена на диске — отправлять её нельзя.",
                  symbol)
        return ""
    return ид


def подтвердить(ид: str, тикет: int, объём: float = 0.0,
                folder: str = "") -> bool:
    """Заявка доказанно стала позицией. Запись снимается."""
    записи = _прочитать(folder)
    нашлась = False
    for з in записи:
        if з.get("ид") == ид:
            з["статус"] = ПОДТВЕРЖДЕНА
            з["тикет"] = int(тикет or 0)
            з["исполнено"] = float(объём or 0.0)
            нашлась = True
    _записать([з for з in записи if з.get("статус") == ОЖИДАЕТ], folder)
    return нашлась


def отменить(ид: str, причина: str, folder: str = "") -> bool:
    """Брокер отказал ВНЯТНО — позиции нет и не будет.

    Только внятный отказ. Молчание брокера сюда не годится: заявка могла
    исполниться, а потеряться мог лишь ответ."""
    записи = _прочитать(folder)
    осталось = [з for з in записи if з.get("ид") != ид]
    убрали = len(осталось) != len(записи)
    if убрали:
        log.info("Ожидаемая заявка %s снята: %s", ид, причина)
    _записать(осталось, folder)
    return убрали


def снять_человеком(кто: str, комментарий: str = "", folder: str = "") -> int:
    """Убрать все неподтверждённые записи ПО РЕШЕНИЮ ЧЕЛОВЕКА.

    ЗАЧЕМ ОТДЕЛЬНО ОТ `отменить`. Та означает внятный отказ брокера:
    позиции нет и не будет. Здесь другое — человек сходил в терминал,
    посмотрел сам и берёт ответственность на себя. Смешивать эти два
    случая нельзя: по журналу потом не отличить, кто решил.

    ЗАЧЕМ ВООБЩЕ. Без этого снятие запрета не помогало: записи оставались,
    и при следующем запуске сверка снова их не находила, снова открывала
    инцидент и снова останавливала торговлю. Владелец: «мне не нужно,
    чтобы бот постоянно стоял в запрете».

    Каждая убранная запись пишется в журнал целиком — чтобы через месяц
    было видно, что именно списали и с чьих слов.

    Возвращает, сколько записей убрано."""
    записи = _прочитать(folder)
    убираем = [з for з in записи if з.get("статус") == ОЖИДАЕТ]
    if not убираем:
        return 0
    for з in убираем:
        log.warning(
            "Ожидаемая заявка СНЯТА ЧЕЛОВЕКОМ (%s): %s %s объём %s, "
            "отправлена %s, ид %s. Комментарий: %s",
            кто, з.get("символ"), з.get("направление"), з.get("лот"),
            з.get("когда_utc"), з.get("ид"), комментарий)
    _записать([з for з in записи if з.get("статус") != ОЖИДАЕТ], folder)
    return len(убираем)


def открытые(folder: str = "") -> list:
    """Заявки, чей исход не доказан."""
    return [з for з in _прочитать(folder) if з.get("статус") == ОЖИДАЕТ]


def _подходит(запись: dict, позиция, magic=None) -> bool:
    """Похожа ли позиция на ту, что мы ждали.

    Сверяется по инструменту и направлению, а НЕ по номеру: номера у нас
    как раз и нет — иначе запись была бы подтверждена.

    И по magic — если он задан. Без этого наша неподтверждённая заявка
    «закрывалась» ЧУЖОЙ позицией: владелец открыл EURUSD руками, а
    программа решила, что это её заявка исполнилась. Тогда след
    снимается, а настоящая заявка остаётся неучтённой — то есть
    получается ровно то, от чего журнал и написан. Указал проверяющий."""
    if str(getattr(позиция, "symbol", "")) != запись.get("символ"):
        return False
    if magic is not None:
        if int(getattr(позиция, "magic", 0) or 0) != int(magic):
            return False
    тип = int(getattr(позиция, "type", -1))
    направление = 1 if тип == 0 else -1
    return направление == int(запись.get("направление", 0))


def _подходит_сделка(запись: dict, сделка, magic=None) -> bool:
    """Похожа ли ЗАКРЫТАЯ сделка из истории на ту заявку, что мы ждали.

    ЗАЧЕМ ЭТО ВООБЩЕ. Раньше сверка смотрела только на ОТКРЫТЫЕ позиции.
    Но позиция могла открыться и закрыться по стопу до следующего
    запуска: среди открытых её нет, а в истории есть. Такая заявка
    объявлялась «пропавшей», открывался инцидент и торговля вставала
    намертво — при том, что заявка отработала штатно. Ровно это и
    случилось у владельца: три дня без единой сделки.

    Сверяем то же, что и по позиции: инструмент, magic и направление. И
    дополнительно — что сделка ВХОДНАЯ (entry == 0) и произошла НЕ РАНЬШЕ
    того, как мы отправили заявку: сделка, случившаяся до отправки, — не
    наша, сколько бы полей ни совпало."""
    if str(getattr(сделка, "symbol", "")) != запись.get("символ"):
        return False
    if magic is not None:
        if int(getattr(сделка, "magic", 0) or 0) != int(magic):
            return False
    # entry: 0 = вход в рынок. Выход из позиции нам не подходит — он
    # относится к сделке, которая уже была открыта.
    if int(getattr(сделка, "entry", -1)) != 0:
        return False
    тип = int(getattr(сделка, "type", -1))
    if тип not in (0, 1):
        return False
    направление = 1 if тип == 0 else -1
    if направление != int(запись.get("направление", 0)):
        return False

    когда = запись.get("когда_utc")
    время_сделки = getattr(сделка, "time", None)
    if когда and время_сделки:
        try:
            отправлена = datetime.fromisoformat(str(когда))
            if отправлена.tzinfo is None:
                отправлена = отправлена.replace(tzinfo=timezone.utc)
            случилась = datetime.fromtimestamp(float(время_сделки),
                                               tz=timezone.utc)
            # Пять минут запаса: часы терминала и наши могут разойтись.
            if (случилась - отправлена).total_seconds() < -300:
                return False
        except (TypeError, ValueError, OSError):
            # Время не разобралось — по времени не отсеиваем, но и не
            # выдумываем совпадения: остальные поля уже сошлись.
            pass
    return True


def сверить(позиции, folder: str = "", magic=None, сделки=None) -> dict:
    """Что из ожидаемого нашлось на счету, а что нет.

    `сделки` — история сделок за окно, покрывающее время отправки заявок
    (mt5_connector.deals_or_none). Необязательна, но БЕЗ НЕЁ заявка,
    успевшая открыться и закрыться, считается пропавшей — а это ложная
    тревога, которая останавливает торговлю на ровном месте.

    None означает «спросить историю не удалось» и трактуется как «истории
    нет»: выдумывать доказательство из неполученного ответа нельзя.

    Ничего не меняет и не снимает: посмотреть, что произошло, должно быть
    безопасно. Решение принимает вызывающий."""
    ждём = открытые(folder)
    свободные = list(позиции or [])
    свободные_сделки = list(сделки or [])
    нашлись, пропали = [], []
    for з in ждём:
        совпало = next((p for p in свободные if _подходит(з, p, magic)), None)
        if совпало is not None:
            свободные.remove(совпало)
            нашлись.append({"запись": з,
                            "тикет": int(getattr(совпало, "ticket", 0)),
                            "где": "позиция"})
            continue
        # Позиции нет — смотрим историю: могла открыться и закрыться.
        сделка = next((d for d in свободные_сделки
                       if _подходит_сделка(з, d, magic)), None)
        if сделка is not None:
            свободные_сделки.remove(сделка)
            нашлись.append({"запись": з,
                            "тикет": int(getattr(сделка, "order", 0) or 0),
                            "где": "история сделок"})
            continue
        пропали.append(з)
    return {"нашлись": нашлись, "пропали": пропали, "всего_ждём": len(ждём)}


def риск_неподтверждённых(folder: str = "") -> float:
    """Сколько денег риска висит на заявках без доказанного исхода."""
    return sum(float(з.get("риск_денег", 0) or 0) for з in открытые(folder))
