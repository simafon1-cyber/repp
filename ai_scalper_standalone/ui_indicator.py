"""ui_indicator.py — маленький огонёк рядом с кнопкой: нажата или нет.

ЗАЧЕМ

Владелец: «сделай маленький индикатор зелёный, когда кнопка нажата, чтобы
видно было нажатие; когда она не работает — отжата, красный».

Беда простая и обычная: у обычной кнопки нет памяти. Нажал «Пауза» —
кнопка вернулась в исходный вид, и через минуту уже не помнишь, включил
ты паузу или только собирался. То же с запуском: подпись «Старт» выглядит
одинаково и до запуска, и после.

ЧТО РЕШАЕТ ЭТОТ ФАЙЛ

Только одно: какого цвета огонёк. Ни рисованием, ни расстановкой он не
занимается — это делает окно.

ДВА СОСТОЯНИЯ, А НЕ ТРИ

Зелёный — действие в силе (бот запущен, пауза включена, кнопку только что
нажали). Красный — не в силе: отжата или недоступна.

Соблазн добавить третий цвет для «недоступна» был, и я от него отказался:
владелец просил два. Но причина всё равно называется словами — в подписи
рядом, чтобы «красный» не значил одновременно «выключено» и «сломано».

ЦВЕТА БЕРУТСЯ ИЗ ТЕМЫ

Не «зелёный» и «красный» вообще, а profit и loss из текущей палитры. Так
огонёк остаётся читаемым во всех трёх темах, и его контраст уже проверен
теми же правилами, что и остальной текст (см. ui_theme.CONTRAST_RULES).
"""

from __future__ import annotations

НАЖАТА = "нажата"
ОТЖАТА = "отжата"
НЕДОСТУПНА = "недоступна"

# Какой ключ палитры брать для каждого состояния.
ЦВЕТ = {
    НАЖАТА: "profit",
    ОТЖАТА: "loss",
    НЕДОСТУПНА: "loss",
}

# Что написать человеку, если он наведёт мышь или спросит.
ПОДПИСЬ = {
    НАЖАТА: "включено",
    ОТЖАТА: "выключено",
    НЕДОСТУПНА: "сейчас недоступно",
}

ЗНАК = "●"


def состояние(включено: bool, доступна: bool = True) -> str:
    """Одно из трёх слов.

    ПОРЯДОК ПРОВЕРОК НЕ СЛУЧАЕН, и с первого раза я его перепутал.

    Сначала стояло «недоступна важнее всего» — и при работающем боте
    кнопка «Старт» горела КРАСНЫМ: нажать её нельзя, значит недоступна.
    Но запуск-то в силе, и красный огонёк рядом с работающим ботом
    означал бы ровно противоположное правде.

    Правильно так: если действие ДЕЙСТВУЕТ — зелёный, и неважно, можно
    ли нажать кнопку ещё раз. Недоступность различается только тогда,
    когда действие не в силе: одно дело «выключено, включай», другое —
    «сейчас нельзя»."""
    if включено:
        return НАЖАТА
    return ОТЖАТА if доступна else НЕДОСТУПНА


def цвет(состояние_кнопки: str, палитра: dict) -> str:
    """Цвет огонька из палитры темы."""
    ключ = ЦВЕТ.get(состояние_кнопки, "loss")
    return (палитра or {}).get(ключ, "#c02626")


def подпись(состояние_кнопки: str) -> str:
    return ПОДПИСЬ.get(состояние_кнопки, "")


def состояния_кнопок(бот_запущен: bool, на_паузе: bool,
                     торговля_закрыта: bool = False,
                     недавно_нажато=()) -> dict:
    """Состояние огонька у каждой кнопки верхней панели.

    ПОЧЕМУ У «СТОП» ЗЕЛЁНЫЙ, КОГДА БОТ ОСТАНОВЛЕН. Огонёк показывает не
    «нажали ли кнопку минуту назад», а действует ли сейчас то, что она
    делает. Иначе он был бы бесполезен после перезапуска программы:
    нажатия не было, а состояние есть.

    ОДНОРАЗОВЫЕ КНОПКИ — другое дело. У «Перезапуска», «Сохранить» и
    «Выхода» нет длящегося состояния, и им огонёк нужен ровно затем, за
    чем просил владелец: чтобы было ВИДНО НАЖАТИЕ. Они зажигаются на
    несколько секунд после щелчка — их имена приходят в недавно_нажато.
    """
    недавно = set(недавно_нажато or ())
    return {
        # Кнопка: (включено ли, доступна ли)
        "старт": состояние(бот_запущен, доступна=not бот_запущен),
        "стоп": состояние(not бот_запущен, доступна=бот_запущен),
        "пауза": состояние(на_паузе, доступна=бот_запущен),
        "перезапуск": состояние("перезапуск" in недавно),
        "сохранить": состояние("сохранить" in недавно),
        "выход": состояние("выход" in недавно),
    }
