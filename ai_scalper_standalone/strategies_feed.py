# СИТА
# =====================================================================
def известные_настройки() -> set:
    """Имена настроек, которые у программы ВООБЩЕ есть.

    Источник один — эталон config.py.example. Придумать настройку из
    интернета нельзя: её просто некуда применить, а вот сломать разбор
    файла настроек она может."""
    import ast
    import strategies as st
    путь = os.path.join(st._корень_данных(), "ai_scalper_standalone",
                        "config.py.example")
    if not os.path.exists(путь):
        # В собранной программе эталон лежит рядом с распакованными
        # файлами, без подпапки.
        путь = os.path.join(st._корень_данных(), "config.py.example")
    if not os.path.exists(путь):
        путь = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                            "config.py.example")
    try:
        дерево = ast.parse(open(путь, encoding="utf-8").read())
    except (OSError, SyntaxError) as e:
        log.warning("Не прочитан эталон настроек (%s) — "
                    "скачанные стратегии не принимаются", e)
        return set()          # fail-closed: не знаем — не пускаем
    имена = set()
    for узел in дерево.body:
        if isinstance(узел, ast.Assign):
            for цель in узел.targets:
                if isinstance(цель, ast.Name):
                    имена.add(цель.id)
    return имена


def запрещённые_имена() -> set:
    """Что скачанной стратегии трогать нельзя ни при каких условиях."""
    import remote_settings
    import strategies as st
    запрет = set(remote_settings.FORBIDDEN) | set(st.PROTECTED_PARAMS)
    # Своё имя тоже нельзя: иначе стратегия из сети переключила бы
    # активную стратегию или отключила бы саму проверку списка.
    запрет |= {"ACTIVE_STRATEGY", "USE_STRATEGY_SIGNAL",
               "STRATEGY_FEED_ENABLED", "STRATEGY_FEED_HOURS",
               "LIVE_TRADING"}
    return запрет


def _простое_значение(з) -> bool:
    return isinstance(з, (bool, int, float, str)) and not isinstance(з, bytes)


def проверить_стратегию(сырая: dict, известные: set, запрет: set,
                        встроенные: set) -> tuple:
    """(стратегия или None, причина отказа).

    Проверяется КАЖДОЕ поле. Молчаливое исправление кривой записи — это
    способ однажды принять то, чего принимать не собирались."""
    if not isinstance(сырая, dict):
        return None, "запись не является объектом"

    ключ = str(сырая.get("key") or "").strip()
    if not ключ:
        return None, "не задан ключ"
    if not ключ.replace("_", "").replace("-", "").isalnum():
        return None, f"ключ «{ключ}» содержит недопустимые знаки"
    if ключ in встроенные:
        return None, (f"ключ «{ключ}» совпадает со встроенной стратегией. "
                      f"Файл из сети не может её переопределить")

    поля = {}
    for имя in ("title", "idea", "when", "caution"):
        значение = str(сырая.get(имя) or "").strip()
        if not значение:
            return None, f"у «{ключ}» не заполнено поле {имя}"
        поля[имя] = значение

    настройки = сырая.get("params")
    if not isinstance(настройки, dict) or not настройки:
        return None, f"у «{ключ}» нет настроек — такая стратегия ничего не меняет"
    if len(настройки) > МАКСИМУМ_НАСТРОЕК:
        return None, (f"у «{ключ}» настроек {len(настройки)}, "
                      f"больше предела {МАКСИМУМ_НАСТРОЕК}")

    чистые = {}
    for имя, значение in настройки.items():
        имя = str(имя)
        if имя in запрет:
            return None, (f"«{ключ}» пытается менять {имя} — это запрещено "
                          f"файлам из сети")
        if имя not in известные:
            return None, (f"«{ключ}» задаёт настройку {имя}, которой у "
                          f"программы нет")
        if not _простое_значение(значение):
            return None, (f"«{ключ}»: значение {имя} не простое "
                          f"({type(значение).__name__})")
        чистые[имя] = значение

    import strategies as st
    стратегия = st.Strategy(
        key=ключ, title=поля["title"], idea=поля["idea"],
        when=поля["when"],
        # Происхождение приписывается ВСЕГДА и убрать его из файла нельзя:
        # человек обязан видеть, что стратегия пришла из сети, а не
        # проверена вместе с программой.
        caution=(поля["caution"] +
                 " [Загружена из репозитория, вместе с программой НЕ "
                 "проверялась. Прибыльность не обещана.]"),
        params=чистые)
    return стратегия, ""


def разобрать(текст: str) -> tuple:
    """(список стратегий, список замечаний). Ошибка — пустой список."""
    import strategies as st
    if not текст or len(текст.encode("utf-8", "ignore")) > МАКСИМУМ_БАЙТ:
        return [], ["файл пустой или больше допустимого размера"]
    try:
        данные = json.loads(текст)
    except ValueError as e:
        return [], [f"файл не читается как JSON: {e}"]
    if not isinstance(данные, dict):
        return [], ["в файле ожидался объект"]

    сырые = данные.get("стратегии")
    if not isinstance(сырые, list):
        return [], ["в файле нет списка «стратегии»"]
    if len(сырые) > МАКСИМУМ_СТРАТЕГИЙ:
        return [], [f"стратегий {len(сырые)}, больше предела "
                    f"{МАКСИМУМ_СТРАТЕГИЙ}"]

    известные = известные_настройки()
    if not известные:
        return [], ["не удалось прочитать список настроек программы — "
                    "принимать файл из сети нельзя"]
    запрет = запрещённые_имена()
    встроенные = {s.key for s in st.STRATEGIES}

    готовые, замечания = [], []
    видели = set()
    for сырая in сырые:
        стратегия, почему = проверить_стратегию(сырая, известные, запрет,
                                                встроенные)
        if стратегия is None:
            замечания.append(почему)
            continue
        if стратегия.key in видели:
            замечания.append(f"ключ «{стратегия.key}» повторяется в файле")
            continue
        видели.add(стратегия.key)
        готовые.append(стратегия)
    return готовые, замечания


