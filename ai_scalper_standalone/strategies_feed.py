"""strategies_feed.py — стратегии подтягиваются из репозитория, без пересборки.

ОТКУДА ЭТО

Владелец, дословно: «сделай, чтобы стратегии они хранились на гитхабе и
чтобы программа просто делала запрос, смотрела какие есть стратегии…
чтобы не приходилось каждый раз обновление делать самой программы
сборки, пускай она просто подтягивает… раз в пять часов».

ЧТО ЭТО МЕНЯЕТ И ЧЕГО НЕ МЕНЯЕТ

Меняет: список стратегий можно пополнять, не пересобирая .exe.
НЕ меняет: применяет стратегию по-прежнему ЧЕЛОВЕК, нажатием в окне.
Скачанный файл не может ничего включить сам.

ПОЧЕМУ ЗДЕСЬ СТОЛЬКО ПРОВЕРОК

Файл приходит из интернета. Кто управляет файлом — управляет настройками
торговли. Поэтому скачанная стратегия проходит ЧЕТЫРЕ сита, и каждое по
отдельности её отбрасывает:

  1. НАСТРОЙКА ОБЯЗАНА УЖЕ СУЩЕСТВОВАТЬ в программе (в config.py.example).
     Придумать новую настройку из интернета нельзя.
  2. ЗАПРЕЩЁННЫЕ ИМЕНА не проходят. Список берётся из remote_settings —
     тот самый, что уже прошёл аудит: токены, пароли, пути, логины,
     обновление, предторговый барьер, зеркало.
  3. ПАРАМЕТРЫ РИСКА не проходят: PROTECTED_PARAMS из strategies.py.
     Размер сделки и лимиты убытка задаются профилем риска и настройками
     счёта, а не файлом из сети.
  4. ЗНАЧЕНИЕ обязано быть простым: да/нет, число или строка. Ни списков,
     ни словарей, ни чего-либо, что можно было бы истолковать как код.

Ключ скачанной стратегии не может совпасть со встроенным: иначе файл из
сети переопределил бы «С-001» или «Зеркало», и человек нажал бы не то,
что думает.

ЧЕГО ЗДЕСЬ НЕТ НАРОЧНО

Ни одна скачанная стратегия не включается сама и не становится активной.
Сеть недоступна — работают встроенные стратегии и последний удачно
скачанный список из кэша. Пустой ответ, битый файл, отказ сети — не
повод остаться без стратегий вовсе.
"""

from __future__ import annotations

import json
import logging
import os
import time

log = logging.getLogger("strategies_feed")

# Имя файла в репозитории и имя кэша рядом с программой.
ФАЙЛ_В_РЕПОЗИТОРИИ = "strategies_online.json"
ФАЙЛ_КЭША = "strategies_online_кэш.json"

# Пределы. Файл из сети не должен уметь занять всю память или экран.
МАКСИМУМ_СТРАТЕГИЙ = 50
МАКСИМУМ_НАСТРОЕК = 60
МАКСИМУМ_БАЙТ = 512 * 1024

ЧАСОВ_ПО_УМОЛЧАНИЮ = 5.0


# =====================================================================
# НАСТРОЙКИ
# =====================================================================
def включено(cfg) -> bool:
    return bool(getattr(cfg, "STRATEGY_FEED_ENABLED", True))


def часов_между_проверками(cfg) -> float:
    try:
        часов = float(getattr(cfg, "STRATEGY_FEED_HOURS", ЧАСОВ_ПО_УМОЛЧАНИЮ))
    except (TypeError, ValueError):
        return ЧАСОВ_ПО_УМОЛЧАНИЮ
    # Ноль и отрицательное значение означали бы «дёргать GitHub без
    # передышки». Меньше часа тоже незачем: список стратегий не та вещь,
    # что меняется ежеминутно.
    return max(1.0, часов)


def путь_кэша() -> str:
    import updater
    return os.path.join(updater.app_dir(), ФАЙЛ_КЭША)


