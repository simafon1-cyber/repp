def скачать(timeout: int = 20) -> tuple:
    """(текст файла, ошибка). Читает ТОТ репозиторий, что задан обновлением.

    Отдельного адреса нарочно нет: свой адрес означал бы вторую дверь,
    которую можно подменить удалённо. UPDATE_REPO и UPDATE_BRANCH менять
    удалённо запрещено, и список стратегий наследует эту защиту."""
    import updater
    репозиторий = updater.repo()
    if "/" not in репозиторий:
        return "", "репозиторий не задан (UPDATE_REPO)"
    ветка = updater.branch() or "main"
    url = f"{updater.RAW}/{репозиторий}/{ветка}/{ФАЙЛ_В_РЕПОЗИТОРИИ}"
    try:
        with updater._request(url, accept="text/plain",
                              timeout=timeout) as ответ:
            сырое = ответ.read(МАКСИМУМ_БАЙТ + 1)
    except Exception as e:  # noqa: BLE001
        return "", f"{type(e).__name__}: {e}"
    if len(сырое) > МАКСИМУМ_БАЙТ:
        return "", "файл больше допустимого размера"
    try:
        return сырое.decode("utf-8"), ""
    except UnicodeDecodeError as e:
        return "", f"файл не в UTF-8: {e}"


def записать_кэш(текст: str, стратегий: int) -> bool:
    import safe_files
    запись = {"когда": time.time(), "стратегий": стратегий, "текст": текст}
    try:
        safe_files.atomic_write_text(
            путь_кэша(), json.dumps(запись, ensure_ascii=False))
        return True
    except Exception as e:  # noqa: BLE001
        log.debug("Кэш стратегий не записан: %s", e)
        return False


def прочитать_кэш() -> tuple:
    """(текст, когда_скачан). Пустая строка — кэша нет или он битый."""
    try:
        с = json.loads(open(путь_кэша(), encoding="utf-8").read())
        return str(с.get("текст") or ""), float(с.get("когда") or 0.0)
    except Exception:  # noqa: BLE001
        return "", 0.0


def пора(cfg, сейчас: float = None) -> bool:
    сейчас = time.time() if сейчас is None else сейчас
    _, когда = прочитать_кэш()
    if когда <= 0:
        return True
    return (сейчас - когда) >= часов_между_проверками(cfg) * 3600.0


def из_кэша() -> list:
    """Стратегии из последнего удачного скачивания. Пусто — значит пусто."""
    текст, _ = прочитать_кэш()
    if not текст:
        return []
    готовые, _ = разобрать(текст)
    return готовые


def обновить(cfg) -> dict:
    """Скачать и разобрать. Ничего не применяет и применить не может."""
    итог = {"скачано": False, "стратегий": 0, "замечаний": [], "почему": ""}
    if not включено(cfg):
        итог["почему"] = "подтягивание стратегий выключено (STRATEGY_FEED_ENABLED)"
        return итог
    текст, ошибка = скачать()
    if ошибка:
        итог["почему"] = ошибка
        return итог
    готовые, замечания = разобрать(текст)
    итог["замечаний"] = замечания
    if not готовые:
        итог["почему"] = ("в файле нет ни одной пригодной стратегии: "
                          + "; ".join(замечания[:3]) if замечания
                          else "в файле нет стратегий")
        return итог
    записать_кэш(текст, len(готовые))
    итог["скачано"] = True
    итог["стратегий"] = len(готовые)
    return итог
