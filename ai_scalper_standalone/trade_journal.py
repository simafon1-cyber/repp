"""trade_journal.py — ФАКТИЧЕСКИЕ СДЕЛКИ У БРОКЕРА И СВЕРКА С РЕШЕНИЯМИ.

ЗАЧЕМ ЭТОТ ФАЙЛ

Регламент демо-приёмки требует разбирать КАЖДУЮ закрытую сделку по
фактам: был ли сигнал по правилам, исполнился ли вход так, как
ожидалось, и какое именно правило закрыло позицию.

Для этого нужны две разные вещи, и путать их нельзя:

    журнал решения  — что ПРОГРАММА знала и решила в момент входа;
    история сделок  — что у БРОКЕРА произошло на самом деле.

Источник истины — второе. Журнал программы объясняет причину решения, но
доказательством исполнения он быть не может: он написан той же
программой, чьё поведение проверяют.

ЧЕГО ЗДЕСЬ РАНЬШЕ НЕ ХВАТАЛО

Журнал выходов в программе уже был. Но он писал НАШУ картину: наши
замеры, нашу причину закрытия, нашу цену. Выгрузки того, что записал сам
терминал — с номерами сделки, заявки и позиции, комиссией и свопом, — не
было вовсе. Значит, сверить было не с чем, и любое расхождение осталось
бы незамеченным.

ГЛАВНОЕ ПРАВИЛО ЭТОГО ФАЙЛА

Неизвестность — не ноль. Если историю спросить не удалось, здесь НЕ
пишется «сделок нет». Пишется «НЕИЗВЕСТНО», и приёмка обязана
остановиться. Пустая выгрузка, выданная за доказательство отсутствия
сделок, хуже отсутствия выгрузки.

ЧТО ЭТОТ ФАЙЛ НЕ ДЕЛАЕТ

Не торгует, не считает лот, не трогает стопы, цели, риск и стратегию. Он
только записывает и сверяет.
"""

