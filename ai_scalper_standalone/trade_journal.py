# ВЫГРУЗКА ИСТОРИИ СДЕЛОК У БРОКЕРА
# =====================================================================
def _поле(сделка, имя, поумолчанию=""):
    значение = getattr(сделка, имя, None)
    return поумолчанию if значение is None else значение


def строка_сделки(сделка) -> dict:
    """Одна сделка терминала в виде строки. Ничего не досчитывается."""
    return {
        "deal_ticket": int(_поле(сделка, "ticket", 0) or 0),
        "order_ticket": int(_поле(сделка, "order", 0) or 0),
        "position_id": int(_поле(сделка, "position_id", 0) or 0),
        "время_utc": datetime.fromtimestamp(
            float(_поле(сделка, "time", 0) or 0), timezone.utc).isoformat(),
        "символ": str(_поле(сделка, "symbol", "")),
        "тип": int(_поле(сделка, "type", -1)),
        "вход_или_выход": int(_поле(сделка, "entry", -1)),
        "объём": float(_поле(сделка, "volume", 0) or 0),
        "цена": float(_поле(сделка, "price", 0) or 0),
        "стоп": float(_поле(сделка, "sl", 0) or 0),
        "цель": float(_поле(сделка, "tp", 0) or 0),
        "комиссия": float(_поле(сделка, "commission", 0) or 0),
        "своп": float(_поле(сделка, "swap", 0) or 0),
        "прибыль": float(_поле(сделка, "profit", 0) or 0),
        "magic": int(_поле(сделка, "magic", 0) or 0),
        "причина_брокера": int(_поле(сделка, "reason", -1)),
        "комментарий": str(_поле(сделка, "comment", "")),
    }


def без_опознания(строки) -> list:
    """Сделки, у которых нет обязательного идентификатора.

    Регламент требует по каждой сделке deal ticket, order ticket и
    position ID. Строку без них нельзя ни сверить, ни разобрать, и
    выбрасывать её молча тоже нельзя: пропажа доказательства выглядела бы
    как «сделки не было»."""
    плохие = []
    for с in строки:
        нет = [и for и in ("deal_ticket", "order_ticket", "position_id")
               if not int(с.get(и, 0) or 0)]
        if нет:
            плохие.append({"строка": с, "нет_полей": нет})
    return плохие


def выгрузить_сделки(коннектор, начало, конец, куда: str,
                     magic=None) -> dict:
    """Записать историю сделок брокера за период в каталог выгрузки.

    коннектор — модуль с deals_or_none(начало, конец). Отдельным
    параметром, а не импортом: так тест подставляет поддельного брокера,
    не подменяя ничего в живой программе.

    magic=None означает «все сделки счёта», включая открытые руками. Это
    намеренно: чужая сделка на счёте — тоже факт, и прятать её из
    доказательства нельзя.

    Спросить не удалось — Неизвестно. НЕ пустой список."""
    сделки = коннектор.deals_or_none(начало, конец)
    if сделки is None:
        raise Неизвестно(
            "История сделок у брокера не получена. Это НЕ значит, что "
            "сделок не было: терминал мог быть недоступен. Приёмка "
            "останавливается — доказательства нет.")

    строки = [строка_сделки(с) for с in сделки]
    if magic is not None:
        строки = [с for с in строки if с["magic"] == int(magic)]
    строки.sort(key=lambda с: (с["время_utc"], с["deal_ticket"]))

    путь = os.path.join(куда, ФАЙЛ_СДЕЛОК)
    with open(путь, "w", newline="", encoding="utf-8") as f:
        писарь = csv.DictWriter(f, fieldnames=СТОЛБЦЫ_СДЕЛОК,
                                extrasaction="ignore")
        писарь.writeheader()
        for с in строки:
            писарь.writerow(с)

    неопознанные = без_опознания(строки)
    return {"путь": путь, "сделок": len(строки), "неопознанные": неопознанные}


# =====================================================================
# ВЫГРУЗКА САМА, ПО ЧАСАМ
# =====================================================================
# Владелец потребовал: без его участия. Кнопку нажимать не надо.
#
# ПОЧЕМУ ПО ЧЁТНЫМ ЧАСАМ, А НЕ «ЧЕРЕЗ ДВА ЧАСА ПОСЛЕ ПРОШЛОГО РАЗА».
# Второе кажется проще, но оно ползёт: перезапуск программы сдвигает
# отсчёт, и через неделю выгрузки идут в случайное время. По чётным
# часам владелец и проверяющий заранее знают, когда файл обязан
# появиться, и его отсутствие сразу видно. Это разница между «наверное,
# ещё не время» и «выгрузки нет — разбираемся».
ЧАСОВ_МЕЖДУ_ВЫГРУЗКАМИ = 2

# Первая выгрузка после установки забирает сутки: история у терминала
# есть, а лишние строки безвредны. Пропуск — вреден.
ПЕРВОЕ_ОКНО_ЧАСОВ = 24

# Нахлёст окна. Сделка могла попасть в историю с задержкой — окно
# «ровно от прошлого раза» её потеряло бы навсегда. Повтор строки
# безобиден: у сделки есть свой номер, дубликат виден.
НАХЛЁСТ_МИНУТ = 15

# Терминал недоступен — пробуем снова не на каждом обороте цикла (он
# крутится каждые несколько секунд), но и не через два часа.
ПОВТОР_ПОСЛЕ_НЕУДАЧИ_МИНУТ = 5

ФАЙЛ_СОСТОЯНИЯ = "последняя_выгрузка.json"


def слот_окна(момент: datetime) -> datetime:
    """Начало текущего окна: ближайший чётный час вниз, по UTC."""
    момент = момент.astimezone(timezone.utc)
    час = (момент.hour // ЧАСОВ_МЕЖДУ_ВЫГРУЗКАМИ) * ЧАСОВ_МЕЖДУ_ВЫГРУЗКАМИ
    return момент.replace(hour=час, minute=0, second=0, microsecond=0)


def пора_выгружать(состояние: dict, сейчас: datetime) -> bool:
    """Наступило ли новое окно.

    Ответ зависит ТОЛЬКО от записанного состояния и от времени — ни от
    чего больше. Поэтому его можно проверить тестом, не поднимая ни
    терминал, ни торговый цикл."""
    слот = слот_окна(сейчас).isoformat()
    if (состояние or {}).get("слот") == слот:
        return False                      # в этом окне уже выгружали
    неудача = (состояние or {}).get("неудачная_попытка")
    if неудача:
        try:
            прошло = (сейчас - datetime.fromisoformat(неудача)).total_seconds()
        except (TypeError, ValueError):
            return True
        if прошло < ПОВТОР_ПОСЛЕ_НЕУДАЧИ_МИНУТ * 60:
            return False                  # только что не вышло, ждём
    return True


def прочитать_состояние(корень: str = "") -> dict:
    путь = os.path.join(корень or ВЫГРУЗКИ, ФАЙЛ_СОСТОЯНИЯ)
    try:
        with open(путь, encoding="utf-8") as f:
            return json.load(f)
    except Exception:  # noqa: BLE001
        return {}


def записать_состояние(состояние: dict, корень: str = ""):
    корень = корень or ВЫГРУЗКИ
    os.makedirs(корень, exist_ok=True)
    with open(os.path.join(корень, ФАЙЛ_СОСТОЯНИЯ), "w", encoding="utf-8") as f:
        json.dump(состояние, f, ensure_ascii=False, indent=1)


def окно_выгрузки(состояние: dict, сейчас: datetime):
    """С какого по какое время спрашивать историю."""
    до = (состояние or {}).get("до_utc")
    if до:
        try:
            # Нахлёст нужен ТОЛЬКО когда продолжаем с прошлого раза:
            # сделка могла попасть в историю с задержкой.
            return (datetime.fromisoformat(до)
                    - timedelta(minutes=НАХЛЁСТ_МИНУТ)), сейчас
        except (TypeError, ValueError):
            pass
    # Первый раз (или запись испорчена) — ровно сутки. Нахлёст поверх
    # суток ничего не добавил бы, а число в отчёте стало бы не тем,
    # которое здесь написано.
    return сейчас - timedelta(hours=ПЕРВОЕ_ОКНО_ЧАСОВ), сейчас


def выгрузить_если_пора(коннектор, корень: str = "", сейчас=None,
                        magic=None, счёт=None, сервер: str = "",
                        версия_стратегии: str = "", ключ: str = "") -> dict:
    """Выгрузить историю сделок, если наступило новое окно.

    НИКОГДА не бросает: вызывается из торгового цикла, а наблюдатель не
    имеет права уронить наблюдаемого.

    Но и молча не проваливается. Каждый исход назван:

        рано         — окно ещё не сменилось, это нормальный ход дел;
        сделано      — файл записан, состояние сдвинуто;
        НЕИЗВЕСТНО   — терминал не ответил. Состояние НЕ сдвигается:
                       окно не считается закрытым, попробуем снова;
        ошибка       — что-то другое, тоже без сдвига состояния.

    Разница между «рано» и «НЕИЗВЕСТНО» — вся суть. Первое значит «файла
    нет и не должно быть», второе — «файла нет, и это плохо»."""
    корень = корень or ВЫГРУЗКИ
    сейчас = (сейчас or datetime.now(timezone.utc)).astimezone(timezone.utc)
    состояние = прочитать_состояние(корень)

    if not пора_выгружать(состояние, сейчас):
        return {"состояние": "рано",
                "слот": слот_окна(сейчас).isoformat()}

    начало, конец = окно_выгрузки(состояние, сейчас)
    try:
        куда = новая_выгрузка(
            корень, слот_окна(сейчас).strftime("%Y-%m-%dT%H-%M-%SZ"))
    except Exception as e:  # noqa: BLE001
        log.error("Каталог выгрузки не создан: %s", e)
        return {"состояние": "ошибка", "почему": str(e)}

    try:
        итог = выгрузить_сделки(коннектор, начало, конец, куда, magic=magic)
    except Неизвестно as e:
        состояние["неудачная_попытка"] = сейчас.isoformat()
        состояние["почему"] = str(e)
        записать_состояние(состояние, корень)
        log.error("Выгрузка сделок не удалась: %s", e)
        # Пустой каталог убираем: пустая папка выглядит как выгрузка,
        # в которой ничего не нашлось. Это разные вещи.
        _убрать_если_пусто(куда)
        return {"состояние": НЕИЗВЕСТНО, "почему": str(e)}
    except Exception as e:  # noqa: BLE001
        log.error("Выгрузка сделок сорвалась: %s", e)
        _убрать_если_пусто(куда)
        return {"состояние": "ошибка", "почему": str(e)}

    try:
        записать_паспорт(куда, счёт=счёт, сервер=сервер,
                         версия_стратегии=версия_стратегии, ключ=ключ)
    except Exception as e:  # noqa: BLE001
        log.error("Паспорт выгрузки не записан: %s", e)

    записать_состояние({
        "слот": слот_окна(сейчас).isoformat(),
        "когда_utc": сейчас.isoformat(),
        "до_utc": конец.isoformat(),
        "каталог": os.path.basename(куда),
        "сделок": итог["сделок"],
        "неопознанных": len(итог["неопознанные"]),
    }, корень)

    log.info("Выгрузка сделок: %d строк в %s", итог["сделок"], куда)
    return {"состояние": "сделано", "каталог": куда,
            "сделок": итог["сделок"],
            "неопознанные": итог["неопознанные"],
            "слот": слот_окна(сейчас).isoformat()}


def _убрать_если_пусто(путь: str):
    try:
        if os.path.isdir(путь) and not os.listdir(путь):
            os.rmdir(путь)
    except Exception:  # noqa: BLE001
        pass


