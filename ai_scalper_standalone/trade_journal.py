# СВЕРКА: РЕШЕНИЯ ПРОГРАММЫ ПРОТИВ ИСТОРИИ БРОКЕРА
# =====================================================================
def сверить(решения: list, сделки: list, magic=None) -> dict:
    """Сопоставить решения программы с фактическими сделками.

    Сверяется по номеру позиции. Разбираются ТРИ случая, и все три —
    расхождения, а не «шум»:

      * программа записала вход, а сделки у брокера нет;
      * у брокера есть наша сделка, которой программа не решала;
      * объём исполнения у брокера не совпал с записанным.

    Второе важнее первого. Сделка, которой никто не решал, — это либо
    чужой magic, либо потерянная запись, либо повторная отправка заявки.
    Ни одно из трёх нельзя пропустить."""
    наши_сделки = [с for с in сделки
                   if magic is None or int(с.get("magic", 0) or 0) == int(magic)]
    входы_брокера = {}
    for с in наши_сделки:
        if int(с.get("вход_или_выход", -1)) != 0:
            continue                      # 0 — вход в позицию
        входы_брокера.setdefault(int(с.get("position_id", 0) or 0), []).append(с)

    расхождения = []
    исполнение = []
    сошлось = 0
    решённые_входы = [р for р in решения
                      if str(р.get("событие", "")).upper() == "ВХОД"
                      and str(р.get("статус_заявки", "")).upper() != "ОТКАЗ"]

    for р in решённые_входы:
        тикет = int(float(р.get("тикет", 0) or 0))
        у_брокера = входы_брокера.pop(тикет, None)
        if not у_брокера:
            расхождения.append({
                "вид": "решение без сделки",
                "тикет": тикет,
                "что": (f"программа записала вход по {р.get('символ')}, а "
                        f"сделки с номером позиции {тикет} у брокера нет"),
            })
            continue
        записано = _число(р.get("лот_исполнен"))
        фактически = round(sum(float(с.get("объём", 0) or 0) for с in у_брокера), 8)
        if записано is not None and abs(записано - фактически) > 1e-8:
            расхождения.append({
                "вид": "объём не совпал",
                "тикет": тикет,
                "что": (f"программа записала {записано}, у брокера "
                        f"{фактически}"),
            })
            continue
        сошлось += 1
        # Проскальзывание считается ЗДЕСЬ, а не в момент входа: в момент
        # входа фактической цены ещё нет, есть только ответ брокера без
        # неё. Цена берётся из выгруженной истории — то есть у того, кто
        # исполнял, а не у того, кто просил.
        ожидаемая = _число(р.get("цена_ожидаемая"))
        точка = _число(р.get("точка_цены"))
        if ожидаемая and точка:
            объём = sum(float(с.get("объём", 0) or 0) for с in у_брокера) or 1.0
            средняя = sum(float(с.get("цена", 0) or 0)
                          * float(с.get("объём", 0) or 0)
                          for с in у_брокера) / объём
            напр = 1 if str(р.get("направление", "")).upper().startswith("B") else -1
            исполнение.append({
                "тикет": тикет,
                "символ": р.get("символ"),
                "цена_ожидаемая": ожидаемая,
                "цена_брокера": round(средняя, 8),
                "проскальзывание_пунктов": проскальзывание(
                    ожидаемая, средняя, точка, напр),
            })

    for тикет, остаток in входы_брокера.items():
        расхождения.append({
            "вид": "сделка без решения",
            "тикет": тикет,
            "что": (f"у брокера есть вход по {остаток[0].get('символ')} "
                    f"(позиция {тикет}), которого программа не решала"),
        })

    return {
        "сошлось": сошлось,
        "решений_входа": len(решённые_входы),
        "расхождения": расхождения,
        "исполнение": исполнение,
        "итог": "СОШЛОСЬ" if not расхождения else "РАСХОЖДЕНИЕ",
    }


def _число(значение):
    try:
        return float(значение)
    except (TypeError, ValueError):
        return None


