def отпечаток_файла(путь: str) -> str:
    h = hashlib.sha256()
    with open(путь, "rb") as f:
        for кусок in iter(lambda: f.read(1 << 20), b""):
            h.update(кусок)
    return h.hexdigest()


def ревизия(корень: str = "") -> str:
    try:
        return subprocess.check_output(
            ["git", "-C", корень or os.path.dirname(ЗДЕСЬ), "rev-parse", "HEAD"],
            stderr=subprocess.DEVNULL).decode().strip()
    except Exception:  # noqa: BLE001
        return "неизвестна"


def записать_паспорт(куда: str, счёт=None, сервер: str = "",
                     версия_стратегии: str = "", путь_config: str = "",
                     ключ: str = "") -> dict:
    """Паспорт выгрузки: чем она получена и от чего зависит.

    Связывает доказательство с ревизией кода и хешем настроек. Без этого
    выгрузка — просто таблица: непонятно, какая именно программа её
    сделала."""
    файлы = {}
    for имя in (ФАЙЛ_СДЕЛОК, ФАЙЛ_РЕШЕНИЙ):
        п = os.path.join(куда, имя)
        if os.path.exists(п):
            файлы[имя] = отпечаток_файла(п)

    путь_config = путь_config or os.path.join(ЗДЕСЬ, "config.py")
    паспорт = {
        "версия_формата": ВЕРСИЯ_ФОРМАТА,
        "когда_utc": _сейчас(),
        "версия_стратегии": версия_стратегии or НЕИЗВЕСТНО,
        "счёт": счёт if счёт is not None else НЕИЗВЕСТНО,
        "сервер": сервер or НЕИЗВЕСТНО,
        "ревизия": ревизия(),
        "sha256_config": (отпечаток_файла(путь_config)
                          if os.path.exists(путь_config) else НЕИЗВЕСТНО),
        "версия_python": sys.version.split()[0],
        "файлы": файлы,
    }

    # Подпись считается ТЕМ ЖЕ способом, что и у снимков счёта: один
    # механизм на весь проект, чтобы не пришлось доверять двум разным.
    try:
        import demo_acceptance as да
        защита = да.ПОДПИСЬ if ключ else да.ОБЫЧНЫЙ
        паспорт["защита"] = защита
        паспорт["хеш"] = да.хеш(паспорт, ключ, защита)
    except Exception as e:  # noqa: BLE001
        log.error("Подпись паспорта выгрузки не поставлена: %s", e)
        паспорт["защита"] = НЕИЗВЕСТНО

    with open(os.path.join(куда, ФАЙЛ_ПАСПОРТА), "w", encoding="utf-8") as f:
        json.dump(паспорт, f, ensure_ascii=False, indent=1)
    return паспорт


