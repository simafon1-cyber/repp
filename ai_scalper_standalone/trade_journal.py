def _сейчас() -> str:
    return datetime.now(timezone.utc).isoformat()


def метка_времени() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H-%M-%SZ")


def новая_выгрузка(корень: str = "", имя: str = "") -> str:
    """Создать каталог выгрузки. Существующий НЕ переписывается.

    Выгрузка — доказательство. Затереть доказательство новой попыткой
    нельзя даже случайно, поэтому здесь не makedirs(exist_ok=True), а
    честный отказ.

    Имя задаётся снаружи не для красоты. Выгрузка по расписанию называет
    каталог по ОКНУ, а не по стенным часам: иначе две выгрузки, попавшие
    в одну секунду, столкнулись бы, а по имени каталога нельзя было бы
    сказать, какое окно он покрывает. Это поймал собственный тест —
    вторая выгрузка возвращала «ошибка: каталог уже существует»."""
    корень = корень or ВЫГРУЗКИ
    путь = os.path.join(корень, имя or метка_времени())
    if os.path.exists(путь):
        raise FileExistsError(
            f"Каталог выгрузки {путь} уже существует. Прошлая выгрузка не "
            f"переписывается: это доказательство, а не черновик.")
    os.makedirs(путь)
    return путь


# =====================================================================
# ЖУРНАЛ РЕШЕНИЙ ПРОГРАММЫ
# =====================================================================
class ЖурналРешений:
    """Дописывающий CSV: одна строка на одно решение.

    Дописывающий, а не переписывающий: строку, однажды записанную, эта
    программа изменить не должна."""

    def __init__(self, путь: str):
        self.путь = путь
        новый = not os.path.exists(путь)
        каталог = os.path.dirname(путь)
        if каталог:
            os.makedirs(каталог, exist_ok=True)
        self._файл = open(путь, "a", newline="", encoding="utf-8")
        self._писарь = csv.DictWriter(self._файл, fieldnames=СТОЛБЦЫ_РЕШЕНИЙ,
                                      extrasaction="ignore")
        if новый:
            self._писарь.writeheader()
            self._файл.flush()

    def записать(self, запись: dict):
        строка = {к: "" for к in СТОЛБЦЫ_РЕШЕНИЙ}
        строка.update({к: з for к, з in (запись or {}).items()
                       if к in СТОЛБЦЫ_РЕШЕНИЙ})
        if not строка["время_utc"]:
            строка["время_utc"] = _сейчас()
        self._писарь.writerow(строка)
        # Сбрасываем на диск сразу: программу могут убить в любой момент,
        # и решение, оставшееся в буфере, для приёмки не существует.
        self._файл.flush()

    def закрыть(self):
        try:
            self._файл.close()
        except Exception:  # noqa: BLE001
            pass

    def __enter__(self):
        return self

    def __exit__(self, *a):
        self.закрыть()


# ---------------------------------------------------------------------
# ОДИН ЖУРНАЛ НА ПРОГРАММУ
# ---------------------------------------------------------------------
# Вызывающему коду не нужно знать про открытие и закрытие файла: он
# занят торговлей. Здесь общий журнал, который можно включить один раз.
_общий: "ЖурналРешений | None" = None


def включить(путь: str) -> bool:
    """Начать вести журнал решений. Возвращает, получилось ли."""
    global _общий
    выключить()
    try:
        _общий = ЖурналРешений(путь)
        return True
    except Exception as e:  # noqa: BLE001
        log.error("Журнал решений не открылся (%s): %s", путь, e)
        _общий = None
        return False


def выключить():
    global _общий
    if _общий is not None:
        _общий.закрыть()
        _общий = None


def ведётся() -> bool:
    return _общий is not None


def записать(запись: dict) -> bool:
    """Записать решение в общий журнал. НИКОГДА не бросает.

    Это намеренно и это единственное место в проекте, где проглатывание
    ошибки правильно. Журнал — наблюдатель. Уронить торговлю из-за того,
    что не записалась строка наблюдения, значит поменять поведение
    программы ошибкой в её описании.

    Обратная сторона: молчаливый пропуск строки испортил бы приёмку. Он
    не молчаливый — считается и попадает в отчёт (см. пропущено())."""
    global _пропущено
    if _общий is None:
        return False
    try:
        _общий.записать(запись)
        return True
    except Exception as e:  # noqa: BLE001
        _пропущено += 1
        log.error("Решение НЕ записано в журнал: %s", e)
        return False


_пропущено = 0


def пропущено() -> int:
    """Сколько решений не удалось записать. Ноль — обязателен для приёмки."""
    return _пропущено


def сбросить_счётчик():
    global _пропущено
    _пропущено = 0


def проскальзывание(ожидаемая, фактическая, точка, направление: int):
    """Проскальзывание в пунктах со знаком: минус — исполнили хуже.

    Считается по направлению сделки. Без знака число бесполезно: «два
    пункта» может значить и подарок, и потерю."""
    try:
        ож, фк, тчк = float(ожидаемая), float(фактическая), float(точка)
    except (TypeError, ValueError):
        return ""
    if тчк <= 0 or ож <= 0 or фк <= 0:
        return ""
    # Покупка дороже ожидаемого — хуже; продажа дешевле — тоже хуже.
    разница = (ож - фк) if направление == 1 else (фк - ож)
    return round(разница / тчк, 2)


