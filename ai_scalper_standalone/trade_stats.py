"""trade_stats.py — полная статистика по списку сделок.

Здесь нет ни одного торгового решения: только счёт по уже случившимся
сделкам. Считается то, что просил владелец, и ровно так, как это принято
считать в отчётах MetaTrader — чтобы числа можно было сверить с настоящим
отчётом брокера, а не только с самим собой.

ПОЧЕМУ НЕ ХВАТАЕТ ОДНОЙ ЧИСТОЙ ПРИБЫЛИ. Она ничего не говорит о цене, за
которую получена. Две системы с одинаковой прибылью не равны: та, что шла к
ней без глубоких провалов и без серий из десяти убытков подряд, лучше —
её человек не выключит руками на середине.

ЧТО ЗНАЧАТ РЕДКИЕ СОКРАЩЕНИЯ:
  R    — результат сделки, поделённый на её собственный риск (расстояние до
         стопа). Сделка «+2R» заработала вдвое больше, чем рисковала. Это
         единственный способ сравнивать сделки с разной шириной стопа.
  MAE  — насколько глубоко сделка уходила в минус до того, как закрылась.
         Показывает, сколько человеку пришлось вытерпеть.
  MFE  — насколько высоко сделка поднималась в плюс. Разница между MFE и
         результатом — это то, что было в руках и не взято.
"""

import logging

from validation import max_drawdown, recovery_factor

log = logging.getLogger("trade_stats")

# Ниже этого числа сделок выводы не делаются. Тот же порог, что в воротах
# проверки изменений — один на весь проект.
from backtest import МАЛО_СДЕЛОК  # noqa: E402  (порог берём, а не дублируем)


def _среднее(значения) -> float:
    ряд = list(значения or ())
    return sum(ряд) / len(ряд) if ряд else 0.0


def max_streak(trades, выигрышные: bool) -> int:
    """Самая длинная серия подряд: побед или поражений."""
    лучшая = текущая = 0
    for t in trades or ():
        плюс = float(t.get("money", t.get("points", 0)) or 0) > 0
        if плюс == выигрышные:
            текущая += 1
            лучшая = max(лучшая, текущая)
        else:
            текущая = 0
    return лучшая


def медиана(значения) -> float:
    ряд = sorted(значения or ())
    n = len(ряд)
    if n == 0:
        return 0.0
    return ряд[n // 2] if n % 2 else (ряд[n // 2 - 1] + ряд[n // 2]) / 2.0


def sharpe(значения) -> float:
    """Отношение средней сделки к её разбросу.

    Считается ПО СДЕЛКАМ, а не по дням, и БЕЗ безрисковой ставки — то есть
    это не тот Sharpe, что печатают в проспектах фонда, и сравнивать его с
    чужими цифрами нельзя. Сравнивать можно только две версии одной системы
    между собой, что здесь и требуется."""
    ряд = [float(x) for x in (значения or ())]
    n = len(ряд)
    if n < 2:
        return 0.0
    ср = sum(ряд) / n
    разброс = (sum((x - ср) ** 2 for x in ряд) / (n - 1)) ** 0.5
    return round(ср / разброс, 3) if разброс > 0 else 0.0


def sortino(значения) -> float:
    """То же, но разброс считается ТОЛЬКО по убыточным сделкам.

    Смысл отличия: колебания вверх человека не расстраивают, и наказывать за
    них систему незачем. Если убыточных сделок нет, возвращается 0.0, а не
    бесконечность — «минусов не было» на коротком отрезке означает мало
    данных, а не идеальную систему."""
    ряд = [float(x) for x in (значения or ())]
    n = len(ряд)
    if n < 2:
        return 0.0
    ср = sum(ряд) / n
    вниз = [x for x in ряд if x < 0]
    if not вниз:
        return 0.0
    разброс = (sum(x ** 2 for x in вниз) / len(вниз)) ** 0.5
    return round(ср / разброс, 3) if разброс > 0 else 0.0


def summarize(trades, label: str = "") -> dict:
    """Полная статистика по списку сделок.

    Ожидаемые поля сделки: direction (1/-1), money, points, r, mae_points,
    mfe_points, held_seconds. Отсутствующие поля считаются нулями — статистика
    просто не покажет то, чего не измеряли, вместо того чтобы выдумать."""
    сделки = list(trades or ())
    n = len(сделки)
    деньги = [float(t.get("money", 0) or 0) for t in сделки]
    плюсы = [m for m in деньги if m > 0]
    минусы = [-m for m in деньги if m < 0]
    сумма_плюсов = sum(плюсы)
    сумма_минусов = sum(минусы)
    итог = sum(деньги)

    просадка = max_drawdown(деньги)
    держали = [float(t.get("held_seconds", 0) or 0) for t in сделки]

    return {
        "label": label,
        "сделок": n,
        "чистая_прибыль": round(итог, 2),
        # Профит-фактор: сумма выигрышей / сумма проигрышей. Бесконечности не
        # выдаём — «минусов не было» на коротком отрезке означает мало данных.
        "профит_фактор": round(сумма_плюсов / сумма_минусов, 2) if сумма_минусов > 0 else 0.0,
        "ожидание": round(итог / n, 4) if n else 0.0,
        "винрейт": round(len(плюсы) / n * 100.0, 1) if n else 0.0,
        "средний_выигрыш": round(_среднее(плюсы), 2),
        "средний_проигрыш": round(_среднее(минусы), 2),
        "макс_просадка": round(просадка, 2),
        "фактор_восстановления": recovery_factor(деньги),
        "средний_R": round(_среднее([float(t.get("r", 0) or 0) for t in сделки]), 3),
        "средний_MAE": round(_среднее([abs(float(t.get("mae_points", 0) or 0))
                                       for t in сделки]), 1),
        "средний_MFE": round(_среднее([abs(float(t.get("mfe_points", 0) or 0))
                                       for t in сделки]), 1),
        "макс_серия_убытков": max_streak(сделки, False),
        "макс_серия_побед": max_streak(сделки, True),
        "среднее_время_в_сделке_мин": round(_среднее(держали) / 60.0, 1),
        "итог_пунктов": round(sum(float(t.get("points", 0) or 0) for t in сделки), 1),
        # --- добавлено по требованию отчёта о версиях выхода ---
        "медианный_R": round(медиана([float(t.get("r", 0) or 0) for t in сделки]), 3),
        "медианное_время_мин": round(медиана(держали) / 60.0, 1),
        "крупнейший_выигрыш": round(max(деньги), 2) if деньги else 0.0,
        "крупнейший_убыток": round(min(деньги), 2) if деньги else 0.0,
        # Sharpe и Sortino считаются по R, а не по деньгам: деньги зависят от
        # лота и депозита, и две версии выхода с разным числом сделок дали бы
        # несравнимые числа. R от размера позиции не зависит.
        "sharpe_R": sharpe([float(t.get("r", 0) or 0) for t in сделки]),
        "sortino_R": sortino([float(t.get("r", 0) or 0) for t in сделки]),
        "средний_MFE_R": round(_среднее([float(t.get("mfe_r", 0) or 0)
                                         for t in сделки]), 3),
        "средний_MAE_R": round(_среднее([float(t.get("mae_r", 0) or 0)
                                         for t in сделки]), 3),
        # Достаточно ли данных, чтобы вообще делать выводы.
        "достаточно_данных": n >= МАЛО_СДЕЛОК,
    }


def by_direction(trades) -> dict:
    """Отдельно покупки, отдельно продажи.

    Разделять обязательно: система может быть прибыльной в одну сторону и
    убыточной в другую, а вместе они дадут ровное «около нуля», по которому
    ничего не понять."""
    покупки = [t for t in trades or () if int(t.get("direction", 0) or 0) == 1]
    продажи = [t for t in trades or () if int(t.get("direction", 0) or 0) == -1]
    return {
        "BUY": summarize(покупки, "BUY"),
        "SELL": summarize(продажи, "SELL"),
    }


def by_bucket(trades, bucket_key: str) -> dict:
    """Разбивка по любому признаку, записанному в сделке (сессия, режим ATR,
    новость рядом). Признак пишет тот, кто проводит сделку, — здесь только
    группировка и счёт."""
    группы = {}
    for t in trades or ():
        ключ = str(t.get(bucket_key, "") or "не указано")
        группы.setdefault(ключ, []).append(t)
    return {имя: summarize(ряд, имя) for имя, ряд in sorted(группы.items())}


def compare(first: dict, second: dict, first_name: str = "A",
            second_name: str = "B") -> str:
    """Сравнение двух наборов статистики словами, с оговоркой о выборке."""
    строки = [f"{'Показатель':<26}{first_name:>14}{second_name:>14}"]
    поля = [
        ("сделок", "Сделок"),
        ("чистая_прибыль", "Чистая прибыль"),
        ("профит_фактор", "Профит-фактор"),
        ("ожидание", "Ожидание на сделку"),
        ("винрейт", "Винрейт, %"),
        ("средний_выигрыш", "Средний выигрыш"),
        ("средний_проигрыш", "Средний проигрыш"),
        ("макс_просадка", "Макс. просадка"),
        ("фактор_восстановления", "Фактор восстановления"),
        ("средний_R", "Средний R"),
        ("макс_серия_убытков", "Макс. серия убытков"),
    ]
    for ключ, имя in поля:
        строки.append(f"{имя:<26}{first.get(ключ, 0)!s:>14}{second.get(ключ, 0)!s:>14}")

    мало = [имя for имя, св in ((first_name, first), (second_name, second))
            if not св.get("достаточно_данных")]
    if мало:
        строки.append("")
        строки.append(f"ВНИМАНИЕ: у {', '.join(мало)} меньше {МАЛО_СДЕЛОК} сделок. "
                      f"Это не слабое доказательство, а его отсутствие: сравнивать "
                      f"такие числа между собой нельзя.")
    return "\n".join(строки)


def describe(stats: dict) -> str:
    """Одна статистика словами."""
    if not stats.get("сделок"):
        return f"{stats.get('label', '')}: сделок не было."
    строки = [
        f"=== {stats.get('label', 'ИТОГ')} ===",
        f"Сделок: {stats['сделок']}   Винрейт: {stats['винрейт']}%",
        f"Чистая прибыль: {stats['чистая_прибыль']}   "
        f"Профит-фактор: {stats['профит_фактор']}",
        f"Ожидание на сделку: {stats['ожидание']}   Средний R: {stats['средний_R']}",
        f"Средний выигрыш: {stats['средний_выигрыш']}   "
        f"Средний проигрыш: {stats['средний_проигрыш']}",
        f"Макс. просадка: {stats['макс_просадка']}   "
        f"Фактор восстановления: {stats['фактор_восстановления']}",
        f"MAE: {stats['средний_MAE']} пт   MFE: {stats['средний_MFE']} пт",
        f"Серии подряд: побед {stats['макс_серия_побед']}, "
        f"убытков {stats['макс_серия_убытков']}",
        f"Среднее время в сделке: {stats['среднее_время_в_сделке_мин']} мин",
    ]
    if not stats.get("достаточно_данных"):
        строки.append(f"СТАТУС: UNKNOWN — сделок меньше {МАЛО_СДЕЛОК}, "
                      f"выводы делать нельзя.")
    return "\n".join(строки)
