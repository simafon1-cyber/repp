"""reservations.py — сделки, открытые в ТЕКУЩЕМ обходе символов.

=====================================================================
ЗАЧЕМ ЭТО ВООБЩЕ НУЖНО
=====================================================================
Главный цикл берёт список открытых позиций ОДИН раз за проход и отдаёт
один и тот же список всем инструментам подряд — так задумано, это экономит
десятки обращений к терминалу за круг.

Но внутри того же прохода инструменты ОТКРЫВАЮТ сделки. И список от этого
не меняется. Получается:

    EURUSD открылся и занял слот
      -> следом идёт GBPUSD
      -> он видит СТАРЫЙ список, где EURUSD ещё нет
      -> и тоже проходит лимиты

По этому устаревшему списку считаются три защиты сразу:

    MAX_SIMULTANEOUS_POSITIONS   общее число сделок
    max_total_risk_pct           общий риск по счёту
    MAX_POSITIONS_PER_CURRENCY   ставка на одну валюту

То есть обойти можно не что-нибудь, а ровно то, что бережёт депозит.

=====================================================================
ПОЧЕМУ РЕЗЕРВИРОВАНИЕ, А НЕ ПОВТОРНЫЙ ЗАПРОС
=====================================================================
Напрашивается простое: после каждого открытия заново спросить у терминала
список позиций. Это выглядит честнее — ведь брокер и есть источник правды.

Так делать не стоит по одной причине: **терминал отвечает не мгновенно**.
Между подтверждением ордера и появлением позиции в списке проходит время,
и оно не гарантировано. Повторный запрос может вернуть список БЕЗ только
что открытой сделки — и мы получим ровно ту же дыру, но теперь ещё и с
лишними обращениями к терминалу, то есть медленнее.

Резерв же не может недосчитать. Он ставится СРАЗУ после подтверждения
ордера и живёт до конца прохода. Ошибиться он может только в одну
сторону — посчитать лишнее, если сделка мгновенно закрылась по стопу. Это
безопасная сторона: в худшем случае мы не откроем сделку, которую могли бы.
Потерять на этом нельзя.

Сверка с действительностью происходит сама: в начале следующего прохода
резервы стираются, а свежий список к тому времени уже содержит настоящие
позиции. Ничего сверять руками не надо и рассинхронизация невозможна.

=====================================================================
ЧЕГО ЭТОТ МОДУЛЬ НЕ ДЕЛАЕТ
=====================================================================
Он не принимает торговых решений, не считает риск сам и не знает про
стратегию. Он только помнит, что уже открыто в этом проходе, и отвечает на
три вопроса: сколько, по каким инструментам и на какую сумму риска.
"""

import logging

log = logging.getLogger("reservations")


class Книга:
    """Резервы текущего прохода по символам.

    Живёт ровно один обход: очищается в начале каждого прохода главного
    цикла, когда получен свежий список позиций."""

    def __init__(self):
        self._записи = []

    # ---------------------------------------------------------------
    def очистить(self) -> None:
        """Забыть всё. Вызывается СРАЗУ после получения свежего списка
        позиций: он уже содержит то, что резервы описывали."""
        self._записи = []

    def забронировать(self, symbol: str, direction: int,
                      risk_money: float = 0.0) -> None:
        """Записать только что открытую сделку.

        Вызывается ТОЛЬКО после подтверждения ордера брокером. Резерв на
        неподтверждённую сделку означал бы, что мы сами себе запретили
        торговать из-за ордера, которого нет."""
        self._записи.append({
            "symbol": str(symbol or ""),
            "direction": int(direction or 0),
            "risk_money": max(0.0, float(risk_money or 0.0)),
        })

    # ---------------------------------------------------------------
    def сколько(self, symbol: str = None) -> int:
        """Сколько сделок забронировано: всего или по одному инструменту."""
        if symbol is None:
            return len(self._записи)
        return sum(1 for з in self._записи if з["symbol"] == symbol)

    def символы(self) -> list:
        """Инструменты, по которым в этом проходе уже открылись.

        Порядок сохраняется, повторы убираются: проверка валютной
        экспозиции считает ИНСТРУМЕНТЫ, а не сделки."""
        итог = []
        for з in self._записи:
            if з["symbol"] and з["symbol"] not in итог:
                итог.append(з["symbol"])
        return итог

    def риск_денег(self) -> float:
        """Сколько денег риска забронировано в этом проходе."""
        return sum(з["risk_money"] for з in self._записи)

    def риск_процент(self, equity: float) -> float:
        """То же, но в процентах счёта — как считает общий потолок риска.

        При нулевом или отрицательном капитале возвращается ноль: делить
        на него нельзя, а выдумывать число вместо ответа — тем более."""
        try:
            e = float(equity)
        except (TypeError, ValueError):
            return 0.0
        if e <= 0:
            return 0.0
        return self.риск_денег() / e * 100.0

    # ---------------------------------------------------------------
    def __len__(self) -> int:
        return len(self._записи)

    def __bool__(self) -> bool:
        # Пустая книга — это ЛОЖЬ, а не «объект существует». Иначе
        # `if резервы:` в вызывающем коде читалось бы как «резервы есть»,
        # а срабатывало бы всегда.
        return bool(self._записи)


def объединить_символы(открытые, резервы: "Книга") -> list:
    """Инструменты из снимка ПЛЮС забронированные в этом проходе.

    Отдельная функция, а не выражение по месту: объединение нужно в двух
    местах, и разъехаться они не должны."""
    итог = list(открытые or ())
    for имя in (резервы.символы() if резервы else ()):
        if имя not in итог:
            итог.append(имя)
    return итог
