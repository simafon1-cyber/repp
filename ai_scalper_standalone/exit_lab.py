"""exit_lab.py — ДИАГНОСТИКА: есть ли вообще ход цены, из которого можно
построить прибыльный выход.

=====================================================================
ЗАЧЕМ ЭТОТ ФАЙЛ СУЩЕСТВУЕТ — И КАКУЮ ОШИБКУ ОН ИСПРАВЛЯЕТ
=====================================================================
Раньше вывод «сделки не доходят далеко» делался по MFE из отчёта о сделке.
Это было НЕВЕРНО, и ошибка серьёзная.

MFE в отчёте измеряется, ПОКА СДЕЛКА ОТКРЫТА. Закрывает её трейлинг-стоп.
Значит само правило выхода обрезает наблюдение — данные ЦЕНЗУРИРОВАНЫ
справа. По ним нельзя отличить

    «рынок не даёт хода»           (проблема во входе)

от

    «мы сами вышли слишком рано»   (проблема в выходе),

а это ровно тот вопрос, ради которого всё и считалось. Вывод, сделанный по
таким данным, был замкнутым кругом: трейлинг закрывал сделку рано, и по
короткому наблюдению делался вывод, что ходить некуда.

Здесь берётся НЕЦЕНЗУРИРОВАННЫЙ путь: от каждого входа ход цены пишется на
фиксированное число баров вперёд, независимо от того, когда сделка закрылась.

=====================================================================
ЧТО ЭТО ПОЗВОЛЯЕТ И ЧЕГО НЕ ПОЗВОЛЯЕТ
=====================================================================
ПОЗВОЛЯЕТ примерить к ОДНИМ И ТЕМ ЖЕ входам любой стоп и любую цель и
получить поверхность ожидания. Считается мгновенно: путь уже записан.

НЕ ПОЗВОЛЯЕТ утверждать, что при другом выходе был бы ровно такой набор
входов. Позиция в программе одна: другой выход — другое время занятости —
другие последующие входы. Поэтому здесь считается ДВА варианта:

  * все входы подряд (перекрывающиеся) — честная оценка «на одну сделку»;
  * без перекрытий — ближе к жизни, годится для просадки.

И ни один результат отсюда не является рекомендацией. Это диагностика:
она отвечает на вопрос «где находится проблема», а не «что поставить».

=====================================================================
ВНУТРИБАРОВАЯ НЕОПРЕДЕЛЁННОСТЬ
=====================================================================
Если внутри одного бара задет и стоп, и цель, порядок касаний по четырём
ценам бара неизвестен. Здесь считаются три сценария: худший (сначала стоп),
лучший (сначала цель) и нейтральный (случайный порядок с закреплённым
зерном). Лучший сценарий НИКОГДА не используется как доказательство
прибыльности — только как верхняя граница.
"""

import logging
import math
import random

log = logging.getLogger("exit_lab")

# Сколько баров вперёд писать от каждого входа. 100 баров M5 — это восемь
# часов. Средняя сделка живёт 8 минут вживую и 30 минут в расчёте, так что
# восемь часов — заведомый запас: если хода нет и там, его нет нигде.
ГОРИЗОНТ = 100

# Сетка для поверхности выходов. Стоп в ATR (так его задаёт программа), цель
# в долях стопа (R). Значения покрывают и заметно более тесный стоп, и
# заметно более широкий, чем нынешние 2.0 ATR.
СЕТКА_SL_ATR = (1.0, 1.5, 2.0, 2.5)
СЕТКА_TP_R = (0.5, 0.75, 1.0, 1.5, 2.0, 3.0)

# Пороги, по которым считается, доходила ли сделка до уровня.
УРОВНИ_R = (0.25, 0.5, 0.75, 1.0, 1.5, 2.0, 3.0)

# Корзины для распределения MFE.
КОРЗИНЫ_R = ((0.0, 0.25), (0.25, 0.5), (0.5, 0.75), (0.75, 1.0),
             (1.0, 1.5), (1.5, 2.0), (2.0, 3.0), (3.0, float("inf")))

СЦЕНАРИИ = ("worst", "neutral", "best")


# =====================================================================
# СБОР ПУТЕЙ
# =====================================================================
def collect(symbol: str, bars, meta: dict, max_bars: int = 0,
            horizon: int = ГОРИЗОНТ, progress=None, only_direction: int = 0) -> list:
    """Прогнать живую стратегию и записать путь цены после каждого входа."""
    import baseline_engine
    итог = baseline_engine.run(symbol, bars, meta, max_bars=max_bars,
                               progress=progress, only_direction=only_direction,
                               record_horizon=horizon)
    return итог.get("paths", [])


# =====================================================================
# ПРИМЕРКА ВЫХОДА К ЗАПИСАННОМУ ПУТИ
# =====================================================================
def simulate_one(путь: dict, sl_atr: float, tp_r: float, intrabar: str = "worst",
                 rnd: random.Random = None, max_bars: int = 0,
                 costs: bool = True, extra_cost_r: float = 0.0) -> dict:
    """Что стало бы с этой сделкой при таком стопе и такой цели.

    Возвращает {"r", "bars", "exit", "exit_time"}. r — результат в единицах
    риска: −1 это ровно стоп."""
    шаги = путь["path"]
    if not шаги or sl_atr <= 0:
        return {"r": 0.0, "bars": 0, "exit": "нет данных", "exit_time": 0}

    tp_atr = tp_r * sl_atr
    # Спред платится один раз, как и в живой программе: вход по худшей
    # стороне. В единицах риска это постоянный вычет.
    издержки = ((путь.get("spread_atr", 0.0) / sl_atr) if costs else 0.0) + float(extra_cost_r)
    предел = int(max_bars) if max_bars else len(шаги)

    for k, (fav, adv, close, время) in enumerate(шаги[:предел], 1):
        стоп_задет = adv >= sl_atr
        цель_задета = tp_atr > 0 and fav >= tp_atr
        if стоп_задет and цель_задета:
            # Порядок внутри бара неизвестен — вот здесь и решается сценарий.
            if intrabar == "best":
                сначала_стоп = False
            elif intrabar == "neutral":
                сначала_стоп = (rnd or random).random() < 0.5
            else:
                сначала_стоп = True
            return {"r": (-1.0 if сначала_стоп else tp_r) - издержки,
                    "bars": k, "exit": "стоп" if сначала_стоп else "цель",
                    "exit_time": время, "спорный": True}
        if стоп_задет:
            return {"r": -1.0 - издержки, "bars": k, "exit": "стоп",
                    "exit_time": время}
        if цель_задета:
            return {"r": tp_r - издержки, "bars": k, "exit": "цель",
                    "exit_time": время}

    # Горизонт кончился, сделка жива — закрываем по последней цене закрытия.
    # Выдумывать её судьбу нельзя, а бросать открытой значит потерять сделку.
    последний = шаги[min(предел, len(шаги)) - 1]
    return {"r": последний[2] / sl_atr - издержки, "bars": предел,
            "exit": "по времени", "exit_time": последний[3]}


def simulate(пути, sl_atr: float, tp_r: float, intrabar: str = "worst",
             seed: int = 0, overlap: bool = False, max_bars: int = 0,
             costs: bool = True, extra_cost_r: float = 0.0) -> dict:
    """Примерить выход ко всем входам.

    overlap=False — как в жизни: пока сделка открыта, новые входы
    пропускаются. overlap=True — все входы подряд, честная оценка «на одну
    сделку» без влияния очерёдности."""
    rnd = random.Random(seed)
    результаты = []
    занят_до = 0
    пропущено = 0
    спорных = 0
    for путь in пути:
        if not overlap and путь["entry_time"] < занят_до:
            пропущено += 1
            continue
        исход = simulate_one(путь, sl_atr, tp_r, intrabar, rnd, max_bars,
                             costs, extra_cost_r)
        if исход["exit"] == "нет данных":
            continue
        спорных += 1 if исход.get("спорный") else 0
        результаты.append(исход)
        занят_до = исход["exit_time"]
    return {"sl_atr": sl_atr, "tp_r": tp_r, "intrabar": intrabar,
            "r": [и["r"] for и in результаты], "исходы": результаты,
            "пропущено_перекрытий": пропущено, "спорных_баров": спорных}


# =====================================================================
# СТАТИСТИКА В ЕДИНИЦАХ РИСКА
# =====================================================================
def _перцентиль(ряд, доля):
    if not ряд:
        return 0.0
    р = sorted(ряд)
    место = доля * (len(р) - 1)
    низ = int(math.floor(место))
    верх = min(низ + 1, len(р) - 1)
    вес = место - низ
    return р[низ] * (1 - вес) + р[верх] * вес


def stats_r(значения) -> dict:
    """Сводка по списку результатов в R. Всё, что нужно для суждения."""
    ряд = [float(x) for x in (значения or ())]
    n = len(ряд)
    if not n:
        return {"сделок": 0, "среднее": 0.0, "медиана": 0.0, "винрейт": 0.0,
                "средний_выигрыш": 0.0, "средний_проигрыш": 0.0,
                "профит_фактор": 0.0, "ожидание": 0.0, "просадка": 0.0,
                "восстановление": 0.0, "безубыточный_винрейт": 0.0,
                "итог": 0.0}
    выигрыши = [x for x in ряд if x > 0]
    проигрыши = [x for x in ряд if x < 0]
    сумма_в = sum(выигрыши)
    сумма_п = -sum(проигрыши)
    ср_в = (сумма_в / len(выигрыши)) if выигрыши else 0.0
    ср_п = (сумма_п / len(проигрыши)) if проигрыши else 0.0

    итог = 0.0
    пик = 0.0
    просадка = 0.0
    for x in ряд:
        итог += x
        пик = max(пик, итог)
        просадка = max(просадка, пик - итог)

    # БЕЗУБЫТОЧНЫЙ ВИНРЕЙТ ИЗ ФАКТИЧЕСКОГО РАСПРЕДЕЛЕНИЯ, а не из упрощённой
    # формулы: берутся настоящие средние выигрыш и проигрыш этой выборки.
    бе = (ср_п / (ср_в + ср_п) * 100.0) if (ср_в + ср_п) > 0 else 0.0

    return {
        "сделок": n,
        "среднее": round(sum(ряд) / n, 4),
        "медиана": round(_перцентиль(ряд, 0.5), 4),
        "винрейт": round(len(выигрыши) / n * 100, 1),
        "средний_выигрыш": round(ср_в, 4),
        "средний_проигрыш": round(ср_п, 4),
        "профит_фактор": round(сумма_в / сумма_п, 3) if сумма_п > 0 else 0.0,
        "ожидание": round(sum(ряд) / n, 4),
        "просадка": round(просадка, 2),
        "восстановление": round(итог / просадка, 2) if просадка > 0 else 0.0,
        "безубыточный_винрейт": round(бе, 1),
        "итог": round(итог, 2),
    }


# =====================================================================
# РАСПРЕДЕЛЕНИЕ ХОДА ЦЕНЫ (НЕЦЕНЗУРИРОВАННОЕ)
# =====================================================================
def excursions(пути, sl_atr: float = 0.0, max_bars: int = 0) -> list:
    """MFE и MAE каждого входа в единицах риска, БЕЗ обрезания выходом.

    sl_atr=0 означает «взять тот стоп, который стоял на самом деле»."""
    ряд = []
    for путь in пути:
        риск = float(sl_atr or путь.get("sl_atr") or 0.0)
        if риск <= 0 or not путь["path"]:
            continue
        шаги = путь["path"][:int(max_bars)] if max_bars else путь["path"]
        mfe = max((f for f, a, c, t in шаги), default=0.0) / риск
        mae = max((a for f, a, c, t in шаги), default=0.0) / риск
        # Когда именно случился лучший ход — важно для вопроса о времени жизни.
        лучший_бар = 0
        лучшее = -float("inf")
        for k, (f, a, c, t) in enumerate(шаги, 1):
            if f > лучшее:
                лучшее, лучший_бар = f, k
        ряд.append({
            "mfe_r": round(mfe, 4), "mae_r": round(mae, 4),
            "бар_лучшего_хода": лучший_бар,
            "direction": путь["direction"], "session": путь["session"],
            "atr_bucket": путь["atr_bucket"], "regime": путь["regime"],
            "entry_time": путь["entry_time"], "score": путь["score"],
            "sl_atr_факт": путь.get("sl_atr", 0.0),
            "spread_r": round((путь.get("spread_atr", 0.0) / риск), 4),
        })
    return ряд


def distribution(значения) -> dict:
    """Перцентили ряда. Медиана одна ничего не говорит о хвостах."""
    ряд = [float(x) for x in (значения or ())]
    if not ряд:
        return {"n": 0}
    return {
        "n": len(ряд),
        "среднее": round(sum(ряд) / len(ряд), 3),
        "P25": round(_перцентиль(ряд, 0.25), 3),
        "медиана": round(_перцентиль(ряд, 0.50), 3),
        "P75": round(_перцентиль(ряд, 0.75), 3),
        "P90": round(_перцентиль(ряд, 0.90), 3),
        "P95": round(_перцентиль(ряд, 0.95), 3),
        "P99": round(_перцентиль(ряд, 0.99), 3),
        "максимум": round(max(ряд), 3),
    }


def buckets(значения, корзины=КОРЗИНЫ_R) -> list:
    """Сколько сделок попало в каждую корзину хода."""
    ряд = [float(x) for x in (значения or ())]
    n = len(ряд) or 1
    итог = []
    for низ, верх in корзины:
        сколько = sum(1 for x in ряд if низ <= x < верх)
        имя = f"{низ}-{верх}R" if верх != float("inf") else f">{низ}R"
        итог.append({"корзина": имя, "сделок": сколько,
                     "процент": round(сколько / n * 100, 1)})
    return итог


def reached(замеры, уровни=УРОВНИ_R) -> list:
    """Сколько входов дошло до каждого уровня прибыли — и что было дальше.

    ЭТО ГЛАВНАЯ ТАБЛИЦА ВСЕЙ ДИАГНОСТИКИ. Она отвечает на вопрос, ради
    которого всё считалось: если сделка дошла до +0.5R, стоит ли её держать
    дальше или надо забирать?"""
    n = len(замеры) or 1
    итог = []
    for уровень in уровни:
        дошли = [з for з in замеры if з["mfe_r"] >= уровень]
        # Что было бы, если бы на этом уровне мы просто забирали прибыль:
        # доходность равна уровню (минус спред), иначе −1.
        if дошли:
            дальше = distribution([з["mfe_r"] for з in дошли])
            медиана_дальше = дальше["медиана"]
        else:
            медиана_дальше = 0.0
        итог.append({
            "уровень": уровень,
            "дошли": len(дошли),
            "процент": round(len(дошли) / n * 100, 1),
            "медиана_MFE_дошедших": медиана_дальше,
        })
    return итог


def take_at(замеры, уровень: float, sl_r: float = 1.0) -> dict:
    """Простейшая стратегия выхода: забирать ровно на этом уровне.

    Это НЕ рекомендация, а способ измерить, сколько всего есть в движении.
    Сделка, дошедшая до уровня, даёт +уровень; не дошедшая — −sl_r. Порядок
    касаний тут не важен: если MFE >= уровня, но MAE >= стопа, то что было
    раньше, неизвестно — такие случаи считаются ХУДШИМ образом, как стоп."""
    результаты = []
    for з in замеры:
        дошёл = з["mfe_r"] >= уровень
        выбило = з["mae_r"] >= sl_r
        if дошёл and not выбило:
            результаты.append(уровень - з["spread_r"])
        elif выбило:
            результаты.append(-sl_r - з["spread_r"])
        else:
            результаты.append(0.0)
    return stats_r(результаты)


def surface(пути, sl_grid=СЕТКА_SL_ATR, tp_grid=СЕТКА_TP_R,
            intrabar: str = "worst", overlap: bool = False,
            max_bars: int = 0, extra_cost_r: float = 0.0, seed: int = 0) -> dict:
    """Поверхность SL x TP -> сводка. Ключ клетки — пара (sl_atr, tp_r)."""
    итог = {}
    for sl in sl_grid:
        for tp in tp_grid:
            прогон = simulate(пути, sl, tp, intrabar, seed=seed,
                              overlap=overlap, max_bars=max_bars,
                              extra_cost_r=extra_cost_r)
            св = stats_r(прогон["r"])
            св["спорных_баров"] = прогон["спорных_баров"]
            св["пропущено_перекрытий"] = прогон["пропущено_перекрытий"]
            итог[(sl, tp)] = св
    return итог


def best_cell(поверхность, минимум_сделок: int = 100):
    """Лучшая клетка по ожиданию — но только среди тех, где хватает сделок.

    Без ограничения по числу сделок «лучшей» почти всегда оказывается клетка
    с десятком сделок и случайно красивым числом."""
    годные = {к: в for к, в in поверхность.items()
              if в["сделок"] >= минимум_сделок}
    источник = годные or поверхность
    ключ = max(источник, key=lambda к: источник[к]["ожидание"])
    return ключ, источник[ключ], bool(годные)
