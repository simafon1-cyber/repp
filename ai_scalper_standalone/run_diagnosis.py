"""run_diagnosis.py — ОДНА КОМАНДА: где именно находится проблема.

Отвечает на один вопрос и ни на какой другой:

    ЕСТЬ ЛИ ВООБЩЕ ХОД ЦЕНЫ ПОСЛЕ ВХОДА, ИЗ КОТОРОГО МОЖНО ПОСТРОИТЬ
    ПРИБЫЛЬНЫЙ ВЫХОД?

Если хода нет — проблема во входном сигнале, и никакой стоп, никакая цель и
никакой трейлинг её не исправят. Если ход есть, а деньги теряются — проблема
в выходе, и тогда видно, где именно.

Ничего не меняет и ничего не рекомендует. Только измеряет.

Запуск:

    python run_diagnosis.py                 — EURUSD и XAUUSD
    python run_diagnosis.py XAUUSD          — один инструмент
    python run_diagnosis.py --bars 50000    — по последним свечам
"""

import logging
import os
import sys

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, ЗДЕСЬ)

import run_baseline  # noqa: E402  (ставит config и заглушку MetaTrader5)

import exit_lab       # noqa: E402
import history_data   # noqa: E402
import optimize       # noqa: E402

logging.basicConfig(level=logging.ERROR,
                    format="%(levelname)s %(name)s: %(message)s")

СИМВОЛЫ = ["EURUSD", "XAUUSD"]


def заголовок(текст, знак="="):
    print()
    print(знак * 74)
    print(текст)
    print(знак * 74)


def таблица_R(имя, св):
    print(f"  {имя:<26} сделок {св['сделок']:>5}  PF {св['профит_фактор']:>6}  "
          f"ожидание {св['ожидание']:>8}R  винрейт {св['винрейт']:>5}%  "
          f"ср.выигрыш {св['средний_выигрыш']:>6}R  ср.проигрыш "
          f"{св['средний_проигрыш']:>6}R  безубыт.винрейт "
          f"{св['безубыточный_винрейт']:>5}%  просадка {св['просадка']:>7}R  "
          f"восст. {св['восстановление']:>6}")


def разбить_по_времени(замеры_или_пути, границы_времени):
    """Разрезать по тем же границам, что и в PHASE 3 — по времени входа."""
    t1, t2 = границы_времени
    train = [з for з in замеры_или_пути if з["entry_time"] < t1]
    valid = [з for з in замеры_или_пути if t1 <= з["entry_time"] < t2]
    oos = [з for з in замеры_или_пути if з["entry_time"] >= t2]
    return {"TRAIN": train, "VALIDATION": valid, "OOS": oos}


def по_инструменту(symbol: str, max_bars: int) -> dict:
    заголовок(f"ДИАГНОСТИКА: {symbol}")

    данные = history_data.load(symbol)
    if not данные["clean"] or not данные["quality"]["usable"]:
        print("СТАТУС: INSUFFICIENT DATA — данных нет или они негодны.")
        return {"symbol": symbol, "статус": "INSUFFICIENT DATA"}

    bars = данные["clean"]
    if max_bars and len(bars) > max_bars:
        bars = bars[-int(max_bars):]
    границы = optimize.segments(bars)
    границы_времени = (int(bars[границы["VALIDATION"][0]]["time"]),
                       int(bars[границы["OOS"][0]]["time"]))

    print(f"Свечей: {len(bars)}. Горизонт наблюдения после входа: "
          f"{exit_lab.ГОРИЗОНТ} баров M5 (около 8 часов).")
    print("Путь цены пишется НЕЗАВИСИМО от того, когда сделка закрылась, —")
    print("иначе наблюдение обрезал бы сам трейлинг-стоп, и вопрос «мало")
    print("хода или мы рано вышли» остался бы без ответа.")

    пути = exit_lab.collect(symbol, bars, данные["meta"],
                            progress=lambda t: print(f"  {t}", flush=True))
    if not пути:
        print("СТАТУС: нет входов — считать нечего.")
        return {"symbol": symbol, "статус": "НЕТ ВХОДОВ"}

    замеры = exit_lab.excursions(пути)
    print(f"\nВходов записано: {len(замеры)}")

    # ---------------------------------------------------------- 1. MFE / MAE
    заголовок(f"1. РАСПРЕДЕЛЕНИЕ ХОДА ЦЕНЫ (нецензурированное). {symbol}", "-")
    mfe = exit_lab.distribution([з["mfe_r"] for з in замеры])
    mae = exit_lab.distribution([з["mae_r"] for з in замеры])
    print("  Мера — R, то есть фактический стоп этой сделки.")
    print(f"  {'':<10}{'сред':>8}{'P25':>8}{'медиана':>10}{'P75':>8}"
          f"{'P90':>8}{'P95':>8}{'P99':>8}{'макс':>8}")
    for имя, d in (("MFE", mfe), ("MAE", mae)):
        print(f"  {имя:<10}{d['среднее']:>8}{d['P25']:>8}{d['медиана']:>10}"
              f"{d['P75']:>8}{d['P90']:>8}{d['P95']:>8}{d['P99']:>8}"
              f"{d['максимум']:>8}")

    бары = exit_lab.distribution([з["бар_лучшего_хода"] for з in замеры])
    print(f"\n  Когда случается лучший ход (номер бара после входа):")
    print(f"    медиана {бары['медиана']}, P75 {бары['P75']}, "
          f"P90 {бары['P90']}, максимум {бары['максимум']}")
    print(f"    Один бар M5 = 5 минут. Медиана {бары['медиана']} бара ≈ "
          f"{бары['медиана'] * 5:.0f} минут.")

    спред = exit_lab.distribution([з["spread_r"] for з in замеры])
    print(f"\n  Спред в единицах риска: медиана {спред['медиана']}R, "
          f"P90 {спред['P90']}R")

    # ------------------------------------------------------- 2. Корзины MFE
    заголовок(f"2. КОРЗИНЫ ХОДА В ПРИБЫЛЬ. {symbol}", "-")
    for к in exit_lab.buckets([з["mfe_r"] for з in замеры]):
        print(f"  {к['корзина']:<12} сделок {к['сделок']:>5}  {к['процент']:>5}%")

    # --------------------------------------------- 3. Дошли до уровня и дальше
    заголовок(f"3. ДОХОДИМОСТЬ ДО УРОВНЕЙ. {symbol}", "-")
    print("  «Дошли» — цена КОГДА-ЛИБО побывала на этом уровне за 8 часов.")
    print("  Само по себе это ещё ничего не значит: она могла сначала сходить")
    print("  вниз и выбить стоп. Поэтому рядом считается результат по ПОРЯДКУ")
    print("  движения: стоп 2 ATR (как сейчас), цель на этом уровне.")
    print(f"  {'уровень':<10}{'дошли':>8}{'%':>7}   ->  выход «стоп 2 ATR, "
          f"цель здесь»")
    for стр in exit_lab.reached(замеры):
        прогон = exit_lab.simulate(пути, 2.0, стр["уровень"], "worst")
        св = exit_lab.stats_r(прогон["r"])
        оценка = ("ПРИБЫЛЬНО" if св["ожидание"] > 0 else "убыточно")
        print(f"  +{стр['уровень']:<9}{стр['дошли']:>8}{стр['процент']:>7}"
              f"   ->  сделок {св['сделок']:>5}  ожидание {св['ожидание']:>8}R  "
              f"PF {св['профит_фактор']:>6}  винрейт {св['винрейт']:>5}%  {оценка}")

    # ------------------------------------------ 4. Фактическая статистика в R
    заголовок(f"4. ФАКТИЧЕСКАЯ ДОХОДНОСТЬ ПРИ НЫНЕШНЕМ ВЫХОДЕ. {symbol}", "-")
    print("  Это то, что даёт стратегия как есть — для сравнения с тем, что")
    print("  было бы возможно.")
    import baseline_engine
    прогон = baseline_engine.run(symbol, bars, данные["meta"])
    сделки = прогон["trades"]
    r_все = [float(t["r"]) for t in сделки if t.get("r") is not None]
    таблица_R("как сейчас, всё", exit_lab.stats_r(r_все))
    for сторона, метка in ((1, "как сейчас, BUY"), (-1, "как сейчас, SELL")):
        r = [float(t["r"]) for t in сделки if t["direction"] == сторона]
        таблица_R(метка, exit_lab.stats_r(r))

    # ------------------------------------------------- 5. Поверхность выходов
    заголовок(f"5. ПОВЕРХНОСТЬ ВЫХОДОВ: SL x TP -> ожидание. {symbol}", "-")
    print("  ВЫБОР ДЕЛАЕТСЯ ТОЛЬКО ПО TRAIN. Считать поверхность по всей")
    print("  истории и потом хвалиться лучшей клеткой — это подгонка: из 24")
    print("  клеток какая-нибудь окажется лучшей всегда, даже на случайных")
    print("  данных. Поэтому клетка выбирается здесь, а проверяется дальше.")
    print("  Худший сценарий внутри бара. Без перекрытия сделок, как в жизни.")

    куски = разбить_по_времени(пути, границы_времени)
    поверхность_train = exit_lab.surface(куски["TRAIN"])
    поверхность_вся = exit_lab.surface(пути)

    def печать_поверхности(пов, подпись):
        print(f"\n  {подпись}")
        print("  " + "SL \\ TP".ljust(9)
              + "".join(f"{tp}R".rjust(11) for tp in exit_lab.СЕТКА_TP_R))
        for sl in exit_lab.СЕТКА_SL_ATR:
            строка = "  " + f"{sl} ATR".ljust(9)
            for tp in exit_lab.СЕТКА_TP_R:
                строка += f"{пов[(sl, tp)]['ожидание']:>11}"
            print(строка)
        print("  " + "сделок".ljust(9)
              + "".join(f"{пов[(exit_lab.СЕТКА_SL_ATR[0], tp)]['сделок']:>11}"
                        for tp in exit_lab.СЕТКА_TP_R)
              + "   (при SL 1.0 ATR; в других строках близко)")

    печать_поверхности(поверхность_train, "TRAIN (по нему и выбираем):")
    печать_поверхности(поверхность_вся, "вся история (только для описания):")

    (sl_л, tp_л), св_л, хватило = exit_lab.best_cell(поверхность_train)
    print(f"\n  Лучшая клетка на TRAIN: SL {sl_л} ATR, TP {tp_л}R -> "
          f"ожидание {св_л['ожидание']}R, PF {св_л['профит_фактор']}, "
          f"сделок {св_л['сделок']}, винрейт {св_л['винрейт']}%")
    if not хватило:
        print("  ВНИМАНИЕ: ни в одной клетке не набралось 100 сделок. Клетка "
              "выбрана из недостаточных выборок — верить ей нельзя.")
    положительных = sum(1 for св in поверхность_train.values()
                        if св["ожидание"] > 0)
    print(f"  Клеток с положительным ожиданием на TRAIN: {положительных} из "
          f"{len(поверхность_train)}")

    # --------------------------------------------- 5б. Время удержания
    заголовок(f"5б. А ЕСЛИ ОГРАНИЧИТЬ ВРЕМЯ В СДЕЛКЕ. {symbol}", "-")
    print("  Вживую сделка живёт 8 минут. Выход, который держит позицию 8")
    print("  часов, — это уже другая стратегия, а не настройка нынешней.")
    print("  Лучшая клетка TRAIN при разном пределе времени:")
    for предел in (6, 12, 24, 48, 100):
        прогон = exit_lab.simulate(куски["TRAIN"], sl_л, tp_л, "worst",
                                   max_bars=предел)
        таблица_R(f"не дольше {предел * 5} мин", exit_lab.stats_r(прогон["r"]))

    # --------------------------------------------- 5в. Издержки
    заголовок(f"5в. ЧУВСТВИТЕЛЬНОСТЬ К ИЗДЕРЖКАМ. {symbol}", "-")
    спред_данных = exit_lab.distribution([з["spread_r"] for з in замеры])
    print(f"  В данных демо-счёта спред: медиана {спред_данных['медиана']}R, "
          f"P90 {спред_данных['P90']}R.")
    print("  Комиссия и своп в данных ОТСУТСТВУЮТ ВОВСЕ. На настоящем счёте")
    print("  они есть. Поэтому смотрим, что будет при добавочных издержках:")
    for добавка in (0.0, 0.02, 0.05, 0.10):
        прогон = exit_lab.simulate(куски["TRAIN"], sl_л, tp_л, "worst",
                                   extra_cost_r=добавка)
        таблица_R(f"+{добавка}R издержек", exit_lab.stats_r(прогон["r"]))

    # ------------------------------------- 6. Внутрибаровая чувствительность
    заголовок(f"6. ВНУТРИБАРОВАЯ ЧУВСТВИТЕЛЬНОСТЬ. {symbol}", "-")
    print("  Если внутри одного бара задет и стоп, и цель — порядок касаний")
    print("  по четырём ценам бара неизвестен. Лучший сценарий НЕ")
    print("  доказательство прибыльности, только верхняя граница.")
    print("  Смотрим и тесные клетки (там спорных случаев больше всего),")
    print("  и выбранную.")
    for sl, tp, метка in ((1.0, 0.5, "тесная 1.0/0.5"),
                          (1.0, 1.0, "тесная 1.0/1.0"),
                          (2.0, 1.0, "как сейчас 2.0/1.0"),
                          (sl_л, tp_л, f"выбранная {sl_л}/{tp_л}")):
        печатали_спорные = False
        for сценарий in exit_lab.СЦЕНАРИИ:
            прогон = exit_lab.simulate(куски["TRAIN"], sl, tp, сценарий, seed=1)
            св = exit_lab.stats_r(прогон["r"])
            if not печатали_спорные:
                доля = прогон["спорных_баров"] / max(len(прогон["r"]), 1) * 100
                print(f"\n  {метка}: спорных сделок "
                      f"{прогон['спорных_баров']} из {len(прогон['r'])} "
                      f"({доля:.1f}%)")
                печатали_спорные = True
            таблица_R(f"  {сценарий}", св)

    # ------------------------------------------ 7. Лучшая клетка на TRAIN/OOS
    заголовок(f"7. ЛУЧШАЯ КЛЕТКА НА ЧИСТОЙ ПРОВЕРКЕ. {symbol}", "-")
    print("  Клетка выбрана по TRAIN. Здесь она встречается с данными,")
    print("  которых при выборе не было. VALIDATION — предупреждение,")
    print("  OOS — приговор.")
    for имя, кусок in куски.items():
        if not кусок:
            continue
        итог = exit_lab.simulate(кусок, sl_л, tp_л, "worst")
        таблица_R(имя, exit_lab.stats_r(итог["r"]))

    # ----------------------------------------------- 8. BUY / SELL по окнам
    заголовок(f"8. BUY И SELL ПО ОКНАМ ВРЕМЕНИ. {symbol}", "-")
    print("  Сторона, плохая в одном окне и хорошая в другом, — это шум.")
    for сторона, метка in ((1, "BUY"), (-1, "SELL")):
        только = [з for з in замеры if з["direction"] == сторона]
        d = exit_lab.distribution([з["mfe_r"] for з in только])
        print(f"\n  {метка}: входов {d.get('n', 0)}, медиана MFE "
              f"{d.get('медиана', 0)}R, P90 {d.get('P90', 0)}R")
        for имя, кусок in разбить_по_времени(
                [п for п in пути if п["direction"] == сторона],
                границы_времени).items():
            if not кусок:
                continue
            итог = exit_lab.simulate(кусок, sl_л, tp_л, "worst")
            таблица_R(f"  {метка} {имя}", exit_lab.stats_r(итог["r"]))

    # ------------------------------------------------------- 9. Разбивки
    заголовок(f"9. РАЗБИВКИ ХОДА ЦЕНЫ. {symbol}", "-")
    for ключ, имя in (("session", "ПО СЕССИЯМ"), ("atr_bucket", "ПО ВОЛАТИЛЬНОСТИ"),
                      ("regime", "ПО РЕЖИМУ РЫНКА")):
        print(f"\n  {имя}:")
        группы = {}
        for з in замеры:
            группы.setdefault(з[ключ], []).append(з["mfe_r"])
        for имя_гр, значения in sorted(группы.items()):
            d = exit_lab.distribution(значения)
            метка = "" if d["n"] >= 100 else "  [UNKNOWN: мало входов]"
            print(f"    {имя_гр:<22} входов {d['n']:>5}  медиана MFE "
                  f"{d['медиана']:>6}R  P90 {d['P90']:>6}R{метка}")

    return {
        "symbol": symbol,
        "статус": "OK",
        "входов": len(замеры),
        "mfe": mfe,
        "mae": mae,
        "лучшая_клетка": {"sl_atr": sl_л, "tp_r": tp_л, "сводка": св_л},
        "положительных_клеток": положительных,
        "всего_клеток": len(поверхности["worst"]),
        "как_сейчас": exit_lab.stats_r(r_все),
        "oos_лучшей": exit_lab.stats_r(
            exit_lab.simulate(куски["OOS"], sl_л, tp_л, "worst")["r"])
        if куски["OOS"] else None,
    }


def main(argv) -> int:
    max_bars = 0
    символы = []
    i = 0
    while i < len(argv):
        а = argv[i]
        if а == "--bars":
            try:
                max_bars = int(argv[i + 1])
            except (IndexError, ValueError):
                print("После --bars нужно число.")
                return 2
            i += 2
            continue
        if not а.startswith("--"):
            символы.append(а)
        i += 1
    символы = символы or СИМВОЛЫ

    заголовок("ДИАГНОСТИКА СТРАТЕГИИ: ГДЕ НАХОДИТСЯ ПРОБЛЕМА")
    print("Ничего не меняется и ничего не рекомендуется. Только измерения.")
    print(f"Настройки взяты из: {run_baseline.ОТКУДА_НАСТРОЙКИ}")
    print(f"Терминал: {run_baseline.ОТКУДА_ТЕРМИНАЛ}")
    print()
    print("ГЛАВНАЯ ПОПРАВКА К ПРЕДЫДУЩЕМУ АНАЛИЗУ.")
    print("Раньше MFE брался из отчёта о сделке. Он измеряется, ПОКА СДЕЛКА")
    print("ОТКРЫТА, а закрывает её трейлинг-стоп — то есть данные обрезаны")
    print("самим правилом выхода. По ним нельзя отличить «рынок не даёт хода»")
    print("от «мы вышли слишком рано». Здесь путь цены пишется независимо от")
    print("выхода, и этот вопрос наконец получает ответ.")

    результаты = [по_инструменту(s, max_bars) for s in символы]

    заголовок("СВОДКА")
    for r in результаты:
        if r.get("статус") != "OK":
            print(f"{r['symbol']}: {r['статус']}")
            continue
        к = r["лучшая_клетка"]
        oos = r["oos_лучшей"]
        print(f"{r['symbol']}: входов {r['входов']}, медиана MFE "
              f"{r['mfe']['медиана']}R, P90 {r['mfe']['P90']}R")
        print(f"  как сейчас:      ожидание {r['как_сейчас']['ожидание']}R, "
              f"PF {r['как_сейчас']['профит_фактор']}")
        print(f"  лучший выход:    SL {к['sl_atr']} ATR / TP {к['tp_r']}R -> "
              f"ожидание {к['сводка']['ожидание']}R, PF "
              f"{к['сводка']['профит_фактор']}")
        print(f"  он же на OOS:    ожидание {oos['ожидание']}R, PF "
              f"{oos['профит_фактор']}, сделок {oos['сделок']}"
              if oos else "  он же на OOS:    нет данных")
        print(f"  клеток с плюсом: {r['положительных_клеток']} из "
              f"{r['всего_клеток']}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
