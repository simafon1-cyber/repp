"""ui_status.py — ПОЧЕМУ СЕЙЧАС НЕТ СДЕЛОК. Одним ответом, на видном месте.

ЗАЧЕМ ЭТОТ ФАЙЛ

Программа умеет отказываться торговать по нескольким причинам, и каждая
из них — правильная защита:

  * открыто происшествие (неясный ответ брокера) — до разбирательства;
  * отметку о происшествии не удалось записать, и её потеряли;
  * есть позиция без стоп-лосса — её убыток ничем не ограничен;
  * остались отправленные заявки, которым не нашлось позиции;
  * пауза после серии убытков;
  * LIVE_TRADING выключен — ордера вообще не уходят.

Беда была не в защитах, а в том, что человек о них не узнавал. В окне
писалось «Работает», а причина молчания лежала либо в журнале, либо в
ленте последних трёх событий, откуда её вытесняло следующее сообщение.
Владелец видел работающую программу без сделок и решал, что она зависла.

ЧТО ДЕЛАЕТ ЭТОТ ФАЙЛ

Из снимка состояния и нескольких флагов собирает КОРОТКИЙ список: что
сейчас с торговлей и почему. Ничего не решает, ничего не меняет, к
терминалу не обращается.

ПОЧЕМУ ОТДЕЛЬНЫМ ФАЙЛОМ, А НЕ ВНУТРИ ОКНА

Чтобы это можно было проверить тестом, не запуская окно. Ровно та же
причина, по которой отдельно живут ui_layout (ширина вкладок) и ui_theme
(контраст): решение принимается числом и текстом, а не «на глаз».

ЧЕГО ЭТОТ ФАЙЛ НЕ ДЕЛАЕТ

Не торгует, не снимает остановки, не трогает риск и стратегию. Он только
объясняет словами то, что программа уже решила.
"""

from __future__ import annotations

# Насколько строка важна. Определяет только вид, но порядок в списке
# задаётся именно ею: сначала то, из-за чего сделок НЕ БУДЕТ.
СТОП = "стоп"          # торговля остановлена или входы запрещены
ВНИМАНИЕ = "внимание"  # работает, но с оговоркой
СПОКОЙНО = "спокойно"  # всё в порядке

ПОРЯДОК = {СТОП: 0, ВНИМАНИЕ: 1, СПОКОЙНО: 2}


def _строка(важность: str, заголовок: str, пояснение: str = "") -> dict:
    return {"важность": важность, "заголовок": заголовок,
            "пояснение": пояснение}


def позиции_без_стопа(снимок: dict, magic_поле: str = "is_bot") -> list:
    """Наши открытые позиции без стоп-лосса — по данным, уже имеющимся у окна.

    Считаются только СВОИ. Чужая позиция без стопа — решение владельца, и
    новые входы бота она не блокирует: так же считает и торговый цикл."""
    итог = []
    for п in (снимок or {}).get("positions", []) or []:
        if not п.get(magic_поле, False):
            continue
        try:
            стоп = float(п.get("sl", 0) or 0)
        except (TypeError, ValueError):
            стоп = 0.0
        if стоп <= 0:
            итог.append(п)
    return итог


def собрать(снимок: dict = None,
            инцидент_открыт: bool = False,
            инцидент_причина: str = "",
            запись_терялась: bool = False,
            ожидающих_заявок: int = 0,
            на_паузе: bool = False,
            бот_запущен: bool = True) -> list:
    """Список строк о состоянии торговли, самые важные — первыми.

    Список НИКОГДА не бывает пустым: если сказать нечего, это тоже надо
    сказать. Пустое место человек читает как «программа молчит», а
    молчание он уже однажды принял за зависание."""
    снимок = снимок or {}
    строки = []

    # --- то, из-за чего сделок НЕ БУДЕТ ---
    if запись_терялась:
        строки.append(_строка(
            СТОП, "Торговля остановлена: отметка о происшествии потеряна",
            "Программа однажды не смогла записать её на диск, и её "
            "перезапустили. Что случилось — неизвестно. Проверьте счёт в "
            "терминале и удалите файл «инцидент_не_записан.txt» рядом с "
            "программой, когда разберётесь."))

    if инцидент_открыт:
        строки.append(_строка(
            СТОП, "Торговля остановлена: незакрытое происшествие",
            (инцидент_причина or "причина не читается")
            + ". Новые сделки не открываются, пока вы не проверите счёт в "
              "терминале и не снимете отметку."))

    без_стопа = позиции_без_стопа(снимок)
    if без_стопа:
        номера = ", ".join(str(п.get("ticket", "?")) for п in без_стопа[:5])
        строки.append(_строка(
            СТОП, f"Новых сделок не будет: позиция без стоп-лосса ({номера})",
            "У такой позиции убыток не ограничен ничем, кроме размера "
            "счёта. Поставьте стоп в терминале — и входы разрешатся сами."))

    if ожидающих_заявок:
        строки.append(_строка(
            СТОП if ожидающих_заявок else ВНИМАНИЕ,
            f"Отправленных заявок без подтверждения: {ожидающих_заявок}",
            "Заявка могла исполниться позже или быть ещё активной. Пока "
            "это не выяснено, риск по ним считается как по открытым."))

    # --- работает, но с оговоркой ---
    if not бот_запущен:
        строки.append(_строка(
            ВНИМАНИЕ, "Бот не запущен",
            "Сделок не будет, пока не нажата кнопка запуска."))
    elif на_паузе:
        строки.append(_строка(
            ВНИМАНИЕ, "Пауза",
            "Новые сделки не открываются. Открытые позиции при этом "
            "продолжают вестись как обычно."))

    if снимок.get("live_trading") is False:
        строки.append(_строка(
            ВНИМАНИЕ, "Проверочный режим: ордера брокеру НЕ отправляются",
            "Программа считает и записывает всё то же самое, но ни одна "
            "сделка на счёте не откроется. Это не поломка, а настройка "
            "LIVE_TRADING."))

    # --- если сказать нечего ---
    if not строки:
        строки.append(_строка(
            СПОКОЙНО, "Торговля разрешена",
            "Помех нет. Отсутствие сделок сейчас означает, что сигнал не "
            "прошёл порог, а не поломку — причины по каждой паре видны на "
            "вкладке «Символы»."))

    return упорядочить(строки)


def упорядочить(строки) -> list:
    """Сначала то, из-за чего сделок НЕ БУДЕТ, потом оговорки, потом «всё
    в порядке».

    ОТДЕЛЬНОЙ ФУНКЦИЕЙ, а не строчкой внутри собрать(), намеренно.
    Внутри собрать() строки и так добавляются по убыванию важности, и
    сортировка там ничего не меняет — а значит, её пропажу невозможно
    заметить тестом: список выглядит одинаково и с ней, и без неё.
    Именно так и вышло при первой проверке «наоборот».

    Здесь порядок можно проверить на заведомо перемешанном списке, и
    тогда проверка ловит настоящую пропажу, а не совпадение."""
    return sorted(строки or (), key=lambda с: ПОРЯДОК.get(с.get("важность"), 9))


def торговля_остановлена(строки) -> bool:
    """Есть ли среди причин хоть одна, из-за которой сделок не будет."""
    return any(с["важность"] == СТОП for с in строки or ())


def одной_строкой(строки) -> str:
    """Самое важное одной строкой — для верхней панели окна."""
    if not строки:
        return ""
    первая = строки[0]
    return первая["заголовок"]
