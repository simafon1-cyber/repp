"""run_edge_test.py — ЕСТЬ ЛИ У ВХОДА ПРЕИМУЩЕСТВО. Главный вопрос.

=====================================================================
ПОЧЕМУ БЕЗ КОНТРОЛЬНОЙ ГРУППЫ ОТВЕТА НЕТ
=====================================================================
Сказать «после наших входов цена проходит 2R» — значит не сказать ничего.
Она проходит 2R после ЛЮБОГО бара: за восемь часов рынок успевает сходить
куда угодно. Вопрос всегда сравнительный:

    ЛУЧШЕ ЛИ НАШИ ВХОДЫ, ЧЕМ ВЗЯТЫЕ НАУГАД
    в то же время, на том же инструменте, с тем же выходом?

Если не лучше — преимущества нет, и никакой стоп, никакая цель и никакой
трейлинг его не создадут. Выход умеет только сохранить или потерять то, что
дал вход; создать он не может ничего.

=====================================================================
КАК УСТРОЕНО СРАВНЕНИЕ
=====================================================================
Оба набора входов собираются В ОДНОМ ПРОГОНЕ по одним и тем же свечам:

  * НАШИ — те, что выбрала стратегия со всеми её фильтрами;
  * СЛУЧАЙНЫЕ — на случайном баре, в случайную сторону, без единого фильтра.

К обоим применяется ОДИН И ТОТ ЖЕ выход и одна и та же мера. Разница между
ними — это и есть вклад входного сигнала, очищенный от всего остального.

Проверяется не только среднее, но и случайность разницы: перестановочный
тест отвечает, могла ли такая разница получиться сама собой.
"""

import logging
import os
import random
import sys

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, ЗДЕСЬ)

import run_baseline  # noqa: E402

