import exit_lab         # noqa: E402
import history_data     # noqa: E402
import optimize         # noqa: E402

logging.basicConfig(level=logging.ERROR,
                    format="%(levelname)s %(name)s: %(message)s")

СИМВОЛЫ = ["EURUSD", "XAUUSD"]

# Доля баров, на которых берётся случайный вход. Подобрана так, чтобы
# случайных входов вышло примерно столько же, сколько настоящих: сравнивать
# выборки очень разного размера неудобно, а больше — незачем.
ДОЛЯ_СЛУЧАЙНЫХ = 0.06

# Выходы, при которых идёт сравнение. Разные нарочно: если преимущество есть,
# оно должно быть видно не при одном удачно подобранном выходе.
ВЫХОДЫ = ((2.0, 1.0), (2.0, 2.0), (1.5, 3.0), (1.0, 1.0))

ПЕРЕСТАНОВОК = 5000


def заголовок(текст, знак="="):
    print()
    print(знак * 78)
    print(текст)
    print(знак * 78)


def перестановочный_тест(a, b, перестановок=ПЕРЕСТАНОВОК, seed=0):
    """Могла ли разница средних получиться случайно.

    Метки «наши» и «случайные» тасуются тысячи раз. Если случайное деление
    даёт такую же разницу не реже чем в 5 случаях из 100, разница ничего не
    значит — сколько бы красиво она ни выглядела."""
    a = [float(x) for x in a]
    b = [float(x) for x in b]
    if not a or not b:
        return {"разница": 0.0, "случайность": 1.0}
    наблюдаемая = sum(a) / len(a) - sum(b) / len(b)
    общий = a + b
    rnd = random.Random(seed)
    не_хуже = 0
    for _ in range(перестановок):
        rnd.shuffle(общий)
        x = общий[:len(a)]
        y = общий[len(a):]
        if abs(sum(x) / len(x) - sum(y) / len(y)) >= abs(наблюдаемая) - 1e-12:
            не_хуже += 1
    return {"разница": round(наблюдаемая, 4),
            "случайность": round((не_хуже + 1) / (перестановок + 1), 4)}


def строка(имя, св):
    print(f"  {имя:<24} входов {св['сделок']:>5}  PF {св['профит_фактор']:>6}  "
          f"ожидание {св['ожидание']:>8}R  винрейт {св['винрейт']:>5}%  "
          f"в ноль {св['доля_нулевых']:>5}%  "
          f"ср.выигрыш {св['средний_выигрыш']:>6}R  ср.проигрыш "
          f"{св['средний_проигрыш']:>6}R  просадка {св['просадка']:>7}R")


def по_инструменту(symbol, max_bars):
    заголовок(f"ЕСТЬ ЛИ ПРЕИМУЩЕСТВО У ВХОДА: {symbol}")

    данные = history_data.load(symbol)
    if not данные["clean"] or not данные["quality"]["usable"]:
        print("СТАТУС: INSUFFICIENT DATA")
        return {"symbol": symbol, "статус": "INSUFFICIENT DATA"}

    bars = данные["clean"]
    if max_bars and len(bars) > max_bars:
        bars = bars[-int(max_bars):]
    границы = optimize.segments(bars)
    t1 = int(bars[границы["VALIDATION"][0]]["time"])
    t2 = int(bars[границы["OOS"][0]]["time"])

    print(f"Свечей: {len(bars)}. Оба набора входов собираются В ОДНОМ прогоне")
    print("по одним и тем же свечам, и к обоим применяется один и тот же выход.")

    итог = baseline_engine.run(symbol, bars, данные["meta"],
                               record_horizon=exit_lab.ГОРИЗОНТ,
                               record_random=ДОЛЯ_СЛУЧАЙНЫХ,
                               progress=lambda t: print(f"  {t}", flush=True))
    наши = итог["paths"]
    случайные = итог["random_paths"]
    print(f"\nНаших входов: {len(наши)}. Случайных: {len(случайные)}.")
    if not наши or not случайные:
        print("СТАТУС: сравнивать нечего.")
        return {"symbol": symbol, "статус": "НЕТ ДАННЫХ"}

    # ------------------------------------------------- ход цены сам по себе
    заголовок(f"ХОД ЦЕНЫ: НАШИ ВХОДЫ ПРОТИВ СЛУЧАЙНЫХ. {symbol}", "-")
    print("  Если фильтры что-то ловят, после наших входов цена должна")
    print("  проходить в нашу сторону больше, чем после случайных.")
    зам_наши = exit_lab.excursions(наши)
    зам_случ = exit_lab.excursions(случайные)
    for имя, з in (("НАШИ", зам_наши), ("СЛУЧАЙНЫЕ", зам_случ)):
        mfe = exit_lab.distribution([x["mfe_r"] for x in з])
        mae = exit_lab.distribution([x["mae_r"] for x in з])
        print(f"  {имя:<12} MFE: медиана {mfe['медиана']:>6}R  среднее "
              f"{mfe['среднее']:>6}R  P90 {mfe['P90']:>6}R   |   "
              f"MAE: медиана {mae['медиана']:>6}R  среднее {mae['среднее']:>6}R")

    # Разница MFE минус MAE — «перевес» в нашу сторону. У честной монеты ноль.
    перевес_наши = [x["mfe_r"] - x["mae_r"] for x in зам_наши]
    перевес_случ = [x["mfe_r"] - x["mae_r"] for x in зам_случ]
    ср_н = sum(перевес_наши) / len(перевес_наши)
    ср_с = sum(перевес_случ) / len(перевес_случ)
    тест = перестановочный_тест(перевес_наши, перевес_случ)
    print(f"\n  Перевес (MFE минус MAE), у монеты был бы ноль:")
    print(f"    НАШИ      {ср_н:+.4f}R")
    print(f"    СЛУЧАЙНЫЕ {ср_с:+.4f}R")
    print(f"    разница   {тест['разница']:+.4f}R, вероятность случайности "
          f"{тест['случайность']}")

    # ------------------------------------------------- при разных выходах
    заголовок(f"РЕЗУЛЬТАТ ПРИ ОДНОМ И ТОМ ЖЕ ВЫХОДЕ. {symbol}", "-")
    сводка = []
    for sl, tp in ВЫХОДЫ:
        r_наши = exit_lab.simulate(наши, sl, tp, "worst")["r"]
        r_случ = exit_lab.simulate(случайные, sl, tp, "worst")["r"]
        св_н = exit_lab.stats_r(r_наши)
        св_с = exit_lab.stats_r(r_случ)
        тест = перестановочный_тест(r_наши, r_случ)
        значимо = тест["случайность"] <= 0.05
        print(f"\n  ВЫХОД: стоп {sl} ATR, цель {tp}R")
        строка("    наши входы", св_н)
        строка("    случайные входы", св_с)
        print(f"    разница ожиданий {тест['разница']:+.4f}R, вероятность "
              f"случайности {тест['случайность']}  -> "
              f"{'ЗНАЧИМО' if значимо else 'НЕ ЗНАЧИМО'}")
        сводка.append({"sl": sl, "tp": tp, "наши": св_н, "случайные": св_с,
                       "тест": тест, "значимо": значимо})

    # ------------------------------------------------- по кускам времени
    заголовок(f"ТО ЖЕ ПО КУСКАМ ВРЕМЕНИ (эталонный выход 2 ATR / 1R). {symbol}", "-")
    print("  Преимущество, которое есть в одном куске и пропадает в другом,")
    print("  преимуществом не является.")
    for имя, отбор in (("TRAIN", lambda p: p["entry_time"] < t1),
                       ("VALIDATION", lambda p: t1 <= p["entry_time"] < t2),
                       ("OOS", lambda p: p["entry_time"] >= t2)):
        r_н = exit_lab.simulate([p for p in наши if отбор(p)], 2.0, 1.0, "worst")["r"]
        r_с = exit_lab.simulate([p for p in случайные if отбор(p)], 2.0, 1.0, "worst")["r"]
        т = перестановочный_тест(r_н, r_с)
        св_н, св_с = exit_lab.stats_r(r_н), exit_lab.stats_r(r_с)
        print(f"\n  {имя}:")
        строка("    наши", св_н)
        строка("    случайные", св_с)
        print(f"    разница {т['разница']:+.4f}R, случайность {т['случайность']}")

    return {"symbol": symbol, "статус": "OK", "наших": len(наши),
            "случайных": len(случайные), "сводка": сводка,
            "перевес_наши": round(ср_н, 4), "перевес_случайные": round(ср_с, 4)}


def main(argv) -> int:
    max_bars = 0
    символы = []
    i = 0
    while i < len(argv):
        а = argv[i]
        if а == "--bars":
            try:
                max_bars = int(argv[i + 1])
            except (IndexError, ValueError):
                print("После --bars нужно число.")
                return 2
            i += 2
            continue
        if not а.startswith("--"):
            символы.append(а)
        i += 1
    символы = символы or СИМВОЛЫ

    заголовок("ГЛАВНЫЙ ВОПРОС: ЛУЧШЕ ЛИ НАШИ ВХОДЫ СЛУЧАЙНЫХ")
    print("Выход умеет только сохранить или потерять то, что дал вход.")
    print("Создать преимущество он не может. Поэтому сначала проверяется вход.")

    результаты = [по_инструменту(s, max_bars) for s in символы]

    заголовок("ВЕРДИКТ")
    for r in результаты:
        if r.get("статус") != "OK":
            print(f"{r['symbol']}: {r['статус']}")
            continue
        значимых = [с for с in r["сводка"] if с["значимо"]]
        лучше = [с for с in значимых
                 if с["тест"]["разница"] > 0]
        print(f"\n{r['symbol']}: наших входов {r['наших']}, "
              f"случайных {r['случайных']}")
        print(f"  перевес наших {r['перевес_наши']:+}R против "
              f"{r['перевес_случайные']:+}R у случайных")
        print(f"  выходов, где разница значима: {len(значимых)} из "
              f"{len(r['сводка'])}; из них в нашу пользу: {len(лучше)}")
        if not значимых:
            print("  ВЫВОД: отличить наши входы от случайных не удалось.")
        elif len(лучше) == len(значимых):
            print("  ВЫВОД: наши входы значимо лучше случайных.")
        else:
            print("  ВЫВОД: разница есть, но не в одну сторону — это шум.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
