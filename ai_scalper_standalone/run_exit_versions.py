def окно_минуток(bars, m1_bars):
    """Кусок M5, целиком покрытый минутками. Пусто — покрытия нет.

    Считать версию B на всей истории нельзя: там, где минуток нет, она
    молча превратилась бы в версию A, и разница означала бы не «M1 лучше»,
    а «на этом куске другие сделки»."""
    if not bars or not m1_bars:
        return []
    начало = max(int(bars[0]["time"]), int(m1_bars[0]["time"]))
    конец = min(int(bars[-1]["time"]), int(m1_bars[-1]["time"]))
    return [b for b in bars if начало <= int(b["time"]) <= конец]


def проверка_по_минуткам(symbol, bars, meta, m1_bars):
    """BASELINE, лестница и версия B на ОДНОМ И ТОМ ЖЕ куске истории."""
    кусок = окно_минуток(bars, m1_bars)
    if len(кусок) < baseline_engine_окно() * 2:
        print(f"  {symbol}: минутки покрывают слишком короткий кусок "
              f"({len(кусок)} свечей M5) — версию B считать не на чем")
        return None

    доля = len(кусок) / len(bars) * 100
    заголовок(f"{symbol}: ВЕРСИЯ B НА ОКНЕ, ГДЕ ЕСТЬ МИНУТКИ "
              f"({len(кусок)} свечей M5 = {доля:.0f}% истории)")
    print("ВНИМАНИЕ. Это НЕ полная проверка. Минутки покрывают только конец\n"
          "истории, и этот конец попадает в отрезок OOS. Подбирать по нему\n"
          "нельзя — можно только посмотреть. Все три версии считаются на\n"
          "ОДНОМ куске, поэтому между собой они сравнимы.\n")

    пометка_совпадения(ВЕРСИИ)
    отрезок = (0, len(кусок))
    итоги = {}
    for версия in ВЕРСИИ:
        если_B = bool(версия.get("по_минуткам"))
        прогон = optimize.run_variant(symbol, кусок, meta, версия, отрезок,
                                      m1_bars=m1_bars if если_B else None)
        итоги[версия["код"]] = прогон
        print(f"  {версия['код']:<20} сделок {len(прогон['trades']):>5}  "
              f"итог {sum(прогон['money']):>10.2f}$", flush=True)

    коды = [в["код"] for в in ВЕРСИИ]
    печать_таблицы({к: итоги[к]["сводка"] for к in коды}, коды)

    print()
    база = итоги["BASELINE"]
    for код in ("A", "B"):
        если_есть = итоги.get(код)
        if not если_есть:
            continue
        итог = optimize.compare(база, если_есть)
        print(f"  {код:<4} против BASELINE: {итог['решение'].upper()}, "
              f"способов за {итог['способов_за']}/5 — {итог['причина']}")
    if итоги.get("A") and итоги.get("B"):
        итог = optimize.compare(итоги["A"], итоги["B"])
        print(f"  B против A (то есть ЧТО ДАЛИ САМИ МИНУТКИ): "
              f"{итог['решение'].upper()}, способов за {итог['способов_за']}/5")
        print(f"       {итог['причина']}")
    return итоги


