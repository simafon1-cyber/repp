def загрузить(symbol: str, max_bars: int):
    данные = history_data.load(symbol)
    if not данные["clean"] or not данные["quality"]["usable"]:
        return None, None, None
    bars = данные["clean"]
    if max_bars and len(bars) > max_bars:
        bars = bars[-int(max_bars):]
    return bars, данные["meta"], загрузить_минутки(symbol)


def загрузить_минутки(symbol: str):
    """Минутные свечи или None. Их отсутствие — обычное дело, а не ошибка."""
    try:
        м = history_data.load(symbol, timeframe="M1")
    except Exception:
        return None
    if not м or not м.get("clean"):
        return None
    return м["clean"]


def версии_для(m1_bars):
    """Версия B участвует только тогда, когда есть чем её считать."""
    if m1_bars:
        return list(ВЕРСИИ)
    return [в for в in ВЕРСИИ if not в.get("по_минуткам")]


def совпадает_с_нынешними(версия) -> bool:
    """Вариант уже стал настройкой по умолчанию?

    Так бывает после внедрения: вариант приняли, записали в config.py — и
    он превратился в копию BASELINE. Числа при этом верные, а подпись
    врёт: читатель видит два столбца и думает, что сравнил два поведения.
    Поэтому такие варианты помечаются вслух."""
    import config as cfg
    настройки = версия.get("настройки") or {}
    if not настройки:
        return False
    for имя, знач in настройки.items():
        текущее = getattr(cfg, имя, None)
        if isinstance(знач, (list, tuple)) and isinstance(текущее, (list, tuple)):
            if [list(x) for x in знач] != [list(x) for x in текущее]:
                return False
        elif текущее != знач:
            return False
    return True


def пометка_совпадения(список_версий):
    """Сказать вслух, какие столбцы окажутся одинаковыми и почему."""
    одинаковые = [в["код"] for в in список_версий
                  if в["код"] != "BASELINE" and совпадает_с_нынешними(в)]
    if одинаковые:
        print("  ВНИМАНИЕ: " + ", ".join(одинаковые) + " — это уже НАСТРОЙКА "
              "ПО УМОЛЧАНИЮ.\n  Столбец совпадёт с BASELINE до последней "
              "цифры. Это не ошибка расчёта:\n  вариант когда-то приняли и "
              "записали в config.py.")
    return одинаковые


