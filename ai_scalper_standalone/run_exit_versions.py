def отношение(св: dict) -> float:
    убыток = float(св.get("средний_проигрыш", 0) or 0)
    return float(св.get("средний_выигрыш", 0) or 0) / убыток if убыток > 0 else 0.0


def печать_таблицы(сводки: dict, заголовки):
    """сводки: код версии -> сводка. Столбцы в порядке заголовки."""
    ширина = 20
    print(f"{'':<22}" + "".join(f"{к[:ширина - 1]:>{ширина}}" for к in заголовки))
    for подпись, ключ, формат in СТРОКИ_ОТЧЁТА:
        ячейки = []
        for к in заголовки:
            св = сводки.get(к) or {}
            знач = отношение(св) if ключ == "_отношение" else св.get(ключ, 0)
            try:
                ячейки.append(f"{формат.format(float(знач or 0)):>{ширина}}")
            except (TypeError, ValueError):
                ячейки.append(f"{'—':>{ширина}}")
        print(f"{подпись:<22}" + "".join(ячейки))


