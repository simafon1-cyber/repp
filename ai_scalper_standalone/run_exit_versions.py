def по_инструменту(symbol: str, max_bars: int):
    заголовок(f"{symbol}: ВЕРСИИ УПРАВЛЕНИЯ ОТКРЫТОЙ СДЕЛКОЙ")

    bars, meta, m1_bars = загрузить(symbol, max_bars)
    if bars is None:
        print("СТАТУС: INSUFFICIENT DATA — истории нет или она негодна.")
        return None

    список_версий = версии_для(m1_bars)
    if m1_bars:
        print(f"  минутных свечей: {len(m1_bars)} — версия B считается")
    else:
        print("  минутных свечей нет — версия B ПРОПУЩЕНА (проверить нечем)")

    пометка_совпадения(список_версий)
    границы = optimize.segments(bars)
    результаты = {}          # отрезок -> код версии -> прогон

    for имя_отрезка in ("TRAIN", "VALIDATION", "OOS"):
        результаты[имя_отрезка] = {}
        for версия in список_версий:
            прогон = прогон_версии(symbol, bars, meta, версия,
                                   границы[имя_отрезка], m1_bars)
            результаты[имя_отрезка][версия["код"]] = прогон
            print(f"  {имя_отрезка:<11} {версия['код']:<20} "
                  f"сделок {len(прогон['trades']):>5}  "
                  f"итог {sum(прогон['money']):>10.2f}$", flush=True)

    коды = [в["код"] for в in список_версий]

    for имя_отрезка in ("TRAIN", "VALIDATION", "OOS"):
        заголовок(f"{symbol} / {имя_отрезка}", "-")
        печать_таблицы(
            {к: результаты[имя_отрезка][к]["сводка"] for к in коды}, коды)

    # ВОРОТА. Считаются на TRAIN и на VALIDATION. На OOS — НЕТ: по правилу
    # владельца OOS нельзя использовать для подбора, его можно только
    # посмотреть в конце.
    for имя_отрезка in ("TRAIN", "VALIDATION"):
        заголовок(f"{symbol} / {имя_отрезка}: ПЯТЬ ВОРОТ ПРОВЕРКИ", "-")
        база = результаты[имя_отрезка]["BASELINE"]
        for версия in список_версий[1:]:
            вариант = результаты[имя_отрезка][версия["код"]]
            итог = optimize.compare(база, вариант)
            # gate отдаёт СПИСОК подробностей по каждому способу, а не
            # словарь: у каждого способа есть своё имя внутри записи.
            способы = ", ".join(
                f"{с.get('способ', '?')}:"
                f"{'за' if с.get('улучшение') else 'против'}"
                for с in (итог.get("способы") or ()))
            print(f"  {версия['код']:<20} {итог['решение'].upper():<10} "
                  f"способов за {итог['способов_за']}/5   "
                  f"прибылен: {'да' if итог['прибылен'] else 'НЕТ'}")
            print(f"  {'':<20} {способы}")
            print(f"  {'':<20} {итог['причина']}")

    заголовок(f"{symbol} / OOS: только посмотреть, подбирать по нему нельзя", "-")
    for к in коды:
        св = результаты["OOS"][к]["сводка"]
        print(f"  {к:<20} сделок {св['сделок']:>5}  PF {св['профит_фактор']:>6.3f}  "
              f"ожидание {св['ожидание']:>9.4f}$  просадка {св['макс_просадка']:>8.2f}$  "
              f"восстановление {св['фактор_восстановления']:>6.3f}")

    # ПОКУПКИ И ПРОДАЖИ ОТДЕЛЬНО — задание, пункт 17.
    заголовок(f"{symbol}: ПОКУПКИ И ПРОДАЖИ ОТДЕЛЬНО (все отрезки вместе)", "-")
    for к in коды:
        все = [t for о in ("TRAIN", "VALIDATION", "OOS")
               for t in результаты[о][к]["trades"]]
        стороны = trade_stats.by_direction(все)
        for сторона in ("BUY", "SELL"):
            св = стороны.get(сторона) or {}
            print(f"  {к:<20} {сторона:<5} сделок {св.get('сделок', 0):>5}  "
                  f"PF {св.get('профит_фактор', 0):>6.3f}  "
                  f"ожидание {св.get('ожидание', 0):>9.4f}$")

    return результаты


