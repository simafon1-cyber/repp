"""run_exit_versions.py — BASELINE против новых версий управления сделкой.

Отвечает на один вопрос:

    СТАЛО ЛИ ЛУЧШЕ ОТ НОВОГО ВЕДЕНИЯ ОТКРЫТОЙ ПОЗИЦИИ?

Ничего не подбирает и не оптимизирует. Прогоняет заранее заданные версии
на ОДНОЙ И ТОЙ ЖЕ истории, с одним и тем же входом, одним и тем же риском
и одним и тем же первоначальным стопом — и показывает числа рядом.

ЧТО ТАКОЕ ВЕРСИИ

    BASELINE    нынешнее поведение, как оно есть в config.py
    A           лестница защиты прибыли по R + без механизмов, зависящих
                от времени (задание владельца, пункты 4 и 6)
    A-БЕЗ-ВРЕМЕНИ  только выключение механизмов времени, лестница прежняя
    A-ТОЛЬКО-ЛЕСТНИЦА  только новая лестница, механизмы времени на месте
    B           A + ведение позиции по M1

Две средние версии нужны, чтобы не путать два изменения в одном. Если A
окажется лучше или хуже, по ней одной невозможно понять, что именно
сработало, — а это ровно та ошибка, из-за которой потом «улучшение»
разваливается.

ПОЧЕМУ ВЕРСИИ B ЗДЕСЬ НЕТ. Для ведения по M1 нужны минутные свечи, а в
репозитории их нет — есть только M5. Пункт 16 задания требует «одинаковую
историю» для всех версий, и подменить M1 чем-то другим значит сравнивать
разные вещи. Версия B помечена НЕ ПРОВЕРЕНА и ждёт выгрузки M1.

Запуск:
    python run_exit_versions.py                # EURUSD и XAUUSD
    python run_exit_versions.py EURUSD         # один инструмент
    python run_exit_versions.py --bars 40000   # по последним свечам
"""

