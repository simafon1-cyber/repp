def вход_A(ряд, i):
    """Immediate breakout: вход по закрытию первого бара после выпуска,
    в сторону его тела."""
    б = ряд[i]
    знак = 1 if б["c"] > б["o"] else (-1 if б["c"] < б["o"] else 0)
    return (i + 1, б["c"], знак) if знак else None


def вход_B(ряд, i, доля=0.33, ждать=3):
    """First impulse + pullback: после импульсного бара ждём отката на треть
    его диапазона, входим по направлению импульса."""
    б = ряд[i]
    знак = 1 if б["c"] > б["o"] else (-1 if б["c"] < б["o"] else 0)
    if not знак:
        return None
    диапазон = б["h"] - б["l"]
    if диапазон <= 0:
        return None
    уровень = (б["c"] - доля * диапазон) if знак == 1 else (б["c"] + доля * диапазон)
    for k in range(i + 1, min(i + 1 + ждать, len(ряд))):
        достиг = (ряд[k]["l"] <= уровень) if знак == 1 else (ряд[k]["h"] >= уровень)
        if достиг:
            return (k + 1, уровень, знак)
    return None


def вход_C(ряд, i):
    """Breakout confirmation: вход только если ВТОРОЙ бар закрылся за
    экстремумом первого в ту же сторону."""
    б, в = ряд[i], ряд[i + 1]
    знак = 1 if б["c"] > б["o"] else (-1 if б["c"] < б["o"] else 0)
    if not знак:
        return None
    подтвердил = (в["c"] > б["h"]) if знак == 1 else (в["c"] < б["l"])
    return (i + 2, в["c"], знак) if подтвердил else None


def вход_D(ряд, i, ждать=6):
    """Delayed breakout: вход через 30 минут, в сторону накопленного хода."""
    k = i + ждать
    if k + 1 >= len(ряд):
        return None
    ход = ряд[k]["c"] - ряд[i]["o"]
