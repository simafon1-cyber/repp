def выход(ряд, начало, цена, знак, sl_atr, tp_r, atr, предел_баров,
          издержки_r=0.0):
    """Пройти путь по порядку. Возвращает результат в R и число баров."""
    sl = sl_atr * atr
    tp = tp_r * sl
    for k in range(начало, min(начало + предел_баров, len(ряд))):
        плюс = (ряд[k]["h"] - цена) if знак == 1 else (цена - ряд[k]["l"])
        минус = (цена - ряд[k]["l"]) if знак == 1 else (ряд[k]["h"] - цена)
        стоп = минус >= sl
        цель = tp > 0 and плюс >= tp
        if стоп and цель:
            return -1.0 - издержки_r, k - начало + 1, "спорный"
        if стоп:
            return -1.0 - издержки_r, k - начало + 1, "стоп"
        if цель:
            return tp_r - издержки_r, k - начало + 1, "цель"
    k = min(начало + предел_баров, len(ряд)) - 1
    if k < начало:
        return 0.0, 0, "нет данных"
    итог = ((ряд[k]["c"] - цена) if знак == 1 else (цена - ряд[k]["c"])) / sl
    return итог - издержки_r, k - начало + 1, "по времени"


