def события(ряд: list, окно: str) -> list:
    """Все дни, где в нужную минуту есть бар. Возвращает список словарей.

    Индекс i — бар, который ЗАКРЫВАЕТСЯ через 5 минут после выпуска, то есть
    первый бар, целиком содержащий реакцию. Его открытие = момент выпуска."""
    час, мин = ОКНА[окно] if окно in ОКНА else КОНТРОЛЬ
    по_времени = индекс_по_времени(ряд)
    итог = []
    видели = set()
    for b in ряд:
        день = dt.datetime.utcfromtimestamp(b["t"]).date()
        if день in видели:
            continue
        видели.add(день)
        момент = серверное_время_события(день, час, мин)
        if момент is None:
            continue
        ts = int(момент.replace(tzinfo=dt.timezone.utc).timestamp())
        i = по_времени.get(ts)
        if i is None or i < 30 or i + ГОРИЗОНТ_БАРОВ >= len(ряд):
            continue
        итог.append({"i": i, "день": день, "ts": ts,
                     "nfp": первая_пятница(день),
                     "среда": день.weekday() == 2})
    return итог


