"""news_research.py — ИССЛЕДОВАНИЕ: есть ли отдельный edge вокруг новостей.

НИЧЕГО НЕ МЕНЯЕТ В ПРОГРАММЕ. Только читает выгруженные свечи и считает.

=====================================================================
ГЛАВНОЕ ОГРАНИЧЕНИЕ, КОТОРОЕ НАДО ЗНАТЬ ДО ВСЕХ ЧИСЕЛ
=====================================================================
ИСТОРИЧЕСКОГО КАЛЕНДАРЯ НЕТ. Ни один из источников программы (MT5
CalendarExport, Forex Factory, Finnhub) не хранит прошлые события у нас на
диске: они отдают ближайшие дни и только. Значит нельзя ни разделить NFP и
CPI, ни узнать actual/forecast/previous, ни посчитать сюрприз.

Выдумывать эти данные нельзя. Поэтому здесь используется ЗАМЕНИТЕЛЬ, и он
честно назван заменителем:

    ВРЕМЕННОЕ ОКНО ВЫПУСКА, А НЕ КОНКРЕТНАЯ НОВОСТЬ.

Основные макроданные США выходят по расписанию, в одни и те же минуты:
  * 08:30 по Нью-Йорку — NFP, CPI, PPI, розничные продажи, ВВП, заявки;
  * 10:00 по Нью-Йорку — ISM, индексы настроений;
  * 14:00 по Нью-Йорку — решение ФРС (по средам, восемь раз в год).

Эти минуты известны заранее и заглядыванием вперёд не являются: расписание
публикуется за год. Что именно вышло в конкретный день — неизвестно, и это
записано в ограничениях.

ОДНО ИСКЛЮЧЕНИЕ, ГДЕ СОБЫТИЕ ОПОЗНАЁТСЯ ТОЧНО: NFP выходит в первую пятницу
месяца в 08:30 по Нью-Йорку. Это календарное правило, а не подгонка под
данные, поэтому такие дни выделены отдельно.

=====================================================================
ЧАСОВОЙ ПОЯС — ПРОВЕРЕН ПО САМИМ ДАННЫМ, А НЕ ВЗЯТ ИЗ ПАСПОРТА
=====================================================================
В паспорте выгрузки записано смещение сервера -2.0 ч (EURUSD) и -3.0 ч
(XAUUSD). Это НЕВЕРНО: у одного сервера не может быть двух часовых поясов.
Смещение там вычислялось по свежести последнего тика, а выгрузка шла в
субботу, когда рынок закрыт, — получилась не разница поясов, а возраст
последней котировки.

Настоящий пояс определён по недельным разрывам в самих свечах: неделя
закрывается в пятницу 23:55 и открывается в понедельник 00:00 по времени
сервера. Форекс закрывается в 17:00 по Нью-Йорку, значит сервер живёт по
EET/EEST — UTC+2 зимой и UTC+3 летом, переходя вместе с Европой.

Отсюда важное следствие: и Нью-Йорк, и сервер переходят на летнее время,
поэтому 08:30 по Нью-Йорку — это 15:30 по серверу КРУГЛЫЙ ГОД. Кроме двух
коротких промежутков в марте и в конце октября, когда Европа и США
переключаются в разные дни: эти недели исключаются целиком.
"""

import csv
import datetime as dt
import math
import os
import random

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))

# Минуты выпуска по времени НЬЮ-ЙОРКА. Расписание публичное и известно
# заранее — заглядыванием вперёд не является.
ОКНА = {
    "US_0830": (8, 30),      # NFP, CPI, PPI, розница, ВВП, заявки
    "US_1000": (10, 0),      # ISM, индексы настроений
    "US_1400": (14, 0),      # решение ФРС (по средам)
}

# Спокойная минута для контрольной группы: в это время макроданных США не
# выходит. Нужна, чтобы отличить «эффект новости» от «эффекта любой минуты».
КОНТРОЛЬ = (5, 30)

# Сколько баров M5 после события смотрим. 12 баров = час.
ГОРИЗОНТ_БАРОВ = 12

БАР = 300               # секунд в баре M5


# =====================================================================
# ВРЕМЯ
