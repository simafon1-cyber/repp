def _последнее_воскресенье(год: int, месяц: int) -> dt.date:
    д = dt.date(год, месяц, 1)
    следующий = dt.date(год + (месяц == 12), (месяц % 12) + 1, 1)
    д = следующий - dt.timedelta(days=1)
    return д - dt.timedelta(days=(д.weekday() + 1) % 7)


def _второе_воскресенье_марта(год: int) -> dt.date:
    д = dt.date(год, 3, 1)
    первое = д + dt.timedelta(days=(6 - д.weekday()) % 7)
    return первое + dt.timedelta(days=7)


def _первое_воскресенье_ноября(год: int) -> dt.date:
    д = dt.date(год, 11, 1)
    return д + dt.timedelta(days=(6 - д.weekday()) % 7)


def летнее_в_сша(день: dt.date) -> bool:
    """Действует ли летнее время в США. Со второго воскресенья марта по
    первое воскресенье ноября."""
    return _второе_воскресенье_марта(день.year) <= день < _первое_воскресенье_ноября(день.year)


def летнее_в_европе(день: dt.date) -> bool:
    """Действует ли летнее время в Европе. С последнего воскресенья марта по
    последнее воскресенье октября."""
    return (_последнее_воскресенье(день.year, 3) <= день
            < _последнее_воскресенье(день.year, 10))


def смещение_сервера(день: dt.date) -> int:
    """Часы сервера относительно UTC. EET зимой (+2), EEST летом (+3)."""
    return 3 if летнее_в_европе(день) else 2


def рассинхрон(день: dt.date) -> bool:
    """Недели, когда Европа и США уже/ещё на разном времени.

    В эти дни привязка «08:30 Нью-Йорка = 15:30 сервера» ломается на час.
    Их проще исключить целиком, чем подгонять: их мало, а ошибка в час
    полностью обесценила бы замер."""
    return летнее_в_сша(день) != летнее_в_европе(день)


def серверное_время_события(день: dt.date, час_ny: int, мин_ny: int):
    """Момент выпуска в СЕРВЕРНОМ времени. None — день исключён."""
    if рассинхрон(день):
        return None
    смещение_ny = -4 if летнее_в_сша(день) else -5
    utc_час = час_ny - смещение_ny
    сервер_час = utc_час + смещение_сервера(день)
    return dt.datetime(день.year, день.month, день.day) + dt.timedelta(
        hours=сервер_час, minutes=мин_ny)


def первая_пятница(день: dt.date) -> bool:
    """NFP выходит в первую пятницу месяца. Правило календарное, не подогнано
    под данные."""
    return день.weekday() == 4 and день.day <= 7


