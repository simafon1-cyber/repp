def замер(ряд: list, событие: dt.date, i: int, point: float) -> dict:
    """Что произошло после выпуска. Всё — в единицах ATR ДО события."""
    atr = atr_до(ряд, i)
    if atr <= 0:
        return {}
    старт = ряд[i]["o"]                     # цена в момент выпуска
    окно = ряд[i:i + ГОРИЗОНТ_БАРОВ]

    доходности = {}
    for минут in (5, 10, 15, 30, 60):
        k = минут // 5 - 1
        if k < len(окно):
            доходности[минут] = (окно[k]["c"] - старт) / atr

    вверх = max(b["h"] for b in окно) - старт
    вниз = старт - min(b["l"] for b in окно)
    бар_вверх = max(range(len(окно)), key=lambda k: окно[k]["h"])
    бар_вниз = min(range(len(окно)), key=lambda k: окно[k]["l"])

    импульс = окно[0]["c"] - окно[0]["o"]
    знак = 1 if импульс > 0 else (-1 if импульс < 0 else 0)
    диапазон = окно[0]["h"] - окно[0]["l"]

    спред_до = sum(ряд[k]["s"] for k in range(i - 12, i)) / 12.0
    спред_после = окно[0]["s"]
    спред_макс = max(b["s"] for b in окно[:6])

    # Куда пошло ДАЛЬШЕ, после первого бара — совпало ли с первым импульсом.
    потом = окно[-1]["c"] - окно[0]["c"]
    return {
        "день": событие, "atr": atr, "point": point,
        "доходности": доходности,
        "MFE": вверх / atr, "MAE": вниз / atr,
        "бар_MFE": бар_вверх + 1, "бар_MAE": бар_вниз + 1,
        "импульс_atr": импульс / atr, "импульс_знак": знак,
        "диапазон_atr": диапазон / atr,
        "спред_до": спред_до, "спред_после": спред_после,
        "спред_макс": спред_макс,
        "спред_до_atr": спред_до * point / atr,
        "спред_после_atr": спред_после * point / atr,
        "продолжение": 1 if потом * знак > 0 else (-1 if потом * знак < 0 else 0),
    }


