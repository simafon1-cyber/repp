def читать(symbol: str) -> list:
    путь = os.path.join(ЗДЕСЬ, "history", "raw", f"{symbol}_M5.csv")
    if not os.path.exists(путь):
        return []
    ряд = []
    with open(путь, encoding="utf-8") as f:
        for r in csv.DictReader(f, delimiter=";"):
            ряд.append({
                "t": int(r["time"]),
                "o": float(r["open"]), "h": float(r["high"]),
                "l": float(r["low"]), "c": float(r["close"]),
                "v": int(r["tick_volume"]), "s": int(float(r["spread"])),
            })
    ряд.sort(key=lambda b: b["t"])
    return ряд


def индекс_по_времени(ряд: list) -> dict:
    return {b["t"]: i for i, b in enumerate(ряд)}


def atr_до(ряд: list, i: int, период: int = 14) -> float:
    """ATR по барам СТРОГО ДО i. Ни одного бара из будущего."""
    if i < период + 1:
        return 0.0
    сумма = 0.0
    for k in range(i - период, i):
        пред = ряд[k - 1]["c"]
        tr = max(ряд[k]["h"] - ряд[k]["l"],
                 abs(ряд[k]["h"] - пред), abs(пред - ряд[k]["l"]))
        сумма += tr
    return сумма / период


