def перцентиль(ряд, доля):
    if not ряд:
        return 0.0
    р = sorted(ряд)
    м = доля * (len(р) - 1)
    н = int(math.floor(м))
    в = min(н + 1, len(р) - 1)
    return р[н] * (1 - (м - н)) + р[в] * (м - н)


def сводка(r):
    ряд = [float(x) for x in (r or ())]
    n = len(ряд)
    if not n:
        return {"n": 0, "ожидание": 0.0, "PF": 0.0, "винрейт": 0.0,
                "ср_выигрыш": 0.0, "ср_проигрыш": 0.0, "просадка": 0.0,
                "итог": 0.0}
    в = [x for x in ряд if x > 0]
    п = [x for x in ряд if x < 0]
    сум_в, сум_п = sum(в), -sum(п)
    итог = пик = про = 0.0
    for x in ряд:
        итог += x
        пик = max(пик, итог)
        про = max(про, пик - итог)
    return {
        "n": n,
        "ожидание": round(sum(ряд) / n, 4),
        "PF": round(сум_в / сум_п, 3) if сум_п > 0 else 0.0,
        "винрейт": round(len(в) / n * 100, 1),
        "ср_выигрыш": round(сум_в / len(в), 3) if в else 0.0,
        "ср_проигрыш": round(сум_п / len(п), 3) if п else 0.0,
        "просадка": round(про, 2),
        "итог": round(итог, 2),
    }


def перестановка(a, b, раз=5000, seed=0):
    """Могла ли разница средних получиться случайно."""
    a = [float(x) for x in a]
    b = [float(x) for x in b]
    if not a or not b:
        return 1.0
    набл = sum(a) / len(a) - sum(b) / len(b)
    общий = a + b
    rnd = random.Random(seed)
    не_хуже = 0
    for _ in range(раз):
        rnd.shuffle(общий)
        x, y = общий[:len(a)], общий[len(a):]
        if abs(sum(x) / len(x) - sum(y) / len(y)) >= abs(набл) - 1e-12:
            не_хуже += 1
    return (не_хуже + 1) / (раз + 1)


def бутстрап(r, раз=2000, seed=0):
    """Границы 95% для ожидания."""
    ряд = [float(x) for x in r]
    if len(ряд) < 5:
        return (0.0, 0.0)
    rnd = random.Random(seed)
    средние = []
    for _ in range(раз):
        выборка = [ряд[rnd.randrange(len(ряд))] for _ in range(len(ряд))]
        средние.append(sum(выборка) / len(выборка))
    средние.sort()
    return (round(перцентиль(средние, 0.025), 4),
            round(перцентиль(средние, 0.975), 4))
