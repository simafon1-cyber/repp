def серия_баров(ряд, i, сколько=4):
    """После нескольких однонаправленных свечей — вход ПРОТИВ них.

    Народная идея «слишком далеко зашло». Проверяем, а не верим."""
    if i < сколько + 1:
        return 0
    вверх = all(ряд["close"][j] > ряд["open"][j]
                for j in range(i - сколько + 1, i + 1))
    вниз = all(ряд["close"][j] < ряд["open"][j]
               for j in range(i - сколько + 1, i + 1))
    if вверх:
        return -1
    if вниз:
        return 1
    return 0


def продолжение_серии(ряд, i, сколько=4):
    """То же самое, но вход ПО направлению серии.

    Зеркальная гипотеза к предыдущей. Обе в списке намеренно: если ни одна
    не работает, это сильнее, чем если бы мы проверили только одну."""
    return -серия_баров(ряд, i, сколько)


def сужение_диапазона(ряд, i, окно=20, доля=0.6):
    """Затишье перед движением: ATR сжался, входим в сторону пробоя.

    Идея старая: за низкой волатильностью следует высокая."""
    if i < окно + ATR_ПЕРИОД + 1 or ряд["atr"][i] <= 0:
        return 0
    средний_atr = sum(ряд["atr"][i - окно:i]) / окно
    if средний_atr <= 0 or ряд["atr"][i] > средний_atr * доля:
        return 0
    # Сжались. Направление — по последней свече.
    if ряд["close"][i] > ряд["open"][i]:
        return 1
    if ряд["close"][i] < ряд["open"][i]:
        return -1
    return 0


