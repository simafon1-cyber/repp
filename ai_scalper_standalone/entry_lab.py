"""entry_lab.py — ПОИСК ПРЕИМУЩЕСТВА ВО ВХОДЕ.

=====================================================================
ЗАЧЕМ ЭТОТ ФАЙЛ СУЩЕСТВУЕТ
=====================================================================
Диагностика показала: нынешний вход НЕОТЛИЧИМ от случайного и от своего
собственного зеркала. Пока это так, никакая работа над выходом не изменит
знак ожидания — она только меняет скорость потери.

Значит нужен вход, у которого преимущество ЕСТЬ. Здесь оно ищется.

=====================================================================
ГЛАВНОЕ ПРАВИЛО: ОДИН ПРИЗНАК — ОДИН ОТВЕТ
=====================================================================
Соблазн очевидный: набрать полсотни признаков, прогнать все и взять
лучший. Так делать нельзя, и вот почему.

Если проверить 50 случайных признаков, примерно 2-3 покажут «значимое»
улучшение просто по случайности — при пороге 5% это ровно то, что порог и
означает. Выбрав лучший из пятидесяти, вы гарантированно выберете шум.

Поэтому:
  * список признаков ЗАФИКСИРОВАН заранее и короткий;
  * каждый проверяется отдельно, а не в комбинации;
  * поправка на число проверок применяется честно;
  * признак обязан работать на НЕСКОЛЬКИХ инструментах, а не на одном.

=====================================================================
ТРИ КОНТРОЛЯ, БЕЗ КОТОРЫХ ЧИСЛА НИЧЕГО НЕ ЗНАЧАТ
=====================================================================
1. ЗЕРКАЛО. Тот же бар, тот же момент, противоположное направление. Если
   признак говорит «покупай», а зеркало «продавай», и результат одинаков —
   признак не выбирает направление, он выбирает только момент. Это самый
   строгий из контролей: он держит постоянными спред, волатильность и
   время суток.

2. СЛУЧАЙНЫЙ ВХОД. Столько же сделок, на тех же барах, направление
   монеткой. Показывает, сколько «зарабатывает» отсутствие идеи.

3. ПЕРЕСТАНОВКА. Метки признака тасуются тысячи раз. Если случайное
   деление даёт такую же разницу — разницы нет.

=====================================================================
ЧЕГО ЗДЕСЬ НЕТ
=====================================================================
Здесь НЕ подбираются параметры выхода: он один и тот же для всех
признаков (СТОП_ATR / ЦЕЛЬ_R), потому что сравниваются входы, а не выходы.
Здесь НЕ подбирается размер позиции: результат считается в R.
Здесь НЕ используется будущее: каждый признак считается по свечам,
закрывшимся ДО входа.
"""

