# =====================================================================
# ЭТАЛОННЫЙ ВЫХОД — ОДИН НА ВСЕ ПРИЗНАКИ
# =====================================================================
# Числа не подбирались: это простейший симметричный выход, который в
# диагностике оказался лучше нынешней цепочки. Он здесь не потому, что
# хорош, а потому, что ОДИНАКОВ для всех — иначе сравнивались бы выходы.
СТОП_ATR = 2.0          # стоп = 2 ATR
ЦЕЛЬ_R = 1.0            # цель = 1R
ГОРИЗОНТ = 100          # сколько баров ждать исхода
ATR_ПЕРИОД = 14

# Сколько перестановок в проверке на случайность.
ПЕРЕСТАНОВОК = 2000

# Минимум сделок, ниже которого вывод не делается.
МИНИМУМ_СДЕЛОК = 100


# =====================================================================
# ПОДГОТОВКА РЯДА
# =====================================================================
def подготовить(bars, atr_период: int = ATR_ПЕРИОД):
    """Посчитать всё, что понадобится признакам, ОДИН раз.

    Каждое значение по индексу i считается ТОЛЬКО по свечам с индексами
    меньше или равными i. Заглядывания вперёд здесь нет и быть не может:
    признаки читают ряд по тому же индексу, а вход происходит на i+1."""
    n = len(bars)
    high = [float(b["high"]) for b in bars]
    low = [float(b["low"]) for b in bars]
    close = [float(b["close"]) for b in bars]
    open_ = [float(b["open"]) for b in bars]
    time = [int(b["time"]) for b in bars]
    spread = [int(b.get("spread", 0) or 0) for b in bars]

    # ATR по Уайлдеру — та же формула, что в indicators.py.
    tr = [0.0] * n
    for i in range(1, n):
        tr[i] = max(high[i] - low[i],
                    abs(high[i] - close[i - 1]),
                    abs(low[i] - close[i - 1]))
    atr = [0.0] * n
    if n > atr_период:
        atr[atr_период] = sum(tr[1:atr_период + 1]) / atr_период
        k = 1.0 / atr_период
        for i in range(atr_период + 1, n):
            atr[i] = atr[i - 1] + k * (tr[i] - atr[i - 1])

    return {"high": high, "low": low, "close": close, "open": open_,
            "time": time, "spread": spread, "atr": atr, "n": n}


# =====================================================================
# ПРИЗНАКИ. СПИСОК ЗАФИКСИРОВАН ЗАРАНЕЕ.
# =====================================================================
# Каждый признак — функция (ряд, i) -> направление: 1, -1 или 0.
# i — индекс ПОСЛЕДНЕЙ ЗАКРЫТОЙ свечи. Вход происходит на открытии i+1.
#
# Признаки намеренно простые и общеизвестные. Мудрёный признак с пятью
# порогами всегда найдёт что-нибудь в прошлом — на то он и мудрёный.

def пробой_экстремума(ряд, i, окно=20):
    """Классический пробой: закрытие выше максимума последних N свечей.

    Идея: цена, вышедшая за границу недавнего диапазона, чаще продолжает
    движение, чем возвращается."""
    if i < окно + 1:
        return 0
    макс = max(ряд["high"][i - окно:i])
    мин = min(ряд["low"][i - окно:i])
    c = ряд["close"][i]
    if c > макс:
        return 1
    if c < мин:
        return -1
    return 0


def возврат_к_средней(ряд, i, окно=20, порог=2.0):
    """Обратная идея: цена, ушедшая далеко от средней, возвращается.

    Отклонение считается в ATR — так один порог годится и для золота, и
    для валют."""
    if i < окно + 1 or ряд["atr"][i] <= 0:
        return 0
    средняя = sum(ряд["close"][i - окно:i]) / окно
    отклонение = (ряд["close"][i] - средняя) / ряд["atr"][i]
    if отклонение > порог:
        return -1          # ушли высоко -> ждём возврата вниз
    if отклонение < -порог:
        return 1
    return 0


