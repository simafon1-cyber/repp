# =====================================================================
# ИСХОД ОДНОЙ СДЕЛКИ
# =====================================================================
def исход(ряд, i, направление: int, стоп_atr: float = СТОП_ATR,
          цель_r: float = ЦЕЛЬ_R, горизонт: int = ГОРИЗОНТ):
    """Чем кончилась бы сделка, открытая на ОТКРЫТИИ свечи i+1.

    Возвращает результат в R или None, если посчитать нельзя.

    ХУДШИЙ ВАРИАНТ ВНУТРИ БАРА. Порядок касаний внутри свечи неизвестен.
    Если в одной свече задеты и стоп, и цель, засчитывается СТОП. Иначе
    проверка врала бы в нашу пользу ровно там, где это приятнее всего.

    СПРЕД ПЛАТИТСЯ ОДИН РАЗ, при входе. Второй раз вычитать его нельзя —
    это была бы двойная плата за одну сделку (уже попадалось в exit_lab)."""
    n = ряд["n"]
    if i + 1 >= n or ряд["atr"][i] <= 0:
        return None
    atr = ряд["atr"][i]
    риск = atr * стоп_atr
    if риск <= 0:
        return None

    вход = ряд["open"][i + 1]
    # ИЗДЕРЖКИ ЗДЕСЬ НЕ ВЫЧИТАЮТСЯ. Спред и комиссия одинаковы для
    # признака, зеркала и случайного входа — они сокращаются при
    # сравнении. Вычитать их внутри значило бы платить трижды за одно и
    # то же. Абсолютный уровень издержек учитывается отдельно, параметром
    # издержки_r в прогнать(), и только там, где сравнивают с нулём.
    стоп = вход - направление * риск
    цель = вход + направление * риск * цель_r

    конец = min(n, i + 1 + горизонт)
    for j in range(i + 1, конец):
        h, l = ряд["high"][j], ряд["low"][j]
        стоп_задет = (l <= стоп) if направление == 1 else (h >= стоп)
        цель_задета = (h >= цель) if направление == 1 else (l <= цель)
        if стоп_задет:
            return -1.0
        if цель_задета:
            return цель_r
    # Горизонт кончился — закрываем по цене закрытия последней свечи.
    выход = ряд["close"][конец - 1]
    return ((выход - вход) * направление) / риск


# =====================================================================
# ПРОГОН ОДНОГО ПРИЗНАКА
# =====================================================================
def прогнать(ряд, признак, начало: int = 0, конец: int = 0,
             seed: int = 0, издержки_r: float = 0.0):
    """Сделки признака, его зеркала и случайного входа на тех же барах.

    Возвращает {"признак": [...], "зеркало": [...], "случай": [...]} —
    списки результатов в R.

    ЗЕРКАЛО СЧИТАЕТСЯ НА ТЕХ ЖЕ БАРАХ И В ТОТ ЖЕ МОМЕНТ. Это удерживает
    постоянными спред, волатильность и время суток — меняется ТОЛЬКО
    направление. Если результаты совпадают, признак не умеет выбирать
    сторону."""
    n = ряд["n"]
    конец = конец or n - 1
    случай = random.Random(seed)

    свои, зеркало, случайные = [], [], []
    for i in range(max(начало, ATR_ПЕРИОД + 30), min(конец, n - 1)):
        d = признак(ряд, i)
        if not d:
            continue
        r = исход(ряд, i, d)
        if r is None:
            continue
        свои.append(r - издержки_r)

        зр = исход(ряд, i, -d)
        if зр is not None:
            зеркало.append(зр - издержки_r)

        сл = исход(ряд, i, 1 if случай.random() < 0.5 else -1)
        if сл is not None:
            случайные.append(сл - издержки_r)

    return {"признак": свои, "зеркало": зеркало, "случай": случайные}


