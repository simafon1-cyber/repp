# ПРОГОН ОДНОГО ПРИЗНАКА
# =====================================================================
def прогнать(ряд, признак, начало: int = 0, конец: int = 0,
             seed: int = 0, symbol: str = "", издержки: bool = True):
    """Сделки признака, его зеркала и случайного входа на тех же барах.

    Возвращает {"признак": [...], "зеркало": [...], "случай": [...]} —
    списки ЗАПИСЕЙ О СДЕЛКАХ (см. сделка()), а не голых чисел.

    ЧТО ИЗМЕНИЛОСЬ. Раньше отсюда возвращались числа в R, а издержки
    передавались параметром `издержки_r` и просто вычитались из каждого.
    Хуже того — вызывающий скрипт этот параметр НЕ ПЕРЕДАВАЛ, так что
    прогон считал вообще без издержек, а таблица «после издержек» в
    отчёте была посчитана вручную.

    Теперь издержки живут внутри каждой сделки, а итоговые метрики
    считаются по записям. Проверить можно прогоном.

    ЗЕРКАЛО СЧИТАЕТСЯ НА ТЕХ ЖЕ БАРАХ И В ТОТ ЖЕ МОМЕНТ. Это удерживает
    постоянными спред, волатильность и время суток — меняется ТОЛЬКО
    направление. Если результаты совпадают, признак не умеет выбирать
    сторону."""
    n = ряд["n"]
    конец = конец or n - 1
    случай = random.Random(seed)

    свои, зеркало, случайные = [], [], []
    for i in range(max(начало, ATR_ПЕРИОД + 30), min(конец, n - 1)):
        d = признак(ряд, i)
        if not d:
            continue
        своя = сделка(ряд, i, d, symbol, издержки=издержки)
        if своя is None:
            continue
        свои.append(своя)

        зр = сделка(ряд, i, -d, symbol, издержки=издержки)
        if зр is not None:
            зеркало.append(зр)

        сл = сделка(ряд, i, 1 if случай.random() < 0.5 else -1, symbol,
                    издержки=издержки)
        if сл is not None:
            случайные.append(сл)

    return {"признак": свои, "зеркало": зеркало, "случай": случайные}


def эрки(сделки, чистые: bool = True):
    """Результаты в R одним списком.

    чистые=True — после издержек, и это то, что сравнивают с нулём.
    чистые=False — без издержек, и это то, что сравнивают с зеркалом:
    там издержки одинаковы и сокращаются."""
    ключ = "r_чистый" if чистые else "r_грязный"
    return [float(с.get(ключ, с.get("r_грязный", 0.0))) for с in (сделки or ())]


