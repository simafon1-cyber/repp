def исход(ряд, i, направление: int, стоп_atr: float = СТОП_ATR,
          цель_r: float = ЦЕЛЬ_R, горизонт: int = ГОРИЗОНТ):
    """Чем кончилась бы сделка, открытая на ОТКРЫТИИ свечи i+1.

    Возвращает результат в R БЕЗ ИЗДЕРЖЕК или None, если посчитать нельзя.
    Издержки считает сделка() — здесь только движение цены.

    ХУДШИЙ ВАРИАНТ ВНУТРИ БАРА. Порядок касаний внутри свечи неизвестен.
    Если в одной свече задеты и стоп, и цель, засчитывается СТОП. Иначе
    проверка врала бы в нашу пользу ровно там, где это приятнее всего."""
    запись = сделка(ряд, i, направление, "", стоп_atr, цель_r, горизонт,
                    издержки=False)
    return None if запись is None else запись["r_грязный"]


# =====================================================================
# ОДНА СДЕЛКА СО ВСЕМИ ИЗДЕРЖКАМИ
# =====================================================================
def сделка(ряд, i, направление: int, symbol: str,
           стоп_atr: float = СТОП_ATR, цель_r: float = ЦЕЛЬ_R,
           горизонт: int = ГОРИЗОНТ, издержки: bool = True,
           лот: float = None):
    """Полная запись одной сделки: цены, издержки, чистый результат.

    ЗАЧЕМ ЭТО ВООБЩЕ. Раньше отсюда возвращалось одно число — результат в
    R без издержек, — а издержки приписывались к итоговой таблице потом,
    вручную. Проверить такую таблицу было нельзя: прогон её не
    воспроизводил.

    Теперь издержки входят в расчёт КАЖДОЙ сделки, а итоговые метрики
    считаются по этим записям. Совпадение проверяется отдельным тестом.

    Возвращает словарь или None, если сделку посчитать нельзя."""
    n = ряд["n"]
    if i + 1 >= n or ряд["atr"][i] <= 0:
        return None
    atr = ряд["atr"][i]
    риск_цены = atr * стоп_atr
    if риск_цены <= 0:
        return None

    вход = ряд["open"][i + 1]
    стоп = вход - направление * риск_цены
    цель = вход + направление * риск_цены * цель_r

    конец = min(n, i + 1 + горизонт)
    выход = None
    причина = ""
    индекс_выхода = конец - 1
    for j in range(i + 1, конец):
        h, l = ряд["high"][j], ряд["low"][j]
        стоп_задет = (l <= стоп) if направление == 1 else (h >= стоп)
        цель_задета = (h >= цель) if направление == 1 else (l <= цель)
        if стоп_задет:
            выход, причина, индекс_выхода = стоп, "стоп", j
            break
        if цель_задета:
            выход, причина, индекс_выхода = цель, "цель", j
            break
    if выход is None:
        выход = ряд["close"][конец - 1]
        причина = "горизонт"
        индекс_выхода = конец - 1

    r_грязный = ((выход - вход) * направление) / риск_цены

    запись = {
        "время_входа": ряд["time"][i + 1],
        "время_выхода": ряд["time"][индекс_выхода],
        "инструмент": symbol,
        "направление": "BUY" if направление == 1 else "SELL",
        "вход": вход,
        "выход": выход,
        "стоп": стоп,
        "цель": цель,
        "баров_в_сделке": индекс_выхода - i,
        "причина_выхода": причина,
        "r_грязный": r_грязный,
    }

    if not издержки:
        # Быстрый путь для сравнения признака с зеркалом: там издержки
        # одинаковы и сокращаются. Деньги считать незачем.
        return запись

    л = ЛОТ_ИССЛЕДОВАНИЯ if лот is None else лот
    # ПРИБЛИЖЕНИЕ, КОТОРОЕ НАДО НАЗВАТЬ. У пар с долларом слева (USDJPY и
    # прочие) прибыль получается в чужой валюте, и переводить её в доллары
    # правильно по курсу ВЫХОДА. Здесь берётся курс входа.
    #
    # Ошибка от этого меньше десятой доли процента: за время сделки курс
    # успевает измениться на пару сотых процента, а издержки и прибыль
    # переводятся по одному и тому же курсу, так что их отношение (то есть
    # результат в R) почти не меняется. На вывод «преимущество меньше
    # издержек» это повлиять не может — там разница в разы.
    цена_пункта = costs.стоимость_пункта(symbol, вход, л)
    пункт = costs.пункт(symbol)

    риск_денег = (риск_цены / пункт) * цена_пункта if пункт > 0 else 0.0
    грязная_прибыль = ((выход - вход) * направление / пункт) * цена_пункта \
        if пункт > 0 else 0.0

    спред_пунктов = costs.спред_пунктов(symbol, ряд["spread"][min(i + 1, n - 1)])
    спред = costs.спред_деньгами(symbol, спред_пунктов, вход, л)
    комиссия = costs.комиссия(л)
    ночей = costs.ночей(запись["время_входа"], запись["время_выхода"])
    своп = costs.своп(symbol, направление, ночей, л)

    # Своп бывает и положительным. В издержки он входит со своим знаком:
    # приписывать ему только плохую сторону было бы так же неверно, как
    # забыть про него вовсе.
    издержки_всего = спред + комиссия - своп
    чистая_прибыль = грязная_прибыль - издержки_всего

    запись.update({
        "лот": л,
        "риск_денег": риск_денег,
        "грязная_прибыль": грязная_прибыль,
        "спред_пунктов": спред_пунктов,
        "спред": спред,
        "комиссия": комиссия,
        "ночей": ночей,
        "своп": своп,
        "издержки_всего": издержки_всего,
        "чистая_прибыль": чистая_прибыль,
        "r_чистый": (чистая_прибыль / риск_денег) if риск_денег > 0 else 0.0,
    })
    return запись


