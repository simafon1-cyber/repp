# СЧЁТ
# =====================================================================
def сводка(значения) -> dict:
    """Краткий счёт по списку результатов в R.

    Принимает и голые числа, и записи о сделках: раньше сюда приходили
    только числа, и перепутать было бы легко."""
    ряд = [float(x.get("r_чистый", x.get("r_грязный", 0.0)))
           if isinstance(x, dict) else float(x)
           for x in (значения or ())]
    n = len(ряд)
    if n == 0:
        return {"сделок": 0, "ожидание": 0.0, "профит_фактор": 0.0,
                "винрейт": 0.0, "разброс": 0.0}
    плюсы = [x for x in ряд if x > 0]
    минусы = [-x for x in ряд if x < 0]
    ср = sum(ряд) / n
    разброс = ((sum((x - ср) ** 2 for x in ряд) / (n - 1)) ** 0.5) if n > 1 else 0.0
    return {
        "сделок": n,
        "ожидание": round(ср, 4),
        "профит_фактор": round(sum(плюсы) / sum(минусы), 3) if минусы else 0.0,
        "винрейт": round(len(плюсы) / n * 100, 1),
        "разброс": round(разброс, 3),
    }


def метрики(сделки) -> dict:
    """Полный счёт ПО ЖУРНАЛУ СДЕЛОК, в деньгах и в R.

    Все итоговые числа считаются здесь и только здесь. Приписать что-то к
    итоговой таблице мимо журнала теперь нельзя: таблица берётся отсюда, а
    совпадение проверяется тестом."""
    записи = [с for с in (сделки or ()) if isinstance(с, dict)]
    n = len(записи)
    если_пусто = {
        "сделок": 0, "винрейт": 0.0, "средний_выигрыш": 0.0,
        "средний_проигрыш": 0.0, "профит_фактор": 0.0, "ожидание": 0.0,
        "чистая_прибыль": 0.0, "грязная_прибыль": 0.0, "издержки": 0.0,
        "ожидание_r": 0.0, "ожидание_r_грязное": 0.0,
    }
    if n == 0:
        return если_пусто

    чистые = [float(с.get("чистая_прибыль", 0.0)) for с in записи]
    выигрыши = [x for x in чистые if x > 0]
    проигрыши = [-x for x in чистые if x < 0]

    return {
        "сделок": n,
        "винрейт": round(len(выигрыши) / n * 100, 2),
        "средний_выигрыш": round(sum(выигрыши) / len(выигрыши), 2) if выигрыши else 0.0,
        "средний_проигрыш": round(-sum(проигрыши) / len(проигрыши), 2) if проигрыши else 0.0,
        "профит_фактор": round(sum(выигрыши) / sum(проигрыши), 3) if проигрыши else 0.0,
        "ожидание": round(sum(чистые) / n, 4),
        "чистая_прибыль": round(sum(чистые), 2),
        "грязная_прибыль": round(sum(float(с.get("грязная_прибыль", 0.0))
                                     for с in записи), 2),
        "издержки": round(sum(float(с.get("издержки_всего", 0.0))
                              for с in записи), 2),
        "ожидание_r": round(sum(float(с.get("r_чистый", 0.0))
                                for с in записи) / n, 4),
        "ожидание_r_грязное": round(sum(float(с.get("r_грязный", 0.0))
                                        for с in записи) / n, 4),
    }


def перестановка(a, b, прогонов: int = ПЕРЕСТАНОВОК, seed: int = 0) -> float:
    """Вероятность увидеть такую разницу средних по чистой случайности.

    Метки тасуются на объединённом наборе. Счёт ДВУСТОРОННИЙ: случайность
    одинаково легко даёт разницу в любую сторону, и считать только удобную
    нам — это самообман."""
    a = [float(x) for x in (a or ())]
    b = [float(x) for x in (b or ())]
    if not a or not b:
        return 1.0
    наблюдаемая = sum(a) / len(a) - sum(b) / len(b)
    общий = a + b
    сл = random.Random(seed)
    не_хуже = 0
    for _ in range(прогонов):
        сл.shuffle(общий)
        x = общий[:len(a)]
        y = общий[len(a):]
        if abs(sum(x) / len(x) - sum(y) / len(y)) >= abs(наблюдаемая):
            не_хуже += 1
    # +1 в числителе и знаменателе: наблюдаемое деление тоже одно из
    # возможных, и «вероятность ноль» не бывает.
    return (не_хуже + 1) / (прогонов + 1)


def порог_с_поправкой(проверок: int, база: float = 0.05) -> float:
    """Порог значимости с поправкой на число проверенных признаков.

    Проверяя шесть признаков, мы шесть раз бросаем кости. Без поправки
    «нашли значимое» означало бы только это."""
    return база / max(1, int(проверок))
