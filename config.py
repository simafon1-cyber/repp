# на этот коэффициент — независимо от профиля/фиксированной денежной цели
# прибыли (target_profit_money). Раньше денежные цели профилей (особенно
# "Истеричка" — $1) никак не были привязаны к фактическому долларовому риску
# на сделку (который растёт вместе с эквити) — из-за этого одна убыточная
# сделка "съедала" множество мелких прибыльных. Теперь калькулятор TP
# (risk_manager.calc_tp_distance / calc_tp_distance_money) всегда поднимает
# TP минимум до SL × MIN_RISK_REWARD_RATIO, если посчитанный TP оказался
# меньше. См. также USE_MAX_PROFIT_RIDE выше — пока он включён, TP вообще не
# ставится (сделку ведёт трейлинг), и это ограничение неактуально; но как
# только USE_MAX_PROFIT_RIDE выключат — данная защита не даст повторить
# прежнюю ошибку.
MIN_RISK_REWARD_RATIO = 3.0

# По просьбе пользователя — "тянуть максимальную прибыль, сколько возможно":
# сделка открывается БЕЗ фиксированного TP (ни в пунктах, ни в деньгах) — вместо
# этого её полностью ведут Break Even + ATR-трейлинг + Profit Lock ниже: они
# постепенно поднимают стоп-лосс вслед за ценой, а закрытие происходит только
# когда цена разворачивается и выбивает этот подтянутый стоп. Так позиция может
# забрать любую прибыль, какую даст движение рынка, а не только фиксированную
# небольшую цель. Выключи (False), чтобы вернуть прежнее поведение с TP_* /
# RISK_REWARD_RATIO / target_profit_money (см. process_symbol в main.py).
USE_MAX_PROFIT_RIDE = True

USE_BREAK_EVEN = True
