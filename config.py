USE_PROFIT_LOCK_TRAILING = True
PROFIT_LOCK_START_POINTS = 20   # авто-масштабируется (ATR-порог; см. также PROFIT_LOCK_START_R_FRACTION ниже — итоговый порог берётся МАКСИМУМ из двух)

# КРИТИЧНО: порог запуска Profit Lock не может быть меньше этой доли ОТ
# РИСКА САМОЙ СДЕЛКИ (её 1R = исходное расстояние price_open<->SL при
# открытии). Диагноз по реальным сделкам (xauusd/btcusd, профиль "Истеричка"):
# ATR-порог выше был НЕ привязан к тому, насколько узкий стоп у профиля —
# у "Истерички" (atr_sl_multiplier=0.5) это давало запуск лока уже на ~30%
# риска, РАНЬШЕ даже безубытка. Сделка фиксировалась в крошечный плюс
# (иногда за 1-2 секунды на волатильном золоте), а неудачная теряла всю
# дистанцию стопа — отсюда "мелкие плюсы, крупные минусы" в реальной
# статистике. 1.0 = Profit Lock не стартует, пока прибыль не отобьёт
# собственный риск сделки целиком (1R) — дальше уже работает
# PROFIT_LOCK_TIERS, чем выше пик, тем больше запирается.
PROFIT_LOCK_START_R_FRACTION = 1.0
# Было 50 — поднято до 70 по жалобе пользователя (сделка держала пиковый
# плавающий профит $300-360, а закрывалась в районе $10-150 — почти вся
# прибыль отдавалась обратно рынку при развороте). См. также
# USE_TIERED_PROFIT_LOCK ниже — с ним PROFIT_LOCK_PERCENT работает как
# запасной вариант (если тиры выключить) и как один из уровней тира.
PROFIT_LOCK_PERCENT = 70

# Ступенчатая (ratchet) фиксация прибыли: чем выше КОГДА-ЛИБО ДОСТИГНУТЫЙ пик
# профита по сделке — тем больший % от него запирается стопом, вместо одного
# фиксированного PROFIT_LOCK_PERCENT для любого пика. Раньше сделка, которая
# доходила до пика лишь чуть выше порога PROFIT_LOCK_START_POINTS, ловила
# лишь минимальный % защиты (или вообще только Break Even, если разворот
# был быстрее следующего опроса) — отсюда случаи "видел +360, закрылось на
# +10..40". Тиры заданы как (множитель от порога PROFIT_LOCK_START_POINTS,
# % пика к фиксации); используется САМЫЙ старший тир, до которого дорос пик.
USE_TIERED_PROFIT_LOCK = True
PROFIT_LOCK_TIERS = [
    (1.0, 40),   # пик едва перевалил за стартовый порог -> запереть 40%
    (2.0, 55),
    (4.0, 70),
    (8.0, 85),   # очень большой пик (напр. золото на резком движении) -> запереть 85%
]

